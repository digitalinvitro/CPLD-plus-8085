def main():
    src = io.open(SRC, encoding='utf-8').read()
    s = src
    for old, new, tag in EDITS:
        n = s.count(old)
        if n != 1:
            print('ОШИБКА: якорь %r встречается %d раз (ожидался 1)' % (tag, n))
            sys.exit(1)
        s = s.replace(old, new)
        print('ок: %s' % tag)

    # Контроль 1: конструкции v4.0.1 на месте, старых нет.
    for frag, want in (
        ("assign por_ce = x1_n;", 1),
        ("reg [3:0] por_sh = 4'hF;", 1),
        ("{1'b0, por_sh[3:1]}", 1),
        ("(cnt == 3'd1) | (cnt == 3'd6)", 0),
        ("por_sh[7:1]", 0),
        ("reg [7:0] por_sh", 0),
        ("П.27", 0),   # п.27 пишется строчными
    ):
        got = s.count(frag)
        if got != want:
            print('ОШИБКА: %r встречается %d раз (ожидалось %d)' % (frag, got, want))
            sys.exit(1)
    print('ок: конструкции v4.0.1 на месте, старых нет')

    # Контроль 2: норм-путь бит-в-бит v4.0.0 (делитель, GSR, ядро UART).
    for frag in ("assign X1 = (cnt != 3'd0) ^ x1_n;",
                 "assign X2 = (cnt == 3'd0) ^ x1_n;",
                 "reg [2:0] cnt = 3'd0;",
                 "if (cnt == 3'd6) cnt <= 3'd0;",
                 "if (cnt == 3'd3)      x1_n <= 1'b1;",
                 "else if (cnt == 3'd4) x1_n <= 1'b0;",
                 "por_run <= por_sh[0];",
                 "(!IOM && A15 && !por_run)",
                 "assign RESET_IN = ~(RST | por_run);",
                 "wire io_wr_tx = (state == S_T2) && !WRn && IOM && !tx_run && !rx_run && !por_run",
                 "&& (addr_latch[2:0] == 3'b100);",
                 "assign TX  = shreg[0];",
                 "assign rx_int = rx_full;",
                 "assign SID = RX;",
                 "shreg    <= 9'h1FF;   // idle '1' (SET-ветка GSR)"):
        if s.count(frag) != 1:
            print('ОШИБКА: норм-путь повреждён: %r' % frag)
            sys.exit(1)
    print('ок: делитель/GSR/шина/ядро UART бит-в-бит v4.0.0')

    # Контроль 3: оба async-блока ядра и FSM на месте (GSR-домен п.18/п.26).
    n_async = s.count("always @(posedge clk or posedge RST) begin")
    if n_async != 2:
        print('ОШИБКА: async-блоков %d (ожидалось 2: FSM + ядро UART)' % n_async)
        sys.exit(1)
    print('ок: async-блоки GSR-домена на месте (2)')

    # Контроль 4: cpu_rst в КОДЕ ровно 0 упоминаний (v4.0.0 удалил wire).
    code_mentions = 0
    for ln in s.split('\n'):
        bare = ln.split('//')[0]
        code_mentions += bare.count('cpu_rst')
    if code_mentions != 0:
        print('ОШИБКА: cpu_rst в КОДЕ %d раз (ожидалось 0)' % code_mentions)
        sys.exit(1)
    print('ок: cpu_rst в коде 0 упоминаний')

    io.open(OUT_U8, 'w', encoding='utf-8', newline='').write(s)

    # CP1251-версия: строго (любой символ вне CP1251 - ошибка).
    try:
        data = s.encode('cp1251')
    except UnicodeEncodeError as e:
        print('ОШИБКА CP1251: %s' % e)
        sys.exit(1)
    io.open(OUT_CP, 'wb').write(data)

    # Round-trip: CP1251 -> UTF-8 == utf8-версия.
    back = data.decode('cp1251')
    assert back == s, 'round-trip CP1251 сломан'
    print('ок: round-trip CP1251 проверен (%d байт CP1251, %d байт UTF-8)'
          % (len(data), len(s.encode('utf-8'))))


