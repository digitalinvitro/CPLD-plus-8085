# Выход: top_suart_por6_v391_utf8.v + top_suart_por6_v391.v (CP1251).
import sys, difflib, io

SRC = "/home/z/my-project/CPLD-plus-8085/beta/hiclock/top_suart_por6_v39_utf8.v"
DST_U = "/home/z/my-project/CPLD-plus-8085/beta/hiclock/top_suart_por6_v391_utf8.v"
DST_C = "/home/z/my-project/CPLD-plus-8085/beta/hiclock/top_suart_por6_v391.v"

with io.open(SRC, "r", encoding="utf-8") as f:
    txt = f.read()

def rep1(old, new):
    """Замена фрагмента, который обязан встретиться РОВНО один раз."""
    global txt
    n = txt.count(old)
    assert n == 1, "Фрагмент найден %d раз (ожидался 1):\n%s" % (n, old)
    txt = txt.replace(old, new)

# ---- R1: титул (строка 2) ----
rep1(
"// top_suart.v v3.9 - retro_pcld_top + SOFT-UART ТРАНЗИТЫ + CPU 3,57 МГц (X1/X2 = 7,14 МГц; кольцо делителя расширено 5 -> 7 триггеров, N=7)\n",
"// top_suart.v v3.9.1 - retro_pcld_top + SOFT-UART ТРАНЗИТЫ + CPU 3,57 МГц (X1/X2 = 7,14 МГц, кольцо N=7; CS_n в writeback ОТ СОСТОЯНИЯ FSM - защёлка wb_ram_q УДАЛЕНА, эквивалентность доказана, п.16)\n")

# ---- R2: цепочка истории в титуле (v3.9.1 - 2026-10-30) ----
rep1(
"//  не тянет - нестабильный старт) - 2026-10-29). База: v1 (Task 70-a, логика чтения/захвата\n",
"//  не тянет - нестабильный старт) - 2026-10-29; v3.9.1 CS_n в writeback\n//  от состояния FSM, защёлка wb_ram_q удалена (п.16) - 2026-10-30). База: v1 (Task 70-a, логика чтения/захвата\n")

# ---- R3: сноска в п.5 (защёлка удалена в v3.9.1) ----
rep1(
"//     ставится в момент захвата строба (T2, A15/IOM стабильны до конца\n//     цикла).\n//  6) ЗАХВАТ T1H СТРУКТУРНО ЗАЩИЩЁН:",
"//     ставится в момент захвата строба (T2, A15/IOM стабильны до конца\n//     цикла). В v3.9.1 защёлка УДАЛЕНА - п.16: CS_n в WB от состояния\n//     FSM, эквивалентность доказана.\n//  6) ЗАХВАТ T1H СТРУКТУРНО ЗАЩИЩЁН:")

# ---- R4: новый п.16 перед TODO 78 ----
rep1(
"// Что делать владельцу (TODO 78, ред. v3.9):\n",
"""// ЧТО ИЗМЕНЕНО в v3.9.1 (2026-10-30, CS_n writeback без защёлки, clk10-62):
// 16) ЗАЩЁЛКА wb_ram_q УДАЛЕНА (предложение коллеги, вердикт clk10-61:
//     ПРАВ). Единственный читатель wb_ram_q был CS_n, а in_wb
//     (state >= S_WB1) уже влечёт условие защёлки:
//     - S_WB1 достижим ТОЛЬКО из ветки «запись завершена» в T2
//       (wr_seen && WRn) и ТОЛЬКО при !IOM && A15 - тем же фронтом
//       ставится и защёлка (в v3.9: строки 794+797 в одном begin);
//     - в WB2..WB4 wb_ram_q не переприсваивается (держит 1);
//     - сброс СИНХРОННЫЙ, одним фронтом со state (в v3.9: 743+746) -
//       окна «state в WB, wb_ram_q=0» нет даже при cpu_rst посреди
//       импульса /WE;
//     - драйверы WB (A-сети, D-шина, WE_n) УЖЕ работали от in_wb без
//       защёлки - правка делает CS_n консистентным с WB-трактом.
//     Изменение RTL (против v3.9): удалены reg wb_ram_q, его сброс и
//     взвод; уравнение:
//       было:  assign CS_n = (in_wb && wb_ram_q) ? 1'b0 : (!A15 | IOM);
//       стало: assign CS_n = in_wb ? 1'b0 : (!A15 | IOM);
//     остальное байт-в-байт v3.9 (кольцо N=7, POR, TX v3.7, автомат).
//     ЗАЩИТА ЗАПИСИ СОХРАНЕНА ПОСТРОЕНИЕМ: в WB1..WB4 CS_n=0 БЕЗ
//     A15/IOM - живой декод во время конфликта адресов по-прежнему не
//     участвует; /WE как был, от in_welo (2 тика = 80 нс).
//     ЭКВИВАЛЕНТНОСТЬ (scripts/sim_v391_equiv.py + scripts/tb_v391_diff.v,
//     Icarus Verilog 12.0): (а) полный перебор произведения машин
//     (state, rd_seen, wr_seen, wb_ram_q) x 64 комбинации входов от
//     стартового состояния - 0 расхождений, инвариант «in_wb ->
//     wb_ram_q=1» на всех достижимых состояниях; (б) дифференциальная
//     симуляция двух RTL (v3.9 и v3.9.1 в одном тестбенче, общий
//     стимул): все выходы/шины/лог ОЗУ бит-в-бит на направленных
//     сценариях (запись ОЗУ с новым ALE-циклом и сменой адреса посреди
//     WB - защита п.5, PUSH-стресс, IO/ПЗУ записи, ALE-глюк в T2,
//     cpu_rst в каждой фазе WB1..WB4, «дыхание» защёлки, TX-захват,
//     POR) и на случайном стимуле, 0 расхождений; спеки /WE = ровно
//     80 нс и t_AS >= 40 нс соблюдены.
//     ЦЕНА/ВЫГОДА (по фиту v3.9): -1 МЦ (88 -> 87; wb_ram_q = FB2_17,
//     зарытая, пина нет), -5 ПТ (214 -> ~209), FB1 -1 вход; факт
//     подтверждает фит владельца (п.3 TODO, чек-лист g/h).
//
// Что делать владельцу (TODO 78, ред. v3.9.1):
""")

# ---- R5: TODO п.3 - обязательные точки v3.9.1 ----
