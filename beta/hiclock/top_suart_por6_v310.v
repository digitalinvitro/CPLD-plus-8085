//       (ветка g_div2p5 и вся остальная логика байт-в-байт);
//     - АВТОМАТ ШИНЫ НЕ ТРОНУТ (домен 25 МГц: /WE 80 нс, t_AS 40 нс).
//       T_CPU = 240 нс: зазор WR#(вверх)->след.ALE сжимается до
//       0,25..0,45 T = 60..108 нс (v3.9: 70..126) - окно T1H закрыто
//       по расчёту с запасом ~2-3 такта 25 МГц; ПОСЛЕ ФИТА
//       ПЕРЕИЗМЕРИТЬ зазор на осциллографе (п.4 шапки; арбитр -
//       осциллограф, как и для фазы X1/X2);
//     - ПРОГНОЗ ресурсов: узел 8 -> 5 FF (-3 МЦ: ~85/108), птермы
//       ~+2 (декоды cnt) -> ~216/540, входы ФБ ~198-202/216;
//     - ПОСЛЕДСТВИЯ: CLK OUT = 4,167 МГц duty 50%; t_RD/t_WR CPU
//       сжимаются на 14% против v3.9 (маржа памяти остаётся: /WE
//       80 нс фиксирован автоматом); если экземпляр не потянет 4,17 -
//       откат на v3.9 jed (3,57 МГц, терминал 6857) без переделок;
//       далее вверх на этой опоре пути НЕТ (следующая точка сетки
//       10,00 МГц - CPU 5,00, не тянет).
//=====================================================================
// История (как в v1/top_nouart, логика чтения не менялась):
// Топология: AD0-AD7 процессора, A0-A7 flash/SRAM и CPLD - ОДНА медь
// (сети A0..A7). CPLD = регистровый трансивер:
//   чтение: память видит адрес в T1 (ALE=1) -> данные на D0-D7
//   захватываются в последний тик T1 -> в T2 (CPU отпустил AD) CPLD
//   выдаёт данные на A-сети;
//   запись: в T2 CPU гонит данные по A-сетям (CPLD Hi-Z), CPLD захватывает;
//   после WR#(вверх) - «отложенная запись» (writeback): CPLD сам ставит
//   защёлкнутый адрес на A-сети + данные на D-сети и даёт импульс
//   /WE_RAM (в v3: импульс защищён от ALE, см. п.4 шапки).
// Метод захвата - повторное сэмплирование, пока строб активен (последний
// сэмпл гарантированно валиден); без edge-детекторов и PT-клоков - один
// домен 25 МГц (ARCHITECTURE.md v0.3, §4, §9.3).
// Сброс: SW20 -> RST (нажатие = 1, Task 25) + POR (v3.4: сдвиговый;
// ~860-900 нс @ 8,33 МГц в v3.10; было 1120 @ 7,14 в v3.9) -> RESET_IN=0;
// GSR НЕ используется - сброс всех триггеров через cpu_rst.
// RAM подтверждена на железе (Task 69-j: 4 паттерна x 32K без ошибок,
// T=1280 нс; режим T=400 нс - этот файл; tb v3: T3b/T3d/T3e PUSH-stress).
//=====================================================================

module retro_pcld_top #(parameter POR_W = 6,    // v3.4: НЕ используется (POR - сдвиговый 8 бит, п.9 шапки); оставлен для совместимости тестбенча
                        parameter CLK_DIV = 3,  // v3.10 ЦЕЛЕВАЯ: 3 = делитель /3 -> X1 = 25/3 = 8,333 МГц (CPU 4,167; g_div_odd XOR-пара, п.16); история: 2+HALF=1 -> 10 МГц (v3.6-v3.9); 4 -> 6,25 (v3.4); 2+HALF=0 -> 12,5 ВНЕ ТУ; 5 = XOR-пара legacy (п.9)
                        parameter CLK_HALF = 0) ( // 1 учитывается ТОЛЬКО при CLK_DIV=2 (полуцелая ветка g_div2p5 v3.8/v3.9 - работает на плате, откат); v3.10: 0; v3.7: параметр TXM_W УДАЛЕН вместе с TX-маской (п.13)
    // ---- такт и глобальный сброс ----
    input  wire       clk,          // 25 МГц (измерено Task 29-d: GCK3 = 25,00), U1.29 (P29)
    input  wire       RST,          // SW20, U1.1 (P1, GSTR): покой = 0, нажатие = 1 (актив.1 - доказано платой, Task 25)
    // ---- шина i8085 (входы автомата) ----
    input  wire       ALE,          // cpu1 U1.93 (P93), нога 30
    input  wire       WRn,          // cpu2 U1.92 (P92), нога 31 (активный 0)
    input  wire       RDn,          // cpu3 U1.91 (P91), нога 32 (активный 0)
    input  wire       IOM,          // cpu5 U1.88 (P88), нога 34: 1=IO, 0=память
    input  wire       A15,          // U1.97 (P97) - декод памяти
    // ---- мультиплексированная шина AD0-AD7 = сети A0..A7 (bidir) ----
    inout  wire [7:0] A,            // A0=P26 A1=P21 A2=P19 A3=P17 A4=P15 A5=P13 A6=P11 A7=P9
    // ---- шина данных памяти (bidir) ----
    inout  wire [7:0] D,            // D0=P30 D1=P32 D2=P35 D3=P36 D4=P34 D5=P31 D6=P27 D7=P22
    // ---- управление памятью (активный 0) ----
    output wire       CSr_n,        // P20 /CE_ROM -> U10.22 (flash /CE)
    output wire       OEr_n,        // P16 /OE_ROM -> U10.24
    output wire       CS_n,         // P25 /CE_RAM -> U4.22  (RAM /CE)
    output wire       OE_n,         // P37 /OE_RAM -> U4.24
    output wire       WE_n,         // P24 /WE_RAM -> U4.29 (только writeback!)
    output wire       CS1,          // P99 CS(CE2) -> U4.30, константа '1'
    // ---- поддержка процессора ----
    output wire       X1,           // P68 cpu21, нога 1: 7,14 МГц (50/7, XOR-пара (~r0)^x1_n, период ровно 140 нс) -> CPU 3,57 МГц (v3.9, кольцо N=7)
    output wire       READY,        // P87 cpu6, нога 35: константа '1' (без wait)
    output wire       RESET_IN,     // P84 cpu7, нога 36: активный 0 = ~(RST|POR)
    // ---- soft-UART транзиты (Task 70-a) ----
    output wire       SID,          // P73 cpu17, нога 5 (CPU.SID): транзит RX -> приём (RIM 20h)
    output wire       TX,           // P39: цепь платы «RX» -> CH340G.RXD; TX = tx_q - регистровый транзит SOD с захватом (v3.7, SIM 30h)
    // ---- индикация и звук (выходы активным 0, §6) ----
    output wire [7:0] seg,          // {dp56,g,f,e,d,c,b,a} = P60/5/66/58/57/61/62/45
    output wire [3:0] dig,          // dig0..3 = P6/63/65/48 -> R -> VT1..VT4
    output wire       SND,          // P67 -> BUZZER1.1 (пассивный, прямой бит; A4 порта 01h)
    // ---- наблюдатели: «мёртвые» пины как Hi-Z входы (* keep *) ----
    // (* keep *) обязателен для ног БЕЗ нагрузки: без него XST выкидывает
    // входы (Xst:3005), а выкиннутый пин опция "Ground on Unused IOs"
    // ЗАЗЕМЛИТ - там выходы CPU и X2 (GND запрещён даташитом). ЭТО И ЕСТЬ
    // «ОШИБКА С НОГАМИ» ИЗ ФИТА владельца (Task 68-f).
    // SOD (P72) и RX (P38) теперь ИСПОЛЬЗУЮТСЯ (транзиты) - keep им больше
    // не нужен, но входами остаются.
    (* keep = "TRUE" *) output wire X2,  // P69 cpu20, нога 2: противофаза X1 (v3.8/v3.9: r0 ^ x1_n, SOP(X2) != SOP(X1), п.10/14/15); keep - сеть отдельно (страховка, п.9)
    (* keep = "TRUE" *) input wire RSTOUT,    // P70 cpu19, нога 3
    input  wire       SOD,          // P72 cpu18, нога 4 (CPU.SOD) - теперь транзит в TX
    (* keep = "TRUE" *) input wire INTAn,     // P80 cpu11, нога 11
    (* keep = "TRUE" *) input wire HLDA,      // P82 cpu9,  нога 38
    (* keep = "TRUE" *) input wire CLKOUT,    // P83 cpu8,  нога 37
    (* keep = "TRUE" *) input wire S0,        // P94 cpu0,  нога 29
    (* keep = "TRUE" *) input wire S1,        // P89 cpu4,  нога 33
    (* keep = "TRUE" *) input wire AH8,       // P10 цепь A8,  нога 21 - адрес памяти
    (* keep = "TRUE" *) input wire AH9,       // P12 цепь A9,  нога 22
    (* keep = "TRUE" *) input wire AH10,      // P18 цепь A10, нога 23
    (* keep = "TRUE" *) input wire AH11,      // P14 цепь A11, нога 24
    (* keep = "TRUE" *) input wire AH12,      // P4  цепь A12, нога 25
    (* keep = "TRUE" *) input wire AH13,      // P8  цепь A13, нога 26
    (* keep = "TRUE" *) input wire AH14,      // P3  цепь A14, нога 27
    input  wire       RX,           // P38 цепь платы «TX» (CH340G.TXD) - теперь транзит в SID; заземлять НЕЛЬЗЯ (выход CH340G)
    // ---- клавиатура (Task 34) ----
    output wire       col0,         // P44 SW1/SW5/SW9/SW13/SW17 (KBCOL.0)
    output wire       col1,         // P43 SW2/SW6/SW10/SW14/SW18 (KBCOL.1)
    output wire       col2,         // P42 SW3/SW7/SW11/SW15/SW19 (KBCOL.2)
    output wire       col3,         // P41 SW4/SW8/SW12/SW16 (KBCOL.3; SW20 вне матрицы)
    input  wire       row0,         // P56 R25 подтяжка, SW1
    input  wire       row1,         // P55 R24, SW5
    input  wire       row2,         // P54 R23, SW9
    input  wire       row3,         // P52 R22, SW13
    input  wire       row4          // P51 R21, SW17
);

  //=============================================================
  // Делитель 25 МГц (v3.6 clk10-49; v3.8 one-hot кольцо clk10-52;
  // v3.9: кольцо РАСШИРЕНО 5 -> 7 триггеров, clk10-54).
  // ЦЕЛЕВАЯ ветка v3.10 - g_div_odd (CLK_DIV=3, п.16 шапки): N=3 ->
  // X1 = 25/3 = 8,333 МГц РОВНО 50/50, CPU = 4,167 МГц. Декоды
  // равенства по cnt (==0/==2) - 2-битные, дёшевы (класс п.9 касался
  // 4-битных декодов в старом узле). ПРЕДЫДУЩИЙ кандидат v3.8/v3.9
  // (кольцо, РАБОТАЕТ НА ПЛАТЕ clk10-55) - ветка g_div2p5 ниже,
  // при (3,0) элайзится. Целевые ветки v3.4 (div2/div4, без декодов)
  // и fallback-ветки сохранены для отката - элайзятся, в нетлист
  // не попадают.
  // ВНИМАНИЕ: старый HDLCompiler (ISE) НЕ принимает localparam и
  // reg-инициализаторы ВНУТРИ generate-блока -> выносим на scope модуля.
  //=============================================================
  // v3.10: ширина cnt сужена до минимума (CNT_W=2 при CLK_DIV<=4):
  // старшие биты всё равно застряли бы в 0, а фиттер v3.6 держал их
  // как МЦ (потеря 2 МЦ). Поведение веток бит-в-бит не меняется
  // (sim_v310_div3.py, проверка K: cnt[1:0] == cnt[3:0]).
  localparam [2:0] CNT_W = (CLK_DIV > 8) ? 3'd4 :
                           (CLK_DIV > 4) ? 3'd3 : 3'd2;
  reg [CNT_W-1:0] cnt = 4'd0; // fallback-ветки (N>=6, нечётные) + ЦЕЛЕВАЯ v3.10 g_div_odd
  wire por_ce;

  // Константы делителя (на уровне модуля, не в generate!) - нужны
  // только fallback-ветке (чётные N>=6) и нечётной ветке (v3.10 ЦЕЛЕВАЯ)
  localparam [3:0] MEV   = CLK_DIV / 2 - 1;   // для чётного N
  localparam [3:0] NMOD  = CLK_DIV - 1;       // для нечётного N
  localparam [3:0] NHALF = (CLK_DIV + 1) / 2; // =3 при /5 (НЕ 2!); =2 при /3 (v3.10)

  // Триггеры делителя (reg) тоже на уровне модуля (инициализаторы
  // в generate тоже проблемные для этого XST). Неиспользуемые ветки XST вырезает.
  reg  x1_q = 1'b1;  // чётные 2/4 (откат): INIT=1, X1 стартует с '1'
  reg  t0_q = 1'b0;  // каскад полу-такта для CLK_DIV=4 (t0_q = clk/2)
  reg  x1_p = 1'b1;  // ЦЕЛЕВАЯ v3.10 g_div_odd (нечётная XOR-пара); v3.8/v3.9: элайзился
  reg  x1_n = 1'b0;  // ЦЕЛЕВАЯ v3.10 g_div_odd (NEGEDGE); v3.8/v3.9: g_div2p5
  reg  x2_q = 1'b0;  // v3.5: противофаза X2, чётные ветки (INIT=0 при x1_q=1)
  reg  x2_p = 1'b0;  // ЦЕЛЕВАЯ v3.10: двойник x1_p с инверсными INIT и D (v3.5)
  // v3.10: r0..r6 (кольцо v3.8/v3.9) ЭЛАЙЗЯТСЯ - ЦЕЛЕВАЯ g_div_odd (п.16).
  // v3.8/v3.9 (ЦЕЛЕВАЯ g_div2p5): one-hot кольцо (п.14/15 шапки).
  // v3.9: 7 триггеров, INIT = 1000000 -> состояние 0 при старте;
  // самоочистка «убей преемника И его соседа» + рестарт из 00 (NOR7) -
  // в коде ветки (усиление против v3.8: пары на дистанции 3-4 в N=7
  // иначе орбитируют вечно). x1_p == ~r0, x2_p == r0 ТОЧНО (один
  // posedge) -> двойники сокращены. Legacy cnt/x1_p/x2_p НЕ тронуты
  // (элайзятся).
  reg  r0 = 1'b1;    // состояние 0 (X1/X2 = XOR с ~r0/r0; рестарт из 00)
  reg  r1 = 1'b0;    // состояние 1 (por_ce = r1 | r6)
  reg  r2 = 1'b0;    // состояние 2
  reg  r3 = 1'b0;    // состояние 3 (set x1_n)
  reg  r4 = 1'b0;    // состояние 4 (clear x1_n)
  reg  r5 = 1'b0;    // состояние 5 (v3.9: расширение кольца 5 -> 7)
  reg  r6 = 1'b0;    // состояние 6 (por_ce = r1 | r6)

  // v3.5: X2 - РЕГИСТР противофазы (п.10 шапки, clk10-41): каждая ветка
  // generate даёт СВОЙ драйвер X2 и свой регистр (x2_q / x2_p) с D,
  // ОТЛИЧНЫМ от D(x1) - same-D слияние невозможно по построению
  // (в v3.4 комб. ~X1 фиттер снова поднял в регистр В ФАЗЕ, п.9).
  // keep на порте X2 удерживает сеть отдельной (страховка).
  // v3.8: в g_div2p5 двойник СОКРАЩЁН - X2 = r0 ^ x1_n; SOP(X2) !=
  // SOP(X1) - same-D слияние по-прежнему невозможно по построению.

  generate
    if (CLK_DIV == 2 && CLK_HALF == 1) begin : g_div2p5
      // v3.8/v3.9 ветка (кольцо N=5/N=7, п.14/15 шапки; в v3.10
      // элайзится - ЦЕЛЕВАЯ g_div_odd): X1 = 2x25/7 =
      // 7,143 МГц, CPU = 3,571 МГц. Машина (узор по полутактам 20 нс:
      // X1 = "1111100" повтор, X2 = "0000011" повтор):
      //   r0..r6: one-hot кольцо по posedge, СОСТОЯНИЕ = ВЫХОД ТРИГГЕРА
      //     (декодов равенства НЕТ - класс п.9 в узле уничтожен):
      //     r_i <= r_{i-1} & ~r_i & ~r_{i+1} & ~r_{i+2}; в легальном
      //     one-hot kill-литералы всегда '1' -> D = r_{i-1}. Самоочистка
      //     ДВОЙНАЯ (усиление против v3.8 - п.15 шапки): одинарная
      //     «убей преемника» для N=7 оставляет парам '1' на дистанции
      //     3-4 вечную орбиту (14 состояний из 128); двойной kill:
      //     gap-1 -> 00 -> рестарт, gap-2/3 - последователь блокирован,
      //     gap-4 - лидер блокирован через wrap; из 00 - рестарт r0
      //     (NOR7): ЛЮБОЕ из 128 состояний -> one-hot за <= 2 фронта
      //     (sim_v39_ring7.py; наивное r_i <= r_{i-1} НЕ годится: пара
      //     '1' ходит вечно, 0000000 = мёртвый клок);
      //   x1_p/x2_p сокращены: x1_p == ~r0, x2_p == r0 ТОЧНО (один и
      //     тот же posedge) -> X1/X2 берут r0 напрямую;
      //   x1_n (NEGEDGE, INIT=0): set при r3, clear при r4
      //     (SET=(N-1)/2=3, CLR=(N+1)/2=4 для N=7) -> импульс 40 нс;
      //   X1 = (~r0) ^ x1_n: фронты через РОВНО 140 нс (7,143 МГц),
      //     high 100 / low 40 нс (duty 71/29); внутренний /2 ВМ85А
      //     тактируется ФРОНТАМИ X1 -> CLK = 3,571 МГц, период 280 нс,
      //     duty РОВНО 50%;
      //   X2 = r0 ^ x1_n = ~X1 ТОЧНО (SOP функций X1/X2 различны ->
      //     same-D слияние невозможно, п.10);
      //   INIT (r0=1, r1..r6=0, x1_n=0): состояние 0 при старте, узор
      //     установившийся с 1-го полутакта, переходного процесса нет.
      // por_ce = r1 | r6: интервалы 200/80 нс попеременно (сэмпл по
      //   posedge), в среднем РОВНО 140 нс = 1 импульс за период X1.
      //   POR = 8 x 140 = 1120 нс (норма 3 такта CLK = 840 нс, запас
      //   1,33x - тот же, что в v3.8).
      always @(posedge clk) begin
        // сдвиг + двойной kill + рестарт из 00 (усиление - п.15 шапки)
        r0 <= (r6 & ~r0 & ~r1 & ~r2) | (~r0 & ~r1 & ~r2 & ~r3 & ~r4 & ~r5 & ~r6);
        r1 <= r0 & ~r1 & ~r2 & ~r3;
        r2 <= r1 & ~r2 & ~r3 & ~r4;
        r3 <= r2 & ~r3 & ~r4 & ~r5;
        r4 <= r3 & ~r4 & ~r5 & ~r6;
        r5 <= r4 & ~r5 & ~r6 & ~r0;
        r6 <= r5 & ~r6 & ~r0 & ~r1;
      end
      always @(negedge clk)
        if (r3)      x1_n <= 1'b1;
        else if (r4) x1_n <= 1'b0;
      assign X1 = (~r0) ^ x1_n;  // = x1_p ^ x1_n (x1_p == ~r0, п.14);
                                 // 7,143 МГц, период ровно 140 нс (100/40)
      assign X2 = r0 ^ x1_n;     // = x2_p ^ x1_n = ~X1 ТОЧНО
      assign por_ce = r1 | r6;   // интервалы 200/80 нс, в среднем 140 (п.15)
    end else if (CLK_DIV == 2) begin : g_div2
      // ЦЕЛЕВАЯ ветка /2: x1_q тогглит КАЖДЫЙ клок - вентиль = константа,
      // декодов нет вовсе
      always @(posedge clk)
        x1_q <= ~x1_q;
      always @(posedge clk)
        x2_q <= x1_q;          // v3.5: задержка 1 клок = ПОЛПЕРИОДА (период 2),
                               // D=x1_q != D(x1_q)=~x1_q; init (1,0) -> x2=~x1
      assign X1 = x1_q;        // 12,5 МГц, duty 50%
      assign X2 = x2_q;        // v3.5: регистровая противофаза
      assign por_ce = ~x1_q;   // 1 такт из 2 = 1 раз за период X1
    end else if (CLK_DIV == 4) begin : g_div4
      // ЦЕЛЕВАЯ ветка /4 (v3.4): каскад t0_q -> x1_q; x1_q тогглит при
      // t0_q=1 (каждые 2 клока). Вентиля - литералы t0_q/x1_q, декодов НЕТ
      always @(posedge clk)
        t0_q <= ~t0_q;              // clk/2
      always @(posedge clk)
        if (t0_q) x1_q <= ~x1_q;    // clk/4, duty 50%
      always @(posedge clk)
        x2_q <= ~(x1_q ^ t0_q);     // v3.5: x2_q(t+1) = ~x1_q(t+1) - точная
                                    // противофаза с 0-го такта; D=XNOR != D(x1_q)=XOR
      assign X1 = x1_q;             // 6,25 МГц
      assign X2 = x2_q;             // v3.5: регистровая противофаза
      assign por_ce = ~t0_q & ~x1_q; // 1 такт из 4 = 1 раз за период X1
    end else if (CLK_DIV % 2 == 0) begin : g_div_even
      // FALLBACK чётных N>=6: старый счётчик mod-N/2 (СОДЕРЖИТ декоды -
      // только для отката; целевые режимы 2/4 - выше)
      always @(posedge clk)
        cnt <= (cnt == MEV) ? 4'd0 : cnt + 4'd1;
      always @(posedge clk)
        if (cnt == MEV) x1_q <= ~x1_q;
      always @(posedge clk)
        if (cnt == MEV) x2_q <= ~x2_q;  // v3.5: toggle СИНХРОННО с x1_q,
                                        // init (1,0) -> комплементарны всегда
      assign X1 = x1_q;                        // duty 50% (период CLK_DIV тактов)
      assign X2 = x2_q;                        // v3.5: регистровая противофаза
      assign por_ce = (cnt == 4'd0) && !x1_q;  // 1 раз за период X1
    end else begin : g_div_odd
      // ЦЕЛЕВАЯ ветка v3.10 (CLK_DIV=3): нечётное деление (ветка v3):
      // XOR-пара - НЕ ТРОНУТА с clk10-35 (исторически работала на /5
      // = 5 МГц). N=3: NMOD=NHALF=2 - x1_p тогглит на posedge при
      // cnt==0 (фронты 20+120k), x1_n - на negedge при cnt==2 (фронты
      // 80+120k) -> фронты X1 РОВНО через 60 нс с первого (t=20 нс),
      // X1 стартует '1', глобально периодична с t=0 (переходного
      // процесса нет; INIT cnt=0 лежит на легальной орбите);
      // X1 = 25/3 = 8,333 МГц РОВНО 50/50 (60/60 нс), CPU = 4,167 МГц
      // (240 нс), por_ce = (cnt==0): импульс 40 нс каждые 120 нс ->
      // POR = 8x120 = 960 нс (норма 3x240 = 720, запас 1,19-1,25x);
      // терминал 8000 8N1. Симуляция scripts/sim_v310_div3.py -
      // 16/16 ПАСС (п.16 шапки).
      always @(posedge clk)
        cnt <= (cnt == NMOD) ? 4'd0 : cnt + 4'd1;
      always @(posedge clk)
        if (cnt == 4'd0) x1_p <= ~x1_p;    // переворот каждые CLK_DIV тактов
      always @(negedge clk)
        if (cnt == NHALF) x1_n <= ~x1_n;   // сдвиг полпериода -> duty 50%
      always @(posedge clk)
        if (cnt == 4'd0) x2_p <= ~x2_p;    // v3.5: двойник x1_p (INIT 0 vs 1)
      assign X1 = x1_p ^ x1_n;             // duty РОВНО 50% (100/100 нс)
      assign X2 = x2_p ^ x1_n;             // v3.5: = ~x1_p ^ x1_n = ~X1 ТОЧНО,
                                           // без сдвига duty (не задержка на клок)
      assign por_ce = (cnt == 4'd0);       // 1 раз за период X1
    end
  endgenerate
  
  //=============================================================
  // POR (v3.4, clk10-35): 8-битный СДВИГОВЫЙ регистр por_sh.
  // 0 в MSB сдвигается вправо, bit0 очищается ПОСЛЕДНИМ -> por_run
  // снимается ровно через 8 тиков por_ce. ДЕКОДОВ НЕТ (ни ==0, ни !=0):
  // фиттер дважды печатал por-декоды с потерянной инверсией (фит 7:31:
  // por_cnt(0): T=NOT en -> POR=1 клок; фит 8:55: por_run.D=(por_cnt==0))
  // - класс конструкций убран, терять больше нечему.
  // INIT=FF/1 -> RESET_IN=0 до всякого клока (счёт только при живом
  // clk через por_ce из делителя); por_run остаётся РЕГИСТРОМ (v3.2,
  // п.8 шапки - защита от схлопывания PT / Placement Failed).
  // Длительность: POR = 8 x por_ce. @ N=7 (v3.9) por_ce = 140 нс
  // (200/80 нс попеременно) -> POR = 1120 нс; норма 3 такта CLK OUT =
  // 840 нс @ 3,57 МГц (запас 1,33x - тот же, что в v3.4/v3.8).
  // Повторный POR невозможен: после 00 сдвиг держит нули навсегда.
  //=============================================================
  reg [7:0] por_sh = 8'hFF;      // сдвиг вправо: FF -> 7F -> ... -> 01 -> 00
  reg  por_run = 1'b1;           // FF-копия для cpu_rst (v3.2; INIT=SET)
  wire cpu_rst = RST | por_run;  // CPU в сбросе: SW20 нажата или POR
  always @(posedge clk) begin
    por_run <= por_sh[0];        // снятие, когда '0' дойдёт до bit0 (8-й тик)
    if (por_ce) por_sh <= {1'b0, por_sh[7:1]};
  end

  //=============================================================
  // TX-транзит с ЗАХВАТОМ (v3.7, clk10-51; п.3/13 шапки) - замена
  // TX-маски v2-v3.6: txm_cnt (8 FF, ~9 МЦ) и параметр TXM_W УДАЛЕНЫ,
  // окно больше НЕ таймерное. Факт датасшита IM1821ВМ85А (вывод SR):
  // аппаратный сброс очищает триггер TFD (SOD) в '0' -> после снятия
  // RESET_IN линия SOD='0' до первого SIM прошивки с SDE=1 (fw_mon v5:
  // TXIDLE, ~4-20 мкс при CPU 5 МГц). Голый транзит SOD->TX дал бы
  // «фиктивный start-bit» - пустой фрейм в терминале. Вместо таймера -
  // схемный захват ПО УРОВНЮ (частота и длина init прошивки не важны):
  //   sod_q   - синхронизация входа SOD по clk 25 МГц (XST положит в
  //             IO-MC входа P72; метастабильность гасится ДО использо-
  //             вания, статический путь пин SOD -> пин TX разорван);
  //   tx_pass - «линия захвачена прошивкой»: async clear по cpu_rst,
  //             взводится первым сэмплом SOD='1' после сброса;
  //   tx_q    - выходной регистр TX (IO-MC пина P39, INIT=1, async set
  //             по cpu_rst): в сбросе TX='1' мгновенно и БЕЗ клока;
  //             после захвата - транзит sod_q с латентностью <= 2 такта
  //             25 МГц (80 нс = 0,4 такта CLK 200 нс = 0,08% бита 9600).
  // Полный цикл: POR/кнопка -> TX='1'; CPU вне сброса, SOD='0'
  // (сброшен SR-ом) -> TX='1' ДЕРЖИТСЯ сам (ноль не пропускается);
  // TXIDLE прошивки (SOD 0->1) -> захват, дальше бит-в-бит транзит.
  // Теория (см. п.13): ложный SOD='1' в окне открыл бы захват раньше -
  // физически невероятен (вход CPU в сбросе статичен); лечение -
  // захват по 2 сэмплам подряд (+1 FF).
  //=============================================================
  reg sod_q   = 1'b0;            // синхронизатор входа SOD (без сброса)
  reg tx_pass = 1'b0;            // «линия захвачена прошивкой» (INIT=0)
  reg tx_q    = 1'b1;            // выходной регистр TX (IO-MC; INIT=1)
  always @(posedge clk)
    sod_q <= SOD;                                  // свободный ход, без сброса
  always @(posedge clk or posedge cpu_rst)
    if (cpu_rst)    tx_pass <= 1'b0;
    else if (sod_q) tx_pass <= 1'b1;               // первый SOD='1' от прошивки
  always @(posedge clk or posedge cpu_rst)
    if (cpu_rst) tx_q <= 1'b1;
    else         tx_q <= tx_pass ? sod_q : 1'b1;   // до захвата - чистый idle

  //=============================================================
  // Автомат шины: 7 состояний = 3 триггера (v3; в v1 было 10/4 триггера -
  // WBW/WBS/WBS2 удалены: hold-off 0, см. п.4 шапки; WB1..WB4 ЗАЩИЩЕНЫ
  // от ALE)
  //=============================================================
  localparam S_IDLE = 3'd0,   // ожидание ALE; A/D в Hi-Z; /OE включён (декод)
             S_T1H  = 3'd1,   // T1: CPU держит адрес на A-сетях; идёт захват
             S_T2   = 3'd2,   // строб: чтение - выдача данных на A; запись - захват
             S_WB1  = 3'd3,   // WB: адрес на A + данные на D (t_AS 40 нс до /WE)
             S_WB2  = 3'd4,   // /WE=0 - импульс НАЧАЛСЯ: защищён от ALE
             S_WB3  = 3'd5,   // /WE=0 (импульс = 2 тика = 80 нс >= t_WP ОЗУ)
             S_WB4  = 3'd6;   // /WE=1: удержание адреса/данных (t_AH/t_DH памяти)

  // Task 46: прагма против ONE-HOT перекодировки автомата XST
  // (контроль у владельца: в .rpt НЕ должно быть state_FSM_FFd4..10;
  // v3: автомат = РОВНО 3 триггера state_FSM_FFd1..3; 7 состояний (без WBW).
  // synthesis attribute fsm_encoding of state is "compact"
  reg  [2:0] state  = S_IDLE;
  reg        rd_seen = 1'b0;    // строб чтения замечен в T2
  reg        wr_seen = 1'b0;    // строб записи замечен в T2
  reg        wb_ram_q = 1'b0;   // защёлка «WB - это запись в ОЗУ» (для CS_n, v3 п.5)

  // Захваченные шинные регистры
  reg [7:0] addr_latch = 8'h00;  // адрес с A-сетей (T1) - нужен writeback и декоду порта
  reg [7:0] bus_reg    = 8'h00;  // данные: чтение (с D-сети в T1) ИЛИ запись (с A-сети в T2)

  // Порты индикации/звука (§5): захват по записи в порт при IO/M#=1
  reg [7:0] seg_q = 8'hFF;       // 1 в регистре = сегмент горит; выход инвертируется
  reg [3:0] dig_q = 4'hF;        // 1 = цифра выбрана; выход инвертируется
  reg       snd_q = 1'b0;
  reg [3:0] kbcol_q = 4'h0;      // колонки (порт 02h), INIT 0000 = все выкл
  wire io_rd_kb = IOM & ~addr_latch[2] & addr_latch[1] & addr_latch[0]; // чтение 03h (KBROW)

  // Комбинационные группы (v3):
  //   wb_out = in_wb БЕЗ !ALE: драйверы A/D держат адреса/данные до конца
  //     защищённого импульса (п.4 шапки); снятие - при выходе в IDLE.
  //   rd_drive с !ALE - чтение как в v1 (мгновенный обрыв при новом цикле).
  wire in_wb   = (state >= S_WB1);                       // WB1..WB4: A/D драйвятся
  wire in_welo = (state == S_WB2) || (state == S_WB3);   // /WE низ
  wire wr_phase = (state >= S_T2);                       // T2..WB4: /OE памяти off
  wire wb_out   = in_wb;                                 // защищённый writeback-драйв
  wire rd_drive = (state == S_T2) && rd_seen && !RDn && !ALE; // A-пины отдают данные

  //=============================================================
  // Шинный движок
  //=============================================================
  always @(posedge clk) begin        // синхронный сброс всех триггеров по (RST|POR) - Task 25
    if (cpu_rst) begin
      state      <= S_IDLE;
      rd_seen    <= 1'b0;
      wr_seen    <= 1'b0;
      wb_ram_q   <= 1'b0;
      addr_latch <= 8'h00;
      bus_reg    <= 8'h00;
      seg_q      <= 8'hFF;   // INIT «8888.» на индикаторе
      dig_q      <= 4'hF;
      snd_q      <= 1'b0;
      kbcol_q    <= 4'h0;
    end else begin
      // --- захват повторным сэмплированием: последний сэмпл валиден ---
      // v3: захват возможен только в T1H, т.е. ПОСЛЕ завершения WB
      // (структурно: из WB в T1H попадаешь только через IDLE) - adm.
      // addr_latch НЕ может перезаписаться посреди импульса (п.6 шапки).
      if (state == S_T1H && ALE) begin
        addr_latch <= A;                 // адрес стабилен весь T1
        if (!IOM) bus_reg <= D;          // данные памяти (доступ начался в начале T1)
      end
      if (state == S_T2 && !WRn) begin
        bus_reg <= A;                    // данные записи (CPU держит до WR#(вверх))
        if (IOM) begin                   // запись в порт: декод по тройке A2,A1,A0 (Task 34)
          case (addr_latch[2:0])
            3'b000: seg_q <= A;          // 00h: сегменты
            3'b001: begin                // 01h: разряды + SND
              dig_q <= A[3:0];
              snd_q <= A[4];
            end
            3'b010: kbcol_q <= A[3:0];   // 02h: колонки клавиатуры
            default: ;                   // 03h чтение; 04h-07h резерв (UART удалён, Task 69)
          endcase
        end
      end
      // --- трекинг стробов ---
      if (state == S_T2 && !RDn) rd_seen <= 1'b1;
      if (state == S_T2 && !WRn) wr_seen <= 1'b1;
      // --- переходы ---
      // v3: ALE ОБРЫВАЕТ только T2 (защита от глюка); в WB1..WB4 НЕ
      // вмешивается - импульс /WE защищён (п.4 шапки).
      if (ALE && state == S_T2 && !((wr_seen && WRn) || (rd_seen && RDn))) begin
        state   <= S_IDLE;
        rd_seen <= 1'b0;
        wr_seen <= 1'b0;
      end else begin
        case (state)
          S_IDLE: if (ALE) state <= S_T1H;
          S_T1H:  if (!ALE) state <= S_T2;
          S_T2: begin
            // приоритет записи: RDn-глюк во время записи не должен прерывать её
            if (wr_seen && WRn) begin
              wr_seen  <= 1'b0;
              wb_ram_q <= !IOM && A15;   // защёлка декода для CS_n в WB (v3)
              // writeback только для записи в ОЗУ (8000-FFFF); запись в ПЗУ
              // отбрасывается (по железу /WE flash не подключён), порт пропускается
              state <= (!IOM && A15) ? S_WB1 : S_IDLE;
            end else if (rd_seen && RDn) begin
              rd_seen <= 1'b0;
              state <= S_IDLE;         // отпускание A-пинов через 1 тик после RD#(вверх)
            end
          end
          S_WB1: state <= S_WB2;       // t_AS 40 нс; hold-off 0 (см. п.4 шапки)
          S_WB2: state <= S_WB3;       // /WE низ - защищён, идёт до конца
          S_WB3: state <= S_WB4;
          S_WB4: state <= S_IDLE;      // импульс закончен, всё снято в IDLE
          default: state <= S_IDLE;
        endcase
      end
    end
  end

  //=============================================================
  // Тристейт-драйверы шины
  //=============================================================
  // Task 34: при чтении порта 03h A_I(0..4) = row0-4 (mux KBROW),
  // AD7-5 = 000. UART-статус (IN 05h) удалён вместе с UART (Task 69).
  assign A = rd_drive ? (io_rd_kb ? {3'b000, row4, row3, row2, row1, row0}
                                  : bus_reg)
            : wb_out   ? addr_latch : 8'bZZZZZZZZ;
  assign D = wb_out ? bus_reg : 8'bZZZZZZZZ;

  //=============================================================
  // Декод памяти минимальной ширины (§5): 1 терм на кристалл
  // v3: /CE ОЗУ в writeback - ЗАЩЁЛКНУТЫЙ wb_ram_q (п.5 шапки):
  // живой декод A15 во время конфликта адресов брал бы НОВЫЙ адрес CPU.
  //=============================================================
  assign CSr_n = A15 | IOM;             // /CE_ROM = !( !A15 & !IOM )
  assign CS_n  = (in_wb && wb_ram_q) ? 1'b0 : (!A15 | IOM);
  assign OEr_n = CSr_n | wr_phase;      // /OE гасится с T2 - данные уже захвачены,
  assign OE_n  = CS_n  | wr_phase;      // иначе SRAM воевала бы с CPLD на D в writeback
  // v3: /WE НЕ обрывается ALE - импульс доводится до конца (п.4 шапки);
  // безопасно: автомат доходит до WB4/IDLE за 5 тиков, сброс (cpu_rst) гасит.
  assign WE_n  = !in_welo;
  assign CS1   = 1'b1;

  //=============================================================
  // Поддержка CPU (§3, ред. Task 19) + soft-UART транзиты (Task 70-a).
  // Держатели '0' (TRAP, RST7.5/6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины (9 шт) заземлит фиттер (Ground on Unused IOs).
  // SID (P73) с Task 70-a - ВЫХОД CPLD (транзит RX), в держатели
  // больше не входит (PGND 10 -> 9).
  //=============================================================
  assign RESET_IN = ~(RST | por_run); // активный 0 по даташиту: 0 = сброс CPU (SW20 нажата или POR)
  assign READY = 1'b1;          // без wait-state - иначе вечные TW
  // Транзиты soft-UART (Task 70-a); TX - регистровый, см. блок v3.7 выше:
  assign SID = RX;              // приём:  CH340G.TXD (P38) -> CPU.SID (P73), RIM 20h
  assign TX  = tx_q;            // передача: CPU.SOD (P72) -> CH340G.RXD (P39), SIM 30h;
                                // регистр с захватом после первого SOD='1' (v3.7):
                                // в покое прошивка держит SOD='1' (stop/idle) - это
                                // и есть enable линии; в сбросе/до захвата TX='1'

  //=============================================================
  // Индикация и звук: выходы инвертированы (общий анод, активный 0)
  //=============================================================
  assign seg = ~seg_q;
  assign dig = ~dig_q;
  assign SND = snd_q;
  // Task 34: колонки клавиатуры - зарегистрированные выходы, прямые уровни
  // (активная колонка = 1, остальные 0; после сброса 0000 - безопасно)
  assign col0 = kbcol_q[0];
  assign col1 = kbcol_q[1];
  assign col2 = kbcol_q[2];
  assign col3 = kbcol_q[3];

endmodule