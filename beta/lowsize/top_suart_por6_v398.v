    input  wire       row1,         // P55 R24, SW5
    input  wire       row2,         // P54 R23, SW9
    input  wire       row3,         // P52 R22, SW13
    input  wire       row4          // P51 R21, SW17
);

  //=============================================================
  // Узел тактирования v3.9.8 (п.23 шапки, схема владельца 11-6bis-2):
  // вход 50 МГц (H1 БЕЗ шунта - DIV=/2 U7; было 25 при /4), кольцо
  // r0..r6 (п.22, БЕЗ ИЗМЕНЕНИЙ) на clk 50 МГц (период 140 нс);
  // X1 = r0 (фронт строго каждые 140 нс = 7,143 МГц, duty 1/7),
  // X2 = r1|..|r6 = ~r0, внутренний /2 ВМ85А -> CPU 3,571 МГц duty
  // 50% (частота НЕ изменилась); x1_n УДАЛЁН (вторая кромка теперь
  // даётся самим clk 50). ЛОГИКА - на clk25 = /2-триггер clk25_q
  // (25 МГц: /WE 80 нс, квалификатор 320 нс, все тиковые константы
  // живы; XC95108-15 FSM на 50 МГц не закроет). por-цепь - в
  // 50-домене (por_sh 8 бит, строб r0; сэмпл стробов тактом clk25 -
  // фазовая лотерея). Legacy-ветки (div2/div4/чёт/нечёт) сохранены
  // для отката - при (2,1) элайзятся, в них clk25 = прямой clk.
  // ВНИМАНИЕ: старый HDLCompiler (ISE) НЕ принимает localparam и
