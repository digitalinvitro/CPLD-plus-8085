    (* keep = "TRUE" *) output wire X2,  // P69 cpu20, нога 2: противофаза X1 (v3.9.8: r1|r2|r3|r4|r5|r6 = ~r0 в легальном one-hot, БЕЗ инверсии регистра - п.10/23); keep - сеть отдельно (страховка, п.9)
