  reg  x1_p = 1'b1;  // нечётная legacy-ветка (при (2,1) элайзится)
  // v3.9.8: clk25 - /2-триггер для ЛОГИКИ (rst/TX/FSM/порты): XC95108-15
  // FSM/шина на 50 МГц не закрывает, а все тиковые константы (/WE 80 нс,
  // квалификатор 320 нс) обязаны остаться - логика живёт на 25 МГц,
  // узел тактирования (кольцо/por-цепь) - на 50. INIT=0 - фаза
  // фиксирована (первый posedge clk25 - второй posedge clk пина).
  reg  clk25_q = 1'b0;  // /2: такт ЛОГИКИ 25 МГц из clk 50 МГц (ЦЕЛЕВАЯ g_div2p5)
