  reg  r2 = 1'b0;    // состояние 2 (вход X2)
  reg  r3 = 1'b0;    // состояние 3 (вход X2)
  reg  r4 = 1'b0;    // состояние 4 (вход X2)
  reg  r5 = 1'b0;    // состояние 5 (вход X2)
