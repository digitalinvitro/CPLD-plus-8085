                          // целевая g_div2p5 с v3.9.7 - КОЛЬЦО r0..r6, п.22).
                          // Сужение [3:0]->[2:0] по рецепту v3.10: старшие
                          // биты - балласт МЦ; 3 бит хватает всем legacy
                          // N<=14 (MEV<=7)
  wire por_ce;

