def match_with_complaint(sig_buttons, sig_wire, sig_cycle):
    """Симптомы владельца: кнопка N раз - нуль; проводничок - нуль;
    передёргивание - лотерея, рано или поздно помогает."""
    return (sig_buttons.startswith("НУЛЬ")
            and sig_wire.startswith("НУЛЬ")
            and "ЛОТЕРЕЯ" in sig_cycle)

#------------------------------------------------------------------------------
# R2: Монте-Карло лотереи включений
#------------------------------------------------------------------------------

def monte_carlo(p_clk_start: float, sessions: int = 10000, seed: int = 20261106,
                max_cycles: int = 30):
    """Каждое включение: осциллятор стартует с вероятностью p_clk_start.
    Мёртвая сессия лечится передёргиванием (повторный розыгрыш).
    Возвращает статистику: доля мёртвых первых включений, распределение
    числа передёргиваний до выздоровления."""
    rng = random.Random(seed)
    dead_first = 0
    cycles_hist = {}
    for _ in range(sessions):
        cycles = 0
        while cycles <= max_cycles:
            if rng.random() < p_clk_start:
                break
            cycles += 1                      # мёртвая сессия - передёргивание
        if cycles > 0:
            dead_first += 1
        cycles_hist[cycles] = cycles_hist.get(cycles, 0) + 1
    dead_share = dead_first / sessions
    # медиана и 95-квантиль числа передёргиваний
    acc, median, q95 = 0, None, None
    for c in sorted(cycles_hist):
        acc += cycles_hist[c]
        share = acc / sessions
        if median is None and share >= 0.5:
            median = c
        if q95 is None and share >= 0.95:
            q95 = c
    return dead_share, median, q95

