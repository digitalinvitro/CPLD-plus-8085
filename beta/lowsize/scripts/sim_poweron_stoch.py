#------------------------------------------------------------------------------
# Цифровое ядро пор-цепи (бит-в-бит RTL v3.9.5; для v3.9.2 - параметры)
#------------------------------------------------------------------------------

def por_release_ticks(v392: bool):
    """Сколько posedge clk нужно пор-цепи, чтобы снять por_run, при живом
    clk, из ЛЮБОГО начального состояния. Возвращает (норма, максимум).
    Норма = из INIT (F/1). Максимум - по всем 16 (256 у v3.9.2) состояниям.
    Без clk: (None, None) - НЕ СНИМАЕТСЯ ВОВСЕ."""
    if v392:
        # 8-битный por_sh, строб por_ce=(cnt==1)|(cnt==6): 2 строба за
        # период cnt 7 тактов; сдвиг {1'b0, por_sh[7:1]}
        width, shift_per_ce, ces_per_period = 8, 1, 2
        states = 1 << 8
    else:
        # 4-битный por_sh, строб por_ce=x1_n (1 раз за период cnt 7 тактов)
        width, shift_per_ce, ces_per_period = 4, 1, 1
        states = 1 << 4
    def run(init):
        sh, run_, ce_cnt, posedges = init, 1, 0, 0
        for _ in range(1000):
            posedges += 1
            new_run = sh & 1                       # por_run <= por_sh[0]
            if ce_cnt == 0:                        # posedge, совпавший со стробом
                sh = ((sh >> 1) | (0 << (width - 1))) & (states - 1)
            ce_cnt = (ce_cnt + 1) % (7 // ces_per_period)
            run_ = new_run
            if run_ == 0:
                return posedges
        return None
    norm = run((1 << width) - 1)                   # INIT=FF.../F
    worst = max(run(s) for s in range(states))
    return norm, worst

