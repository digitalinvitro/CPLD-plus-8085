def splice_consume(t, start_mark, end_mark, new_body, what):
    """span-замена с ПОГЛОЩЕНИЕМ концевого маркера."""
    i = t.find(start_mark)
    assert i >= 0, "стартовый маркер %s не найден" % what
    assert t.count(start_mark) == 1, "стартовый маркер %s неуникален" % what
    j = t.find(end_mark, i)
    assert j > i, "концевой маркер %s не найден" % what
    assert t.count(end_mark) == 1, "концевой маркер %s неуникален" % what
    return t[:i] + new_body + t[j + len(end_mark):]


def splice_keep(t, start_mark, end_mark, new_body, what):
    """span-замена с СОХРАНЕНИЕМ концевого маркера (как в gen_v397)."""
    i = t.find(start_mark)
    assert i >= 0, "стартовый маркер %s не найден" % what
    assert t.count(start_mark) == 1, "стартовый маркер %s неуникален" % what
    j = t.find(end_mark, i)
    assert j > i, "концевой маркер %s не найден" % what
    assert t.count(end_mark) == 1, "концевой маркер %s неуникален" % what
    return t[:i] + new_body + t[j:]


