def main():
    src = io.open(SRC, encoding='utf-8').read()
    s = src
    for old, new, tag in EDITS:
        n = s.count(old)
        if n != 1:
            print('ОШИБКА: якорь %r встречается %d раз (ожидался 1)' % (tag, n))
            sys.exit(1)
        s = s.replace(old, new)
        print('ок: %s' % tag)

    # Контроль 1: конструкции v3.9.4 на месте, старых нет.
    for frag, want in (
        ("assign por_ce = x1_n;", 1),
        ("reg [3:0] por_sh = 4'hF;", 1),
        ("{1'b0, por_sh[3:1]}", 1),
        ("(cnt == 3'd1) | (cnt == 3'd6)", 0),
        ("por_sh[7:1]", 0),
        ("reg [7:0] por_sh", 0),
    ):
        got = s.count(frag)
        if got != want:
            print('ОШИБКА: %r встречается %d раз (ожидалось %d)' % (frag, got, want))
            sys.exit(1)
    print('ок: конструкции v3.9.4 на месте, старых нет')

    # Контроль 2: норм-путь бит-в-бит v3.9.3 (делитель, GSR, транзиты).
    for frag in ("assign X1 = (cnt != 3'd0) ^ x1_n;",
                 "assign X2 = (cnt == 3'd0) ^ x1_n;",
                 "reg [2:0] cnt = 3'd0;",
                 "if (cnt == 3'd6) cnt <= 3'd0;",
                 "if (cnt == 3'd3)      x1_n <= 1'b1;",
                 "else if (cnt == 3'd4) x1_n <= 1'b0;",
                 "por_run <= por_sh[0];",
                 "always @(posedge clk or posedge RST) begin",
                 "(!IOM && A15 && !por_run)",
                 "assign RESET_IN = ~(RST | por_run);"):
        if s.count(frag) != 1:
            print('ОШИБКА: норм-путь повреждён: %r' % frag)
            sys.exit(1)
    print('ок: делитель/GSR/шина/транзиты бит-в-бит v3.9.3')

    # Контроль 3: cpu_rst в КОДЕ ровно 5 упоминаний (как в v3.9.3).
    code_mentions = 0
    for ln in s.split('\n'):
        bare = ln.split('//')[0]
        code_mentions += bare.count('cpu_rst')
    if code_mentions != 5:
        print('ОШИБКА: cpu_rst в КОДЕ %d раз (ожидалось 5)' % code_mentions)
        sys.exit(1)
    print('ок: cpu_rst в коде ровно 5 упоминаний')

    io.open(OUT_U8, 'w', encoding='utf-8', newline='').write(s)

    # CP1251-версия: строго (любой символ вне CP1251 - ошибка).
    try:
        data = s.encode('cp1251')
    except UnicodeEncodeError as e:
        print('ОШИБКА CP1251: %s' % e)
        sys.exit(1)
    io.open(OUT_CP, 'wb').write(data)

    # Round-trip: CP1251 -> UTF-8 == utf8-версия.
    back = data.decode('cp1251')
    assert back == s, 'round-trip CP1251 сломан'
    print('ок: round-trip CP1251 проверен (%d байт CP1251, %d байт UTF-8)'
          % (len(data), len(s.encode('utf-8'))))


if __name__ == '__main__':
    main()
