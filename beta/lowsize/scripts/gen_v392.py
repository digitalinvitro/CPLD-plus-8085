def main():
    src = io.open(SRC, encoding='utf-8').read()
    s = src
    for old, new, tag in EDITS:
        n = s.count(old)
        if n != 1:
            print('ОШИБКА: якорь %r встречается %d раз (ожидался 1)' % (tag, n))
            sys.exit(1)
        s = s.replace(old, new)
        print('ок: %s' % tag)

    # Контроль: в КОДЕ не осталось r0..r6 (комментарии допустимы).
    code_lines = []
    for i, ln in enumerate(s.split('\n'), 1):
        bare = ln.split('//')[0]
        for r in ('r0', 'r1', 'r2', 'r3', 'r4', 'r5', 'r6'):
            if r in bare:
                code_lines.append((i, ln.strip()))
    if code_lines:
        print('ОШИБКА: r0..r6 остались в КОДЕ:')
        for i, ln in code_lines:
            print('  строка %d: %s' % (i, ln))
        sys.exit(1)
    print('ок: r0..r6 в коде отсутствуют')

    # Контроль: ключевые новые конструкции на месте.
    for frag in ("assign X1 = (cnt != 3'd0) ^ x1_n;",
                 "assign X2 = (cnt == 3'd0) ^ x1_n;",
                 "assign por_ce = (cnt == 3'd1) | (cnt == 3'd6);",
                 "reg [2:0] cnt = 3'd0;"):
        if s.count(frag) != 1:
            print('ОШИБКА: не найден/дублируется %r' % frag)
            sys.exit(1)
    print('ок: новые конструкции на месте')

    io.open(OUT_U8, 'w', encoding='utf-8', newline='').write(s)

    # CP1251-версия: строго (любой символ вне CP1251 - ошибка).
    try:
        data = s.encode('cp1251')
    except UnicodeEncodeError as e:
        print('ОШИБКА CP1251: %s' % e)
        sys.exit(1)
    io.open(OUT_CP, 'wb').write(data)

    # Round-trip: CP1251 -> UTF-8 == utf8-версия.
    back = data.decode('cp1251')
    assert back == s, 'round-trip CP1251 сломан'
    print('ок: round-trip CP1251 проверен (%d байт CP1251, %d байт UTF-8)'
          % (len(data), len(s.encode('utf-8'))))


if __name__ == '__main__':
    main()
