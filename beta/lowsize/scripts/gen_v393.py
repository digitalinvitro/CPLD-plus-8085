def main():
    src = io.open(SRC, encoding='utf-8').read()
    s = src
    for old, new, tag in EDITS:
        n = s.count(old)
        if n != 1:
            print('ОШИБКА: якорь %r встречается %d раз (ожидался 1)' % (tag, n))
            sys.exit(1)
        s = s.replace(old, new)
        print('ок: %s' % tag)

    # Контроль 1: в КОДЕ cpu_rst ровно 5 упоминаний (def + 2 posedge +
    # 2 if (tx_pass/tx_q)); RESET_IN использует RST|por_run напрямую.
    # В v3.9.2 их было 6 (шестой - if (cpu_rst) главного блока).
    code_mentions = 0
    for ln in s.split('\n'):
        bare = ln.split('//')[0]
        code_mentions += bare.count('cpu_rst')
    if code_mentions != 5:
        print('ОШИБКА: cpu_rst в КОДЕ %d раз (ожидалось 5)' % code_mentions)
        sys.exit(1)
    print('ок: cpu_rst в коде ровно 5 упоминаний (def + tx_pass/tx_q)')

    # Контроль 2: синхронного сброса больше нет, асинхронный - один.
    for frag, want in (
        ("always @(posedge clk or posedge RST) begin", 1),
        ("    if (RST) begin", 1),
        ("if (cpu_rst)", 2),                  # tx_pass + tx_q (PT-SR, однострочные if)
        ("(!IOM && A15 && !por_run)", 1),
        ("assign RESET_IN = ~(RST | por_run);", 1),
    ):
        got = s.count(frag)
        if got != want:
            print('ОШИБКА: %r встречается %d раз (ожидалось %d)' % (frag, got, want))
            sys.exit(1)
    print('ок: конструкции v3.9.3 на месте')

    # Контроль 3: пор-цепь и делитель НЕ тронуты (бит-в-бит v3.9.2).
    for frag in ("assign X1 = (cnt != 3'd0) ^ x1_n;",
                 "assign X2 = (cnt == 3'd0) ^ x1_n;",
                 "assign por_ce = (cnt == 3'd1) | (cnt == 3'd6);",
                 "reg [2:0] cnt = 3'd0;",
                 "por_run <= por_sh[0];",
                 "if (por_ce) por_sh <= {1'b0, por_sh[7:1]};"):
        if s.count(frag) != 1:
            print('ОШИБКА: пор/делитель повреждён: %r' % frag)
            sys.exit(1)
    print('ок: пор-цепь и делитель бит-в-бит v3.9.2')

    # Контроль 4: сбрасываемые значения v3.9.2 сохранены в RST-ветке.
    for frag in ("      state      <= S_IDLE;",
                 "      seg_q      <= 8'hFF;   // INIT «8888.» на индикаторе",
                 "      kbcol_q    <= 4'h0;"):
        if s.count(frag) != 1:
            print('ОШИБКА: RST-ветка без %r' % frag)
            sys.exit(1)
    print('ок: значения сброса бит-в-бит v3.9.2')

    io.open(OUT_U8, 'w', encoding='utf-8', newline='').write(s)

    # CP1251-версия: строго (любой символ вне CP1251 - ошибка).
    try:
        data = s.encode('cp1251')
    except UnicodeEncodeError as e:
        print('ОШИБКА CP1251: %s' % e)
        sys.exit(1)
    io.open(OUT_CP, 'wb').write(data)

    # Round-trip: CP1251 -> UTF-8 == utf8-версия.
    back = data.decode('cp1251')
    assert back == s, 'round-trip CP1251 сломан'
    print('ок: round-trip CP1251 проверен (%d байт CP1251, %d байт UTF-8)'
          % (len(data), len(s.encode('utf-8'))))


if __name__ == '__main__':
    main()
