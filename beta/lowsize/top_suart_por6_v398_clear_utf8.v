  // порте X2 удерживает сеть отдельной (страховка).

  generate
    if (CLK_DIV == 2 && CLK_HALF == 1) begin : g_div2p5
      // v3.9.8 ЦЕЛЕВАЯ (и после v3.9.8-clear ЕДИНСТВЕННАЯ) ветка
      // (п.23 шапки, схема владельца 11-6bis-2):
      // кольцо r0..r6 (п.22, БЕЗ ИЗМЕНЕНИЙ) на clk 50 МГц - период
      // 140 нс; X1 = r0 напрямую (x1_n удалён: вторую кромку даёт
      // сам clk 50), X2 = OR(r1..r6) = ~r0 в легальном one-hot,
      // clk25 = /2 для ЛОГИКИ, por-цепь - в 50-домене со стробом r0:
      //   r0..r6: one-hot по posedge с ДВОЙНЫМ kill
      //     r_i <= r_{i-1} & ~r_i & ~r_{i+1} & ~r_{i+2}; рестарт из
      //     00 по NOR7 в r0. ЛЮБОЕ из 128 состояний -> one-hot за
      //     <= 2 фронта (п.15; v3.9.8: P0a tb_poweron_v398 - 2048
      //     комбинаций с por-цепью на RTL);
      //     INIT r0=1, r1..r6=0 - состояние 0;
      //   X1 = r0: фронт строго каждые 140 нс (7,143 МГц), duty 1/7
      //     (high 20 / low 120 нс); внутренний /2 ВМ85А тактируется
      //     ФРОНТАМИ X1 -> CLK = 3,571 МГц, период 280 нс, duty
      //     РОВНО 50% - частота CPU НЕ МЕНЯЛАСЬ (v3.9.2-3.9.7);
      //     ЕСЛИ генерация CPU не заведётся на 20-нс high - откат
      //     одной строкой: X1 = r0 | r1 (high 40 нс);
      //   X2 = r1|r2|r3|r4|r5|r6 = ~r0 в каждом легальном one-hot -
      //     6-ПТ OR БЕЗ инверсии регистра (класс п.10/прецедент
      //     v3.4: фиттер поднимал ~X1 в регистр В ФАЗЕ); в
      //     illegal-кодах на самоочистке (<= 2 фронта при включении)
      //     X2 отличается от ~X1 - транзиент во время POR, схемно
      //     незначимо;
      //   clk25_q (INIT=0): T-триггер от clk 50 -> clk25 = 25 МГц -
      //     такт ВСЕЙ ЛОГИКИ (rst/TX/FSM/порты): тиковые константы
      //     (/WE 80 нс, квалификатор 320 нс) живут бит-в-бит
      //     v3.9.7; фаза фиксирована INIT.
      // por_ce = r0 (50-домен): РОВНО ОДИН строб 20 нс за период
      //   кольца 140 нс («раз в 140 нс» владельца; r1|r6 на кольце
      //   50 давало бы 2 строба за период - POR уполовинился бы).
      //   por-цепь НЕ МОЖЕТ жить на clk25: сэмпл 20-нс стробов
      //   кольца тактом clk25 - фазовая лотерея (при нечётной фазе
      //   clk25 вечно сэмплирует r0/r2/r4 - стробы НЕ ВИДНЫ ВОВСЕ,
      //   POR не кончается НИКОГДА); в 50-домене строб - синхронное
      //   включение того же такта - детерминировано.
      //   por_sh[7:0]: 8 x 140 = 1120 нс - НОМИНАЛ v3.9.4-3.9.7
      //   (4 x 280), запас 1,33x; дрейн 1000 нс и снятие por_run
      //   на кромке 1020 нс СОВПАДАЮТ с v3.9.7.
      always @(posedge clk) begin
        // сдвиг + двойной kill + рестарт из 00 (кольцо п.15/22 - БЕЗ ИЗМЕНЕНИЙ)
        r0 <= (r6 & ~r0 & ~r1 & ~r2) | (~r0 & ~r1 & ~r2 & ~r3 & ~r4 & ~r5 & ~r6);
        r1 <= r0 & ~r1 & ~r2 & ~r3;
        r2 <= r1 & ~r2 & ~r3 & ~r4;
        r3 <= r2 & ~r3 & ~r4 & ~r5;
        r4 <= r3 & ~r4 & ~r5 & ~r6;
        r5 <= r4 & ~r5 & ~r6 & ~r0;
        r6 <= r5 & ~r6 & ~r0 & ~r1;
      end
      always @(posedge clk)
        clk25_q <= ~clk25_q;   // /2: такт ЛОГИКИ 25 МГц (INIT=0 - фаза фиксирована)
      assign clk25 = clk25_q;
      assign X1 = r0;   // 7,143 МГц, период ровно 140 нс, duty 1/7 (20/120)
      assign X2 = r1 | r2 | r3 | r4 | r5 | r6;  // = ~r0 в легальном one-hot,
                        // БЕЗ инверсии регистра (класс п.10/прецедент v3.4)
      assign por_ce = r0;  // v3.9.8: 1 строб 20 нс за период кольца 140 нс -
                           // ровно ОДИН posedge за период по построению
                           // (у владельца r1|r6 - на кольце 25 это 1/140 нс
                           // в среднем; на кольце 50 стало бы 2/140 нс)
    end
  endgenerate
  
  //=============================================================
  // POR (v3.9.8, п.23: М1 ред. - 8-битный СДВИГОВЫЙ регистр por_sh
  // в 50-домене): 0 в MSB сдвигается вправо, bit0 очищается
  // ПОСЛЕДНИМ -> por_run снимается ровно через 8 тиков por_ce.
  // ДЕКОДОВ НЕТ (ни ==0, ни !=0, НИ В СТРОБЕ): фиттер дважды печатал
  // por-декоды с потерянной инверсией (фит 7:31: por_cnt(0): T=NOT en
  // -> POR=1 клок; фит 8:55: por_run.D=(por_cnt==0)) - класс
  // конструкций убран; строб r0 декодов не содержит вовсе.
  // ПОЧЕМУ 50-ДОМЕН: сэмпл 20-нс стробов кольца тактом clk25 -
  // фазовая лотерея (при нечётной фазе clk25 стробы НЕ ВИДНЫ ВОВСЕ -
  // por_run не снимается НИКОГДА); в 50-домене строб - синхронное
  // включение того же такта - детерминировано при любой фазе.
  // INIT=FF/1 -> RESET_IN=0 до всякого клока (счёт только при живом
  // clk через por_ce из делителя); por_run остаётся РЕГИСТРОМ (v3.2,
  // п.8 шапки - защита от схлопывания PT / Placement Failed).
  // Длительность: POR = 8 x 140 нс = 1120 нс (строб r0 - 1 раз за
  // период кольца 140 нс = «раз в 140 нс» владельца); норма 3 такта
  // CLK OUT = 840 нс @ 3,57 МГц (запас 1,33x - тот же, что в
  // v3.9.2-3.9.7); фактический низ RESET_IN от INIT ~1040 нс
  // (дрейн 1000 нс + кромки - СОВПАДАЕТ с v3.9.7).
  // Повторный POR невозможен: после 00 сдвиг держит нули навсегда.
  //=============================================================
  reg [7:0] por_sh = 8'hFF;      // v3.9.8 (п.23): сдвиг вправо, clk 50 МГц:
                                 // FF -> 7F -> 3F -> ... -> 01 -> 00 (8 стробов)
  reg  por_run = 1'b1;           // FF-копия для cpu_rst (v3.2; INIT=SET)
  always @(posedge clk) begin
    por_run <= por_sh[0];        // снятие, когда '0' дойдёт до bit0 (8-й тик)
    if (por_ce) por_sh <= {1'b0, por_sh[7:1]};
  end

  //=============================================================
  // v3.9.6 (п.21): ХАРДРЕНИНГ ЦЕПИ СБРОСА. Сырой пин RST входит в
  // кристалл ТОЛЬКО через 2FF-синхронизатор + квалификатор; решения
  // о сбросе принимают ТОЛЬКО регистры: мид-рейл/дребезг/помеха на
  // SW20 физически не доходят ни до 40 сбросовых входов триггеров,
  // ни до ноги RESET_IN (в v3.9.5 RST шёл НАПРЯМУЮ в гейт RESET_IN
  // и в PTC-сбросы NOT RESET_IN - fallback фита 11-5).
  //   rst_meta/rst_sync - синхронизатор (вне сброса, INIT=0);
  //   rst_qcnt/rst_press - квалификатор: переворот rst_press на 8-м
  //     такте ПОДРЯД устойчивого rst_sync != rst_press (двусторонний:
  //     и взвод, и снятие квалифицированы); дребезг короче 280 нс не
  //     виден вовсе, длиннее - полноценный повторный сброс (каждый
  //     взвод заново чистит все 40 триггеров - ПОСЛЕДНЕЕ снятие
  //     всегда из held-чистого состояния, регистровым фронтом);
  //   cpu_rst = rst_press | por_run - ТОЛЬКО регистровые источники;
  //   reset_q - РЕГИСТР выхода RESET_IN (INIT=0: CPU в сбросе с t=0
  //     до всякого клока; снятие - чистым фронтом, как по питанию).
  // Латентность кнопки: 11 тиков счёта (2FF + 8 такт квалификатора +
  // reset_q) = 400..440 нс от пина на взвод и снятие (кнопка живёт в
  // миллисекундах). POR НЕ ТРОНУТ: por_sh/
  // por_run бит-в-бит v3.9.4, низ RESET_IN по питанию до 1160 нс
  // (норма 840 нс, запас x1,35).
  //=============================================================
  reg  rst_meta  = 1'b0;         // ловец метастабильности (вне сброса, INIT=0)
  reg  rst_sync  = 1'b0;         // синхронизованный RST (вне сброса, INIT=0)
  reg  rst_press = 1'b0;         // квалифицированный сброс кнопки (INIT=0)
  reg [2:0] rst_qcnt = 3'b000;   // счётчик квалификации 0..7 (INIT=0)
  wire cpu_rst = rst_press | por_run; // v3.9.6: сброс ТОЛЬКО от регистров
  reg  reset_q = 1'b0;           // РЕГИСТР RESET_IN (INIT=0 - CPU держится с t=0)
  always @(posedge clk25) begin   // v3.9.8: логика на clk25 (п.23)
    rst_meta <= RST;
    rst_sync <= rst_meta;
  end
  always @(posedge clk25) begin   // v3.9.8: логика на clk25 (п.23)
    if (rst_sync != rst_press) begin
      if (&rst_qcnt) begin
        rst_press <= rst_sync;   // 8-й такт подряд - переворот состояния
        rst_qcnt  <= 3'b000;
      end else
        rst_qcnt  <= rst_qcnt + 3'b001;
    end else
      rst_qcnt  <= 3'b000;       // линия вернулась к состоянию - счёт с нуля
  end
  always @(posedge clk25)       // v3.9.8: логика на clk25 (п.23)
    reset_q <= ~cpu_rst;         // снятие сброса CPU - всегда чистым фронтом

  //=============================================================
  // TX-транзит с ЗАХВАТОМ (v3.7, clk10-51; п.3/13 шапки) - замена
  // TX-маски v2-v3.6: txm_cnt (8 FF, ~9 МЦ) и параметр TXM_W УДАЛЕНЫ,
  // окно больше НЕ таймерное. Факт датасшита IM1821ВМ85А (вывод SR):
  // аппаратный сброс очищает триггер TFD (SOD) в '0' -> после снятия
  // RESET_IN линия SOD='0' до первого SIM прошивки с SDE=1 (fw_mon v5:
  // TXIDLE, ~4-20 мкс при CPU 5 МГц). Голый транзит SOD->TX дал бы
  // «фиктивный start-bit» - пустой фрейм в терминале. Вместо таймера -
  // схемный захват ПО УРОВНЮ (частота и длина init прошивки не важны):
  //   sod_q   - синхронизация входа SOD по clk 25 МГц (XST положит в
  //             IO-MC входа P72; метастабильность гасится ДО использо-
  //             вания, статический путь пин SOD -> пин TX разорван);
  //   tx_pass - «линия захвачена прошивкой»: async clear по cpu_rst
  //             (v3.9.3: СОЗНАТЕЛЬНО НЕ переведён на GSR - cpu_rst
  //             держит tx_pass=0 ВЕСЬ POR, враждебный SOD в окне POR
  //             не «захватывает» линию; см. п.18);
  //             взводится первым сэмплом SOD='1' после сброса;
  //   tx_q    - выходной регистр TX (IO-MC пина P39, INIT=1, async set
  //             по cpu_rst): в сбросе TX='1' мгновенно и БЕЗ клока;
  //             после захвата - транзит sod_q с латентностью <= 2 такта
  //             25 МГц (80 нс = 0,4 такта CLK 200 нс = 0,08% бита 9600).
  // Полный цикл: POR/кнопка -> TX='1'; CPU вне сброса, SOD='0'
  // (сброшен SR-ом) -> TX='1' ДЕРЖИТСЯ сам (ноль не пропускается);
  // TXIDLE прошивки (SOD 0->1) -> захват, дальше бит-в-бит транзит.
  // Теория (см. п.13): ложный SOD='1' в окне открыл бы захват раньше -
  // физически невероятен (вход CPU в сбросе статичен); лечение -
  // захват по 2 сэмплам подряд (+1 FF).
  //=============================================================
  reg sod_q   = 1'b0;            // синхронизатор входа SOD (без сброса)
  reg tx_pass = 1'b0;            // «линия захвачена прошивкой» (INIT=0)
  reg tx_q    = 1'b1;            // выходной регистр TX (IO-MC; INIT=1)
  always @(posedge clk25)                        // v3.9.8: логика на clk25 (п.23)
    sod_q <= SOD;                                  // свободный ход, без сброса
  always @(posedge clk25 or posedge cpu_rst)     // v3.9.8: логика на clk25 (п.23)
    if (cpu_rst)    tx_pass <= 1'b0;
    else if (sod_q) tx_pass <= 1'b1;               // первый SOD='1' от прошивки
  always @(posedge clk25 or posedge cpu_rst)     // v3.9.8: логика на clk25 (п.23)
    if (cpu_rst) tx_q <= 1'b1;
    else         tx_q <= tx_pass ? sod_q : 1'b1;   // до захвата - чистый idle

  //=============================================================
  // Автомат шины: 7 состояний = 3 триггера (v3; в v1 было 10/4 триггера -
  // WBW/WBS/WBS2 удалены: hold-off 0, см. п.4 шапки; WB1..WB4 ЗАЩИЩЕНЫ
  // от ALE)
  //=============================================================
  localparam S_IDLE = 3'd0,   // ожидание ALE; A/D в Hi-Z; /OE включён (декод)
             S_T1H  = 3'd1,   // T1: CPU держит адрес на A-сетях; идёт захват
             S_T2   = 3'd2,   // строб: чтение - выдача данных на A; запись - захват
             S_WB1  = 3'd3,   // WB: адрес на A + данные на D (t_AS 40 нс до /WE)
             S_WB2  = 3'd4,   // /WE=0 - импульс НАЧАЛСЯ: защищён от ALE
             S_WB3  = 3'd5,   // /WE=0 (импульс = 2 тика = 80 нс >= t_WP ОЗУ)
             S_WB4  = 3'd6;   // /WE=1: удержание адреса/данных (t_AH/t_DH памяти)

  // Task 46: прагма против ONE-HOT перекодировки автомата XST
  // (контроль у владельца: в .rpt НЕ должно быть state_FSM_FFd4..10;
  // v3: автомат = РОВНО 3 триггера state_FSM_FFd1..3; 7 состояний (без WBW).
  // synthesis attribute fsm_encoding of state is "compact"
  reg  [2:0] state  = S_IDLE;
  reg        rd_seen = 1'b0;    // строб чтения замечен в T2
  reg        wr_seen = 1'b0;    // строб записи замечен в T2

  // Захваченные шинные регистры
  reg [7:0] addr_latch = 8'h00;  // адрес с A-сетей (T1) - нужен writeback и декоду порта
  reg [7:0] bus_reg    = 8'h00;  // данные: чтение (с D-сети в T1) ИЛИ запись (с A-сети в T2)

  // Порты индикации/звука (§5): захват по записи в порт при IO/M#=1
  reg [7:0] seg_q = 8'hFF;       // 1 в регистре = сегмент горит; выход инвертируется
  reg [3:0] dig_q = 4'hF;        // 1 = цифра выбрана; выход инвертируется
  reg       snd_q = 1'b0;
  reg [3:0] kbcol_q = 4'h0;      // колонки (порт 02h), INIT 0000 = все выкл
  wire io_rd_kb = IOM & ~addr_latch[2] & addr_latch[1] & addr_latch[0]; // чтение 03h (KBROW)

  // Комбинационные группы (v3):
  //   wb_out = in_wb БЕЗ !ALE: драйверы A/D держат адреса/данные до конца
  //     защищённого импульса (п.4 шапки); снятие - при выходе в IDLE.
  //   rd_drive с !ALE - чтение как в v1 (мгновенный обрыв при новом цикле).
  wire in_wb   = (state >= S_WB1);                       // WB1..WB4: A/D драйвятся
  wire in_welo = (state == S_WB2) || (state == S_WB3);   // /WE низ
  wire wr_phase = (state >= S_T2);                       // T2..WB4: /OE памяти off
  wire wb_out   = in_wb;                                 // защищённый writeback-драйв
  wire rd_drive = (state == S_T2) && rd_seen && !RDn && !ALE; // A-пины отдают данные

  //=============================================================
  // Шинный движок
  //=============================================================
  always @(posedge clk25 or posedge cpu_rst) begin // v3.9.6: сброс логики по cpu_rst = rst_press|por_run (регистры, п.21; асинхронная структура GSR п.18/20 сохранена); v3.9.8: такт логики clk25 (п.23)
    if (cpu_rst) begin
      state      <= S_IDLE;
      rd_seen    <= 1'b0;
      wr_seen    <= 1'b0;
      addr_latch <= 8'h00;
      bus_reg    <= 8'h00;
      seg_q      <= 8'hFF;   // INIT «8888.» на индикаторе
      dig_q      <= 4'hF;
      snd_q      <= 1'b0;
      kbcol_q    <= 4'h0;
    end else begin
      // --- захват повторным сэмплированием: последний сэмпл валиден ---
      // v3: захват возможен только в T1H, т.е. ПОСЛЕ завершения WB
      // (структурно: из WB в T1H попадаешь только через IDLE) - adm.
      // addr_latch НЕ может перезаписаться посреди импульса (п.6 шапки).
      if (state == S_T1H && ALE) begin
        addr_latch <= A;                 // адрес стабилен весь T1
        if (!IOM) bus_reg <= D;          // данные памяти (доступ начался в начале T1)
      end
      if (state == S_T2 && !WRn) begin
        bus_reg <= A;                    // данные записи (CPU держит до WR#(вверх))
        if (IOM) begin                   // запись в порт: декод по тройке A2,A1,A0 (Task 34)
          case (addr_latch[2:0])
            3'b000: seg_q <= A;          // 00h: сегменты
            3'b001: begin                // 01h: разряды + SND
              dig_q <= A[3:0];
              snd_q <= A[4];
            end
            3'b010: kbcol_q <= A[3:0];   // 02h: колонки клавиатуры
            default: ;                   // 03h чтение; 04h-07h резерв (UART удалён, Task 69)
          endcase
        end
      end
      // --- трекинг стробов ---
      if (state == S_T2 && !RDn) rd_seen <= 1'b1;
      if (state == S_T2 && !WRn) wr_seen <= 1'b1;
      // --- переходы ---
      // v3: ALE ОБРЫВАЕТ только T2 (защита от глюка); в WB1..WB4 НЕ
      // вмешивается - импульс /WE защищён (п.4 шапки).
      if (ALE && state == S_T2 && !((wr_seen && WRn) || (rd_seen && RDn))) begin
        state   <= S_IDLE;
        rd_seen <= 1'b0;
        wr_seen <= 1'b0;
      end else begin
        case (state)
          S_IDLE: if (ALE) state <= S_T1H;
          S_T1H:  if (!ALE) state <= S_T2;
          S_T2: begin
            // приоритет записи: RDn-глюк во время записи не должен прерывать её
            if (wr_seen && WRn) begin
              wr_seen  <= 1'b0;
              // writeback только для записи в ОЗУ (8000-FFFF); запись в ПЗУ
              // отбрасывается (по железу /WE flash не подключён), порт пропускается
              // v3.9.3 (п.18): гейт POR - FSM в окне POR живой (GSR не
              // активен), шина CPU в сбросе «floated» (ВМ85А: управле-
              // ния/адрес/данные в 3-м состоянии) - вход в writeback
              // ЗАПРЕЩЁН, иначе плавающие ALE/WRn могли бы родить /WE
              state <= (!IOM && A15 && !por_run && !rst_press) ? S_WB1 : S_IDLE; // v3.9.6: гейт и на кнопку (п.21)
            end else if (rd_seen && RDn) begin
              rd_seen <= 1'b0;
              state <= S_IDLE;         // отпускание A-пинов через 1 тик после RD#(вверх)
            end
          end
          S_WB1: state <= S_WB2;       // t_AS 40 нс; hold-off 0 (см. п.4 шапки)
          S_WB2: state <= S_WB3;       // /WE низ - защищён, идёт до конца
          S_WB3: state <= S_WB4;
          S_WB4: state <= S_IDLE;      // импульс закончен, всё снято в IDLE
          default: state <= S_IDLE;
        endcase
      end
    end
  end

  //=============================================================
  // Тристейт-драйверы шины
  //=============================================================
  // Task 34: при чтении порта 03h A_I(0..4) = row0-4 (mux KBROW),
  // AD7-5 = 000. UART-статус (IN 05h) удалён вместе с UART (Task 69).
  assign A = rd_drive ? (io_rd_kb ? {3'b000, row4, row3, row2, row1, row0}
                                  : bus_reg)
            : wb_out   ? addr_latch : 8'bZZZZZZZZ;
  assign D = wb_out ? bus_reg : 8'bZZZZZZZZ;

  //=============================================================
  // Декод памяти минимальной ширины (§5): 1 терм на кристалл
  // v3.9.1 (п.16 шапки): /CE ОЗУ в writeback - ОТ СОСТОЯНИЯ FSM
  // (in_wb); защёлка wb_ram_q удалена - in_wb достижим только через
  // T2-запись в ОЗУ и уже влечёт её условие (эквивалентность v3.9
  // доказана: полный перебор состояний + дифсимуляция двух RTL).
  // Живой декод A15 во время конфликта адресов по-прежнему НЕ
  // участвует: в WB1..WB4 CS_n = 0 без A15/IOM - запись ОЗУ
  // защищена как в v3 (защита п.5 шапки сохранена построением).
  //=============================================================
  assign CSr_n = A15 | IOM;             // /CE_ROM = !( !A15 & !IOM )
  assign CS_n  = in_wb ? 1'b0 : (!A15 | IOM);   // v3.9.1: было (in_wb && wb_ram_q) ? ... (п.16)
  assign OEr_n = CSr_n | wr_phase;      // /OE гасится с T2 - данные уже захвачены,
  assign OE_n  = CS_n  | wr_phase;      // иначе SRAM воевала бы с CPLD на D в writeback
  // v3: /WE НЕ обрывается ALE - импульс доводится до конца (п.4 шапки);
  // безопасно: автомат доходит до WB4/IDLE за 5 тиков; сброс гасит импульс:
  // v3.9.2 - cpu_rst за такт (sync), v3.9.3 - GSR мгновенно (п.18);
  // v3.9.6 - импульс 80 нс квалификатор (400 нс) НЕ успевает оборвать:
  // начатая запись доводится до конца (полный t_WP ОЗУ), сброс гасит
  // драйвы сразу после её завершения (п.21f).
  assign WE_n  = !in_welo;
  assign CS1   = 1'b1;

  //=============================================================
  // Поддержка CPU (§3, ред. Task 19) + soft-UART транзиты (Task 70-a).
  // Держатели '0' (TRAP, RST7.5/6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины (9 шт) заземлит фиттер (Ground on Unused IOs).
  // SID (P73) с Task 70-a - ВЫХОД CPLD (транзит RX), в держатели
  // больше не входит (PGND 10 -> 9).
  //=============================================================
  assign RESET_IN = reset_q;          // v3.9.6 (п.21): РЕГИСТР; активный 0 по даташиту: 0 = сброс CPU (кнопка после квалификатора или POR); INIT=0 - CPU держится с t=0; снятие - чистым регистровым фронтом
  assign READY = 1'b1;          // без wait-state - иначе вечные TW
  // Транзиты soft-UART (Task 70-a); TX - регистровый, см. блок v3.7 выше:
  assign SID = RX;              // приём:  CH340G.TXD (P38) -> CPU.SID (P73), RIM 20h
  assign TX  = tx_q;            // передача: CPU.SOD (P72) -> CH340G.RXD (P39), SIM 30h;
                                // регистр с захватом после первого SOD='1' (v3.7):
                                // в покое прошивка держит SOD='1' (stop/idle) - это
                                // и есть enable линии; в сбросе/до захвата TX='1'

  //=============================================================
  // Индикация и звук: выходы инвертированы (общий анод, активный 0)
  //=============================================================
  assign seg = ~seg_q;
  assign dig = ~dig_q;
  assign SND = snd_q;
  // Task 34: колонки клавиатуры - зарегистрированные выходы, прямые уровни
  // (активная колонка = 1, остальные 0; после сброса 0000 - безопасно)
  assign col0 = kbcol_q[0];
  assign col1 = kbcol_q[1];
  assign col2 = kbcol_q[2];
  assign col3 = kbcol_q[3];

