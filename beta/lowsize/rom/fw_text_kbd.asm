; =====================================================================
; beta/lowsize/rom -- fw_text_kbd: ТЕСТ КЛАВИАТУРЫ (строка/колонка + бип)
;
; Плата: retro_PCLD_board V2, CPLD = beta/lowsize v3.9.1/v3.9.2
; (транзиты kbcol/kbrow/seg/dig/SND идентичны v3.2...v3.9.x).
; Прошивается в flash A29040B с offset 0 (ЗАМЕНЯЕТ fw_mon на время теста).
;
; Сборка (asm85.py, исходник CP1251):
;   python3 asm85.py fw_text_kbd.asm -o fw_text_kbd.hex -l fw_text_kbd.lst
;   быстрый вариант для стендовой симуляции:
;   python3 asm85.py fw_text_kbd.asm -o fw_text_kbd_fast.hex -D FAST=1
;
; МАТРИЦА (Task 34): 4 колонки - зарегистрированные ВЫХОДЫ порт 02h
; (D0..D3 = col0..col3, 1 = колонка заведена; после сброса 0000),
; 5 рядов - ВХОДЫ порт 03h (D0..D4 = row0..row4; подтяжки R21-R25 10к
; на GND, покой = 0; нажатие в активной колонке = 1). Читается ТОЛЬКО
; порт 03h (остальные порты CPLD не драйвит).
;
; ЧТО ДЕЛАЕТ (по ТЗ владельца):
;   1) Непрерывно сканирует матрицу (колонка -> пауза ~25 мкс -> ряды).
;   2) НАЖАТИЕ КНОПКИ СОПРОВОЖДАЕТСЯ ЗВУКОВЫМ СИГНАЛОМ: бип ~0,2 с
;      (тон ~500 Гц, SND тогглится каждый ~1 мс).
;   3) НА ДИСПЛЕЙ ВЫВОДИТСЯ: СЛЕВА (DIG3) - НОМЕР СТРОКИ, СПРАВА (DIG0) -
;      НОМЕР КОЛОНКИ нажатой кнопки. Нумерация АППАРАТНАЯ, с нуля:
;      строки 0..4 (row0..row4, биты D0..D4 порта 03h), колонки 0..3
;      (col0..col3, биты D0..D3 порта 02h). Средние разряды погашены.
;      Регенерация с БЛЭНКИНГОМ (гашение -> разряд -> глиф): послесвечения
;      чужого глифа нет (на плате 10-30 было: сквозь '1' просвечивал '2').
;      До первого нажатия на дисплее "--" (два прочерка).
;   4) После отпускания - пауза-дебаунс ~30 мс, затем скан продолжается
;      (можно нажимать следующую кнопку; дисплей показывает ПОСЛЕДНЮЮ).
;
; ПРИМЕРЫ: SW1 (row0/col0) -> дисплей "0 0"; SW11 (row2/col2) -> "2 2";
;   SW16 (row3/col3) -> "3 3"; SW17 (row4/col0) -> "4 0".
;   (расположение кнопок - PORTS_MAP.md §10: col0=SW1/SW5/SW9/SW13/SW17,
;   col1=SW2/SW6/SW10/SW14/SW18, col2=SW3/SW7/SW11/SW15/SW19,
;   col3=SW4/SW8/SW12/SW16; ряды - по R25..R21 сверху вниз).
;
; ТАЙМИНГ (CPU 3,571 МГц, T-состояние 280 нс):
;   SETTLE ~25 мкс (LXI 10 + 2x24 + 21 + RET = 89 T);
;   BEEP_UNIT ~1 мс (внутр. цикл 3463 T + тоггл SNDST 33 + CALL REFRESH
;     ~225 T с блэнкингом, клк10-67) -> бип 200 ед. ~ 0,21 с, тон ~475 Гц;
;   регенерация дисплея: разряд переключается на каждом проходе скана
;     (4 колонки x ~75 мкс ~ 0,3 мс) -> ~1,7 кГц попеременно, скважность
;     1/1 - мерцания нет;
;   дебаунс нажатия: первая ловля - мгновенно (скан активен всегда),
;     ложные дребезги ПОСЛЕ отпускания гасятся паузой ~30 мс.
;
; ОЖИДАЕМОЕ ПОВЕДЕНИЕ / ИНТЕРПРЕТАЦИЯ:
;   - бип есть, номер не тот -> перепутаны ряды/колонки ( разводка/CPLD);
;   - бипа нет, номер есть -> тракт SND;
;   - бип без нажатия (самозвон) -> ряд висит в 1: подтяжка R21-R25,
;     замыкание ряда на колонку;
;   - двойные срабатывания с одного нажатия -> дребезг контактов
;     (пауза 30 мс гасит штатно; если чаще - деградация контакта);
;   - "--" горит, на нажатия реакции нет -> тракт KBROW/разъём.
; =====================================================================

; ---- константы (переопределяются через -D) ----
FAST    EQU 0               ; 1 = укороченные паузы (для симуляции)
IF FAST
BEEP_MS EQU 4               ; единиц ~1 мс в бипе (быстро)
SET_MS  EQU 2               ; дебаунс после отпускания
ELSE
BEEP_MS EQU 200             ; 200 x ~1,05 мс = ~0,21 с
SET_MS  EQU 30              ; 30 x ~1,04 мс = ~31 мс
ENDIF

K_MS    EQU 144             ; внутренний счётчик ~1 мс

; ---- порты CPLD (декод по A2-A0, зеркала mod 8) ----
SEGP    EQU 00h             ; сегменты: D0=a..D6=g, D7=dp; 1 = горит
DIGP    EQU 01h             ; D3-D0 разряды, D4 = SND
KBCOLP  EQU 02h             ; D3-D0 колонки (1 = заведена)
KBROWP  EQU 03h             ; D4-D0 ряды (1 = нажата в активной колонке)

; ---- ОЗУ ----
ROWNUM  EQU 8000h           ; номер строки 0..4
COLNUM  EQU 8001h           ; номер колонки 0..3
DPH     EQU 8002h           ; фаза регенерации: 08h = левый (строка), 01h = правый
SNDST   EQU 8003h           ; состояние тона 0/1
ROWIMG  EQU 8004h           ; глиф строки (DIG3)
COLIMG  EQU 8005h           ; глиф колонки (DIG0)

; =====================================================================
        ORG 0000h
        JMP MAIN

; ---- глифы '0'..'5' (a,b,c,d,e,f = D0..D5) ----
GTBL:   DB 3Fh              ; '0'
        DB 06h              ; '1'
        DB 5Bh              ; '2'
        DB 4Fh              ; '3'
        DB 66h              ; '4'
        DB 6Dh              ; '5' (запас)


; ---------------------------------------------------------------------
; SETTLE: пауза ~25 мкс (установка ряда после заведения колонки)
; ---------------------------------------------------------------------
SETTLE: LXI B,3
STL:    DCX B
        MOV A,B
        ORA C
        JNZ STL
        RET

; ---------------------------------------------------------------------
; REFRESH: ГАШЕНИЕ -> ПЕРЕКЛЮЧЕНИЕ РАЗРЯДА -> ГЛИФ (без послесвечения).
;   Наивный порядок "глиф -> разряд" даёт призрак: OUT SEGP нового глифа
;   срабатывает, когда СТАРЫЙ разряд ещё горит, и тот ~16 мкс светит
;   ЧУЖОЙ глиф (на плате: сквозь '1' просвечивал '2' при коде "2 1").
;   Порядок (клк10-67):
;   (1) OUT SEGP=0   - старый разряд гаснет, светив СВОЙ глиф;
;   (2) OUT DIGP     - разряд переключается при ПУСТЫХ сегментах:
;                      старый чужой глиф показать уже не может,
;                      новый зажигается пустым;
;   (3) OUT SEGP=глиф - новый разряд зажигается СВОИМ глифом.
;   DPH=08h -> левый разряд (ROWIMG, строка); DPH=01h -> правый (COLIMG).
;   Портит A/B/C (D/E - бит колонки и индекс скана - НЕ трогает).
; ---------------------------------------------------------------------
REFRESH: LDA DPH
        MOV B,A             ; B = биты разряда новой фазы
        CPI 08h
        JZ RF_L
        LDA COLIMG
        JMP RF_G
RF_L:   LDA ROWIMG
RF_G:   MOV C,A             ; C = глиф нового разряда
        LDA SNDST
        ORA A               ; тон включён?
        JZ RF_N
        MOV A,B
        ORI 10h
        JMP RF_D
RF_N:   MOV A,B
RF_D:   MOV B,A             ; B = готовые биты разряда (с SND)
        XRA A
        OUT SEGP            ; (1) гашение: старый разряд погас
        MOV A,B
        OUT DIGP            ; (2) разряд переключён (сегменты пусты)
        MOV A,C
        OUT SEGP            ; (3) зажгли глиф нового разряда
        LDA DPH
        CPI 08h
        JZ RF_T
        MVI A,08h           ; был правый -> левый
        STA DPH
        RET
RF_T:   MVI A,01h           ; был левый -> правый
        STA DPH
        RET

; ---------------------------------------------------------------------
; BEEP_UNIT: ~1 мс + тоггл SNDST + регенерация дисплея
; ---------------------------------------------------------------------
BEEP_UNIT: LXI B,K_MS
BUL:    DCX B
        MOV A,B
        ORA C
        JNZ BUL
        LDA SNDST
        XRI 01h
        STA SNDST
        CALL REFRESH        ; OUT DIGP уносит актуальный бит SND
        RET

; ---------------------------------------------------------------------
; QUIET_UNIT: ~1 мс без звука, дисплей живёт
; ---------------------------------------------------------------------
QUIET_UNIT: LXI B,K_MS
QUL:    DCX B
        MOV A,B
        ORA C
        JNZ QUL
        CALL REFRESH
        RET

; ---------------------------------------------------------------------
; SCANALL: опрос всех 4 колонок; A = ИЛИ рядов (0 = нажатий нет);
; колонки на выходе погашены
; ---------------------------------------------------------------------
SCANALL: XRA A
        MOV E,A             ; E = накопитель (SETTLE трогает только A/B/C)
        MVI D,01h           ; D = бит колонки
SAL1:   MOV A,D
        OUT KBCOLP
        CALL SETTLE
        IN KBROWP
        ANI 1Fh
        ORA E
        MOV E,A
        MOV A,D
        RLC
        MOV D,A
        CPI 10h
        JNZ SAL1
        XRA A
        OUT KBCOLP
        MOV A,E
        RET

; ---------------------------------------------------------------------
; MAIN
; ---------------------------------------------------------------------
MAIN:   LXI SP,8400h
        XRA A
        OUT SEGP            ; дисплей погашен
        OUT DIGP
        OUT KBCOLP          ; колонки off (безопасный INIT)
        MVI A,40h           ; глиф '-' (сегмент g)
        STA ROWIMG
        STA COLIMG          ; до первого нажатия: "--"
        MVI A,01h
        STA DPH             ; старт регенерации с правого
        XRA A
        STA SNDST

        ; ВНИМАНИЕ (нашлено симуляцией verify_fw.py): SETTLE/SCANALL/
        ; BEEP_UNIT затирают A/B/C - бит колонки живёт в D, индекс в E.
SCAN:   MVI E,0             ; индекс колонки 0..3
        MVI D,01h           ; бит колонки
SC1:    MOV A,D
        OUT KBCOLP
        CALL SETTLE
        IN KBROWP
        ANI 1Fh
        JNZ HIT
        MOV A,D
        RLC
        MOV D,A
        INR E               ; следующий индекс колонки
        CPI 10h
        JNZ SC1
        CALL REFRESH        ; нажатий нет - шаг регенерации
        JMP SCAN

HIT:    PUSH PSW            ; A = ряды (один бит)
        XRA A
        OUT KBCOLP          ; колонки off (фиксируем факт нажатия)
        POP PSW
        MVI D,0             ; D = номер строки
H1:     RRC
        JC H2
        INR D
        JMP H1
H2:     MOV A,D
        STA ROWNUM
        MOV A,E
        STA COLNUM
        ; глифы: COLIMG = GTBL[col], ROWIMG = GTBL[row]
        LDA COLNUM
        MOV E,A
        MVI D,0
        LXI H,GTBL
        DAD D
        MOV A,M
        STA COLIMG
        LDA ROWNUM
        MOV E,A
        MVI D,0
        LXI H,GTBL
        DAD D
        MOV A,M
        STA ROWIMG
        ; ---- БИП ~0,2 с (дисплей живёт, глифы уже новые) ----
        LXI H,BEEP_MS
BP1:    CALL BEEP_UNIT
        DCX H
        MOV A,H
        ORA L
        JNZ BP1
        XRA A
        STA SNDST           ; тон гарантированно погашен
        ; ---- ожидание отпускания ----
WREL:   CALL SCANALL
        ANI 1Fh
        JZ WDN
        CALL REFRESH
        JMP WREL
WDN:    LXI H,SET_MS        ; дебаунс после отпускания
ST1:    CALL QUIET_UNIT
        DCX H
        MOV A,H
        ORA L
        JNZ ST1
        JMP SCAN

        END
