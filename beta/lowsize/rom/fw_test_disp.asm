; =====================================================================
; beta/lowsize/rom -- fw_test_disp: ТЕСТ ДИСПЛЕЯ (сегменты + разряды + тон)
;
; Плата: retro_PCLD_board V2, CPLD = beta/lowsize v3.9.1/v3.9.2
; (порты/дисплей/звук идентичны v3.2...v3.9.x - транзиты seg/dig/SND).
; Прошивается в flash A29040B с offset 0 (ЗАМЕНЯЕТ fw_mon на время теста;
; вернуть монитор - перешить его образ). Терминал не используется.
;
; Сборка (asm85.py, исходник CP1251):
;   python3 asm85.py fw_test_disp.asm -o fw_test_disp.hex -l fw_test_disp.lst
;   быстрый вариант для стендовой симуляции/прогонки:
;   python3 asm85.py fw_test_disp.asm -o fw_test_disp_fast.hex -D FAST=1
;
; ЧТО ДЕЛАЕТ (по ТЗ владельца):
;   1) Зажигает ВСЕ сегменты индикатора ПО ПОРЯДКУ, от ПЕРВОГО разряда
;      до последнего: разряды 0 -> 1 -> 2 -> 3 (нумерация платы DIG0..DIG3),
;      внутри разряда сегменты a -> b -> c -> d -> e -> f -> g -> dp
;      (биты D0..D7 порта 00h). В каждый момент горит РОВНО ОДИН сегмент
;      одного разряда - по каждому сегменту видно и зажигание, и гашение.
;   2) Каждый сегмент горит ~0,9 с (в диапазоне 0,8..1,0 с по ТЗ) и
;      СОПРОВОЖДАЕТСЯ ЗВУКОМ - непрерывный тон ~500 Гц всю выдержку
;      (пассивный зуммер: SND тогглится каждый ~1 мс).
;   3) Между сегментами - тёмная пауза ~60 мс (тон погашен).
;   4) После последнего сегмента (dp разряда 3) выводит "tE5t" как
;      завершение: динамическая индикация 4 разрядов (t E 5 t слева
;      направо), без тона, до сброса/выключения. Регенерация с БЛЭНКИНГОМ
;      (гашение -> разряд -> глиф) - послесвечения чужого глифа нет.
;   Итого: 4 x 8 x (0,9 + 0,06) = ~30,6 с, затем "tE5t".
;
; ТАЙМИНГ (CPU 3,571 МГц, T-состояние 280 нс, машинный цикл 1,4 мкс):
;   внутренний цикл dcx/mov/ora/jnz: 6+4+4+10 = 24 T (последний 21);
;   MS_UNIT (1 ед. ~1 мс + тоггл SND): LXI 10 + 24x(K-1) + 21 + тоггл 43
;     + RET 10 = 24x144 + 60 = 3516 T = 984,5 мкс; с CALL и счётчиком
;     цикла: 18 + 3516 + 6+4+4+10 = 3558 T = 996,2 мкс на единицу;
;   выдержка сегмента = 900 x 996,2 мкс = 896,6 мс (0,8-1,0 с: ПАСС);
;   полупериод тона ~1 мс -> ~502 Гц;
;   пауза = 60 x 984 мкс = 59 мс (без тона);
;   tE5t: фаза = 222-цикл + блэнкинг = 5354 T = 1499 мкс на разряд, цикл 4 фаз =
;     6,0 мс -> частота регенерации ~167 Гц (мерцания нет).
;
; ОЖИДАЕМОЕ ПОВЕДЕНИЕ / ИНТЕРПРЕТАЦИЯ:
;   - горит ЛИШНИЙ сегмент/разряд -> замыкание сегментов/драйвера VT;
;   - сегмент НЕ горит -> обрыв сегмента, мёртвый светодиод, CPLD-пин;
;   - тон не меняется/нет -> тракт SND (бит D4 порта 01h);
;   - "8." хаос до старта -> норма (INIT CPLD seg=FF/dig=F до первого OUT);
;   - по завершении устойчивое "tE5t" = ТЕСТ ПРОЙДЕН.
; =====================================================================

; ---- константы (переопределяются через -D) ----
FAST    EQU 0               ; 1 = укороченные выдержки (для симуляции)
IF FAST
SEG_MS  EQU 3               ; единиц ~1 мс на сегмент (быстро)
GAP_MS  EQU 2               ; пауза между сегментами
ELSE
SEG_MS  EQU 900             ; 900 x 996 мкс = 896,6 мс (0,8..1,0 с)
GAP_MS  EQU 60              ; 60 x 984 мкс = 59 мс
ENDIF

K_MS    EQU 144             ; внутренний счётчик ~1 мс (24x144+60 = 3516 T)
K_15    EQU 222             ; счётчик фазы tE5t ~1,5 мс (5335 T = 1494 мкс)

; ---- порты CPLD (декод по A2-A0, зеркала mod 8) ----
SEGP    EQU 00h             ; сегменты: D0=a..D6=g, D7=dp; 1 = горит
DIGP    EQU 01h             ; D3-D0 разряды (1 = вкл), D4 = SND (1 = тон)

; ---- ОЗУ ----
DIGIMG  EQU 8000h           ; образ порта 01h (разряд + SND)
SEGCTR  EQU 8001h           ; счётчик сегментов в разряде (8..1)

; =====================================================================
        ORG 0000h
        JMP MAIN

; ---- глифы "tE5t" (слева направо: DIG3,DIG2,DIG1,DIG0; d,e,f,g / a,d,e,f,g / a,f,g,c,d / t) ----
GTE5T:  DB 78h              ; 't'
        DB 79h              ; 'E'
        DB 6Dh              ; '5'
        DB 78h              ; 't'


; ---------------------------------------------------------------------
; MS_UNIT: ~1 мс + тоггл SND (непрерывный тон, пока вызывается в цикле)
; ---------------------------------------------------------------------
MS_UNIT: LXI B,K_MS
MUL:    DCX B
        MOV A,B
        ORA C
        JNZ MUL
        LDA DIGIMG
        XRI 10h             ; тоггл SND
        STA DIGIMG
        OUT DIGP
        RET

; ---------------------------------------------------------------------
; MS_QUIET: ~1 мс без звука
; ---------------------------------------------------------------------
MS_QUIET: LXI B,K_MS
MQL:    DCX B
        MOV A,B
        ORA C
        JNZ MQL
        RET

; ---------------------------------------------------------------------
; MAIN
; ---------------------------------------------------------------------
MAIN:   LXI SP,8400h
        XRA A
        OUT SEGP            ; сегменты погашены (INIT CPLD "8." гасим сразу)
        OUT DIGP            ; разряды off, SND off
        STA DIGIMG

        ; ВНИМАНИЕ (нашлено симуляцией verify_fw.py): MS_UNIT/MS_QUIET
        ; затирают A/B/C - биты разряда и сегмента живут в D и E
        ; (подпрограммами не трогаются), счётчик сегментов - в ОЗУ.
        MVI D,01h           ; бит разряда: первый = DIG0
DIGL:   MVI E,01h           ; бит сегмента: 'a'
        MVI A,8
        STA SEGCTR          ; 8 сегментов
SEGL:   MOV A,E
        OUT SEGP            ; показать сегмент
        MOV A,D
        ORI 10h             ; разряд + SND=1 (стартовая фаза тона)
        STA DIGIMG
        OUT DIGP
        LXI H,SEG_MS        ; выдержка ~0,9 с с тоном
IVL:    CALL MS_UNIT
        DCX H
        MOV A,H
        ORA L
        JNZ IVL
        MOV A,D             ; пауза: тон погасить, разряд ещё горит
        STA DIGIMG
        OUT DIGP
        MVI A,00h
        OUT SEGP            ; сегмент погашен (тёмная пауза)
        LXI H,GAP_MS
GAPL:   CALL MS_QUIET
        DCX H
        MOV A,H
        ORA L
        JNZ GAPL
        MOV A,E
        RLC                 ; следующий сегмент a->b->...->dp
        MOV E,A
        LDA SEGCTR
        DCR A
        STA SEGCTR
        JNZ SEGL
        MOV A,D
        RLC                 ; следующий разряд DIG0->DIG1->DIG2->DIG3
        MOV D,A
        CPI 10h             ; после DIG3 (08h) - конец обхода
        JNZ DIGL

        ; ---- завершение: "tE5t" (динамика, без тона), навсегда ----
;   Блэнкинг против послесвечения (клк10-67): ГАШЕНИЕ -> РАЗРЯД -> ГЛИФ;
;   наивный "глиф -> разряд" светил бы ЧУЖОЙ глиф на старом разряде
;   (~4 мкс каждый переход: сквозь 't' просвечивал 'E' и т.п.).
TE5T:   MVI C,4             ; 4 фазы
        MVI B,08h           ; старт с DIG3 (левый)
        LXI H,GTE5T
TPH:    MOV D,M             ; D = глиф текущей фазы (D/E тут свободны)
        XRA A
        OUT SEGP            ; (1) гашение: старый разряд гаснет со своим глифом
        MOV A,B
        OUT DIGP            ; (2) разряд переключён при пустых сегментах
        MOV A,D
        OUT SEGP            ; (3) новый разряд зажёгся СВОИМ глифом
        LXI D,K_15          ; ~1,5 мс на фазу
TDL:    DCX D
        MOV A,D
        ORA E
        JNZ TDL
        MOV A,B
        RRC                 ; DIG3->DIG2->DIG1->DIG0
        MOV B,A
        INX H
        DCR C
        JNZ TPH
        JMP TE5T

        END
