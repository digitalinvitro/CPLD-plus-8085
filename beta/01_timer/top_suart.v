            if (wr_seen && WRn) begin
              wr_seen  <= 1'b0;
              wb_ram_q <= !IOM && A15;   // защЄлка декода дл€ CS_n в WB (v3)
              // writeback только дл€ записи в ќ«” (8000-FFFF); запись в ѕ«”
              // отбрасываетс€ (по железу /WE flash не подключЄн), порт пропускаетс€
              state <= (!IOM && A15) ? S_WB1 : S_IDLE;
