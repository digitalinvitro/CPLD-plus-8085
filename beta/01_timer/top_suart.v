  reg        wb_ram_q = 1'b0;   // защЄлка ЂWB Ч это запись в ќ«”ї (дл€ CS_n, v3 п.5)

  // «ахваченные шинные регистры
  reg [7:0] addr_latch = 8'h00;  // адрес с A-сетей (T1) Ч нужен writeback и декоду порта
  reg [7:0] bus_reg    = 8'h00;  // данные: чтение (с D-сети в T1) »Ћ» запись (с A-сети в T2)

  // ѕорты индикации/звука (І5): захват по записи в порт при IO/M#=1
  reg [7:0] seg_q = 8'hFF;       // 1 в регистре = сегмент горит; выход инвертируетс€
  reg [3:0] dig_q = 4'hF;        // 1 = цифра выбрана; выход инвертируетс€
  reg       snd_q = 1'b0;
  reg [3:0] kbcol_q = 4'h0;      // колонки (порт 02h), INIT 0000 = все выкл
  wire io_rd_kb = IOM & ~addr_latch[2] & addr_latch[1] & addr_latch[0]; // чтение 03h (KBROW)

  //  омбинационные группы (v3):
  //   wb_out = in_wb Ѕ≈« !ALE: драйверы A/D держат адреса/данные до конца
  //     защищЄнного импульса (п.4 шапки); сн€тие Ч при выходе в IDLE.
  //   rd_drive с !ALE Ч чтение как в v1 (мгновенный обрыв при новом цикле).
  wire in_wb   = (state >= S_WB1);                       // WB1..WB4: A/D драйв€тс€
  wire in_welo = (state == S_WB2) || (state == S_WB3);   // /WE низ
  wire wr_phase = (state >= S_T2);                       // T2..WB4: /OE пам€ти off
  wire wb_out   = in_wb;                                 // защищЄнный writeback-драйв
