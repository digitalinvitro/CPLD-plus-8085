  // терма вынесены в –≈√»—“–џ (FF не схлопываетс€ Ч урок v3.2 п.8):
  //   tmr_tick_q Ч декод тика (11 входов) в ќƒЌќ… MC, а не схлопнут в 8
  //     бит счЄтчика ($OpTx$FX_SC$97 8 PT/31 вход больше не строитс€);
  //   RST75_r   Ч NOR8 нул€ в MC выхода P75, приЄмникам 1 вход;
  //   tmr_load_q Ч строб загрузки; ширина D-уравнени€ бита счЄтчика
  //     = 7+i входов (было 12-21). Ћаг цепочки +2 такта clk (80 нс) Ч
  //     в допусках tb (±1 тик). —“ќѕ: enable = tick_q & !RST75_r Ч окно
  //     лага 1 такт, следующий тик только через 12 800 тактов.
  //=============================================================
  reg  [7:0] tmr_cnt = 8'hFF;   // счЄтчик тиков: INIT FF = нет ложного фронта RST75 после RESET
  reg        tmr_tick_q = 1'b0; // тик Ч –≈√»—“–: 1 такт clk раз в 51,2 мкс
  reg        tmr_load_q = 1'b0; // строб загрузки Ч –≈√»—“– (данные берЄм из bus_reg)
  reg        RST75_r    = 1'b0; // регистр нул€ счЄтчика = уровень RST 7.5
  wire       tmr_tick = por_ce && (txm_cnt == 8'h7F);      // условие тика (захватывает tmr_tick_q)
  wire       tmr_wr04 = wr_cap && IOM &&
                        (addr_latch[2:0] == 3'b100);        // OUT 04h: загрузка периода

  always @(posedge clk)
    tmr_tick_q <= tmr_tick;   // тик тактом позже: период 51,2 мкс Ќ≈ мен€етс€

  always @(posedge clk)
    tmr_load_q <= tmr_wr04;   // строб тактом позже; bus_reg всЄ это врем€ держит N

  always @(posedge clk)
    if (cpu_rst)              RST75_r <= 1'b0;               // RESET: RST75 = 0 (нет ложного фронта)
    else                      RST75_r <= (tmr_cnt == 8'h00); // NOR8 нул€ Ч один раз, здесь

  always @(posedge clk) begin
    if (cpu_rst)                              tmr_cnt <= 8'hFF;    // RESET: FF, RST75=0
    else if (tmr_load_q)                      tmr_cnt <= bus_reg;  // OUT 04h: N из bus_reg
    else if (tmr_tick_q && !RST75_r)          tmr_cnt <= tmr_cnt - 8'd1;  // тик: вниз до нул€, —“ќѕ
  end

  //=============================================================
  // Ўинный движок
  //=============================================================
  always @(posedge clk) begin        // синхронный сброс всех триггеров по (RST|POR) Ч Task 25
    if (cpu_rst) begin
      state      <= S_IDLE;
      rd_seen    <= 1'b0;
      wr_seen    <= 1'b0;
      wb_ram_q   <= 1'b0;
      addr_latch <= 8'h00;
      bus_reg    <= 8'h00;
      seg_q      <= 8'hFF;   // INIT Ђ8888.ї на индикаторе
      dig_q      <= 4'hF;
      snd_q      <= 1'b0;
      kbcol_q    <= 4'h0;
    end else begin
      // --- захват повторным сэмплированием: последний сэмпл валиден ---
      // v3: захват возможен только в T1H, т.е. ѕќ—Ћ≈ завершени€ WB
      // (структурно: из WB в T1H попадаешь только через IDLE) Ч adm.
      // addr_latch Ќ≈ может перезаписатьс€ посреди импульса (п.6 шапки).
      if (al_cap) begin
