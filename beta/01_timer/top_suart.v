      end
      if (wr_cap) begin
        bus_reg <= A;                    // данные записи (CPU держит до WR#(вверх))
        if (IOM) begin                   // запись в порт: декод по тройке A2,A1,A0 (Task 34)
          case (addr_latch[2:0])
            3'b000: seg_q <= A;          // 00h: сегменты
            3'b001: begin                // 01h: разр€ды + SND
              dig_q <= A[3:0];
              snd_q <= A[4];
            end
            3'b010: kbcol_q <= A[3:0];   // 02h: колонки клавиатуры
            default: ;                   // 03h чтение; 04h = “ј…ћ≈– (загрузка tmr_cnt в своЄм always, beta/01_timer); 05h-07h резерв
          endcase
        end
      end
      // --- трекинг стробов ---
      if (state == S_T2 && !RDn) rd_seen <= 1'b1;
      if (wr_cap) wr_seen <= 1'b1;
      // --- переходы ---
      // v3: ALE ќЅ–џ¬ј≈“ только T2 (защита от глюка); в WB1..WB4 Ќ≈
      // вмешиваетс€ Ч импульс /WE защищЄн (п.4 шапки).
      if (ALE && state == S_T2 && !((wr_seen && WRn) || (rd_seen && RDn))) begin
        state   <= S_IDLE;
        rd_seen <= 1'b0;
        wr_seen <= 1'b0;
      end else begin
        case (state)
          S_IDLE: if (ALE) state <= S_T1H;
          S_T1H:  if (!ALE) state <= S_T2;
          S_T2: begin
