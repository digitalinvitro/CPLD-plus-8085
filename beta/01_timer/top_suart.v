  assign WE_n  = !in_welo;
  assign CS1   = 1'b1;

  //=============================================================
  // ѕоддержка CPU (І3, ред. Task 19) + soft-UART транзиты (Task 70-a).
  // ƒержатели '0' (TRAP, RST6.5/5.5, INTR, HOLD, A16-A18) удалены
