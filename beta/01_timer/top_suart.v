  assign RST75 = RST75_r;
  assign READY = 1'b1;          // без wait-state Ч иначе вечные TW
  // “ранзиты soft-UART (Task 70-a) + TX-маска (v3):
  assign SID = RX;              // приЄм:  CH340G.TXD (P38) -> CPU.SID (P73), RIM 20h
  assign TX  = (cpu_rst || txm_mask_q) ? 1'b1 : SOD;
                                // передача: CPU.SOD (P72) -> CH340G.RXD (P39), SIM 30h;
                                // в покое прошивка держит SOD='1' (stop/idle); пока
                                // сброс/маска Ч TX='1' (чистый idle, без BREAK)

  //=============================================================
  // »ндикаци€ и звук: выходы инвертированы (общий анод, активный 0)
  //=============================================================
  assign seg = ~seg_q;
  assign dig = ~dig_q;
  assign SND = snd_q;
  // Task 34: колонки клавиатуры Ч зарегистрированные выходы, пр€мые уровни
