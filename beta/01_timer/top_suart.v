  // v3.3b3: ’–јЌ»ћџ≈ —“–ќЅџ (* keep *). ”рок двух провальных фитов
  // (п.8, п.10, п.11 шапки): когда фиттеру тесно, он перестаЄт выносить
  // общие стробы в хелперы и схлопывает их в приЄмники Ч уравнени€
  // распухают по FB-входам, регистры высел€ютс€ из пиновых ћ— в BUFR.
  // ‘иксируем факторинг v3.2 ¬ »—’ќƒЌ» ≈: каждый строб = 1 ћ—,
  // приЄмники вид€т 1-2 входа вместо 5-9.
  (* keep = "TRUE" *) wire al_cap = (state == S_T1H) && ALE;  // захват addr_latch
  (* keep = "TRUE" *) wire bus_rd = al_cap && !IOM;           // захват bus_reg с D-сети
  (* keep = "TRUE" *) wire wr_cap = (state == S_T2) && !WRn;  // захваты с A-сети

  //=============================================================
  // beta/01_timer: »Ќ“≈–¬јЋ№Ќџ… “ј…ћ≈– -> RST 7.5 (P75), v3.3b3.
  // ѕрескалер = txm_cnt[7:0] (v3.3b3: свободный счЄт вверх от por_ce,
  // прежний {tmr_hi, por_cnt} удалЄн, -2 ћ—) Ч тик раз в 256 x 200 нс =
  // 51,2 мкс (обЄртка 7Fh->80h; фаза та же: 1-й тик через 128 por_ce
  // после конца POR). —чЄтчик: вниз по
  // тикам, —“ќѕ в 0; загрузка N при OUT 04h из bus_reg (данные там
  // захвачены тем же фронтом, что у seg_q; CPU держит данные до
