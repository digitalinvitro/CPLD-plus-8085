  //=============================================================
  assign RESET_IN = ~(RST | por_run); // активный 0 по даташиту: 0 = сброс CPU (SW20 нажата или POR)
  // beta/01_timer v3.3b2: RST 7.5 Ч из –≈√»—“–ј RST75_r (на ноге нет
  // комбинационного глитча декода нул€); CPU защЄлкивает ‘–ќЌ“, так что
