; =====================================================================
; beta/01_timer -- ДИАГНОСТИКА ВЕРСИЯ 5: «КРИЧАЩИЙ БАННЕР»
; (дискриминатор «одиночный кадр vs тракт» после находки cont-echo-14/15).
; Интервальный таймер CPLD (beta v3.3b3, порт 04h -> RST 7.5),
; 2400 бод (TMR_N=8), 8N1.
;
; ПОСТАНОВКА. 10-24: баннер '>' ДОХОДИЛ до терминала (uart_echo_test v1,
; diag1-3 -- баннер жив во всех отчётах), TX-тракт закрыт ПАССОМ
; timer_test_uart v4. С 10-25: вместо '>' в терминал приходит 00, при
; этом (проверено ридбеками 26-10): файл корректен, в чипе diag4
; байт-в-байт, исполнение идёт (дисплей 8.8.8.8 -> 0000 = кадр прошёл
; все фазы). Дифференциальный факт владельца 26-10: timer_test_uart
; (НЕПРЕРЫВНЫЙ поток кадров) работает, diag4 (ОДИН кадр ~0,6 мс после
; отпускания RESET, сам сброс по осциллограмме ADS00003.BMP ~125 мс)
; -- нет. Единственное терминально-видимое отличие пары --
; ОДНОКРАТНОСТЬ кадра. diag5 превращает баннер в ПОТОК, не трогая
; ни байта TX-автомата:
;
;   1) ISR (0000h-00FFh) = diag4 БАЙТ-В-БАЙТ (ре-арм, вентиль E,
;      TX-автомат, RX-автомат);
;   2) init MAIN (0100h-0129h) = diag4 БАЙТ-В-БАЙТ;
;   3) хвост MAIN заменён: баннер '>' повторяется ВЕЧНО с паузой
;      ~1024 прохода DMUX (~70-140 мс, зависит от такта CPU);
;   4) RX ПОЛНОСТЬЮ ОТКЛЮЧЁН: E=0 навсегда -> вентиль ISR никогда
;      не пускает RX-ветвь, RIM не исполняется, эхо не собирается --
;      тест ЧИСТО про TX;
;   5) DMUX/SEGTAB (0170h-01DFh) = diag4 БАЙТ-В-БАЙТ.
;
; ЧТО НАБЛЮДАТЬ (терминал 2400 8N1, HEX-режим, порт открыть ДО RESET):
;   1. Поток '3E' каждые ~70-150 мс, дисплей считает [кадры][0][0][0]
;      -> TX-тракт ЦЕЛ. Вывод: в diag4 одиночный кадр терялся, пока
;      порт/драйвер/терминал не готовы после RESET; вопрос закрыт,
;      дальше вернуться к эху на повторяющемся баннере.
;   2. Периодические '00' БЕЗ '3E' -> на проводе РЕАЛЬНЫЙ ноль с
;      периодом кадров: кадр выходит из SOD битым (смотреть U3.4
;      осциллографом; противоречит рабочему timer_test_uart ->
;      перепроверить COM/кабель/точку подключения).
;   3. Терминал молчит, дисплей СЧИТАЕТ -> кадр не доходит до моста:
;      осциллограф P39/U6.2 (разрыв после CPLD).
;   4. Терминал молчит, дисплей «0.0.0.0.» застыл -> образ не
;      исполняется: ридбек/перепрошивка.
;   5. Дисплей «8.8.8.8» навсегда -> MAIN не стартовал (ПЗУ/шина/сброс).
;
; Дисплей: DIG0 = B = счётчик отправленных кадров mod 16 (считает
; ~7-13 раз/с); DIG1..3 = 0. Во время кадра подсвечен последний разряд.
;
; ОСЦИЛЛОГРАФ: на 100 мс/дел линия TX (P39/U6.2) покажет периодические
; пачки активности каждые ~0,7-1,5 деления -- не пропустит даже
; медленный одиночник; на 1-2 мс/дел виден целый кадр (старт 0,42 мс,
; d1..d5 ~2,1 мс, d6/d7+стоп). Эталон кадра '3E' @2400:
;   LOW 0,83 мс | HIGH 2,08 мс | LOW 0,83 мс | HIGH (стоп/idle).
;
; ГОНКИ (разобрано): ISR не сохраняет PSW; падение флагов на границах
; циклов ожидания здесь НЕОПАСНО: перезарядка D/C идёт только после
; длинной паузы, когда любой «недобитый» кадр давно дошёл до C=FFh.
; Очередь QCNT=8007h навсегда 0 -> каждый стоп-фаза даёт TXDONE.
;
; Сборка (из этой папки):
;   python3 asm85.py uart_echo_diag5.asm -o uart_echo_diag5.hex -l uart_echo_diag5.lst
; UTF-8 мастер: scripts/uart/uart_echo_diag5.utf8.asm
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B.
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
RXN1    EQU TMR_N//2        ; (в diag5 не используется -- RX отключён)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- 5.5/6.5 маскировать,
                            ; 7.5 разрешить; R7.5=1 -- латч сброшен
SIMLR   EQU 08h             ; (в diag5 не используется -- RX отключён)

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит)
DIGP    EQU 01h             ; DIG: D3-D0 разряды (D4 = SND -- не трогаем)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)

; ---- ОЗУ (SRAM с 8000h, стек на FFFF -- конфликтов нет) ----
MUXI    EQU 8000h           ; индекс разряда дисплея 0..3
BYTE0   EQU 8001h           ; (в diag5 всегда 0)
TSB     EQU 8002h           ; (в diag5 всегда 0)
QBUF    EQU 8004h           ; (в diag5 всегда 0)
SSELF   EQU 8006h           ; (в diag5 всегда 0)
QCNT    EQU 8007h           ; счётчик очереди эха -- навсегда 0

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; Вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = 003Ch-003Fh); ре-арм
; ПЕРВЫМ действием: период = ровно N тиков, длина ISR в сетку не входит.
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ СЕТКИ (7 тактов)
        OUT TMRP            ; (10 тактов) -- 8 квантов = 1 бит

; ---- ISR: вентиль RX -> TX-автомат -> RX-автомат ----
        ORG 0040h
        MOV A,E             ; вентиль: RX активен (E>0)?
        ORA A
        JZ TXRUN
        JMP RX              ; RX активен: TX НЕ двигаем (SOD держит уровень)
TXRUN:  MOV A,C             ; --- TX-автомат ---
        CPI 0FFh            ; 0FFh = покой?
        JZ TXIDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ TXST
        CPI 0Bh             ; 0Bh = холостой бит (урок v4): SOD=1
        JZ TXIDLBIT
        CPI 1               ; 01h = стоп-бит
        JZ TXSP
; --- фаза данных (d0..d7): байт в D ---
        MOV A,D
        RRC                 ; A7 <- D0
        ANI 80h
        ORI 40h             ; SDE=1; MSE=0 -- маски не трогаем
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху
        MOV A,D
        RAR                 ; D >>= 1
        MOV D,A
        JMP RX
TXST:   MVI A,40h           ; SOD=0 -- старт-бит (D заряжен заранее)
        SIM
        JMP RX
TXIDLBIT: MVI A,0C0h        ; холостой бит: SOD=1 (C уже 0Bh ->
        SIM                 ;   следующий DCR даст 0Ah = старт)
        JMP RX
TXSP:   MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        LDA QCNT            ; очередь таймлайна?
        ORA A
        JZ TXDONE
        DCR A
        STA QCNT            ; следующий байт очереди:
        MOV D,A             ;   было 2 -> QBUF, было 1 -> QBUF+1
        CPI 1
        MVI L,QBUF & 0FFh
        JZ TXSP1
        INR L
TXSP1:  MVI H,QBUF//256
        MOV A,M
        MOV D,A
        MVI C,0Ch           ; холостой бит, затем старт очередного
        JMP RX
TXDONE: MVI C,0FFh          ; очередь пуста -- покой
        JMP RX
TXIDLE: MVI A,0C0h          ; покой: SOD=1
        SIM
; --- RX-автомат: каждая выборка -> бит таймлайна TSB; данные ещё и в L ---
RX:     MOV A,E
        ORA A
        JZ RXE              ; E=0 -- приём не активен
        CPI 12              ; 1-й интервал = старт-верификация (мимо L)
        JZ RXBIT
        CPI 4               ; E=3..1 -- хвост (мимо L)
        JM RXBIT
        RIM                 ; SID -> A7 (транзит RX->SID в CPLD)
        ANI 80h
        RLC                 ; v4: CY <- БИТ ЛИНИИ (в v3 был RAR: SID
        MOV A,L             ;   уезжал в A6, в CY попадал 0!)
        RAR                 ; L = (L>>1) | бит -- d0..d7, LSB-first
        MOV L,A
        RLC                 ; v4: CY <- бит снова (A7 сдвинутого байта)
        JMP RXPACK
RXBIT:  RIM                 ; старт/хвост: только в таймлайн
        ANI 80h
        RLC                 ; v4: CY <- бит линии
RXPACK: PUSH H              ; v4: L = накопитель байта -- LHLD TSB
        LHLD TSB            ;   его затирает; HL спасаем на упаковку
        MOV A,H
        RAL
        MOV H,A
        MOV A,L
        RAL
        MOV L,A
        SHLD TSB
        POP H               ; v4: байт возвращён в L
        DCR E               ; интервал отработан
        MOV A,E
        ORA A
        JNZ RXE             ; кадр не кончился
        ; --- РЕЛИЗ: 12 выборок собраны (E=0), L = байт, HL = TSB ---
        MOV A,C             ; TX свободен?
        CPI 0FFh
        JNZ RXE             ; занят -- байт отбрасываем (v1, без очереди)
        MOV A,L             ; принятый байт
        STA BYTE0           ; ДИАГ: байт на дисплей
        MOV D,A             ; эхо, кадр 1 = байт
        LDA TSB             ; v4: в ОЗУ 8002h = tl-hi, 8003h = tl-lo
        STA QBUF            ;   (так ложится H-first цепочка RAL);
        LDA TSB+1           ;   LHLD в релизе переворачивал пару ->
        STA QBUF+1          ;   эхо шло [tl-lo][tl-hi]. Теперь прямо:
        MVI A,2             ;   [байт][tl-hi][tl-lo] по протоколу
        STA QCNT
        MVI C,0Bh           ; следующий фронт = старт-байт эха
RXE:    EI
        RET

; ---- MAIN ----
        ORG 0100h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2)
        MVI A,0C0h          ; SOD=1 (idle) -- гасим возможный BREAK
        SIM                 ; после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся
        MVI A,0             ; ДИАГ: ОЗУ -- с нуля (дисплей «0.0.0.0.»)
        STA MUXI
        STA BYTE0
        STA TSB
        STA TSB+1
        STA SSELF
        STA QCNT
        MVI B,0             ; счётчик отправленных кадров
        MVI E,0             ; RX ПОЛНОСТЬЮ ОТКЛЮЧЁН (вентиль ISR навсегда TX)
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён
        MVI D,'>'           ; баннер-символ (один)
        MVI C,0Bh           ; фаза: следующий фронт = старт '>'
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера
        EI
BAN:    MOV A,C             ; ждём конца кадра (C -> 0FFh): голый спин,
        CPI 0FFh            ; как в diag4 -- шина во время кадра молчит
        JNZ BAN
; --- diag5: пауза ~1024 прохода DMUX (~70-140 мс), баннер повторяется ---
REARM:  LXI H,0400h         ; счётчик паузы
DLAY:   CALL DMUX           ; дисплей живёт в паузе (C=FFh, ISR спокоен)
        DCX H
        MOV A,L
        ORA H
        JNZ DLAY
        INR B               ; кадр отправлен: счётчик -> DIG0 дисплея
        MVI D,'>'           ; баннер-символ снова
        MVI C,0Bh           ; следующий фронт = старт
        JMP BAN

; ---- ДИАГНОСТИКА: мультиплексия дисплея (по разряду за вызов) ----
; DIG0 = B mod 16 (отправленные кадры), DIG1 = SSELF (=0), DIG2/DIG3 =
; BYTE0 (=0). ПОРТИТ ТОЛЬКО A/флаги (HL через PUSH/POP).
        ORG 0170h
DMUX:   LDA MUXI
        INR A
        ANI 3
        STA MUXI
        CPI 1
        JZ DMX1
        CPI 2
        JZ DMX2
        CPI 3
        JZ DMX3
        MOV A,B             ; индекс 0: счётчик кадров
        ANI 0Fh
        CALL HSEG
        MVI A,01h
        OUT DIGP
        RET
DMX1:   LDA SSELF           ; индекс 1: (в diag5 всегда 0)
        ANI 0Fh
        CALL HSEG
        MVI A,02h
        OUT DIGP
        RET
DMX2:   LDA BYTE0           ; индекс 2: мл. ниббл байта (=0)
        ANI 0Fh
        CALL HSEG
        MVI A,04h
        OUT DIGP
        RET
DMX3:   LDA BYTE0           ; индекс 3: ст. ниббл байта (=0)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL HSEG
        MVI A,08h
        OUT DIGP
        RET
HSEG:   PUSH H              ; A = ниббл -> OUT SEGP = паттерн; HL цел
        MOV H,A
        MVI L,SEGTAB & 0FFh
        ADD L               ; lo + ниббл: переноса нет (lo=D0h)
        MOV L,A
        MVI H,SEGTAB//256
        MOV A,M
        POP H
        OUT SEGP
        RET

        ORG 01D0h           ; lo = D0h: D0h+0Fh без переноса -- ADD L точен
SEGTAB: DB 3Fh,06h,5Bh,4Fh,66h,6Dh,7Dh,07h  ; '0'-'7' (a..g, dp=0)
        DB 7Fh,6Fh,77h,7Ch,39h,5Eh,79h,71h  ; '8'-'F'
        END
