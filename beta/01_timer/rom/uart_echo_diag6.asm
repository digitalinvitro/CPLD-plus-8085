; =====================================================================
; beta/01_timer -- ДИАГНОСТИКА ВЕРСИЯ 6: «МОНИТОР SID»
; (последний дискриминатор после ПАССА diag5, cont-echo-16).
; Интервальный таймер CPLD (beta v3.3b3, порт 04h -> RST 7.5),
; 2400 бод (TMR_N=8), 8N1.
;
; ПОСТАНОВКА. Результат diag5 на железе 26-10: поток '>' каждые
; ~70-150 мс + счётчик кадров на DIG0 -- исход N1 из таблицы:
; TX-тракт ЦЕЛ (8085 SIM/SOD -> CPLD P72/P39 -> CH340G -> терминал).
; Остался ровно один неизвестный: УРОВЕНЬ НА SID (RX-вход, U3.5,
; CPLD P73 <- транзит RX P38 <- провод «TX» CH340G.TXD).
; Факт diag4: при SID=0 цикл POLL ловит «старт-бит» на каждом
; проходе, 12 выборок дают L=00, и эхо-автомат выстреливает
; 00 00 00 (~170 Б/с -- совпало со счётчиком 149 на скрине
; терминала). При SID=1 diag4 молчит (0000 на дисплее).
; diag6 показывает уровень SID ЖИВЬЁМ на дисплее -- без приборов:
;
;   1) ISR (0000h-00FFh) = diag4/diag5 БАЙТ-В-БАЙТ (ре-арм,
;      TX-автомат; RX-ветвь мертва: E=0 навсегда);
;   2) init MAIN (0100h-0129h) = diag4/diag5 БАЙТ-В-БАЙТ: один
;      баннер '>' сразу после EI -- маркер «сброс прошёл, образ
;      исполняется» (больше TX молчит: C=FFh -> TXIDLE, SOD=1);
;   3) хвост MAIN -- ПЛОТНЫЙ цикл опроса (~25-50 мкс/проход:
;      старт-бит 0,42 мс ловится ГАРАНТИРОВАННО, 8+ выборок на
;      бит), DMUX вызывается на каждом проходе -- дисплей живёт;
;   4) DMUX/HSEG/SEGTAB (0170h-01DFh) = diag4/diag5 БАЙТ-В-БАЙТ,
;      ничего менять не пришлось: DIG0 уже читает B, DIG1 --
;      SSELF, DIG2/3 -- байт BYTE0 (мл./ст. ниббл в hex).
;
; ДИСПЛЕЙ (обновляется каждые ~25-50 мкс, числа hex):
;   DIG0 = живой уровень SID: '1' = idle (высокий), '0' = низкий;
;   DIG1 = счётчик нулевых выборок (mod 16): КРУТИТСЯ, пока линия
;          низкая; заморожен на 0, если SID всегда 1; ЛЮБАЯ
;          активность с линии НАВСЕГДА уводит его из нуля --
;          «датчик движения» на RX;
;   DIG2/3 = сырое A после RIM (hex): A7=SID, A6=латч RST7.5,
;          A5/A6.5/A5.5-pending, A3=IE, A2/A1/A0=маски M7.5/M6.5/M5.5.
;
; ТАБЛИЦА ИСХОДОВ (терминал 2400 8N1 открыть ДО RESET):
;   1. [1][0][8B] + один '>' при сбросе
;      -> SID=1, IE=1, маски верны: тракт RX до CPU ИСПРАВЕН.
;         Флуд 00 в diag4 = линия была низкой ТОГДА (контакт/провод):
;         перетыкнуть провод CH340G.TXD->P38, вернуть diag4, тест эха.
;   2. [0][крутится][0B]
;      -> SID=0 ПОСТОЯННО: линия прижата. Мультиметр на проводе
;         «TX» (CH340G.TXD) и на P38: ожидание ~3,3-5 В при открытом
;         терминале. Проверить: тот ли пин CH340G (TXD, не RTS/DTR),
;         питание CH340G, пайка P38, нет ли КЗ на корпус.
;   3. [1][0][83] -> IE=0: прерывания выключены -- НЕ должно
;      (diag5 с тем же init работал); разбираться отдельно.
;   4. Набор символов в терминале: DIG0 мигает на '0', DIG1
;      прибавляет -> линия ЖИВАЯ и доходит до CPU: RX-путь цел,
;      можно возвращаться к diag4 (эхо) или main-прошивке.
;   5. DIG3 = 'C' (RIM=CBh) -> латч RST7.5 поймался на чтении --
;      редкая норма (бит сбросится на следующем ISR).
;
; ГОНКИ (разобрано): ISR в покое (E=0, C=FFh) трогает ТОЛЬКО A и
; флаги -- HSEG/DMUX/HL и B не задеваются; флаги перед JNZ SIDOK
; может испортить только «залетевший» между MOV B,A и JNZ ISR --
; вред одном экрану на один проход (ложный счёт/пропуск), следующий
; проход исправляет; MUXI хранится до ветвления -- состояние не
; теряется. Очередь QCNT=8007h навсегда 0 -> TXDONE всегда.
;
; Сборка (из этой папки):
;   python3 asm85.py uart_echo_diag6.asm -o uart_echo_diag6.hex -l uart_echo_diag6.lst
; UTF-8 мастер: scripts/uart/uart_echo_diag6.utf8.asm
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B.
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
RXN1    EQU TMR_N//2        ; (в diag6 не используется -- RX отключён)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- 5.5/6.5 маскировать,
                            ; 7.5 разрешить; R7.5=1 -- латч сброшен
SIMLR   EQU 08h             ; (в diag6 не используется -- RX отключён)

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит)
DIGP    EQU 01h             ; DIG: D3-D0 разряды (D4 = SND -- не трогаем)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)

; ---- ОЗУ (SRAM с 8000h, стек на FFFF -- конфликтов нет) ----
MUXI    EQU 8000h           ; индекс разряда дисплея 0..3
BYTE0   EQU 8001h           ; ДИАГ: сырое A после RIM -> DIG2/DIG3
TSB     EQU 8002h           ; (в diag6 всегда 0)
QBUF    EQU 8004h           ; (в diag6 всегда 0)
SSELF   EQU 8006h           ; ДИАГ: счётчик нулевых выборок SID -> DIG1
QCNT    EQU 8007h           ; счётчик очереди эха -- навсегда 0

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; Вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = 003Ch-003Fh); ре-арм
; ПЕРВЫМ действием: период = ровно N тиков, длина ISR в сетку не входит.
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ СЕТКИ (7 тактов)
        OUT TMRP            ; (10 тактов) -- 8 квантов = 1 бит

; ---- ISR: вентиль RX -> TX-автомат -> RX-автомат ----
        ORG 0040h
        MOV A,E             ; вентиль: RX активен (E>0)?
        ORA A
        JZ TXRUN
        JMP RX              ; RX активен: TX НЕ двигаем (SOD держит уровень)
TXRUN:  MOV A,C             ; --- TX-автомат ---
        CPI 0FFh            ; 0FFh = покой?
        JZ TXIDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ TXST
        CPI 0Bh             ; 0Bh = холостой бит (урок v4): SOD=1
        JZ TXIDLBIT
        CPI 1               ; 01h = стоп-бит
        JZ TXSP
; --- фаза данных (d0..d7): байт в D ---
        MOV A,D
        RRC                 ; A7 <- D0
        ANI 80h
        ORI 40h             ; SDE=1; MSE=0 -- маски не трогаем
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху
        MOV A,D
        RAR                 ; D >>= 1
        MOV D,A
        JMP RX
TXST:   MVI A,40h           ; SOD=0 -- старт-бит (D заряжен заранее)
        SIM
        JMP RX
TXIDLBIT: MVI A,0C0h        ; холостой бит: SOD=1 (C уже 0Bh ->
        SIM                 ;   следующий DCR даст 0Ah = старт)
        JMP RX
TXSP:   MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        LDA QCNT            ; очередь таймлайна?
        ORA A
        JZ TXDONE
        DCR A
        STA QCNT            ; следующий байт очереди:
        MOV D,A             ;   было 2 -> QBUF, было 1 -> QBUF+1
        CPI 1
        MVI L,QBUF & 0FFh
        JZ TXSP1
        INR L
TXSP1:  MVI H,QBUF//256
        MOV A,M
        MOV D,A
        MVI C,0Ch           ; холостой бит, затем старт очередного
        JMP RX
TXDONE: MVI C,0FFh          ; очередь пуста -- покой
        JMP RX
TXIDLE: MVI A,0C0h          ; покой: SOD=1
        SIM
; --- RX-автомат: каждая выборка -> бит таймлайна TSB; данные ещё и в L ---
RX:     MOV A,E
        ORA A
        JZ RXE              ; E=0 -- приём не активен (в diag6 ВСЕГДА)
        CPI 12              ; 1-й интервал = старт-верификация (мимо L)
        JZ RXBIT
        CPI 4               ; E=3..1 -- хвост (мимо L)
        JM RXBIT
        RIM                 ; SID -> A7 (транзит RX->SID в CPLD)
        ANI 80h
        RLC                 ; v4: CY <- БИТ ЛИНИИ (в v3 был RAR: SID
        MOV A,L             ;   уезжал в A6, в CY попадал 0!)
        RAR                 ; L = (L>>1) | бит -- d0..d7, LSB-first
        MOV L,A
        RLC                 ; v4: CY <- бит снова (A7 сдвинутого байта)
        JMP RXPACK
RXBIT:  RIM                 ; старт/хвост: только в таймлайн
        ANI 80h
        RLC                 ; v4: CY <- бит линии
RXPACK: PUSH H              ; v4: L = накопитель байта -- LHLD TSB
        LHLD TSB            ;   его затирает; HL спасаем на упаковку
        MOV A,H
        RAL
        MOV H,A
        MOV A,L
        RAL
        MOV L,A
        SHLD TSB
        POP H               ; v4: байт возвращён в L
        DCR E               ; интервал отработан
        MOV A,E
        ORA A
        JNZ RXE             ; кадр не кончился
        ; --- РЕЛИЗ: 12 выборок собраны (E=0), L = байт, HL = TSB ---
        MOV A,C             ; TX свободен?
        CPI 0FFh
        JNZ RXE             ; занят -- байт отбрасываем (v1, без очереди)
        MOV A,L             ; принятый байт
        STA BYTE0           ; ДИАГ: байт на дисплей
        MOV D,A             ; эхо, кадр 1 = байт
        LDA TSB             ; v4: в ОЗУ 8002h = tl-hi, 8003h = tl-lo
        STA QBUF            ;   (так ложится H-first цепочка RAL);
        LDA TSB+1           ;   LHLD в релизе переворачивал пару ->
        STA QBUF+1          ;   эхо шло [tl-lo][tl-hi]. Теперь прямо:
        MVI A,2             ;   [байт][tl-hi][tl-lo] по протоколу
        STA QCNT
        MVI C,0Bh           ; следующий фронт = старт-байт эха
RXE:    EI
        RET

; ---- MAIN ----
        ORG 0100h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2)
        MVI A,0C0h          ; SOD=1 (idle) -- гасим возможный BREAK
        SIM                 ; после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся
        MVI A,0             ; ДИАГ: ОЗУ -- с нуля
        STA MUXI
        STA BYTE0
        STA TSB
        STA TSB+1
        STA SSELF
        STA QCNT
        MVI B,0             ; DIG0 -- станет уровнем SID на 1-м RIM
        MVI E,0             ; RX ПОЛНОСТЬЮ ОТКЛЮЧЁН (вентиль ISR навсегда TX)
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён
        MVI D,'>'           ; маркер-баннер (ОДИН кадр после EI)
        MVI C,0Bh           ; фаза: следующий фронт = старт '>'
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера
        EI
; --- diag6: ПЛОТНЫЙ цикл монитора SID (~25-50 мкс/проход) ---
SIDLP:  RIM                 ; A = {SID,латчи,IE,маски}
        STA BYTE0           ; сырой байт -> DIG2/DIG3 (hex)
        RLC                 ; SID (A7) -> бит0 (и в CY)
        ANI 01h
        MOV B,A             ; DIG0 = '0'/'1' -- живой уровень линии
        JNZ SIDOK
        LDA SSELF           ; SID=0: счётчик активности ++ (крутится,
        INR A               ; пока линия низкая; любая активность с
        STA SSELF           ; линии навсегда уводит его из нуля)
SIDOK:  CALL DMUX           ; дисплей (ISR в покое трогает только A/флаги)
        JMP SIDLP

; ---- ДИАГНОСТИКА: мультиплексия дисплея (по разряду за вызов) ----
; DIG0 = B (уровень SID 0/1), DIG1 = SSELF (активность на линии),
; DIG2/DIG3 = BYTE0 = сырое RIM (мл./ст. ниббл, hex). ПОРТИТ ТОЛЬКО
; A/флаги (HL через PUSH/POP).
        ORG 0170h
DMUX:   LDA MUXI
        INR A
        ANI 3
        STA MUXI
        CPI 1
        JZ DMX1
        CPI 2
        JZ DMX2
        CPI 3
        JZ DMX3
        MOV A,B             ; индекс 0: уровень SID
        ANI 0Fh
        CALL HSEG
        MVI A,01h
        OUT DIGP
        RET
DMX1:   LDA SSELF           ; индекс 1: активность на линии
        ANI 0Fh
        CALL HSEG
        MVI A,02h
        OUT DIGP
        RET
DMX2:   LDA BYTE0           ; индекс 2: мл. ниббл RIM
        ANI 0Fh
        CALL HSEG
        MVI A,04h
        OUT DIGP
        RET
DMX3:   LDA BYTE0           ; индекс 3: ст. ниббл RIM
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL HSEG
        MVI A,08h
        OUT DIGP
        RET
HSEG:   PUSH H              ; A = ниббл -> OUT SEGP = паттерн; HL цел
        MOV H,A
        MVI L,SEGTAB & 0FFh
        ADD L               ; lo + ниббл: переноса нет (lo=D0h)
        MOV L,A
        MVI H,SEGTAB//256
        MOV A,M
        POP H
        OUT SEGP
        RET

        ORG 01D0h           ; lo = D0h: D0h+0Fh без переноса -- ADD L точен
SEGTAB: DB 3Fh,06h,5Bh,4Fh,66h,6Dh,7Dh,07h  ; '0'-'7' (a..g, dp=0)
        DB 7Fh,6Fh,77h,7Ch,39h,5Eh,79h,71h  ; '8'-'F'
        END
