; =====================================================================
; beta/01_timer -- ТЕСТ-ПРОШИВКА ПЗУ: ПОЛНОЦЕННЫЙ UART (ПРИЁМ-ПЕРЕДАЧА,
; ЭХО) + ДИАГНОСТИКА ВЕРСИЯ 4: v3 + ИСПРАВЛЕННЫЙ ВВОД.
; Интервальный таймер CPLD (beta v3.3b3, порт 04h -> RST 7.5),
; 2400 бод (TMR_N=8), 8N1.
;
; ЭТО diag v3 БЕЗ ИЗМЕНЕНИЯ ПРОТОКОЛА, НО С ИСПРАВЛЕННЫМ ПРИЁМОМ.
; Дамп ПЗУ владельца (10-24) подтвердил: образ = diag3, а поведение --
; эхо [00][00][00] на ЛЮБОЙ ввод, BYTE0 = 00 всегда. Причина найдена
; в коде выборки, две ошибки:
;
;   БАГ 1 (фатальный): в обеих ветвях выборки стоял RAR с комментарием
;   "CY <- бит линии". RAR кладёт в CY бит A0 (=0), а SID (A7) уезжает
;   в A6 и уничтожается следующим MOV A,L / LHLD TSB. В CY попадал
;   ноль => TSB паковал нули, L не получал бит ниоткуда => ЛЮБОЙ кадр
;   декодировался как 00. Исправлено: RLC (CY <- A7 = SID).
;
;   БАГ 2 (скрытый): LHLD TSB в RXPACK каждый тик ПЕРЕЗАПИСЫВАЕТ L из
;   ОЗУ (8003h) -- накопитель байта в L не доживал бы до релиза даже с
;   рабочей выборкой (на релизе вышел бы tl-lo, а не байт). Исправлено:
;   PUSH H перед упаковкой таймлайна, POP H после SHLD.
;
;   БАГ 3 (порядок эха, пойман instruction-level симуляцией): упаковка
;   TSB идёт цепочкой RAL "H-первым" (MOV A,H/RAL/MOV H,A/MOV A,L/RAL/
;   MOV L,A) -- это (V<<1)|бит для пары V=(L:H), поэтому в ОЗУ лежит
;   8002h = tl-hi, 8003h = tl-lo (как и задокументировано). Но релиз
;   копировал пару через LHLD TSB / MOV A,H / MOV A,L: LHLD даёт
;   L=8002h=tl-hi, H=8003h=tl-lo, а в очередь уходил H (tl-lo) ПЕРВЫМ
;   -> эхо [байт][tl-lo][tl-hi] ('a' дала бы 61 37 04 вместо 61 04 37).
;   Исправлено: прямые LDA/STA в порядке ОЗУ: LDA TSB (tl-hi) -> QBUF,
;   LDA TSB+1 (tl-lo) -> QBUF+1.
;
;   ПРИМЕЧАНИЕ: TX-часть (SIM 40h = старт, C0h = единица/mark, т.е.
;   SDE=A6, SOD-data=A7) НЕ ТРОНУТА -- раскладка подтверждена
;   аппаратно (баннер timer_test_uart v4 и эхо 'ю' доходили).
;
; РЕЗУЛЬТАТ ВИДЕН В HEX-ТЕРМИНАЛЕ: на каждый принятый кадр плата шлёт
; ТРИ байта: [принятый байт][таймлайн hi][таймлайн lo].
;
; Файл в кодировке CP1251 (как все исходники проекта, кроме asm85.py).
; UTF-8 мастер: scripts/uart/uart_echo_diag4.utf8.asm
;
; Сборка (из этой папки):
;   python3 asm85.py uart_echo_diag4.asm -o uart_echo_diag4.hex -l uart_echo_diag4.lst
;
; Железо: retro_PCLD_board V2 + CPLD beta v3.3b3 + USB-мост CH340G (U6).
; CPLD НЕ МЕНЯЛСЯ (транзит SID <= RX безусловен, фит проверен по .rpt:
; RX = вход P38, SID = выход P73, SOD = вход P72, TX = выход P39).
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B.
;
; КАК ЧИТАТЬ ЭХО (hex-терминал, вводить по ОДНОМУ символу):
;   [байт][tl-hi][tl-lo], таймлайн = 12 бит MSB-first:
;   tl-hi = 0000 s d0 d1 d2, tl-lo = d3 d4 d5 d6 d7 t1 t2 t3,
;   где s = выборка старта (~0,5 бита; должна быть 0), t1..t3 = хвост
;   (стоп/idle; должны быть 1,1,1).
;   ОЖИДАНИЯ при 2400 (теперь достижимы; проверены instruction-level
;   симуляцией sim_diag4_isr.py):
;                       'a' -> 61 04 37;  'o' -> 6F 07 B7;
;                       Enter -> 0D 05 87;  '3' -> 33 06 67.
;   00 00 00  -- линия НИЗКАЯ ВО ВСЕХ 12 точках (в т.ч. на старте!)
;                кадр "съеден" целиком: линию прижимает на ~5 мс;
;   s=1 (tl-hi >= 08h) -- пойманный "старт" вернулся в 1 (глитч/чужой
;                кадр), данные читались из единиц;
;   хвост 0 (tl-lo & 07 != 07) -- сетка уползла к концу кадра;
;   сдвиг узора при верном старте -- сетка/скорость источника не 2400.
; ДИСПЛЕЙ: [B = счётчик чистых стартов mod 16]
;          [S = счётчик ЗАХВАТОВ ВО ВРЕМЯ СВОЕГО ЭХА mod 16 (S>0 =
;           плата ловит собственную передачу -- петля/самозапуск!)]
;          [байт lo][байт hi].  После RESET: «0.0.0.0.».
;
; ТАЙМИНГ ПРИЁМА (сетка d0..d7 НЕ ИЗМЕНИЛАСЬ): MAIN ловит старт (RIM,
; DI), OUT TMRP <- RXN1 = N/2 = 4 кванта (0,5 бита) -> SIM 08h (атомарный
; выброс латча) -> MVI E,12 -> EI. Первый фронт через (3..4) кванта:
; выборка s на ~0,43-0,55 бита (середина старта). Далее ре-арм в векторе
; 003Ch = ровно 8Q: d0 на 1,5 бита КАК РАНЬШЕ, d7 на 8,5 бита, хвост
; 9,5/10,5/11,5 бита. Кадр = 12 интервалов, релиз при E=0.
; Каждая выборка пакуется в TSB (ОЗУ 8002h/8003h, MSB-first) и в
; накопитель L (LSB-first): RLC -> RAR в L -> RLC -> PUSH H / LHLD /
; RAL / RAL / SHLD / POP H, ~35 мкс на интервал (период 8Q = 405 мкс --
; запас).
;
; ЭХО: TX-автомат v4 однобайтовый + ОЧЕРЕДЬ 2 байта таймлайна в ОЗУ
; (QCNT 8007h): на стоп-фазе, если очередь не пуста, D <- следующий
; байт, фаза 0Ch = ХОЛОСТОЙ БИТ (урок v4: кадры не вплотную). Порядок
; эха: байт, tl-hi, tl-lo. Приоритет RX над TX сохранён (вентиль E>0:
; TX замирает, SOD держит уровень; очередь ждёт в ОЗУ).
;
; РЕГИСТРЫ: C -- фаза TX; D -- сдвиговый TX; E -- интервалы RX (12..1,
;   0 = покой; вентиль RX-приоритета); L -- накопитель байта (d0..d7,
;   в v4 доживает до релиза); B -- счётчик чистых стартов;
;   A/флаги -- рабочие. DMUX (MAIN) портит только A/флаги (HL через
;   PUSH/POP). Вложенных прерываний нет.
;
; ОЗУ (SRAM с 8000h): 8000h MUXI, 8001h BYTE0, 8002h-03h TSB (таймлайн),
; 8004h-05h QBUF (очередь эха), 8006h SSELF, 8007h QCNT. Стек на FFFF.
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
RXN1    EQU TMR_N//2        ; 1-й зазор = 0,5 бита (выборка СТАРТА)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- 5.5/6.5 маскировать,
                            ; 7.5 разрешить; R7.5=1 -- латч сброшен
SIMLR   EQU 08h             ; SIM: R7.5=1, MSE=0, SDE=0 -- только сброс
                            ; латча RST 7.5

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит)
DIGP    EQU 01h             ; DIG: D3-D0 разряды (D4 = SND -- не трогаем)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)

; ---- ОЗУ (SRAM с 8000h, стек на FFFF -- конфликтов нет) ----
MUXI    EQU 8000h           ; индекс разряда дисплея 0..3
BYTE0   EQU 8001h           ; последний принятый байт (для дисплея)
TSB     EQU 8002h           ; таймлайн 12 бит (hi=8002h, lo=8003h)
QBUF    EQU 8004h           ; очередь эха: 8004h = tl-hi, 8005h = tl-lo
SSELF   EQU 8006h           ; счётчик захватов во время своего эха
QCNT    EQU 8007h           ; счётчик очереди эха 0..2

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; Вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = 003Ch-003Fh); ре-арм
; ПЕРВЫМ действием: период = ровно N тиков, длина ISR в сетку не входит.
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ СЕТКИ (7 тактов)
        OUT TMRP            ; (10 тактов) -- 8 квантов = 1 бит

; ---- ISR: вентиль RX -> TX-автомат -> RX-автомат ----
        ORG 0040h
        MOV A,E             ; вентиль: RX активен (E>0)?
        ORA A
        JZ TXRUN
        JMP RX              ; RX активен: TX НЕ двигаем (SOD держит уровень)
TXRUN:  MOV A,C             ; --- TX-автомат ---
        CPI 0FFh            ; 0FFh = покой?
        JZ TXIDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ TXST
        CPI 0Bh             ; 0Bh = холостой бит (урок v4): SOD=1
        JZ TXIDLBIT
        CPI 1               ; 01h = стоп-бит
        JZ TXSP
; --- фаза данных (d0..d7): байт в D ---
        MOV A,D
        RRC                 ; A7 <- D0
        ANI 80h
        ORI 40h             ; SDE=1; MSE=0 -- маски не трогаем
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху
        MOV A,D
        RAR                 ; D >>= 1
        MOV D,A
        JMP RX
TXST:   MVI A,40h           ; SOD=0 -- старт-бит (D заряжен заранее)
        SIM
        JMP RX
TXIDLBIT: MVI A,0C0h        ; холостой бит: SOD=1 (C уже 0Bh ->
        SIM                 ;   следующий DCR даст 0Ah = старт)
        JMP RX
TXSP:   MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        LDA QCNT            ; очередь таймлайна?
        ORA A
        JZ TXDONE
        DCR A
        STA QCNT            ; следующий байт очереди:
        MOV D,A             ;   было 2 -> QBUF, было 1 -> QBUF+1
        CPI 1
        MVI L,QBUF & 0FFh
        JZ TXSP1
        INR L
TXSP1:  MVI H,QBUF//256
        MOV A,M
        MOV D,A
        MVI C,0Ch           ; холостой бит, затем старт очередного
        JMP RX
TXDONE: MVI C,0FFh          ; очередь пуста -- покой
        JMP RX
TXIDLE: MVI A,0C0h          ; покой: SOD=1
        SIM
; --- RX-автомат: каждая выборка -> бит таймлайна TSB; данные ещё и в L ---
RX:     MOV A,E
        ORA A
        JZ RXE              ; E=0 -- приём не активен
        CPI 12              ; 1-й интервал = старт-верификация (мимо L)
        JZ RXBIT
        CPI 4               ; E=3..1 -- хвост (мимо L)
        JM RXBIT
        RIM                 ; SID -> A7 (транзит RX->SID в CPLD)
        ANI 80h
        RLC                 ; v4: CY <- БИТ ЛИНИИ (в v3 был RAR: SID
        MOV A,L             ;   уезжал в A6, в CY попадал 0!)
        RAR                 ; L = (L>>1) | бит -- d0..d7, LSB-first
        MOV L,A
        RLC                 ; v4: CY <- бит снова (A7 сдвинутого байта)
        JMP RXPACK
RXBIT:  RIM                 ; старт/хвост: только в таймлайн
        ANI 80h
        RLC                 ; v4: CY <- бит линии
RXPACK: PUSH H              ; v4: L = накопитель байта -- LHLD TSB
        LHLD TSB            ;   его затирает; HL спасаем на упаковку
        MOV A,H
        RAL
        MOV H,A
        MOV A,L
        RAL
        MOV L,A
        SHLD TSB
        POP H               ; v4: байт возвращён в L
        DCR E               ; интервал отработан
        MOV A,E
        ORA A
        JNZ RXE             ; кадр не кончился
        ; --- РЕЛИЗ: 12 выборок собраны (E=0), L = байт, HL = TSB ---
        MOV A,C             ; TX свободен?
        CPI 0FFh
        JNZ RXE             ; занят -- байт отбрасываем (v1, без очереди)
        MOV A,L             ; принятый байт
        STA BYTE0           ; ДИАГ: байт на дисплей
        MOV D,A             ; эхо, кадр 1 = байт
        LDA TSB             ; v4: в ОЗУ 8002h = tl-hi, 8003h = tl-lo
        STA QBUF            ;   (так ложится H-first цепочка RAL);
        LDA TSB+1           ;   LHLD в релизе переворачивал пару ->
        STA QBUF+1          ;   эхо шло [tl-lo][tl-hi]. Теперь прямо:
        MVI A,2             ;   [байт][tl-hi][tl-lo] по протоколу
        STA QCNT
        MVI C,0Bh           ; следующий фронт = старт-байт эха
RXE:    EI
        RET

; ---- MAIN ----
        ORG 0100h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2)
        MVI A,0C0h          ; SOD=1 (idle) -- гасим возможный BREAK
        SIM                 ; после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся
        MVI A,0             ; ДИАГ: ОЗУ -- с нуля (дисплей «0.0.0.0.»)
        STA MUXI
        STA BYTE0
        STA TSB
        STA TSB+1
        STA SSELF
        STA QCNT
        MVI B,0             ; счётчик чистых стартов
        MVI E,0             ; RX покой
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён
        MVI D,'>'           ; баннер-символ (один)
        MVI C,0Bh           ; фаза: следующий фронт = старт '>'
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера
        EI
BAN:    MOV A,C             ; ждём конца баннера (C -> 0FFh)
        CPI 0FFh
        JNZ BAN
; --- главный цикл: опрос SID (приём) + эхо + мультиплексия дисплея ---
POLL:   CALL DMUX           ; шаг дисплея (EI включён; портит A/флаги)
        DI                  ; опрос БЕЗ ISR: «залетевший» фронт не
        RIM                 ; обслужится, латч ловится -- выбросим ниже
        ANI 80h
        JNZ POLL            ; 1 = idle
        ; --- старт-бит пойман (SID=0) ---
        MVI A,RXN1          ; 0,5 бита: загрузка ДО сброса латча --
        OUT TMRP            ; залетевший фронт мог быть только ДО неё
        MVI A,SIMLR
        SIM                 ; атомарный выброс латча, гонки нет
        MOV A,C             ; ДИАГ: ЧТО поймали? свой эхо-кадр?
        CPI 0FFh            ; (TX занят = ловим во время СВОЕЙ передачи)
        JZ CATCHN
        LDA SSELF           ; свой кадр: SSELF++ (признак петли!)
        INR A
        STA SSELF
        JMP ARMED
CATCHN: INR B               ; чистый старт: B++
ARMED:  XRA A               ; таймлайн -- с нуля
        STA TSB
        STA TSB+1
        MVI L,0             ; накопитель байта -- с нуля
        MVI E,12            ; 12 интервалов: 4Q (старт) + 11x8Q
        EI
RWAIT:  MOV A,E             ; ждём конца приёма (E -> 0 в релизе)
        ORA A
        JNZ RWAIT
EWAIT:  MOV A,C             ; ждём конца эха (C -> 0FFh, вся очередь)
        CPI 0FFh
        JNZ EWAIT
        JMP POLL

; ---- ДИАГНОСТИКА: мультиплексия дисплея (по разряду за вызов) ----
; DIG0 = B mod 16 (чистые старты), DIG1 = SSELF mod 16 (захваты своего
; эха), DIG2/DIG3 = принятый байт (lo/hi). ПОРТИТ ТОЛЬКО A/флаги.
        ORG 0170h           ; v3: сдвинут (ISR/MAIN занимают до 016Ah)
DMUX:   LDA MUXI
        INR A
        ANI 3
        STA MUXI
        CPI 1
        JZ DMX1
        CPI 2
        JZ DMX2
        CPI 3
        JZ DMX3
        MOV A,B             ; индекс 0: чистые старты
        ANI 0Fh
        CALL HSEG
        MVI A,01h
        OUT DIGP
        RET
DMX1:   LDA SSELF           ; индекс 1: захваты своего эха (ждём 0!)
        ANI 0Fh
        CALL HSEG
        MVI A,02h
        OUT DIGP
        RET
DMX2:   LDA BYTE0           ; индекс 2: мл. ниббл байта
        ANI 0Fh
        CALL HSEG
        MVI A,04h
        OUT DIGP
        RET
DMX3:   LDA BYTE0           ; индекс 3: ст. ниббл байта
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL HSEG
        MVI A,08h
        OUT DIGP
        RET
HSEG:   PUSH H              ; A = ниббл -> OUT SEGP = паттерн; HL цел
        MOV H,A
        MVI L,SEGTAB & 0FFh
        ADD L               ; lo + ниббл: переноса нет (lo=D0h)
        MOV L,A
        MVI H,SEGTAB//256
        MOV A,M
        POP H
        OUT SEGP
        RET

        ORG 01D0h           ; lo = D0h: D0h+0Fh без переноса -- ADD L точен
SEGTAB: DB 3Fh,06h,5Bh,4Fh,66h,6Dh,7Dh,07h  ; '0'-'7' (a..g, dp=0)
        DB 7Fh,6Fh,77h,7Ch,39h,5Eh,79h,71h  ; '8'-'F'
        END
