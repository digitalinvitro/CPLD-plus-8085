; =====================================================================
; beta/01_timer -- ТЕСТ-ПРОШИВКА ПЗУ: ВЫВОД В UART, ТАКТИРУЕМЫЙ
; ИНТЕРВАЛЬНЫМ ТАЙМЕРОМ (CPLD beta v3.3b3, порт 04h -> RST 7.5).
;
; Файл в кодировке CP1251 (как все исходники проекта, кроме asm85.py).
;
; Сборка (из этой папки):
;   python3 asm85.py timer_test_uart.asm -o timer_test_uart.hex -l timer_test_uart.lst
;   другие скорости: -D TMR_N=2 (9600) / -D TMR_N=4 (4800) / -D TMR_N=16 (1200)
;
; Железо: retro_PCLD_board V2 + CPLD beta v3.3b3 + USB-мост CH340G (U6).
; Тракт передачи: CPU.SOD (SIM) -> CPLD P72 -> P39 (прозрачный транзит;
; после сброса TX-маска держит '1' 51,2 мкс -- BREAK невозможен)
; -> CH340G.RXD -> виртуальный COM-порт ПК.
; Терминал: 2400 8N1 (по умолчанию), без управления потоком.
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B
; (видимое окно 0000h-7FFFh). После теста вернуть монитор.
;
; ИДЕЯ (задание владельца): битовые интервалы формирует ИНТЕРВАЛЬНЫЙ
; ТАЙМЕР, а не калиброванные программные циклы. ОДНО прерывание
; RST 7.5 = ОДИН бит. Референс "полностью софтверного" варианта --
; uart_sw_test.asm (тот же текст на экране, задержки -- счётчиком
; тактов); таблица сравнения -- в beta/01_timer/README.md.
;
; ТАЙМИНГ. Квант Q = 256 x 5 тактов clk = 1280/clk:
;   clk = 25,000 МГц -> Q = 51,20 мкс;
;   факт: по тону v2 (493 Гц при N=20; период фронтов = РОВНО N тиков --
;   в HDL декремент только по тикам, загрузка приоритетнее, тик при
;   ре-арме раньше следующего тика не теряется) -> Q ~ 50,7 мкс
;   (clk ~ 25,2 МГц, «сверчок» LTC6905 идёт на ~+1% от номинала).
; Ре-арм -- ПЕРВОЕ действие ISR (003Ch: MVI A,N / OUT 04h, ~13 мкс от
; фронта), укладывается в квант, поэтому:
;   период прерываний = РОВНО N x Q; накладные ISR в период НЕ входят
;   (сетка тиков свободно-бежящая). Длина ISR влияет только на добавку
;   фронта SOD от фронта тика: старт/стоп ~+23 мкс, данные ~+35 мкс
;   (ширина бита гуляет в пределах ~13 мкс = 3% бита на 2400 -- приёмник
;   выборкой в середине бита это прощает, запас > 90 мкс, см. README).
; Бит = N x Q (при Q = 50,6..51,2 мкс):
;   N=2  -> 9770-9870 бод (цель 9600, ошибка +1,8..+2,8%)
;   N=4  -> 4883-4936      (4800)
;   N=8  -> 2441-2468      (2400)  <- по умолчанию
;   N=16 -> 1221-1234      (1200)
; Ошибка +1,7..+2,8% -- в допуске UART: дрейф за 9,5 бит ~26% бита при
; лимите ~50%, запас по выборке середины бита > 23% на любой скорости.
; Если терминал показывает мусор -- снизить скорость (TMR_N=16, 1200).
;
; ЧТО ДЕЛАЕТ: бесконечно шлёт строку MSG:
;   "TIMER-UART OK" + CR LF, пауза ~14 бит, повтор.
;   Кадры идут ВПЛОТНУЮ (стоп-фаза сама подгружает следующий байт --
;   холостых бит между символами нет, 10 бит на символ).
; Дисплей: dp на всех 4 разрядах («....») -- маячок «программа жива»
; (отличим от v2-тона: там 'g'+dp; «8.» -- не стартовала).
;
; РЕГИСТРЫ ISR (MAIN живёт в HLT и их не трогает -- сохранять нечего):
;   C  -- фаза кадра: 0Bh=кадр загружен (D готов), 0Ah=старт,
;         09h..02h=данные d0..d7, 01h=стоп (+подготовка следующего
;         байта), 0FFh=покой. Фаза 00h не возникает: стоп-фаза
;         перезаряжает счётчик сама.
;   D  -- сдвиговый регистр данных (LSB-first, единицы втягиваются
;         сверху -- после d7 линия уже '1'); грузится ЗАРАНЕЕ (в MAIN,
;         в стоп-фазе или при выходе из паузы)
;   E  -- счётчик паузы (GAPN бит)
;   HL -- указатель очередного символа MSG
;   A/флаги -- рабочие; B не используется. Вложенных прерываний нет
;   (8085 запрещает IE на входе в ISR), EI только в конце.
;
; ДИАГНОСТИКА:
;   в терминале повторяется "TIMER-UART OK" -> ПАСС: таймер, RST 7.5,
;       ре-арм, автомат, SOD, CH340G, COM-порт
;   дисплей «....», в терминале мусор  -> скорость не совпала: выставить
;       2400; если мусор и на 2400 -- прошить -D TMR_N=16 (1200)
;   дисплей «....», терминал молчит   -> тракт TX: осциллограф на SOD
;       (U3.4, нога 4 CPU) и TX (P39 CPLD); проверить COM/драйвер CH340G
;   дисплей «8.» или пуст             -> программа не стартует (ПЗУ/шина)
;   обрывы/склейки строк              -> потеря прерываний (латч/маска/EI)
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
GAPN    EQU 13              ; пауза между посылками, бит (~5,3-5,4 мс)

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит в регистре)
DIGP    EQU 01h             ; DIG/SND: D3-D0 разряды (SND не используется)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- маски применить: 5.5/6.5
                            ; маскировать, 7.5 РАЗРЕШИТЬ; R7.5=1 -- латч
                            ; сброшен (гасим возможный мусор до EI)

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; ВАЖНО: вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = ровно 003Ch-003Fh),
; JMP не нужен -- автомат продолжает с 0040h. Ре-арм ПЕРВЫМ действием:
; период = N тикам ровно, а выход SOD сдвинут на постоянную добавку
; от фронта тика (приёмник синхронизируется по фронту старт-бита).
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ (7 тактов)
        OUT TMRP            ; (10 тактов) -- от фронта до загрузки ~13 мкс

; ---- автомат передатчика: 1 прерывание = 1 бит ----
        ORG 0040h
        MOV A,C             ; фаза в C
        CPI 0FFh            ; 0FFh = покой (пауза между посылками)?
        JZ IDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ START
        CPI 1               ; 01h = стоп-бит (+подготовка следующего)
        JZ STOPB
; --- фаза данных (09h..02h): выдать D0, сдвинуть вправо с единицей ---
        MOV A,D
        RRC                 ; A7 <- D0 (очередной бит данных)
        ANI 80h
        ORI 40h             ; SSE=1; MSE=0 -- маски НЕ трогаем (см. SIM)
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху: после d7 в D уже '1'
        MOV A,D
        RAR                 ; D >>= 1 (D7 <- 1)
        MOV D,A
        JMP IRET
START:  MVI A,40h           ; SOD=0 -- старт-бит (D уже загружен заранее)
        SIM
        JMP IRET
STOPB:  MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        INX H               ; -- подготовка следующего байта (кадры
        MOV A,M             ;    идут вплотную, холостых бит нет):
        ORA A               ;    00h = конец строки
        JZ ESTR
        MOV D,A             ;    байт -> сдвиговый заранее
        MVI C,0Bh           ;    перезарядить фазу (00h не возникает)
        JMP IRET
ESTR:   MVI C,0FFh          ; строка кончилась -- покой
        MVI E,GAPN          ; пауза GAPN бит
        JMP IRET
IDLE:   MVI A,0C0h          ; покой: SOD=1 (каждый тик подтверждаем)
        SIM
        DCR E
        JNZ IRET
        LXI H,MSG           ; пауза кончилась -- заново (с preload D)
        MOV A,M
        MOV D,A
        MVI C,0Bh
IRET:   EI
        RET

; ---- MAIN ----
        ORG 00A0h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2; на случай
                            ; расширения MAIN -- CALL уже обеспечен SP)
        MVI A,0C0h          ; SOD=1 (idle) -- ПЕРВЫМ делом гасим возможный
        SIM                 ; BREAK: после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся на неё
        MVI A,80h           ; дисплей: только dp на всех разрядах («....»)
        OUT SEGP
        MVI A,0Fh           ; все 4 разряда статически (нагрузка << INIT «8.»)
        OUT DIGP
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера: 1-й фронт через N тик (~0,41 мс)
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён, латч сброшен
        LXI H,MSG           ; первый байт -- заранее в сдвиговый регистр
        MOV A,M
        MOV D,A
        MVI C,0Bh           ; фаза: следующий тик = старт-бит
        EI
HLTLP:  HLT                 ; спим: вся передача -- в ISR (~10% CPU)
        JMP HLTLP

; ---- сообщение: строка + CR LF + терминатор 00h ----
MSG:    DB 'TIMER-UART OK',0Dh,0Ah,00h
        END
