; =====================================================================
; beta/01_timer -- ТЕСТ-ПРОШИВКА ПЗУ: ПОЛНОЦЕННЫЙ UART (ПРИЁМ-ПЕРЕДАЧА,
; ЭХО) + ДИАГНОСТИКА ПРИЁМА НА ДИСПЛЕЕ. Интервальный таймер CPLD
; (beta v3.3b3, порт 04h -> RST 7.5), 2400 бод (TMR_N=8), 8N1.
;
; ЭТО ДИАГНОСТИЧЕСКИЙ ВАРИАНТ uart_echo_test.asm (v1, 229 байт).
; ЛОГИКА ЭХА НЕ ТРОНУТА. Отличия по листингу: +4 байта в релизе ISR
; (копия байта), +CALL DMUX и INR B в MAIN, блок DMUX с 00F0h,
; таблица SEGTAB с 0150h.
;
; Файл в кодировке CP1251 (как все исходники проекта, кроме asm85.py).
;
; Сборка (из этой папки):
;   python3 asm85.py uart_echo_diag.asm -o uart_echo_diag.hex -l uart_echo_diag.lst
;
; Железо: retro_PCLD_board V2 + CPLD beta v3.3b3 + USB-мост CH340G (U6).
; CPLD НЕ МЕНЯЛСЯ (транзиты уже в фите v3.3b3, проверено по .rpt:
; SID <= RX, RX=вход P38, SID=выход P73):
;   приём:   CH340G.TXD (U6.2, цепь платы «TX») -> P38 -> P73 -> CPU.SID (U3.5, RIM 20h);
;   передача: CPU.SOD (U3.4) -> P72 -> P39 -> CH340G.RXD (U6.3, цепь «RX»).
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B
; (видимое окно 0000h-7FFFh). После теста вернуть монитор.
;
; ЗАЧЕМ ДИАГНОСТИКА: TX-тракт доказан (баннер '>' приходит), а приём
; PC->плата упражняется ВПЕРВЫЕ. Дисплей показывает, ДОКАНЬ ли доходит
; ввод: 4 разряда = [счётчик пойманных старт-битов][последний байт].
;
; ЧТО ДОБАВЛЕНО:
;   B     -- счётчик ПОЙМАННЫХ старт-битов (фронтов 1->0 на SID,
;            ловит MAIN; hex, mod 256);
;   BYTE0 (ОЗУ 8001h) -- последний ПРИНЯТЫЙ байт (пишет ISR в релизе,
;            даже если эхо уронено по занятости TX);
;   MUXI  (ОЗУ 8000h) -- индекс разряда мультиплексии 0..3;
;   дисплей, шаг мультиплексии на каждый цикл опроса (4 фазы):
;     DIG0 = мл. ниббл B,  DIG1 = ст. ниббл B   -- счётчик стартов;
;     DIG2 = мл. ниббл байта, DIG3 = ст. ниббл  -- принятый байт.
;   После RESET: «0.0.0.0.» (маячок «стартовала»; отличим от «8.8.8.8.»
;   эха v1 и от «....» TX-теста v4).
;
; КАК ЧИТАТЬ (вводить ПО ОДНОМУ символу; paste -- норма v1 без очереди):
;   '>' есть, счётчик НЕ тикает, байт 00 -- приём мёртв ДО автоматики:
;       (а) flow control в терминале (RTS/CTS или XON/XOFF) --
;           ВЫКЛЮЧИТЬ: модемные линии CH340G (U6.9-15) на плате не
;           разведены, CTS терминал не дождётся никогда и молча
;           придержит ввод; баннер при этом приходит как ни в чём
;           не бывало -- симптом в точности наш;
;       (б) обрыв/непайка CH340G.TXD (U6.2) -> P38;
;       (в) контакт ножки 5 (SID) в ZIF U3 или дефект 1821ВМ85 по SID.
;       Осциллограф: при вводе смотреть P38 и U3.5 (есть ли кадры).
;   счётчик ТИКАЕТ, байт неверный (FFh/мусор), эха нет или мусор --
;       старт ловится, биты читаются мимо сетки: проверить 2400 8N1
;       в терминале; осциллографом форму P38 (задержка/дрожь фронтов
;       CH340G на 2400 ничтожна -- подозревать нечего, но глянуть).
;   счётчик ТИКАЕТ, байт ВЕРНЫЙ, эха НЕТ -- приём исправен целиком
;       (цепь до RIM и сетка выборки), вопрос к релизу эха (малореально:
;       логика релиза не менялась) -- сообщать владельцу код дисплея.
;   счётчик МЧИТСЯ сам, байт 00, без ввода -- линия RX прижата к 0
;       (КЗ/мёртвый CH340G): MAIN ловит «старты» непрерывно и гонит
;       в эхо нули.
;
; ТАЙМИНГ ПРИЁМА (не менялся, подробности в uart_echo_test.asm):
;   MAIN опрашивает SID (RIM) в цикле с DI; поймав старт-фронт:
;   OUT TMRP <- RXN1 (1,5 бита, 12 при N=8) -> SIM 08h (сброс латча
;   RST 7.5 ПОСЛЕ загрузки -- залетевший фронт выброшен атомарно)
;   -> INR B -> L=0, H=11, EI. Сетка ISR: ре-арм в векторе 003Ch;
;   кадр = 12Q (d0) + 8x8Q (d1..d7) + 3x8Q (хвост -- урок v4: эхо-старт
;   ПОСЛЕ конца кадра приёмника ПК). Мультиплексия дисплея ВЫНЕДЕНА
;   из критического пути: CALL DMUX стоит ДО DI (с включёнными
;   прерываниями); DMUX портит ТОЛЬКО A/флаги (HSEG сохраняет HL
;   через PUSH/POP, B..E не трогает; ISR в покое тоже трогает только
;   A/флаги) -- взаимных порчей нет. Цена: ~55 мкс к латентности
;   ловли старта (окно выборки d0 ±208 мкс, запас остаётся >150 мкс).
;
; РЕГИСТРЫ: C -- фаза TX (0Bh заряжен, 0Ah старт, 09h..02h данные,
;   01h стоп, 0FFh покой); D -- сдвиговый TX (LSB-first, единицы
;   сверху); H -- счётчик интервалов RX (11..4 выборки, 3..1 хвост,
;   0 покой); L -- накопитель байта; B -- счётчик старт-битов (ДИАГ,
;   ISR не трогает); A/флаги -- рабочие; E свободен. Между символами
;   MAIN (DMUX) держит: C=0FFh, D -- любое (перезаряжается релизом/
;   баннером), H=0, L -- любое, B -- счётчик. Вложенных прерываний нет.
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
RXN1    EQU TMR_N + TMR_N//2 ; 1-й зазор приёма = 1,5 бита (12 при N=8)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- маски применить: 5.5/6.5
                            ; маскировать, 7.5 РАЗРЕШИТЬ; R7.5=1 -- латч
                            ; сброшен (гасим возможный мусор до EI)
SIMLR   EQU 08h             ; SIM: R7.5=1, MSE=0, SDE=0 -- ТОЛЬКО сброс
                            ; латча RST 7.5 (маски и SOD не трогаем)

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит в регистре)
DIGP    EQU 01h             ; DIG: D3-D0 разряды (D4 = SND -- не трогаем)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)

; ---- диагностика: ОЗУ (SRAM с 8000h, стек на FFFF -- конфликтов нет) ----
MUXI    EQU 8000h           ; индекс разряда дисплея 0..3
BYTE0   EQU 8001h           ; последний принятый байт (пишет ISR)

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; ВАЖНО: вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = 003Ch-003Fh),
; JMP не нужен -- автомат продолжается с 0040h. Ре-арм ПЕРВЫМ действием:
; период = N тикам ровно (сетка не зависит от длины ISR).
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ СЕТКИ (7 тактов)
        OUT TMRP            ; (10 тактов) -- 8 квантов = 1 бит

; ---- ISR: вентиль TX -> TX-автомат -> RX-автомат ----
        ORG 0040h
        MOV A,H             ; вентиль: RX активен (H>0)?
        ORA A
        JZ TXRUN
        JMP RX              ; RX активен: TX НЕ двигаем (заморозка кадра,
                            ;   SOD держит текущий уровень)
TXRUN:  MOV A,C             ; --- TX-автомат (фазы как в v4) ---
        CPI 0FFh            ; 0FFh = покой?
        JZ TXIDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ TXST
        CPI 1               ; 01h = стоп-бит
        JZ TXSP
; --- фаза данных (d0..d7): как в v4, байт уже в D ---
        MOV A,D
        RRC                 ; A7 <- D0 (очередной бит данных)
        ANI 80h
        ORI 40h             ; SSE=1; MSE=0 -- маски НЕ трогаем
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху: после d7 в D уже '1'
        MOV A,D
        RAR                 ; D >>= 1 (D7 <- 1)
        MOV D,A
        JMP RX
TXST:   MVI A,40h           ; SOD=0 -- старт-бит (D загружен ЗАРАНЕЕ:
        SIM                 ;   из релиза приёма или из MAIN)
        JMP RX
TXSP:   MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        MVI C,0FFh          ; однобайтовый режим: сразу в покой (кадры
        JMP RX              ;   редкие -- 2-й стоп-бит не нужен)
TXIDLE: MVI A,0C0h          ; покой: SOD=1 (каждый тик подтверждаем)
        SIM
; --- RX-автомат: интервалы кадра в H, байт копится в L ---
RX:     MOV A,H
        ORA A
        JZ RXE              ; H=0 -- приём не активен
        CPI 4               ; H>=4 (H=11..4) -- фаза данных d0..d7;
        JM RXT              ; H=3..1 -- хвост (без выборки)
        RIM                 ; SID -> A7 (транзит RX->SID в CPLD)
        ANI 80h
        RAR                 ; CY <- SID
        MOV A,L
        RAR                 ; L = (L>>1) | SID<<7 -- LSB-first
        MOV L,A
RXT:    DCR H               ; интервал отработан
        MOV A,H
        ORA A
        JNZ RXE             ; кадр приёма не кончился
        MOV A,L             ; ДИАГ: копия принятого байта на дисплей
        STA BYTE0           ;   (даже если эхо ниже будет уронено)
        MOV A,C             ; --- РЕЛИЗ: кадр кончился (H=0) ---
        CPI 0FFh            ; TX свободен?
        JNZ RXE             ; занят -- байт отбрасываем (v1, без очереди)
        MOV D,L             ; эхо: сдвиговый TX <- принятый байт
        MVI C,0Bh           ; следующий фронт = старт-бит эха
RXE:    EI
        RET

; ---- MAIN ----
        ORG 00A0h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2)
        MVI A,0C0h          ; SOD=1 (idle) -- ПЕРВЫМ делом гасим возможный
        SIM                 ; BREAK: после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся на неё
        MVI A,0             ; ДИАГ: MUXI=0, BYTE0=0 -- дисплей «0.0.0.0.»
        STA MUXI
        STA BYTE0
        MVI B,0             ; ДИАГ: счётчик старт-битов -- с нуля
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён, латч сброшен
        MVI D,'>'           ; баннер-символ (один; кадр уйдёт сами собой)
        MVI C,0Bh           ; фаза: следующий фронт = старт-бит '>'
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера: 1-й фронт через N тиков
        MVI H,0             ; RX покой
        MVI L,0
        EI
BAN:    MOV A,C             ; ждём конца баннера (C -> 0FFh на стоп-фазе)
        CPI 0FFh
        JNZ BAN
; --- главный цикл: опрос SID (приём) + эхо + мультиплексия дисплея ---
POLL:   CALL DMUX           ; ДИАГ: шаг мультиплексии (EI включён; портит
        DI                  ;   только A/флаги -- критично, см. шапку);
                            ;   далее опрос КАК В v1
        RIM                 ; «залетевший» фронт сетки не обслужится,
        ANI 80h             ; латч ловится -- выбросим ниже
        JNZ POLL            ; 1 = idle (покой линии)
        ; --- старт-бит пойман (SID=0) ---
        MVI A,RXN1          ; 1-й зазор = 1,5 бита: загрузка ДО сброса
        OUT TMRP            ; латча! Любой залетевший фронт старого
        MVI A,SIMLR         ; отсчёта мог сработать только ДО этой точки
        SIM                 ; (после загрузки новый фронт >= 11 квантов):
                            ; SIM 08h выбрасывает их АТОМАРНО, гонки нет
        INR B               ; ДИАГ: +1 пойманный старт-бит (вне критичного
                            ;   пути -- ПОСЛЕ арма, до EI)
        MVI L,0             ; накопитель байта -- с нуля
        MVI H,11            ; 11 интервалов: 12Q (d0) + 8x8Q (d1..d7)
        EI                  ;              + 3x8Q (хвост -- урок v4)
RWAIT:  MOV A,H             ; ждём конца приёма (H -> 0 в релизе)
        ORA A
        JNZ RWAIT
EWAIT:  MOV A,C             ; ждём конца эха (C -> 0FFh на стоп-фазе)
        CPI 0FFh
        JNZ EWAIT
        JMP POLL

; ---- ДИАГНОСТИКА: мультиплексия дисплея (по одному разряду за вызов) ----
; DIG0=B.мл, DIG1=B.ст, DIG2=BYTE0.мл, DIG3=BYTE0.ст (hex).
; ПОРТИТ ТОЛЬКО A/флаги (HSEG сохраняет HL через PUSH/POP; B/C/D/E
; не трогает) -- безопасно при EI: ISR в покое тоже портит лишь A.
; Сегменты пишем ДО разряда (SEGP -> DIGP) -- без призраков.
        ORG 00F0h
DMUX:   LDA MUXI
        INR A
        ANI 3
        STA MUXI            ; A = новый индекс 0..3
        CPI 1
        JZ DMX1
        CPI 2
        JZ DMX2
        CPI 3
        JZ DMX3
        MOV A,B             ; индекс 0: мл. ниббл счётчика
        ANI 0Fh
        CALL HSEG
        MVI A,01h
        OUT DIGP
        RET
DMX1:   MOV A,B             ; индекс 1: ст. ниббл счётчика
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL HSEG
        MVI A,02h
        OUT DIGP
        RET
DMX2:   LDA BYTE0           ; индекс 2: мл. ниббл байта
        ANI 0Fh
        CALL HSEG
        MVI A,04h
        OUT DIGP
        RET
DMX3:   LDA BYTE0           ; индекс 3: ст. ниббл байта
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL HSEG
        MVI A,08h
        OUT DIGP
        RET
HSEG:   PUSH H              ; A = ниббл -> OUT SEGP = паттерн; HL целы
        MOV H,A
        MVI L,SEGTAB & 0FFh
        ADD L               ; lo + ниббл: переноса нет (lo=50h, см. ниже)
        MOV L,A
        MVI H,SEGTAB//256
        MOV A,M
        POP H
        OUT SEGP
        RET

        ORG 0150h           ; lo = 50h: 50h+0Fh без переноса -- ADD L точен
SEGTAB: DB 3Fh,06h,5Bh,4Fh,66h,6Dh,7Dh,07h  ; '0'-'7' (a..g, dp=0)
        DB 7Fh,6Fh,77h,7Ch,39h,5Eh,79h,71h  ; '8'-'F'
        END
