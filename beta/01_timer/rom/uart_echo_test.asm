; =====================================================================
; beta/01_timer -- ТЕСТ-ПРОШИВКА ПЗУ: ПОЛНОЦЕННЫЙ UART (ПРИЁМ-ПЕРЕДАЧА,
; ЭХО), битовые интервалы от ИНТЕРВАЛЬНОГО ТАЙМЕРА (CPLD beta v3.3b3,
; порт 04h -> RST 7.5). Первый тест тракта ПРИЁМА.
;
; Файл в кодировке CP1251 (как все исходники проекта, кроме asm85.py).
;
; Сборка (из этой папки):
;   python3 asm85.py uart_echo_test.asm -o uart_echo_test.hex -l uart_echo_test.lst
;   другие скорости: -D TMR_N=16 (1200) / -D TMR_N=4 (4800) / -D TMR_N=2 (9600*)
;   (* 9600: добавка ISR ~60 мкс = 60% бита -- гарантирован только 2400/1200)
;
; Железо: retro_PCLD_board V2 + CPLD beta v3.3b3 + USB-мост CH340G (U6).
; CPLD НЕ МЕНЯЛСЯ (тот же фит v3.3b3): транзиты уже есть --
;   передача: CPU.SOD (SIM) -> CPLD P72 -> P39 -> CH340G.RXD -> COM ПКА;
;   приём:    CH340G.TXD -> CPLD RX (P38) -> P73 -> CPU.SID (RIM 20h).
; Прошивается ВМЕСТО монитора fw_mon с нулевого смещения flash A29040B
; (видимое окно 0000h-7FFFh). После теста вернуть монитор.
;
; ИДЕЯ (задание владельца): после ПАССА TX-теста (v4, «текст ровный»)
; проверить тракт приёма. ЭХО: символ, принятый от терминала, уходит
; обратно. И приём и передача тактируются таймером: ОДНО прерывание =
; ОДИН БИТ (период = ровно N x Q, см. README «Уточнение модели кванта»).
;
; ТАЙМИНГ ПРИЁМА (терминал шлёт на РОВНО 2400 бод, бит 416,67 мкс):
;   MAIN опрашивает SID (RIM) в цикле с DI -- ISR не «залетают» под руку;
;   латентность обнаружения старта ~10 мкс. Поймав старт-фронт:
;     1) OUT TMRP <- RXN1 (= 1,5 бита в квантах, 12 при N=8): 1-я выборка
;        в середине d0. Загрузка даёт фронт через (RXN1-1)..RXN1 квантов
;        (фаза прескалера; окно выборки d0 = +-208 мкс от центра -- запас);
;     2) SIM 08h -- СБРОС латча RST 7.5 ПОСЛЕ загрузки: любой «залетевший»
;        фронт старого отсчёта атомарно выброшен (гонка исключена: после
;        загрузки новый фронт не раньше чем через 11-12 квантов);
;     3) H=11 (счётчик интервалов кадра приёма), EI.
;   Далее сетка ISR: ре-арм в векторе 003Ch грузит N=TMR_N (8 квантов =
;   1 бит). Кадр приёма = 11 интервалов: 12Q (d0) + 8x8Q (d1..d7) +
;   3x8Q (хвост). Дрейф выборки против терминала: сетка 8 квантов =
;   405,7..409,6 мкс против бита 416,67 -- набегает ~7-11 мкс РАНЬШЕ на
;   бит; к d7 выборка на ~72 мкс раньше центра -- лимит +-208 мкс, запас
;   > 130 мкс. ХВОСТ (3 интервала ~ 3 бита) держит MAIN от опроса до
;   ~11,2 бита: ЗАЕРКАЛЕН УРОК V4 -- эхо-старт выходит на линию только
;   ПОСЛЕ конца кадра приёмника ПКА (10 бит), с запасом ~+2 бита.
;   Вектор приёма: биты LSB-first втягиваются в L (MOV A,L / RAR).
;
; РЕГИСТРЫ ISR (MAIN не держит в них ничего долгоживущего):
;   C  -- фаза TX-кадра (как в v4): 0Bh=кадр заряжен, 0Ah=старт,
;         09h..02h=данные d0..d7, 01h=стоп -> 0FFh=покой (однобайтовый
;         режим: 2-й стоп-бит НЕ нужен -- кадры далеко друг от друга);
;   D  -- сдвиговый TX (LSB-first, единицы втягиваются сверху);
;   H  -- счётчик интервалов RX-кадра: 11..4 = выборки данных,
;         3..1 = хвост (без выборки), 0 = покой; H>0 = «RX активен»;
;   L  -- накопитель байта приёма (LSB-first);
;   A/флаги -- рабочие; B, E свободны. Вложенных прерываний нет
;   (8085 запрещает IE на входе в ISR), EI только в конце.
;
; ПРИОРИТЕТ RX НАД TX: пока H>0, TX-автомат не двигается (SOD держит
; уровень -- «заморозка» кадра). При печати за руку это недостижимо
; (эхо кончается через ~5 мс после символа), при ВСТАВКЕ (paste) даёт
; артефакты -- для v1 это задокументированное ограничение (см. README).
; Если в момент конца приёма TX занят -- байт ОТБРАСЫВАЕТСЯ (очереди
; нет; тоже v1).
;
; ЧТО ДЕЛАЕТ: шлёт один баннер-символ '>' и дальше ЭХО: каждый принятый
; символ возвращается терминалу. На дисплее «8.» на всех 4 разрядах
; («8.8.8.8.») -- маячок «программа стартовала» (отличим от «....»
; TX-теста v4 и от «g.» тона v2).
;
; ДИАГНОСТИКА:
;   '>' в терминале, набранные символы возвращаются -> ПАСС: тракт RX
;       (CH340G.TXD -> RX -> SID -> RIM), RX-автомат, эхо через TX
;   '>' есть, эхо НЕТ (или мусор) -> смотреть выборку: RIM в ISR,
;       осциллограф на SID (U3.5, нога 5 CPU) и RX (P38 CPLD)
;   '>' НЕТ, дисплей «8.8.8.8.» -> тракт TX (как в TX-тесте: SOD/P39)
;   дисплей пустой или «8.0» -> программа не стартует (ПЗУ/шина/CPLD)
;   вставка (paste) -> мусор/потери: ЗАДОКУМЕНТИРОВАНО (нет очереди TX,
;       MAIN не опрашивает линию во время чужого кадра)
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 8               ; бит = N x Q: 8 -> ~2460 бод (цель 2400)
RXN1    EQU TMR_N + TMR_N//2 ; 1-й зазор приёма = 1,5 бита (12 при N=8)
SIMW    EQU 1Bh             ; SIM: MSE=1 -- маски применить: 5.5/6.5
                            ; маскировать, 7.5 РАЗРЕШИТЬ; R7.5=1 -- латч
                            ; сброшен (гасим возможный мусор до EI)
SIMLR   EQU 08h             ; SIM: R7.5=1, MSE=0, SDE=0 -- ТОЛЬКО сброс
                            ; латча RST 7.5 (маски и SOD не трогаем)

; ---- порты ----
SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp (1 = горит в регистре)
DIGP    EQU 01h             ; DIG/SND: D3-D0 разряды (SND не используется)
TMRP    EQU 04h             ; таймер: запись N (период = N x Q)

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс
; ВАЖНО: вектор 003Ch занят ре-армом ЦЕЛИКОМ (MVI+OUT = 003Ch-003Fh),
; JMP не нужен -- автомат продолжается с 0040h. Ре-арм ПЕРВЫМ действием:
; период = N тикам ровно (сетка не зависит от длины ISR).
        ORG 003Ch
        MVI A,TMR_N         ; РЕ-АРМ СЕТКИ (7 тактов)
        OUT TMRP            ; (10 тактов) -- 8 квантов = 1 бит

; ---- ISR: вентиль TX -> TX-автомат -> RX-автомат ----
        ORG 0040h
        MOV A,H             ; вентиль: RX активен (H>0)?
        ORA A
        JZ TXRUN
        JMP RX              ; RX активен: TX НЕ двигаем (заморозка кадра,
                            ;   SOD держит текущий уровень)
TXRUN:  MOV A,C             ; --- TX-автомат (фазы как в v4) ---
        CPI 0FFh            ; 0FFh = покой?
        JZ TXIDLE
        DCR C               ; следующая фаза
        MOV A,C
        CPI 0Ah             ; 0Ah = старт-бит
        JZ TXST
        CPI 1               ; 01h = стоп-бит
        JZ TXSP
; --- фаза данных (d0..d7): как в v4, байт уже в D ---
        MOV A,D
        RRC                 ; A7 <- D0 (очередной бит данных)
        ANI 80h
        ORI 40h             ; SSE=1; MSE=0 -- маски НЕ трогаем
        SIM                 ; SOD <- бит
        STC                 ; единицы едут сверху: после d7 в D уже '1'
        MOV A,D
        RAR                 ; D >>= 1 (D7 <- 1)
        MOV D,A
        JMP RX
TXST:   MVI A,40h           ; SOD=0 -- старт-бит (D загружен ЗАРАНЕЕ:
        SIM                 ;   из релиза приёма или из MAIN)
        JMP RX
TXSP:   MVI A,0C0h          ; SOD=1 -- стоп-бит
        SIM
        MVI C,0FFh          ; однобайтовый режим: сразу в покой (кадры
        JMP RX              ;   редкие -- 2-й стоп-бит не нужен)
TXIDLE: MVI A,0C0h          ; покой: SOD=1 (каждый тик подтверждаем)
        SIM
; --- RX-автомат: интервалы кадра в H, байт копится в L ---
RX:     MOV A,H
        ORA A
        JZ RXE              ; H=0 -- приём не активен
        CPI 4               ; H>=4 (H=11..4) -- фаза данных d0..d7;
        JM RXT              ; H=3..1 -- хвост (без выборки)
        RIM                 ; SID -> A7 (транзит RX->SID в CPLD)
        ANI 80h
        RAR                 ; CY <- SID
        MOV A,L
        RAR                 ; L = (L>>1) | SID<<7 -- LSB-first
        MOV L,A
RXT:    DCR H               ; интервал отработан
        MOV A,H
        ORA A
        JNZ RXE             ; кадр приёма не кончился
        MOV A,C             ; --- РЕЛИЗ: кадр кончился (H=0) ---
        CPI 0FFh            ; TX свободен?
        JNZ RXE             ; занят -- байт отбрасываем (v1, без очереди)
        MOV D,L             ; эхо: сдвиговый TX <- принятый байт
        MVI C,0Bh           ; следующий фронт = старт-бит эха
RXE:    EI
        RET

; ---- MAIN ----
        ORG 00A0h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (конвенция v2)
        MVI A,0C0h          ; SOD=1 (idle) -- ПЕРВЫМ делом гасим возможный
        SIM                 ; BREAK: после сброса SOD=0; TX-маска CPLD и так
                            ; держит '1' 51,2 мкс, но не полагаемся на неё
        MVI A,0FFh          ; дисплей: «8.» на всех разрядах (маячок
        OUT SEGP            ; «стартовала»; отличим от «....» TX-теста v4
                            ; и от «g.» тона v2)
        MVI A,0Fh           ; все 4 разряда статически
        OUT DIGP
        MVI A,SIMW
        SIM                 ; маски: 5.5/6.5 закрыты, 7.5 разрешён, латч сброшен
        MVI D,'>'           ; баннер-символ (один; кадр уйдёт сами собой)
        MVI C,0Bh           ; фаза: следующий фронт = старт-бит '>'
        MVI A,TMR_N
        OUT TMRP            ; пуск таймера: 1-й фронт через N тиков
        MVI H,0             ; RX покой
        MVI L,0
        EI
BAN:    MOV A,C             ; ждём конца баннера (C -> 0FFh на стоп-фазе)
        CPI 0FFh
        JNZ BAN
; --- главный цикл: опрос SID (приём) + эхо ---
POLL:   DI                  ; опрос БЕЗ ISR: «залетевший» фронт сетки не
        RIM                 ; обслужится, латч ловится -- выбросим ниже
        ANI 80h
        JNZ POLL            ; 1 = idle (покой линии)
        ; --- старт-бит пойман (SID=0) ---
        MVI A,RXN1          ; 1-й зазор = 1,5 бита: загрузка ДО сброса
        OUT TMRP            ; латча! Любой залетевший фронт старого
        MVI A,SIMLR         ; отсчёта мог сработать только ДО этой точки
        SIM                 ; (после загрузки новый фронт >= 11 квантов):
                            ; SIM 08h выбрасывает их АТОМАРНО, гонки нет
        MVI L,0             ; накопитель байта -- с нуля
        MVI H,11            ; 11 интервалов: 12Q (d0) + 8x8Q (d1..d7)
        EI                  ;              + 3x8Q (хвост -- урок v4)
RWAIT:  MOV A,H             ; ждём конца приёма (H -> 0 в релизе)
        ORA A
        JNZ RWAIT
EWAIT:  MOV A,C             ; ждём конца эха (C -> 0FFh на стоп-фазе)
        CPI 0FFh
        JNZ EWAIT
        JMP POLL
        END
