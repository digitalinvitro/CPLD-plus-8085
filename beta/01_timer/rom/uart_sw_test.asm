; =====================================================================
; beta/01_timer -- РЕФЕРЕНС: ПОЛНОСТЬЮ СОФТВЕРНЫЙ UART (задержки --
; счёт тактов), для сравнения с timer_test_uart.asm (таймерный вариант).
; Тот же текст на экране, тот же дисплей «....».
;
; Файл в кодировке CP1251. Прошивается так же: offset 0 ВМЕСТО fw_mon;
; после теста вернуть монитор. Прошивать НЕ ОБЯЗАТЕЛЬНО -- это эталон
; для таблицы сравнения «таймер против софт-делеев» в README.
;
; Сборка (из этой папки):
;   python3 asm85.py uart_sw_test.asm -o uart_sw_test.hex -l uart_sw_test.lst
;
; ТЕХНОЛОГИЯ. Бит = 1042 такта CPU (2400 бод при 2,5 МГц:
; 1/2400 = 416,67 мкс = 1041,7 такта). Баланс тактов в цикле бита:
;   выдать бит        26 (MOV A,E + ANI + RRC + ORI + SIM)
;   сдвинуть DE >> 1  24 (2 x MOV/RAR/MOV, 16-битный сдвиг)
;   пауза            978 (LXI H,40 + 2 NOP + 40 x {DCX H,MOV A,H,ORA L,JNZ})
;   DCR B + JNZ       14
;   ИТОГО           1042 такта = 416,8 мкс -> 2399,2 бода (погрешность 0,03%)
; Последний бит кадра (стоп) на 3 такта короче (JNZ не переходит) --
; 0,7% бита, приёмнику безразлично. Кадр: старт(0), d0..d7 (LSB-first),
; стоп(1) -- 10 бит в паре DE (см. TXBYTE).
;
; ЦЕНА ПОДХОДА (почему за таймером -- будущее, см. сравнение в README):
;   - калибровка РУЧНАЯ и хрупкая: вставка любой инструкции в цикл бита
;     или смена тактовой частоты сдвигает ВСЕ биты -- пересчитывай LXI;
;   - CPU занят 100% всё время строки (~68 мс), прерывания запрещены;
;   - смена скорости -- пересчёт констант задержки, а не один байт N.
;
; Терминал: 2400 8N1. Прерывания не используются (EI нет; RST 7.5
; замаскирован + латч сброшен; таймер не запускался -- INIT-пробег
; счётчика FFh->0 после сброса никакого фронта в CPU не даёт).
;
; ВНИМАНИЕ: фактический clk ~25,2 МГц («сверчок», см. README) -> CPU
; ~2,52 МГц -> фактический бит 413,4 мкс -> 2419 бод (+0,8%) -- в допуске.
; В этом преимущество и ловушка софт-делеев: скорость следует за клоком,
; но калибровка привязана к ЧИСЛУ тактов, а не к кванту таймера.
; =====================================================================

SEGP    EQU 00h             ; SEG: D0=a..D6=g, D7=dp
DIGP    EQU 01h             ; DIG/SND: D3-D0 разряды

        ORG 0000h
        JMP MAIN
; ---- MAIN ----
        ORG 0006h
MAIN:   DI                  ; прерывания не нужны (и не включаются)
        MVI A,0C0h          ; SOD=1 (idle) -- гасим возможный BREAK
        SIM
        MVI A,1Fh           ; подстраховка: маскировать ВСЁ (5.5/6.5/7.5)
        SIM                 ; и сбросить латч RST 7.5 (таймер не пущен)
        MVI A,80h           ; дисплей: dp на всех разрядах («....»)
        OUT SEGP
        MVI A,0Fh           ; все 4 разряда статически
        OUT DIGP
        LXI SP,0FFFFh       ; стек для CALL/RET
; ---- передача строки, повтор бесконечно ----
SWLP:   LXI H,MSG
SWNXT:  MOV A,M
        ORA A               ; 00h = конец строки
        JZ SWGAP
        MOV C,A
        CALL TXBYTE         ; блокирующая передача 1 символа (~4,17 мс)
        INX H
        JMP SWNXT
SWGAP:  CALL DLGAP          ; пауза ~5,4 мс
        JMP SWLP
; ---- TXBYTE: C = байт, 2400 бод 8N1, кадр в паре DE (LSB-first) ----
; Раскладка кадра: E0=старт(0), E1..E7=d0..d6, D0=d7, D1=стоп(1).
TXBYTE: MOV A,C
        ADD A               ; CY=d7, A=(d<<1): бит0=0 -- старт-бит
        MOV E,A
        MVI A,2             ; старший байт: бит1=1 -- стоп (+d7 в бите 0)
        JNC TXB1
        ORI 1               ; d7 = 1 -- вписать в кадр
TXB1:   MOV D,A
        MVI B,10            ; 10 бит кадра
TXLP:   MOV A,E             ; -- выдать бит (26 тактов) --
        ANI 1
        RRC                 ; A7 <- E0
        ORI 40h             ; SSE=1; MSE=0 -- маски НЕ трогаем
        SIM
        MOV A,D             ; -- сдвиг DE вправо (24 такта, 0 сверху) --
        RAR
        MOV D,A
        MOV A,E
        RAR
        MOV E,A
        LXI H,40            ; -- пауза до конца бита (978 тактов) --
        NOP
        NOP
DLB:    DCX H
        MOV A,H
        ORA L
        JNZ DLB
        DCR B               ; -- следующий бит (14 тактов) --
        JNZ TXLP
        RET
; ---- DLGAP: пауза между посылками ~5,4 мс (13532 такта) ----
DLGAP:  LXI B,562           ; 562 x 24 такта + накладные CALL/LXI/RET
DGL:    DCX B
        MOV A,B
        ORA C
        JNZ DGL
        RET
MSG:    DB 'TIMER-UART OK',0Dh,0Ah,00h
        END
