; =====================================================================
; beta/01_timer -- ТЕСТ-ПРОШИВКА ПЗУ: проверка интервального таймера
; (CPLD beta v3.3b3, порт 04h -> RST 7.5) звуком и миганием сегмента.
;
; Файл в кодировке CP1251 (как все исходники проекта, кроме asm85.py).
;
; Сборка (из этой папки):
;   python3 asm85.py timer_test.asm -o timer_test_tone.hex  -l timer_test_tone.lst
;   python3 asm85.py timer_test.asm -o timer_test_blink.hex -l timer_test_blink.lst -D TONE=0
;
; Железо: retro_PCLD_board V2 + CPLD beta/01_timer v3.3b3 (фит 10-22 22:04).
; Прошивается ВМЕСТО монитора fw_mon, с нулевого смещения flash A29040B
; (видимое окно 0000h-7FFFh). После теста вернуть монитор.
;
; ЧТО ДЕЛАЕТ (см. подробную таблицу диагностики в beta/01_timer/README.md):
;   N = 20: период прерываний = 20 x 51,2 мкс = 1,024 мс (+ 50...60 мкс
;   накладных на вход в ISR и ре-арм -- это нормально и учтено в расчёте).
;   TONE=1: каждое прерывание инвертирует бит D4 (SND) порта 01h -> зуммер
;   даёт тон около 460...470 Гц (идеальные 488 Гц минус накладные ISR).
;   BLINK=1: каждые 464 прерывания инвертируется сегмент 'g' (D6) -> мигание
;   раз в ~0,5 с (полный цикл ~1 с); dp горит постоянно как маячок дисплея.
;
; ОТВЕТ НА ВОПРОС "ЗВУК ИЛИ СЕГМЕНТ": звук -- показательнее (сотни
;   прерываний/с, любой сбой слышен мгновенно, кратность кванта видна по
;   высоте тона), мигание -- удобнее как фоновый визуальный контроль.
;   Основной hex делает ОБА; тихий вариант: -D TONE=0.
;
; ДИАГНОСТИКА:
;   тон + мигание ~1 Гц      -> таймер, RST 7.5, ре-арм: ПАСС
;   тишина, но мигает        -> таймер ОК; смотреть цепь SND/излучатель
;   тон вдвое ниже (~230 Гц) -> квант 102,4 мкс вместо 51,2 (дефект HDL)
;   тишина и горит "8."      -> программа не стартует (ПЗУ/шина/CPLD)
; =====================================================================

; ---- параметры (можно переопределить ключами -D) ----
TMR_N   EQU 20              ; период: 20 x 51,2 мкс = 1,024 мс (1..255)
TONE    EQU 1               ; 1 = зуммер тикает каждое прерывание
BLINK   EQU 1               ; 1 = мигание 'g' каждые KA*KB прерываний

; ---- порты и переменные ----
SEGP    EQU 00h             ; порт SEG:  D0=a..D6=g, D7=dp (1 = горит в регистре)
DIGP    EQU 01h             ; порт DIG/SND: D3-D0 разряды, D4=SND (меандр!)
TMRP    EQU 04h             ; порт таймера: запись N (T = N x 51,2 мкс)
SIMW    EQU 1Bh             ; SIM: маскировать 5.5/6.5, РАЗРЕШИТЬ 7.5, сброс латча
KA      EQU 116             ; мигание: 116 x 4 = 464 прерывания ~ 0,5 с
KB      EQU 4
SEGST   EQU 8000h           ; ОЗУ: копия регистра SEG (для инверсии битов)
DIGST   EQU 8001h           ; ОЗУ: копия регистра DIG/SND

; ---- векторы ----
        ORG 0000h
        JMP MAIN            ; сброс: переход на инициализацию
        ORG 003Ch
        JMP ISR             ; вектор RST 7.5 = 003Ch

; ---- ISR: тон + мигание + РЕ-АРМ (обязателен! автоперезагрузки нет) ----
        ORG 0040h
ISR:    PUSH PSW
        PUSH B
        IF TONE
        LDA DIGST           ; инверсия D4 (SND) в копии и в порту:
        XRI 10h             ; меандр с полупериодом = периоду прерываний
        STA DIGST
        OUT DIGP
        ENDIF
        IF BLINK
        DCR C               ; каскадный счётчик мигания B:C (B=KB, C=KA)
        JNZ TMRGO
        MVI C,KA
        DCR B
        JNZ TMRGO
        MVI B,KB
        LDA SEGST           ; инверсия сегмента 'g' (D6) в копии и в порту
        XRI 40h
        STA SEGST
        OUT SEGP
        ENDIF
TMRGO:  MVI A,TMR_N         ; РЕ-АРМ: счётчик стоит в нуле, загружаем N заново
        OUT TMRP
        POP B
        POP PSW
        EI
        RET

; ---- MAIN: инициализация и сон до прерываний ----
        ORG 0080h
MAIN:   LXI SP,0FFFFh       ; стек -- верх ОЗУ (8000h-FFFFh)
        MVI A,0C0h          ; сегменты: 'g' + dp (мигает 'g', dp -- маячок)
        STA SEGST
        OUT SEGP
        MVI A,0Fh           ; все 4 разряда статически; нагрузка меньше INIT "8."
        STA DIGST           ; (SND=0 -- тишина до первого прерывания)
        OUT DIGP
        LXI B,KB*256+KA     ; счётчик мигания: B=KB=4, C=KA=116
        MVI A,TMR_N
        OUT TMRP            ; загрузить N и запустить (1-е прерывание ~1 мс)
        MVI A,SIMW
        SIM                 ; RST 7.5 разрешён, латч сброшен, 5.5/6.5 маскированы
        EI
HLTLP:  HLT                 ; спим: таймер будит процессор каждые ~1,07 мс
        JMP HLTLP
        END
