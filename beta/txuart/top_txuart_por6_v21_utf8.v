// ДЕЙСТВУЮЩИЕ РЕШЕНИЯ:
//  п.3  (= п.13) (истор. v2.0: TX-транзит ВЫПИЛЕН - заменён ядром
//       TXUART, п.27) TX-ТРАНЗИТ С ЗАХВАТОМ - см. п.13.
//  п.4  WRITEBACK - ЗАЩИЩЁННЫЙ ИМПУЛЬС /WE (главное решение шины!):
//       импульс /WE ДОВОДИТСЯ ДО КОНЦА НЕЗАВИСИМО ОТ ALE (hold-off 0,
//       цепочка WB сжата до 4 состояний): ALE обрывает только T2, в
//       WB1..WB4 НЕ вмешивается. Драйверы A/D держат СТАРЫЙ
//       адрес/данные до конца импульса (wb_out = in_wb БЕЗ !ALE);
//       конфликт с новым адресом CPU выигрывает CPLD (24 мА против
//       2 мА у ВМ85), адрес на входах ОЗУ стабилен весь импульс
//       (t_AS 40 нс, /WE 80 нс), запись попадает по адресу; захват
//       следующего цикла успевает в T1 (из WB в T1H попадаешь только
//       через IDLE - см. п.6).
//  п.5  (истор.) защёлка wb_ram_q УДАЛЕНА в v3.9.1 - см. п.16; защита
//       записи живёт построением п.4/п.16.
//  п.6  ЗАХВАТ T1H СТРУКТУРНО ЗАЩИЩЁН: из WB в T1H можно попасть
//       только через IDLE, поэтому addr_latch НЕ перезаписывается
//       посреди импульса.
//  п.8  por_run - РЕГИСТР, не комбинация: комбинационный декод
//       (por_cnt!=0) фиттер схлопывал в PT всех приёмников cpu_rst ->
//       ширина PT и входы ФБ росли, Placement Failed (фит v3.1); FF-
//       выход схлопыванию не подлежит. Правило живо: por_run.D =
//       por_sh[0].
//  п.9  (ПРАВИЛО ФИТТЕРА) декоды равенства в узле тактирования и
//       POR-цепи ЗАПРЕЩЕНЫ: фиттер трижды терял полярность свёрнутых
//       декодов (фиты 10-22 7:31/8:55 - счётчик залипал, POR
//       схлопывался до 1 клока, X2 вставал регистром в фазу). Поэтому:
//       POR - сдвиговый регистр por_sh БЕЗ декодов; в узле - кольцо
//       (декодов нет вовсе). Появился ==N в уравнениях узла - собран
//       НЕ ТОТ исходник.
//  п.10 (ПРАВИЛО ФИТТЕРА) X2 строится БЕЗ одиночной инверсии регистра:
//       комбинационная ~X1 фиттер поднимал в регистр В ФАЗЕ (keep на
//       порте НЕ спас, фит v3.4 - CPU не заведётся). Здесь X2 = 6-ПТ OR
//       r1..r6 = ~r0 в каждом легальном one-hot - комбинационный, same-D
//       слияние невозможно по построению. X2 в .rpt - регистр в фазе
//       r0: БРАК, не шить.
//  п.13 (истор. v2.0: транзит ВЫПИЛЕН, заменён ядром TXUART - п.27/
//       п.29) TX-ТРАНЗИТ С ЗАХВАТОМ ПО УРОВНЮ (замена TX-маски v2-v3.6,
//       txm_cnt и параметр TXM_W удалены): датасшит ВМ85А - аппаратный
//       сброс очищает SOD в '0', до первого SIM линия '0' = «вечный
//       start-bit» -> пустой фрейм в терминале. Вместо таймера - схемный
//       захват ПО УРОВНЮ (частота и длина init прошивки не важны):
//       sod_q - синхронизатор входа SOD по clk25 (метастабильность
//       гасится до использования, статический путь пин->пин разорван);
//       tx_pass - «линия захвачена»: async clear по cpu_rst (cpu_rst
//       держит tx_pass=0 ВЕСЬ POR - враждебный SOD в окне POR линию не
//       захватывает), взвод первым сэмплом SOD='1'; tx_q - регистр TX
//       (IO-MC пина P39, INIT=1, async set по cpu_rst): в сбросе TX='1'
//       мгновенно и БЕЗ клока, до захвата - чистый idle, после - транзит
//       sod_q (латентность <= 2 такта 25 МГц). Требование к прошивке
//       одно: первое касание SOD после сброса = SOD:=1 (TXIDLE fw_mon).
//       Теоретический ложный SOD='1' - лечение: захват по 2 сэмплам
//       подряд (+1 FF).
//  п.15 КОЛЬЦО С ДВОЙНЫМ KILL (самоочистка): r_i <= r_{i-1} & ~r_i &
//       ~r_{i+1} & ~r_{i+2}, рестарт из 00 по NOR7. ОДИНАРНЫЙ kill
//       («убей преемника», v3.8) на N=7 НЕ гасит пары '1' на дистанции
//       3-4 - они ОРБИТЯТ ВЕЧНО (14 из 128 состояний; поймано перебором
//       sim_v39_ring7.py ДО фита). Двойной kill: ЛЮБОЕ из 128 состояний
//       -> one-hot за <= 2 фронта (полный перебор sim_v39_ring7.py; на
//       RTL v3.9.8 - tb_poweron_v398 P0a: 2560 комбинаций с por-цепью).
//  п.16 CS_n В WRITEBACK - ОТ СОСТОЯНИЯ FSM: assign CS_n = in_wb ?
//       1'b0 : (!A15 | IOM); защёлка wb_ram_q удалена - единственный
//       читатель wb_ram_q был CS_n, а in_wb (state >= S_WB1) влечёт её
//       условие; сброс синхронный, одним фронтом со state. Эквивалент-
//       ность v3.9 доказана (полный перебор произведения машин + дифсим
//       двух RTL, 0 расхождений). В WB1..WB4 CS_n = 0 БЕЗ A15/IOM -
//       живой декод во время конфликта адресов по-прежнему не участвует,
//       запись ОЗУ защищена построением.
//  п.17 (истор.) линия счётчика mod-7 (v3.9.2-3.9.6) заменена кольцом
//       (возврат п.22) - полный текст в DEVLOG. v3.9.8-clear: legacy-
//       ветки делителя и их регистры (cnt/x1_q/t0_q/x1_p/x1_n/x2_q/
//       x2_p) УДАЛЕНЫ из RTL - единственная ветка узла g_div2p5;
//       откат - исходник top_suart_por6_v398.v. Отсутствие в нетлисте
//       проверяет чек-лист h), Xst:1780 более не выдаются.
//  п.18 СБРОС ЛОГИКИ -> СЕТЬ GSR (асинхронный): always @(posedge clk25
//       or posedge cpu_rst) / if (cpu_rst) - условие v3.9.2 (чистка
//       КАЖДЫЙ такт сброса), структура уводит сброс в СЕТЬ GSR. ВНЕ GSR
//       сознательно (бит-в-бит v3.9.2): делитель (X1 не глушится при
//       сбросе, фаза CLKOUT не прыгает), por-цепь (por_run в GSR нельзя
//       - сбрасывал бы сам себя; POR только по питанию), sod_q,
//       tx_pass/tx_q (async SR по cpu_rst - держит tx_pass=0 весь POR).
//       Риск метастабильности снятия GSR - осознанный компромисс: FSM
//       самозатухающий (default->IDLE, abort по ALE, повторный захват).
//       ГЕЙТ ОКНА POR: FSM в окне POR ЖИВОЙ (GSR не активен), а шина
//       CPU в сбросе «floated» (ВМ85А 3-стирует управления/адрес/данные)
//       - вход в writeback ЗАПРЕЩЁН (!por_run в S_T2): импульс /WE в
//       окне POR невозможен ПО ПОСТРОЕНИЮ.
//  п.20 GSR-ИСТОЧНИК = cpu_rst = rst_press | por_run (НЕ сырой RST):
//       в окне POR логика чистится асинхронно с t=0 (por_run=1 с INIT)
//       - чистый выход в IDLE ГАРАНТИРОВАН; дефект v3.9.4 «грязный
//       выход CPU из POR» закрыт (fuzz tb_por_fuzz: грязь на снятии
//       por_run - v3.9.4 100/100, v3.9.5 0/100); кнопка RESET - прежняя
//       семантика (см. п.21).
//  п.21 ХАРДРЕНИНГ RST: пин входит в кристалл ТОЛЬКО через регистры
//       (мид-рейл/дребезг/помеха на SW20 физически не доходят ни до 40
//       сбросовых входов триггеров, ни до ноги RESET_IN; в v3.9.5 RST
//       шёл напрямую в гейт RESET_IN и PTC-сбросы - дефект старта):
//       (a) 2FF-синхронизатор rst_meta/rst_sync (вне сброса, INIT=0);
//       (b) квалификатор rst_press/rst_qcnt - переворот на 8-м такте
//           ПОДРЯД устойчивого rst_sync != rst_press (двусторонний:
//           и взвод, и снятие квалифицированы); дребезг короче 280 нс
//           не виден вовсе, длиннее - ПОЛНОЦЕННЫЙ повторный сброс;
//           ПОСЛЕДНЕЕ снятие всегда из held-чистого состояния;
//       (c) cpu_rst = rst_press | por_run - ТОЛЬКО регистровые
//           источники (комбинаций от пинов в цепи сброса нет);
//       (d) RESET_IN - РЕГИСТР reset_q (INIT=0 - CPU в сбросе с t=0
//           до всякого клока; снятие - чистым фронтом);
//       (e) гейт S_T2: !por_run AND !rst_press (рубеж распространён
//           на окна кнопочного сброса);
//       (f) начатый импульс /WE (80 нс) НЕ обрывается: квалификатор
//           (400 нс) длиннее импульса - запись доводится до конца.
//       Латентность кнопки 400..440 нс (2FF + 8 такт квалификатора +
//       reset_q); НОВОЕ свойство: глитч на RST короче ~280 нс сброс НЕ
//       вызывает. POR НЕ ТРОНУТ (вне GSR, повторный POR невозможен).
//  п.22 КОЛЬЦО one-hot r0..r6 - БАЗОВЫЙ узел (возврат v3.9.7 по
//       директиве владельца: единственная конфигурация узла
//       тактирования, дававшая в ПОЛЕ стабильные сессии у обоих
//       экземпляров; лотерея включения сведена к аналоговой за
//       пределами делителя - детали и чек-лист D1-D4 в DEVLOG).
//       Построение - п.15, домен - п.23.
//  п.23 УЗЕЛ ТАКТИРОВАНИЯ НА 50 МГц (схема владельца 11-6bis-2):
//       вход CPLD 50 МГц - перемычка H1 БЕЗ шунта (DIV=/2 генератора
//       U7; штатное положение с шунтом давало 25). Кольцо r0..r6 (п.22,
//       БЕЗ ИЗМЕНЕНИЙ) тактируется clk 50 МГц НАПРЯМУЮ (период 140 нс);
//       x1_n и negedge-домен УДАЛЕНЫ - вторую кромку даёт сам clk 50
//       (v3.9.8-clear: x1_n вычеркнут и из RTL). X1 = r0: фронт строго
//       каждые 140 нс = 7,143 МГц, duty 1/7 (high 20 / low 120 нс);
//       внутренний /2 ВМ85А тактируется
//       ФРОНТАМИ X1 -> CLK = 3,571 МГц, период 280 нс, duty РОВНО 50%.
//       ЕСЛИ генерация CPU не заведётся на 20-нс high - откат одной
//       строкой RTL: X1 = r0 | r1 (high 40 нс), частоты те же.
//       X2 = r1|r2|r3|r4|r5|r6 = ~r0 в легальном one-hot (п.10); в
//       illegal-кодах самоочистки X2 != ~X1 - транзиент во время POR
//       на мёртвой для CPU фазе, схемно незначимо. ЛОГИКА (rst/TX/FSM/
//       порты) - на clk25 = /2-триггер clk25_q от clk 50 (INIT=0 - фаза
//       фиксирована): XC95108-15 FSM/шина на 50 МГц НЕ закроет, а /WE
//       80 нс (2 тика), квалификатор 320 нс (8 тиков) и все тиковые
//       константы обязаны остаться - логика живёт на 25 МГц, узел - на
//       50. por-цепь - В 50-ДОМЕНЕ: por_sh[7:0] (Init=FF), строб
//       por_ce = r0 - РОВНО ОДИН за период кольца 140 нс («раз в
//       140 нс» владельца; r1|r6 на кольце 50 стреляло бы ДВАЖДЫ за
//       период, а сэмпл 20-нс стробов тактом clk25 - ФАЗОВАЯ ЛОТЕРЕЯ:
//       при нечётной фазе стробы не видны ВОВСЕ - POR не кончается
//       НИКОГДА; в 50-домене строб - синхронное включение того же
//       такта, детерминировано). POR = 8 x 140 = 1120 нс (норма
//       3 такта CLK OUT = 840 нс, запас 1,33x); повторный POR
//       невозможен (после 00 сдвиг держит нули навсегда).
//  п.24 ВЕРИФИКАЦИЯ v3.9.8: дифсимуляция tb_v398_diff.v (Icarus 12.0) -
//       69 044 выборки 5 нс, 0 расхождений с v3.9.7 на всех выходах
//       логики (por_run, RESET_IN, кромки кнопки - на тех же кромках);
//       XP: X1 ровно 140 нс, duty 20/120 у обоих; tb_poweron_v398:
//       P0a 2560 комбинаций (128 кодов кольца x 10 por_sh x 2 фазы
//       clk25) - one-hot <= 2 фронтов, дрейн <= 1600 нс у ВСЕХ;
//       P0b PASS (монотонный дрейн без возврата); P1 - сид-в-сид
//       эталону v3.9.7 (3/100 хвостовых /WE - принятый класс окна);
//       P2-P5 PASS (мёртвый clk, поздний clk, RST=1, лотерея
//       передёргиваний). ЖЕЛЕЗО: подтверждено владельцем - v3.9.8
//       стабильно, зависаний нет (базовый кандидат линии).
//  п.25 АУДИТ ФИТА v3.9.8 (фит владельца) - ВЕРДИКТ «ФИТ ЗОЛОТОЙ»:
//       94/108 МЦ (87%), 287/540 ПТ (53%), 183-185/216 вх.ФБ, 65 рег,
//       72/81 ноги; сравнение IL 16 vs IL 28 - байт-в-байт (остаться
//       на IL 28). Кольцо = RTL байт-в-байт: r0 - FB6_3 (P68, INIT
//       SET, 2 ПТ), r1..r6 - INIT RESET (FB6); двойной kill + рестарт
//       из 00 по NOR7 на месте, декодов равенства НЕТ. X2 - своя МЦ
//       FB6_5 (P69), 1 ПТ: фиттер свернул 6-ПТ OR в NOR-форму с
//       инверсией выхода (класс п.10, эквивалент точный),
//       комбинационный (регистра нет - «в фазе r0» исключено).
//       clk25_q - 1 триггер; por_sh[7:0] на clk 50 (Init=FF), строб
//       r0, por_run.D = por_sh[0]; сброс - п.21. WARNING:Cpld:897 -
//       буфер D<7> (FB5_7) - известный класс, НЕ блокер (первый
//       подозреваемый при сбоях бита D7); сеть clk25 - на глобальной
//       тактовой (прецедент: complement of clk -> GCK2, фит v3.9.5);
//       clk -> GCK3 - единственная глобальная.
//  п.26 АУДИТ РЕФИТА v3.9.8-clear ред.2 (фит владельца 11-7 10:09PM,
