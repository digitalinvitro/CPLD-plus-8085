; =====================================================================
; beta/txuart/v37gen -- fw_diag_ab: ДИАГНОСТИКА RX v2 = АВТОБОД + ДЕКОД.
; Плата retro_pcld (CPLD v37G01, XC95108), CPU 8085 @3,125 МГц.
;
;   ПРЕДЫСТОРИЯ: fw_diag_sid (v1, счётчики фронтов SID) показал +3/+3
;   на символ ('1','2','3' при 8N1 = 3 падения + 3 подъёма) - RX-путь
;   ЖИВ, кадры чистые. Но счёт фронтов НЕ ЗАВИСИТ от скорости: v1 не
;   различает 4800/9600/7E1. Монитор висит на LLLL при ручном
;   ':00000001FF'. Гипотезы: (H1) терминал не 4800/8N1 -> мусор/пропуск
;   молча; (H2) всё декодируется, но выход загрузчика (TICKON) сломан.
;   v2 различает их за один прогон.
;
;   ЧТО ДЕЛАЕТ:
;   1) Ловит падающий фронт SID (старт-бит), меряет его ШИРИНУ в
;      единицах ~11,8 мкс (петля 37T: RIM+ORA+JM+INR+JMP) и берёт
;      минимум по кадрам (d0=0 удваивает ширину - кадр с d0=0
;      отбрасывается: декодируются только кадры, где W <= MINW).
;   2) Классифицирует MINW: [6..13]=9600, [14..27]=4800, [28..55]=2400,
;      [56..110]=1200, прочее - вне диапазона (декод не делается).
;   3) Декодирует текущий кадр по RXD-схеме монитора (полубит-
;      подтверждение, 8 выборок LSB-first, проверка стопа) с константой
;      DLAY(n) = 31T + 14n*T: 9600 -> n=21, 4800 -> n=44, 2400 -> n=90,
;      1200 -> n=183. Полубит = n/2 через RRC.
;
;   ДИСПЛЕЙ (~70 Гц, динамическая развёртка самим ЦП):
;       DIG3 DIG2 | DIG1 DIG0
;       [ W=MINW ] [ байт ]   hex; байт: 'EE' = ошибка стоп-бита,
;       00 (blank) = ещё не декодировано.
;   ЧТЕНИЕ (измеренная ширина в единицах ~11,8 мкс, минус ~2 ед.
;   задержки обнаружения от истинных 17,6/8,8/35,2/70,4):
;       ~15-16 = 4800;  ~7 = 9600;  ~33 = 2400;  ~68 = 1200;
;       ~3-4 = 19200 (не декодируется - слишком быстро для петли).
;   ИНТЕРПРЕТАЦИЯ:
;       W~17 и байт 3A на ':'  -> H2: приём работает, копать выход
;                                 загрузчика (TICKON/LDDONE).
;       W~9 и байт 3A          -> H1: терминал реально на 9600.
;       W~17, байты с битом 7  -> 7 бит данных (7N1/7E1).
;       W~17, байт EE          -> parity/стоп не 8N1.
;   ПЕРВЫЙ СИМВОЛ ПОСЛЕ RESET - ':' (у него d0=1, ширина старт-бита
;   измерится верно; кадры с d0=0 не декодируются по построению).
;   После смены скорости в терминале - RESET платы.
;
;   ПОРТЫ: 00h сегменты D6-D0 (D0=a..D6=g), 01h разряды D3-D0 + D4 SND.
;   RAM: PREV=FFE8, MINW=FFE9, WGLH=FFEA, WGLL=FFEB, BGLH=FFEC,
;   BGLL=FFED. SP=FFE7 (глубина <=3 CALL -> FFE1, всё в ОЗУ).
;   Прерывания не используются (IE=0). Выход - RESET, затем вернуть
;   fw_monitor_ACdE_tm_xstream_v2_0_3.hex (offset 0000h).
; =====================================================================

SEGP    EQU 00h             ; сегменты
DIGP    EQU 01h             ; разряды + SND

PREV    EQU 0FFE8h          ; предыдущий уровень SID (00h/80h)
MINW    EQU 0FFE9h          ; ширина старт-бита (ед. ~11,8 мкс), FF = не мерили
WGLH    EQU 0FFEAh          ; глиф старшей тетрады W
WGLL    EQU 0FFEBh          ; глиф младшей тетрады W
BGLH    EQU 0FFECh          ; глиф старшей тетрады байта
BGLL    EQU 0FFEDh          ; глиф младшей тетрады байта

        ORG 0000h
        JMP START

        ORG 0008h
        RET
        ORG 0010h
        RET
        ORG 0018h
        RET
        ORG 0020h
        RET
        ORG 0024h
        RET
        ORG 0028h
        RET
        ORG 0030h
        RET
        ORG 0038h
        RET
        ORG 003Ch
        RET

; ---------------------------------------------------------------------
        ORG 0040h
START:  LXI SP,0FFE7h
        XRA A
        OUT SEGP            ; сегменты blank
        OUT DIGP            ; разряды off
        STA WGLH            ; все глифы = blank (00h)
        STA WGLL
        STA BGLH
        STA BGLL
        MVI A,0FFh
        STA MINW            ; ширина ещё не измерена
        RIM                 ; текущий уровень SID -> PREV
        ANI 80h
        STA PREV

; ---- главный цикл: развёртка 4 разрядов, в паузах - опрос SID ----
MAIN:   LDA WGLH
        MVI B,08h           ; DIG3
        CALL SLOT
        JC  MEAS            ; в слоте поймано падение -> измерить
        LDA WGLL
        MVI B,04h           ; DIG2
        CALL SLOT
        JC  MEAS
        LDA BGLH
        MVI B,02h           ; DIG1
        CALL SLOT
        JC  MEAS
        LDA BGLL
        MVI B,01h           ; DIG0
        CALL SLOT
        JC  MEAS
        JMP MAIN

; ---------------------------------------------------------------------
; SLOT: показать глиф (A) на разряде (B) ~3 мс. Всю паузу опрашивает
; SID (итерация 39T ~ 12,5 мкс: PREV кэшируется в E, запись в память -
; только при смене уровня); при ПАДАЮЩЕМ фронте (был 1 -> стал 0)
; выходит сразу с CY=1. PREV обновляется при смене уровня. Портит
; A/C/D/E; B сохраняет.
SLOT:   OUT SEGP
        MOV A,B
        OUT DIGP
        MVI D,0C8h
        LDA PREV
        MOV E,A             ; E = кэш PREV на время слота
SLOT1:  RIM                 ; A7 = SID
        ANI 80h
        MOV C,A             ; C = текущий уровень
        MOV A,E
        CMP C               ; уровень сменился?
        JZ  SLOT2           ; нет - продолжить слот
        MOV A,C             ; смена: обновить PREV и кэш
        STA PREV
        MOV E,A
        JC  SLOT2           ; CY=1: 00->80, восходящий - игнор
        STC                 ; падающий (1->0) - старт-бит!
        RET
SLOT2:  DCR D
        JNZ SLOT1
        XRA A               ; CY = 0 - слот отработал целиком
        RET

; ---------------------------------------------------------------------
; MEAS: ширина низкого уровня (старт-бита), минимум по кадрам,
; классификация, декод кадра по схеме RXD монитора.
MEAS:   MVI C,00h
WLP:    RIM                 ; A7 = SID
        ORA A
        JM  WDONE           ; линия ушла в 1 - конец низа
        INR C
        JZ  WOVF            ; >3 мс низа - не UART (break/наводка)
        JMP WLP
WDONE:  MVI A,80h
        STA PREV            ; текущий уровень = 1
        LDA MINW
        CMP C               ; MINW < C? (CY=1) - кадр шире минимума
        JC  MEASX           ; -> фаза сомнительна (d0=0), не декодировать
        MOV A,C
        STA MINW            ; новый минимум
        MOV B,A             ; B = W (GNIB берёт байт в B, сохраняет его)
        CALL GNIBH
        STA WGLH
        CALL GNIBL
        STA WGLL
        MOV A,B             ; классификация W
        CPI 6               ; [2..5] - слишком быстро (19200+)
        JC  MEASX
        CPI 14              ; [7..13] - 9600
        JC  SP9600
        CPI 28              ; [14..27] - 4800
        JC  SP4800
        CPI 56              ; [28..55] - 2400
        JC  SP2400
        CPI 111             ; [56..110] - 1200
        JC  SP1200
        JMP MEASX           ; медленнее 1200 / мусор - только ширина
SP9600: MVI C,21
        JMP RXD2
SP4800: MVI C,44
        JMP RXD2
SP2400: MVI C,90
        JMP RXD2
SP1200: MVI C,183
        ; JMP RXD2
; ---------------------------------------------------------------------
; RXD2: декод кадра. Вход: C = полная задержка бита (ед. DLAY: 14T).
; Ждёт idle-high, затем падение, полубит-подтверждение, 8 выборок
; LSB-first, стоп-бит. Успех: глифы байта; сбой: глифы 'EE'.
RXD2:   RIM                 ; 1) дождаться idle-high (после WMEAS может
        ORA A               ;    быть уже high)
        JP  RXD2
        MVI B,08h
RXW2:   RIM                 ; 2) ждать падение (старт-бит)
        ORA A
        JM  RXW2
        MOV A,C             ; 3) полубит - подтвердить старт
        RRC
        ANI 7Fh             ; RRC для нечётных C тянет A0 в A7 - маскировать
        MOV D,A
        CALL DLAY
        RIM
        ORA A
        JM  RXW2            ; ложный старт
        XRA A
        MOV E,A             ; E = накопитель байта
        MOV A,C
        MOV D,A             ; 4) полный бит - центр D0
        CALL DLAY
RXL2:   RIM                 ; выборка бита
        ANI 80h
        RAR                 ; бит -> CY
        MOV A,E
        RAR                 ; вставить сверху (LSB-first)
        MOV E,A
        MOV A,C
        MOV D,A
        CALL DLAY
        DCR B
        JNZ RXL2
        RIM                 ; 5) центр стоп-бита
        ANI 80h
        JZ  RXERR
        MOV A,E             ; 6) успех - глифы байта
        MOV B,A
        CALL GNIBH
        STA BGLH
        CALL GNIBL
        STA BGLL
        JMP MEASX
RXERR:  MVI A,79h           ; 'E'
        STA BGLH
        STA BGLL
MEASX:  JMP MAIN

; ---------------------------------------------------------------------
; DLAY: задержка (31 + 14*n)T = 9,9 + 4,48n мкс. Вход D = n (>=1).
DLAY:   DCR D
        JNZ DLAY
        RET

; GNIBH/GNIBL: байт в B -> A = глиф старшей/младшей тетрады.
; Сохраняет B/C, портит A/D/E/HL.
GNIBH:  MOV A,B
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        JMP GNIBC
GNIBL:  MOV A,B
        ANI 0Fh
GNIBC:  MOV E,A
        MVI D,00h
        LXI H,GTBL
        DAD D
        MOV A,M
        RET

WOVF:   MVI A,80h           ; слишком долгий низ - просто возобновить
        STA PREV            ; развёртку (PREV уже верен, для порядка)
        JMP MEASX

GTBL:   DB 3Fh              ; '0'
        DB 06h              ; '1'
        DB 5Bh              ; '2'
        DB 4Fh              ; '3'
        DB 66h              ; '4'
        DB 6Dh              ; '5'
        DB 7Dh              ; '6'
        DB 07h              ; '7'
        DB 7Fh              ; '8'
        DB 6Fh              ; '9'
        DB 77h              ; 'A'
        DB 7Ch              ; 'b'
        DB 39h              ; 'C'
        DB 5Eh              ; 'd'
        DB 79h              ; 'E'
        DB 71h              ; 'F'
