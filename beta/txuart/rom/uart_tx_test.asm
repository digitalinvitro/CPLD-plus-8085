; =====================================================================
; beta/txuart/rom/uart_tx_test.asm -- железная проверка аппаратного
; передатчика UART v2.2 (beta/txuart, узел /4 на 25 МГц, шунт H1).
;
; Частоты (v2.2): вход CPLD 25 МГц (H1 С ШУНТОМ!), кольцо s0..s3 ->
;   X1 = 6,25 МГц (duty 1/4), /2 ВМ85А -> CPU 3,125 МГц, T = 320 нс.
; UART: 1 562 500 8N1 (25 МГц / 16), аппаратное ядро v2.1 (18 МЦ).
;   OUT 04h = TXDATA (запись при TXRDY=0 - байт ТИХО ОТБРАСЫВАЕТСЯ!)
;   IN  05h = статус: бит A1 = TXRDY (1 = ядро idle, можно стартовать)
;   Окно POR: запись 04h при por_run отбрасывается ядром (CPU в это
;   время в reset, до старта прошивки не доходит).
; Контракт: README beta/txuart ("Контракт (для прошивки)" п.1-4).
;
; Что делает прошивка:
;   1) Раз в ~200 мс шлёт строку "TXUART v2.2 OK N=xx" + CR LF,
;      xx = счётчик строк (hex, mod 256). Каждый байт - строго после
;      поллинга TXRDY=1 (IN 05h, ANI 02h).
;   2) Индикация: мультиплекс 7-сегм. 1 мс/разряд (250 Гц):
;      DIG3='t' (тест идёт), DIG2=DIG1='-', DIG0=мл. нибл счётчика.
;      OUT 00h = сегменты (1 = горит), OUT 01h = разряды (A3..A0),
;      бит A4 порта 01h = SND - держится 0 (звук молчит).
;   3) Прерывания запрещены (DI; линии INT заземлены PGND), стек
;      в ОЗУ 8000h-FFFFh на 0E000h.
;
; Проверка на ПК: терминал 1 562 500 8N1 (CH340G), ~5 строк/с,
;   счётчик N инкрементируется. Нет строк, но индикатор жив -> TX-путь
;   (CPLD P39 -> CH340G RXD) или терминал; нет и индикатора -> CPU/шина.
;
; Сборка: python3 beta/01_timer/rom/asm85.py
;           beta/txuart/rom/uart_tx_test.asm
;           -o beta/txuart/rom/uart_tx_test.hex
;           -l beta/txuart/rom/uart_tx_test.lst
; Симуляция: python3 beta/txuart/rom/sim_uart_tx_test.py
;            (интерпретатор 8085 по .hex + модель TXRDY/дисплея).
;
; Кодировка исходника: CP1251 (канон проекта); _utf8-двойник рядом.
; =====================================================================

; ---- порты CPLD (карта beta/txuart README + PORTS_MAP) --------------
K_PSEG   EQU 00h            ; сегменты индикатора (регистр 1 = горит)
K_PDIG   EQU 01h            ; разряды A3..A0 (1 = разряд горит); A4 = SND
K_PTX    EQU 04h            ; TXDATA: старт кадра (только при TXRDY=1!)
K_PST    EQU 05h            ; статус: A1 = TXRDY
K_TXRDY  EQU 02h            ; маска TXRDY в статусе
K_MS     EQU 200            ; пауза между строками, мс
K_1MS    EQU 212            ; счётчик 1-мс среза: 3131 T ~ 1001,9 мкс
K_SP     EQU 0E000h         ; стек в верхней половине ОЗУ

K_PHTAB  EQU 02h            ; страница HTAB (таблица глифов, 0200h..020Fh)
K_PDTAB  EQU 03h            ; страница DTAB (маски разрядов, 0300h..0303h)
G_MINUS  EQU 40h            ; глиф '-' (сегмент g)
G_T      EQU 78h            ; глиф 't' (сегменты d,e,f,g)

; ---------------------------------------------------------------------
         ORG  0000h
         JMP  START         ; вектор сброса; RST 08/10/... не используются

         ORG  0100h
START:   DI                 ; прерываний нет и не будет (INT -> PGND)
         LXI  SP,K_SP       ; стек
         MVI  C,00h         ; счётчик строк N (показ на DIG0)
         MVI  E,00h         ; фаза мультиплекса 0..3

; ---- главный цикл: строка -> пауза ----------------------------------
MAIN:    LXI  H,MSG
         CALL PUTS          ; "TXUART v2.2 OK N="
         MOV  A,C           ; старший hex-символ счётчика
         RRC
         RRC
         RRC
         RRC
         ANI  0Fh
         CALL PUTH
         MOV  A,C           ; младший hex-символ счётчика
         ANI  0Fh
         CALL PUTH
         MVI  A,0Dh         ; CR
         CALL PUTC
         MVI  A,0Ah         ; LF
         CALL PUTC
         INR  C             ; N++ (mod 256)
         MVI  B,K_MS        ; пауза K_MS мс с мультиплексом дисплея
DL1:     CALL SLICE         ; 1 мс + один шаг мультиплекса
         DCR  B
         JNZ  DL1
         JMP  MAIN

; ---- PUTC: выдать байт ядру (A = байт) ------------------------------
; Поллинг TXRDY ДО каждого OUT 04h - контракт п.1: запись при busy
; тихо отбрасывается ядром, поэтому только так.
PUTC:    MOV  B,A           ; сохранить байт (A пачкается в поллинге)
PW1:     IN   K_PST         ; IN = 10 T; период опроса ~27 T
         ANI  K_TXRDY       ;   < 6,4 мкс кадра и < 20 T занятости,
         JZ   PW1           ;   TXRDY - уровень: промаха нет
         MOV  A,B
         OUT  K_PTX         ; старт кадра (8N1, 10 бит, 6,4 мкс)
         RET

; ---- PUTH: ASCII hex-цифра (A = 0..15) ------------------------------
; В UART идёт СИМВОЛ ('0'..'9','A'..'F'), а не глиф индикатора
; (HTAB - только для мультиплекса дисплея, урок первой симуляции).
PUTH:    CPI  0Ah
         JC   PHD           ; 0..9 -> '0'..'9'
         ADI  37h           ; 0Ah..0Fh + 37h = 'A'..'F'
         JMP  PUTC
PHD:     ADI  30h           ; + 30h = '0'..'9'
         JMP  PUTC          ; сквозной вызов в PUTC (без CALL)

; ---- PUTS: строка из (HL) до 00h ------------------------------------
PUTS:    MOV  A,M
         ORA  A
         RZ                 ; конец строки
         CALL PUTC
         INX  H
         JMP  PUTS

; ---- SLICE: пауза ~1 мс + один шаг мультиплекса ---------------------
; Внутренний цикл: MVI 7 + (DCR 4 + JNZ 10)*(K_1MS-1) + DCR 4 + JNZ 7
;   = 7 + 14*(K_1MS-1) + 11 = 2972 T; мультиплекс 109-117 T (по фазе);
;   CALL/RET 28 T. ИТОГО 3109..3117 T = 994,9..997,4 мкс (-0,3% к 1 мс;
;   не таймирует UART, только пауза между строками; точно меряет
;   симуляция sim_uart_tx_test.py: C4 медиана 3117 T).
SLICE:   MVI  L,K_1MS
SL1:     DCR  L
         JNZ  SL1
         MOV  A,E           ; выбор глифа по фазе E
         CPI  01h
         JC   M0            ; E=0 -> млад. нибл счётчика C
         CPI  03h
         JC   M12           ; E=1..2 -> '-'
         MVI  A,G_T         ; E=3 -> 't'
         JMP  MW
M0:      MOV  A,C
         ANI  0Fh
         MOV  L,A
         MVI  H,K_PHTAB     ; L уже = индекс глифа 0..F
         MOV  A,M           ; глиф 0..F
         JMP  MW
M12:     MVI  A,G_MINUS
MW:      OUT  K_PSEG        ; сегменты (призрак чужого разряда < 2 мкс)
         MOV  A,E
         MOV  L,A
         MVI  H,K_PDTAB     ; страница таблицы разрядов (DTAB = 0300h+фаза)
         MOV  A,M           ; маска разряда 01/02/04/08 (A4=0 - SND тих)
         OUT  K_PDIG
         INR  E
         MOV  A,E
         ANI  03h
         MOV  E,A
         RET

; ---- данные (HTAB/DTAB на границах страниц: индекс = L) --------------
         ORG  01C0h
MSG:     DB   'TXUART v2.2 OK N='
         DB   00h

         ORG  0200h
HTAB:    DB   3Fh,06h,5Bh,4Fh,66h,6Dh,7Dh,07h   ; глифы 0-7 (1 = горит)
         DB   7Fh,6Fh,77h,7Ch,39h,5Eh,79h,71h   ; глифы 8-F
         ORG  0300h
DTAB:    DB   01h,02h,04h,08h                   ; разряды DIG0..DIG3

         END
