; =====================================================================
; beta/txuart/rom -- fw_monitor_ACdE_tm_xstream v1.1: монитор для платы
; v2.9 (RTL top_txuart_por6_v29, ШАГ-1: СЛИТЫЙ ПОРТ). Единственное
; функциональное отличие от v1.0 - ВСЕ записи колонок клавиатуры идут
; в СТАРШИЙ НИББЛ порта ТАЙМЕРА:
;   OUT 06h: A[3:0] = N таймера (не изменилось), A[7:4] = колонки.
; Порт 02h в RTL v2.9 НЕМАПЛЕН (декод удалён ради стенки входов ФБ) -
; fw v1.0 С ЭТИМ RTL НЕ РАБОТАЕТ (колонки не заведутся), и fw v1.1
; С RTL v28.5-v28.9 ТОЖЕ (N в старшем ниббле не читается). Пара
; жёстко связана: RTL v2.9 <-> fw v1.1.
;   СЛЕДСТВИЯ (Шаг-1, блок 3/4 шапки RTL): каждая запись 06h перезаряжает
; таймер, поэтому записи колонок ДОПУСТИМЫ ТОЛЬКО в управляемых точках -
; в v1.1 это KSCOL (вызывается из ISR) и INIT/TMOFF/TMON (A=0 или TMN).
; Явный ре-арм в конце ISR остаётся ПОСЛЕДНЕЙ записью слота - каденция
; v1.0 сохраняется бит-в-бит. СТОП (N=0) теперь гасит и колонки -
; в B/F/GO и на старте клавиатура не сканируется, семантика безопасна.
;
; Монитор для платы v2.8 (CPLD top_txuart_por6_v28_5, XC95108, ЭКСТРЕМАЛЬНЫЙ ДИЗАЙН,
; тег v2.8.5-extreme). Аппаратный таймер CPLD (узел «ТАЙМЕР») ведёт
; регенерацию дисплея, скан клавиатуры и тик xstream через RST 7.5.
;
; БАЗА: monitor27 v1.1 (beta/txuart/rom, клавиатурный монитор "ACDE"
; + XSTREAM v1 для платы v2.7). Отличия от monitor27:
;
;   1. ТИК-СИСТЕМА ПЕРЕРАБОТАНА ПОД ТАЙМЕР CPLD (v28.5, узел «ТАЙМЕР»):
;      на v2.7 TRAP (P74) получал квадрат 128 мкс (глушился EI;RET-
;      заглушками), на v2.8 P74 = PGND (держатель '0'), а пин P75 =
;      RST 7.5 от ТАЙМЕРА. Контракт таймера (RTL v28.5):
;        OUT 06h, N (A[3:0], N<=15) -> фронт RST 7.5 через N x 4 мкс
;        (4..60 мкс); уровень держится до следующей загрузки;
;        OUT 06h, 0 -> СТОП (один защитный фронт, дальше тишина);
;        RESET -> N=0Fh (первый фронт через ~60 мкс);
;        РЕ-АРМ ОБЯЗАТЕЛЕН В КОНЦЕ ISR (урок xstream TMR_HW=1: ре-арм
;        на входе + тело длиннее периода = защёлка RST 7.5 цепляет
;        ISR сам на себя, главный цикл голодает). ЕДИНЫЙ N=14
;        (56 мкс на фронт).
;   2. TMISR (вектор 003Ch): каждый 6-й фронт = СЛОТ (~0,7 мс):
;        скан 1 колонки клавиатуры (KSCOL: колонка = фаза регенерации
;        DPIDX - нулевое отдельное состояние!) + регенерация 1 разряда
;        (REFRESH из v27, без изменений) + тоггл фазы тона (SNDST.0);
;        ре-арм OUT 06h,0Eh в конце. Промежуточные фронт-ISR минимальны
;        (67 тактов): счётчик слотов живёт В РЕГИСТРЕ E - главный цикл
;        написан БЕЗ E (проверено по всем путям), поэтому ISR не толкает
;        ничего, кроме PSW. Ре-арм в Е-пути тоже в конце тела.
;      РЕГЕНЕРАЦИЯ И СКАН ПОЛНОСТЬЮ CPU-НЕЗАВИСИМЫ: период = 56 мкс CPLD
;      + тело ISR (слабо зависит от CPU), в отличие v27, где всё вело
;      время петлями BUNIT/QUNIT.
;   3. КЛАВИАТУРА: ISR пишет сырой образ колонок в KRAW0..3 (по байту
;      на колонку, биты 0-4 = ряды); главный цикл декодирует и ждёт
;      отпускания по KRAW (спин + 15 мс DLMS). Нажатие = первый контакт
;      (как v27). Клетки KRAW0..3 = шара с LBPC/LACC/LSUM/LTY загрузчика
;      (режимы B и скан не пересекаются: в B таймер СТОП; TMON чистит).
;   4. ЗВУК: TICKON = 15 мс через DLMS; квадрат ~700 Гц делает ISR
;      (тоггл SNDST.0 каждый слот), бит D4 DIGP уносится REFRESH как
;      в v27 (дисплей при тоне не гаснет). Питч ~700 Гц против ~500 в
;      v27 - цена слот-системы без отдельного счётчика.
;   5. XSTREAM (выдача экранной области): кадры идут ПОДРЯД из главного
;      цикла (NOKEY -> XSEND), пейсинг 35T/Б сохранён (кража ISR только
;      УДЛИНЯЕТ гэпы - отбросов TX нет по-прежнему). ВНУТРИ посылки
;      XDIG-паузы УДАЛЕНЫ: регенерацию ведёт ISR, поток не замирает
;      (урок 9 v1.2 закрыт архитектурно). Клиент xstream_view.ps1 v1.2.2
;      (COM @1000000 8N1) - БЕЗ ИЗМЕНЕНИЙ: A5 5A [SEQ] + 2000 Б из
;      B000h-B7CFh. SEQ в FFFAh (шара с LST - как в v27).
;      Кадр ~56 мс @2,5 МГц / ~42 мс @3,125 МГц = ~18/24 FPS.
;      Проектная оценка налога сессии 9 (24,3% @2,5) считала голую
;      ISR-систему; реальность со сканом в слоте: ~50% ЦП ВНУТРИ
;      монитора, НО: пользовательские программы (KGO) не платят НИЧЕГО -
;      TMOFF гасит таймер (в v27 TRAP-тик жрал 6,1% всегда, у программ).
;   6. ДИСЦИПЛИНА B/F/GO (лучше v27):
;        TMOFF: DI + SIM 78h (маски 5.5/6.5/7.5 + СБРОС защёлки RST7.5)
;               + OUT 06h,0 (СТОП, защитный фронт замаскирован);
;        TMON : DI + SIM 78h + чистка KRAW/DPIDX/SNDST + E=6
;               + OUT 06h,0Eh (арм) + SIM 68h (снята маска 7.5) + EI.
;      B (LOADM): таймер СТОП - RXD чист от ISR-джиттера (в v27 глушилка
;      TRAP давала 5,6 мкс джиттера); дисплей статикой (LSTAT).
;      F (RAMT): таймер СТОП - стек статичен, тест 8000h-FFE7h без
;      чужих pushes (в v27 глушилка толкала 2 Б в диапазон теста).
;      GO (KGO): таймер СТОП на всю программу пользователя; программа,
;      которой нужен таймер, сама делает SIM/OUT 06h (вектор 003Ch
;      ведёт в ROM-ISR монитора - см. шапку RTL v28.5).
;   7. Каденция дисплея/скана CPU-независима (п.2), поэтому константы
;      K_MS/RXHB/RXFB остались только в путях, где CPU-время - суть
;      (DLMS паузы, RXD 4800). При разгоне до 3,125 МГц (T=320 нс)
;      трогать ничего не нужно: слоты не разъедутся, FPS вырастет.
;
; СБОРКА (asm85.py, кодировка CP1251):
;   python3 asm85.py fw_monitor_ACdE_tm_xstream.asm -o fw_monitor_ACdE_tm_xstream.hex -l fw_monitor_ACdE_tm_xstream.lst
;   (asm85.py рядом; из каталога rom: python3 asm85.py ...)
; Прошивка: flash A29040B, offset 0000h (ROM-окно 0000h-7FFFh).
; Верификация: python3 verify_tm.py (вектора/таймер/таблицы/объём).
;
; КЛАВИАТУРА (как v27): тетрады 0-F + Enter + F1(меню) + F2(показ
; адреса); меню: A=адрес C=код D=просмотр E=выполнить B=загрузчик
; Intel HEX (SID 4800) F=RAM-тест. Выход из залипшего режима - RESET.
;
; ОЗУ: переменные FFE8h-FFFFh, стек с FFE7h вниз (SP0 = FFE8h).
; ГЛУБИНА СТЕКА: максимум XSEND (4 push) + TMISR (4 push) = FFD4h -
; в свободном ОЗУ, переменные не задеваются.
; =====================================================================

; ---- порты CPLD (декод по A2-A0, зеркала mod 8) ----
SEGP    EQU 00h             ; сегменты: D0=a..D6=g, D7=dp; 1 = горит
DIGP    EQU 01h             ; D3-D0 разряды, D4 = SND
KBCOLP  EQU 02h             ; v1.1: НЕ ИСПОЛЬЗУЕТСЯ (RTL v2.9 немаплен);
                            ; символ оставлен для дифа с v1.0
KBROWP  EQU 03h             ; D4-D0 ряды (1 = нажата в активной колонке)
TXP     EQU 04h             ; OUT: TXDATA -> сериализатор CPLD (1M 8N1)
STP     EQU 05h             ; IN: статус, бит A1 = TXRDY
TMRP    EQU 06h             ; OUT: v1.1 Шаг-1: A[3:0] = N (N x 4 мкс),
                            ;      A[7:4] = колонки (1 = заведена)

; ---- константы таймера/тайминга (CPU 2,5 МГц, T = 400 нс) ----
TMN     EQU 14              ; N таймера: фронт каждые 56 мкс (единый)
TQ_MS   EQU 15              ; дебаунс отпускания ~15 мс (DLMS-единиц)
K_MS    EQU 104             ; DLMS-единица ~1,0 мс (104 x 24T x 400 нс)
RXHB    EQU 15              ; полбита 4800 (PAUSE-итераций, ~103 мкс)
RXFB    EQU 30              ; бит приёма 4800 (PAUSE-итераций, ~211 мкс)

; ---- коды клавиш ----
K_ENT   EQU 10h             ; Enter  (row3/col3, SW16)
K_F1    EQU 11h             ; F1     (row4/col1, SW18) - меню
K_F2    EQU 12h             ; F2     (row4/col2, SW19) - показ адреса
K_NONE  EQU 0FFh            ; пустая позиция матрицы

; ---- состояния ----
ST_MENU EQU 00h             ; меню "ACDE" (B = загрузчик, F = RAM-тест)
ST_ADDR EQU 01h             ; ввод адреса
ST_PROG EQU 02h             ; ввод кода (Code)
ST_VIEW EQU 03h             ; просмотр кода
ST_SHOW EQU 04h             ; показ адреса операций (F2)

; ---- ОЗУ монитора ----
SP0     EQU 0FFE8h          ; SP монитора
SNDST   EQU 0FFE8h          ; бит0 = фаза тона (тогглит ISR), бит1 = тон вкл
STATE   EQU 0FFE9h          ; 0=меню, 1=адрес, 2=код, 3=просмотр, 4=показ
ADDRH   EQU 0FFEAh          ; текущий адрес (старший); в загрузчике = адрес записи
ADDRL   EQU 0FFEBh          ; текущий адрес (младший)
ADCNT   EQU 0FFECh          ; тетрады адреса (0..4); в загрузчике = счётчик байт данных
AF3     EQU 0FFEDh          ; тетрады адреса
AF2     EQU 0FFEEh
AF1     EQU 0FFEFh
AF0     EQU 0FFF0h
BDCNT   EQU 0FFF1h          ; введено тетрад байта (0..2)
BF1     EQU 0FFF2h
BF0     EQU 0FFF3h
DPIDX   EQU 0FFF4h          ; фаза регенерации 0..3 = колонка скана (владеет ISR)
DIGIMG  EQU 0FFF5h          ; глифы разрядов DIG0..DIG3
DIGIMG0 EQU 0FFF5h
DIGIMG1 EQU 0FFF6h
DIGIMG2 EQU 0FFF7h
DIGIMG3 EQU 0FFF8h
PREVST  EQU 0FFF9h          ; прежний режим для F2
; --- парсер Intel HEX (загрузчик B); FFFC-FFFF = шара с KRAW (п.3) ---
LST     EQU 0FFFAh          ; состояние: 0=ждём ':' 1=count 2=addr 3=type 4=data 5=chk
                            ;   (шара с XSSEQ - см. п.5; LOADM чистит на входе)
LNIB    EQU 0FFFBh          ; осталось тетрад в текущем байте поля (1..2)
LBPC    EQU 0FFFBh+1        ; осталось байт в текущем поле   = KRAW0
LACC    EQU 0FFFBh+2        ; накопитель тетрад текущего байта = KRAW1
LSUM    EQU 0FFFBh+3        ; сумма байт записи (mod 256)      = KRAW2
LTY     EQU 0FFFBh+4        ; тип последней записи             = KRAW3
; --- сырой образ клавиатуры (пишет ISR, читает главный цикл) ---
KRAW0   EQU 0FFFBh+1        ; ряды колонки 0 (биты 0-4) = LBPC
KRAW1   EQU 0FFFBh+2        ; ряды колонки 1            = LACC
KRAW2   EQU 0FFFBh+3        ; ряды колонки 2            = LSUM
KRAW3   EQU 0FFFBh+4        ; ряды колонки 3            = LTY

; --- XSTREAM: экран -> UART (тик кадра = непрерывный поток, п.5) ---
TXPORT  EQU TXP             ; TXDATA (04h) - синоним для xstream-кода
XBUF    EQU 0B000h          ; ЭКРАН 80x25 = 2000 Б (B000h..B7CFh)
XSSEQ   EQU 0FFFAh          ; SEQ кадра mod 256 (ячейка LST - см. п.5)
XSCNT   EQU XBUF+06E4h      ; живой счётчик SEQ в демо-экране (строка 22, кол. 4-5)

; =====================================================================
        ORG 0000h
        JMP START

; ---- векторная зона: глушилки EI;RET -------------------------------
; RST 1..7, TRAP (0024h), RST 5.5/6.5. EI обязателен в каждой (снимает
; блокировку после приёма). На v2.8: TRAP-пин = PGND (тишина), 5.5/6.5
; железно=0 и вдобавок замаскированы SIM - заглушки чисто защитные.
; RST 7.5 (003Ch) = ТАЙМЕР - НЕ заглушка, обработчик ниже (п.1).
        ORG 0008h           ; RST 1
        EI
        RET
        ORG 0010h           ; RST 2
        EI
        RET
        ORG 0018h           ; RST 3
        EI
        RET
        ORG 0020h           ; RST 4
        EI
        RET
        ORG 0024h           ; TRAP - защитная заглушка (на v2.8 пин PGND)
        EI
        RET
        ORG 0028h           ; RST 5
        EI
        RET
        ORG 002Ch           ; RST 5.5
        EI
        RET
        ORG 0030h           ; RST 6
        EI
        RET
        ORG 0034h           ; RST 6.5
        EI
        RET
        ORG 0038h           ; RST 7
        EI
        RET
        ORG 003Ch           ; RST 7.5 = ТАЙМЕР (п.1: единый N=14)
        JMP TMISR

; =====================================================================
; Таблицы (ORG 0044h - векторная зона выше освобождена)
; =====================================================================
        ORG 0044h
; ---- глифы '0'..'F' (a,b,c,d,e,f,g = D0..D6) ----
GTBL:   DB 3Fh              ; '0'
        DB 06h              ; '1'
        DB 5Bh              ; '2'
        DB 4Fh              ; '3'
        DB 66h              ; '4'
        DB 6Dh              ; '5'
        DB 7Dh              ; '6'
        DB 07h              ; '7'
        DB 7Fh              ; '8'
        DB 6Fh              ; '9'
        DB 77h              ; 'A'
        DB 7Ch              ; 'b'
        DB 39h              ; 'C'
        DB 5Eh              ; 'd'
        DB 79h              ; 'E'
        DB 71h              ; 'F'

; ---- биты разрядов/колонок (индекс = DPIDX: 0=DIG0 правый ... 3=DIG3 левый) ----
BITTBL: DB 01h,02h,04h,08h

; ---- КАРТА КЛАВИШ: KEYTBL[row*4+col] ----
KEYTBL: DB 0Ah,0Bh,0Ch,0Dh  ; row0: A  B  C  D
        DB 07h,08h,09h,0Eh  ; row1: 7  8  9  E
        DB 04h,05h,06h,0Fh  ; row2: 4  5  6  F
        DB 01h,02h,03h,10h  ; row3: 1  2  3  Enter
        DB 00h,11h,12h,0FFh ; row4: 0  F1 F2 (нет)

; ---- баннер TX @1M (на терминале 4800 = короткая мусорная строка) ----
TXBAN:  DB 'ACDE-TM',0Dh,0Ah,00h

; ---- паттерны RAM-теста: значение + глиф для статического дисплея ----
RAMPAT: DB 00h,3Fh          ; 00h -> "0000"
        DB 0FFh,71h         ; FFh -> "FFFF"
        DB 55h,6Dh          ; 55h -> "5555"
        DB 0AAh,77h         ; AAh -> "AAAA"

; =====================================================================
; СИСТЕМА ТАЙМЕРА: TMOFF/TMON + TMISR + слоты (п.1, п.2, п.6)
; =====================================================================
        ORG 0100h

; ---------------------------------------------------------------------
; TMOFF: СТОП слот-системы. DI + полные маски (SIM 78h = MSE+M7.5+M6.5
; +M5.5, заодно СБРОС защёлки RST 7.5) + OUT 06h,0 (СТОП; его защитный
; фронт защёлкнут, но замаскирован - не выстрелит и после EI).
; Вызывается на входе B/F/GO. Портит A.
; ---------------------------------------------------------------------
TMOFF:  DI
        MVI A,78h           ; MSE=1, M7.5=1 (маска+сброс защёлки), M6.5=1, M5.5=1
        SIM
        XRA A
        OUT TMRP            ; СТОП таймера (N=0: один защитный фронт,
                            ; тишина) + v1.1: колонки off (Шаг-1; в v1.0
                            ; состояние колонок сохранялось - клавиатура
                            ; в B/F/GO не сканируется, семантика ок)
        RET

; ---------------------------------------------------------------------
; TMON: ПУСК слот-системы (START, выход из B/F, MONRET). Чистит
; состояние ISR, заряжает E=6, арм N=14, снимает маску 7.5, EI.
; Первый слот = 6-й фронт (~0,5 мс после выхода).
; ---------------------------------------------------------------------
TMON:   DI
        MVI A,78h           ; маски + сброс защёлки (гасим чужие фронты)
        SIM
        XRA A
        STA SNDST           ; тон off, фаза 0
        STA DPIDX           ; фаза регенерации/колонка 0
        STA KRAW0           ; сырой образ клавиатуры - в ноль
        STA KRAW1
        STA KRAW2
        STA KRAW3
        MVI E,6             ; счётчик слотов В E (п.2: главный цикл без E)
        MVI A,TMN
        OUT TMRP            ; арм: фронт через 56 мкс + v1.1: колонки
                            ; off (TMN=0Eh в младшем ниббле; первый слот
                            ; KSCOL сам заведёт колонку DPIDX)
        MVI A,68h           ; MSE=1, M7.5=0 (7.5 РАЗРЕШЁН), M6.5=1, M5.5=1
        SIM
        EI
        RET

; ---------------------------------------------------------------------
; TMISR: RST 7.5 = фронт таймера (каждые 56 мкс + тело). Счётчик слотов
; В E (п.2); слот = каждый 6-й фронт: скан колонки + регенерация разряда
; + тоггл тона. РЕ-АРМ В КОНЦЕ обеих ветвей (урок TMR_HW=1). Сохраняем
; PSW всегда (флаги главного цикла), B/D/H - только в слоте (там их
; портят KSCOL/REFRESH); E НЕ сохраняем - главный цикл его не держит.
; Такты (@2,5 МГц): быстрый фронт 67T ~ 27 мкс -> период ~83 мкс;
; слот ~543T ~ 217 мкс -> период ~286 мкс; цикл слотов ~0,70 мс.
; ---------------------------------------------------------------------
TMISR:  PUSH PSW            ; 12
        DCR E               ; 4   слот-счётчик (в E, п.2)
        JNZ TMTINY          ; 10  не шестой фронт - быстрый выход
        ; ------------------ СЛОТ (6-й фронт) ------------------
        PUSH B
        PUSH D
        PUSH H
        MVI E,6             ; 6 фронтов до следующего слота
        CALL KSCOL          ; скан колонки (колонка = фаза DPIDX)
        CALL REFRESH        ; регенерация разряда (фаза ++ внутри)
        CALL SNDTOG         ; тон: тоггл фазы SNDST.0
        MVI A,TMN
        OUT TMRP            ; РЕ-АРМ ПОСЛЕ тела (урок TMR_HW=1)
        POP H
        POP D
        POP B
        POP PSW
        EI
        RET
TMTINY: MVI A,TMN           ; 7
        OUT TMRP            ; 10  РЕ-АРМ (тело = проверка счётчика, 27 мкс << 56 мкс)
        POP PSW
        EI
        RET

; ---------------------------------------------------------------------
; KSCOL: скан ОДНОЙ колонки (вызывается из слота). Колонка = текущая
; фаза регенерации DPIDX (п.2) - отдельного счётчика нет. Сырой образ
; рядов (биты 0-4) -> KRAW0..KRAW3[колонка]. Портит A/B/C/D/H/L
; (в ISR - под PUSH B/D/H). Колонка на выходе погашена.
; ---------------------------------------------------------------------
KSCOL:  LDA DPIDX           ; колонка = фаза регенерации 0..3
        ANI 03h
        MOV B,A             ; B = индекс колонки
        MVI C,0
        LXI H,BITTBL
        DAD B               ; HL = BITTBL + колонка
        MOV D,M             ; D = бит колонки (01/02/04/08)
        LXI H,KRAW0
        DAD B               ; HL = KRAW0 + колонка (B/C целы)
        MOV A,D
        RLC                 ; v1.1 Шаг-1: бит колонки (01/02/04/08) ->
        RLC                 ; старший ниббл A[7:4] (RLC x4, переноса нет:
        RLC                 ; бит выходит из младшего ниббла в старший)
        RLC
        ORI TMN             ; младший ниббл = N: запись 06h ПЕРЕЗАРЯЖАЕТ
        OUT TMRP            ; таймер - легально, KSCOL зовётся ТОЛЬКО
                            ; из ISR, концевой ре-арм перекроет
        CALL SETTLE
        IN KBROWP           ; ряды активной колонки
        ANI 1Fh
        MOV M,A             ; KRAW[колонка] = сырой образ рядов
        MVI A,TMN           ; колонки off (0000) + N: перезарядка здесь
        OUT TMRP            ; безвредна - концевой ре-арм останется
                            ; ПОСЛЕДНЕЙ записью слота (каденция v1.0)
        RET

; ---------------------------------------------------------------------
; SNDTOG: тоггл фазы тона SNDST.0, если тон разрешён (SNDST.1). Каждый
; слот ~0,70 мс -> квадрат ~700 Гц (п.4). Дисплей получает бит через
; REFRESH (LDA SNDST) - как в v27. Портит A.
; ---------------------------------------------------------------------
SNDTOG: LDA SNDST
        ANI 02h
        RZ                  ; тон не разрешён (TICKON не включал) - выход
        LDA SNDST
        XRI 01h
        STA SNDST
        RET

; =====================================================================
; Системные процедуры (перенос из fw_mon v5 / monitor27, константы 2,5 МГц)
; =====================================================================

; ---------------------------------------------------------------------
; SETTLE: пауза ~36 мкс (LXI+3 итерации 24T @400 нс; установка рядов
; после заведения колонки). Портит A/B/C. H/L НЕ ТРОГАЕТ (нужно KSCOL).
; ---------------------------------------------------------------------
SETTLE: LXI B,3
STL:    DCX B
        MOV A,B
        ORA C
        JNZ STL
        RET

; ---------------------------------------------------------------------
; REFRESH: один слот регенерации (v27 БЕЗ ИЗМЕНЕНИЙ). ГАШЕНИЕ -> РАЗРЯД
; -> ГЛИФ. DIGIMG[DPIDX] на разряд DPIDX, фаза ++ mod 4. Бит D4 (SND)
; уносится записью DIGP - дисплей при тоне не гаснет. D/E НЕ ТРОГАЕТ
; (в ISR критично: D = бит колонки уже погашен, E = счётчик слотов).
; Портит A/B/C/H/L.
; ---------------------------------------------------------------------
REFRESH: LDA DPIDX
        MOV C,A             ; C = индекс 0..3
        MVI B,0
        LXI H,BITTBL
        DAD B
        MOV B,M             ; B = бит разряда (01,02,04,08)
        LXI H,DIGIMG        ; HL = DIGIMG + DPIDX (цикл вместо ADD)
RFIL:   MOV A,C
        ORA A
        JZ RFGD
        INR L
        DCR C
        JMP RFIL
RFGD:   MOV C,M             ; C = глиф разряда
        LDA SNDST
        ORA A
        JZ RFN
        MOV A,B
        ORI 10h
        MOV B,A             ; B |= SND
RFN:    XRA A
        OUT SEGP            ; (1) гашение: старый разряд погас
        MOV A,B
        OUT DIGP            ; (2) разряд переключён (сегменты пусты)
        MOV A,C
        OUT SEGP            ; (3) зажгли глиф нового разряда
        LDA DPIDX
        INR A
        ANI 03h
        STA DPIDX
        RET

; ---------------------------------------------------------------------
; TICKON: короткий тик подтверждения клавиши ~15 мс (п.4). Квадрат
; ~700 Гц делает ISR (тоггл SNDST.0 каждый слот при SNDST.1=1); здесь
; только окно 15 мс (TQ_MS единиц DLMS) и гарантированное гашение.
; Портит A/B/C/H.
; ---------------------------------------------------------------------
TICKON: LDA SNDST
        ORI 02h             ; тон разрешён (фазу тогглит ISR)
        STA SNDST
        MVI H,TQ_MS         ; 15 мс
TKL:    CALL DLMS
        DCR H
        JNZ TKL
        LDA SNDST
        ANI 0FDh            ; тон off
        STA SNDST
        RET

; ---------------------------------------------------------------------
; GLOOK: A = тетрада 0..F -> A = глиф (GTBL). Портит A/B/C/H/L.
; ---------------------------------------------------------------------
GLOOK:  MOV C,A
        MVI B,0
        LXI H,GTBL
        DAD B
        MOV A,M
        RET
; ---------------------------------------------------------------------
; REDRAW: пересобрать DIGIMG[0..3] по состоянию (как v5/v27).
;   меню : "ACdE"; адрес: тетрады вдвигаются справа; код "__C3";
;   просмотр: [ADDR] в правых разрядах; показ(F2): ADDR на 4 разрядах.
; Портит A/B/C/D/H/L (D - рабочий в RDW/RDV; ISR сохраняет D - безопасно).
; ---------------------------------------------------------------------
REDRAW: LDA STATE
        ORA A
        JZ RDM
        CPI 01h
        JZ RDA
        CPI 03h
        JZ RDV
        CPI 04h
        JZ RDW
        ; ---- ST_PROG ----
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA BDCNT
        CPI 02h
        JC RDPR0            ; <2 - старшая тетрада пуста
        LDA BF1
        CALL GLOOK
        STA DIGIMG1
RDPR0:  LDA BDCNT
        ORA A
        JZ RDRE             ; 0 - младшая тоже пуста
        LDA BF0
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDV:    LDA ADDRH           ; ---- ST_VIEW: [ADDR] в правых разрядах ----
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = ADDR
        MOV A,M             ; A = [ADDR] (HL>=8000h - ОЗУ)
        MOV D,A             ; D = байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh             ; старшая тетрада
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh             ; младшая тетрада
        CALL GLOOK
        STA DIGIMG0
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        JMP RDRE
RDW:    LDA ADDRH           ; ---- ST_SHOW: ADDR на 4 разрядах ----
        MOV D,A             ; D = старший байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG3
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG2
        LDA ADDRL
        MOV D,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDM:    MVI A,77h           ; 'A'
        STA DIGIMG3
        MVI A,39h           ; 'C'
        STA DIGIMG2
        MVI A,5Eh           ; 'd' (D)
        STA DIGIMG1
        MVI A,79h           ; 'E'
        STA DIGIMG0
        JMP RDRE
RDA:    XRA A               ; ---- ST_ADDR: последняя тетрада справа ----
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA ADCNT
        CPI 01h
        JC RDRE             ; 0 тетрад - всё пусто
        LDA AF0
        CALL GLOOK
        STA DIGIMG0
        LDA ADCNT
        CPI 02h
        JC RDRE
        LDA AF1
        CALL GLOOK
        STA DIGIMG1
        LDA ADCNT
        CPI 03h
        JC RDRE
        LDA AF2
        CALL GLOOK
        STA DIGIMG2
        LDA ADCNT
        CPI 04h
        JC RDRE
        LDA AF3
        CALL GLOOK
        STA DIGIMG3
RDRE:   RET

; =====================================================================
; UART-канал v2.8: передача OUT 04h @1M (TXRDY = IN 05h бит A1),
; приём RIM/SID @4800 (мануал, фрагменты 5/7) - как v27
; =====================================================================

; ---------------------------------------------------------------------
; TXBYTE: A = байт -> сериализатор CPLD (1 000 000 8N1). Ожидает TXRDY
; (запись при busy аппаратно отбрасывается). Используется баннером/строками.
; ---------------------------------------------------------------------
TXBYTE: PUSH PSW
TXB1:   IN STP
        ANI 02h             ; бит A1 = TXRDY (tx_idle = ~|bit_cnt)
        JZ TXB1
        POP PSW
        OUT TXP
        RET

; ---------------------------------------------------------------------
; TXSTR: HL = строка с нулевым завершителем -> TX. Портит A/HL.
; ---------------------------------------------------------------------
TXSTR:  MOV A,M
        ORA A
        RZ
        CALL TXBYTE
        INX H
        JMP TXSTR

; ---------------------------------------------------------------------
; PAUSE: пауза D итераций по 6 мкс (DCR+JNZ = 15T @2,5 МГц).
; ---------------------------------------------------------------------
PAUSE:  DCR D
        JNZ PAUSE
        RET

; ---------------------------------------------------------------------
; RXD: приём байта SID 4800 8N1 (мануал, фрагмент 7 + стоп-бит).
; Выход: C = байт, CY = 0 ОК / CY = 1 обрыв кадра (стоп-бит = 0).
; Портит A/B/C/D. Цикл строгий - в режиме B таймер СТОП (TMOFF) и
; прерывания запрещены (DI в TMOFF) - джиттера нет вообще (лучше v27,
; где глушилка TRAP добавляла 5,6 мкс раз в 127 мкс).
; ---------------------------------------------------------------------
RXD:    MVI B,08h
RXW:    RIM                 ; A7 = SID
        ORA A
        JM RXW              ; '1' (покой) - ждать старт-бит
        MVI D,RXHB          ; полбита - в середину старт-бита
        CALL PAUSE
        RIM                 ; подтвердить старт-бит
        ORA A
        JM RXW              ; '1' - ложный старт, ждать заново
        MVI C,00h
        MVI D,RXFB          ; бит - в середину D0
        CALL PAUSE
RXL:    RIM                 ; A7 = SID - центр очередного бита
        ANI 80h
        RAR                 ; бит -> CY
        MOV A,C
        RAR                 ; вставить сверху (LSB-first)
        MOV C,A
        MVI D,RXFB
        CALL PAUSE
        DCR B
        JNZ RXL
        ; после последней итерации RXL (выборка d7 + бит задержки)
        ; линия = середина стоп-бита
        RIM
        ANI 80h             ; CY = 0 (ANI сбрасывает перенос)
        JZ RXBAD            ; стоп-бит = 0 - обрыв кадра
        ORA A               ; CY = 0
        RET                 ; C = байт, CY = 0
RXBAD:  STC
        RET                 ; CY = 1

; ---------------------------------------------------------------------
; NIB: A = ASCII-символ -> CY = 1 и A = тетрада 0-F ('0'-'9','A'-'F',
; 'a'-'f'), иначе CY = 0. Портит A.
; ---------------------------------------------------------------------
NIB:    SUI 30h             ; '0'..'9' -> 0..9
        JC NIBX             ; < '0'
        CPI 0Ah
        JC NIBOK            ; цифра 0..9
        SUI 07h             ; 'A'..'F' -> 10..15
        CPI 10h
        JNC NIB2            ; > 'F' - попробовать строчные a..f
        JMP NIBOK
NIB2:   SUI 20h             ; ('a'-'0')-07h-20h = 10..15
        CPI 10h
        JNC NIBX
        JMP NIBOK
NIBOK:  STC
        RET
NIBX:   ORA A               ; CY = 0
        RET

; ---------------------------------------------------------------------
; LSTAT: A = глиф -> статический дисплей (все 4 разряда, слот-система
; стоит). Для режимов загрузчика/RAM-теста, где ISR выключен (TMOFF).
; ---------------------------------------------------------------------
LSTAT:  PUSH B
        MOV B,A
        XRA A
        OUT SEGP            ; гашение на время переключения
        MVI A,0Fh
        OUT DIGP            ; все 4 разряда, SND = 0
        MOV A,B
        OUT SEGP            ; глиф на все разряды
        POP B
        RET

; ---------------------------------------------------------------------
; DLMS: пауза ~1,03 мс (K_MS итераций 24T). Портит A/B/C. H/L целы.
; ---------------------------------------------------------------------
DLMS:   LXI B,K_MS
DLS1:   DCX B
        MOV A,B
        ORA C
        JNZ DLS1
        RET

; ---------------------------------------------------------------------
; LDSUM: LSUM += B (mod 256). Портит A.
; ---------------------------------------------------------------------
LDSUM:  PUSH PSW
        LDA LSUM
        ADD B
        STA LSUM
        POP PSW
        RET

; ---------------------------------------------------------------------
; LDBEEP: длинный сигнал ~0,3 с (тон ~700 Гц имитируем тогглом D4 DIGP
; вручную: в B/F таймер СТОП - ISR не пишет DIGP, конфликта нет).
; Портит A/B/C/D.
; ---------------------------------------------------------------------
LDBEEP: MVI D,150
LDB1:   MVI A,1Fh           ; SND = 1, разряды on
        OUT DIGP
        CALL DLMS
        MVI A,0Fh           ; SND = 0
        OUT DIGP
        CALL DLMS
        DCR D
        JNZ LDB1
        RET

; =====================================================================
; LOADM: Intel HEX загрузчик (клавиша B). Приём SID 4800 8N1.
; Вход через KLD с TMOFF (таймер СТОП, DI) - как v27 по логике парсера.
; Формат записи: :nnaaaatt[dd...]cc, cc = (-сумма байт) mod 256.
; Статический дисплей LLLL; адрес каждой записи живёт в ADDRH/L.
; Запись только в ОЗУ (A15=1): попадание в ROM-окно = ошибка EEEE.
; Выход: EOF-запись (type 01) -> тик и меню; ошибка -> EEEE + сигнал.
; Выход из зависшего приёма - RESET (SW20).
; NOTE: LACC/LNIB/LBPC/LSUM/LTY = клетки FFFB-FFFF; в обычном режиме
; FFFC-FFFF заняты KRAW (ISR) - в B таймер СТОП, конфликта нет; TMON
; на выходе чистит KRAW. XSSEQ/LST = FFFA: на входе LST=0 (=SEQ 0 -
; клиент логирует рестарт потока), на выходе TMON -> новое SEQ с 0.
; ---------------------------------------------------------------------
LOADM:  XRA A
        STA LST             ; ждем ':' (и XSSEQ = 0 - рестарт потока клиента)
        STA LACC            ; накопитель тетрад тоже с нуля (баг v1.0:
                            ;  сталь ломала первый байт первой записи)
        MVI A,38h           ; 'L'
        CALL LSTAT
LDLP:   CALL RXD            ; C = байт, CY = ошибка кадра
        JC LDERR
        MOV A,C
        CPI ':'
        JZ LDNEW            ; начало записи
        CALL NIB            ; тетрада?
        JNC LDLP            ; прочее (\r\n и т.п.) - пропустить
        MOV E,A             ; E = тетрада (таймер СТОП - E свободен)
        LDA LACC
        RLC
        RLC
        RLC
        RLC                 ; накопитель << 4
        ORA E
        STA LACC
        LDA LNIB
        DCR A
        STA LNIB
        JNZ LDLP            ; байт поля ещё не собран
        ; --- байт поля собран - применить по состоянию ---
        LDA LACC
        MOV B,A             ; B = байт
        XRA A
        STA LACC            ; накопитель очищен к следующему байту
        LDA LST
        ORA A
        JZ LDLP             ; байт вне записи - игнор
        DCR A
        JZ LDCNT            ; 1 = count
        DCR A
        JZ LDADR            ; 2 = addr
        DCR A
        JZ LDTYP            ; 3 = type
        DCR A
        JZ LDDAT            ; 4 = data
        JMP LDCHK           ; 5 = checksum
LDCNT:  MOV A,B
        STA ADCNT           ; сколько байт данных в записи
        CALL LDSUM
        MVI A,02h           ; поле addr: 4 тетрады = 2 байта
        STA LST
        STA LBPC
        STA LNIB
        JMP LDLP
LDADR:  MOV A,B
        STA LTY             ; временно: тип ещё не читался
        LDA LBPC
        CPI 02h
        JNZ LDAD1
        LDA LTY
        STA ADDRH           ; старший байт адреса (big-endian)
        MVI A,01h
        STA LBPC
        CALL LDSUM
        JMP LDLP
LDAD1:  LDA LTY
        STA ADDRL           ; младший байт адреса
        CALL LDSUM
        MVI A,03h
        STA LST             ; type
        MVI A,01h
        STA LBPC
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP:  MOV A,B
        STA LTY
        CALL LDSUM
        LDA LTY
        CPI 01h
        JZ LDTYP1
        LDA ADCNT           ; type 00: данные
        STA LBPC
        MVI A,04h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP1: XRA A               ; type 01 (EOF): данных нет
        STA LBPC
        MVI A,05h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT:  LDA ADDRH
        ANI 80h             ; запись разрешена только в ОЗУ
        JZ LDERR            ; ROM-окно - ошибка
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,B             ; [ADDR] = байт (writeback CPLD)
        INX H
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL LDSUM
        LDA LBPC
        DCR A
        STA LBPC
        JNZ LDDAT2
        MVI A,05h           ; данные кончились - ждать checksum
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT2: MVI A,02h
        STA LNIB
        JMP LDLP
LDCHK:  LDA LSUM            ; контрольная сумма записи
        ADD B               ; сумма всех байт + cc = 0 mod 256?
        JNZ LDERR
        LDA LTY
        CPI 01h
        JZ LDDONE           ; EOF - конец загрузки
        XRA A
        STA LST             ; ждем ':' следующей записи
        JMP LDLP
LDNEW:  MVI A,01h           ; ':' - новая запись
        STA LST
        MVI A,02h
        STA LNIB
        XRA A
        STA LSUM
        JMP LDLP
LDDONE: CALL TICKON         ; подтверждение успешной загрузки
        RET
LDERR:  MVI A,79h           ; 'E' -> дисплей EEEE
        CALL LSTAT
        CALL LDBEEP         ; длинный сигнал
        RET                 ; в меню (ADDRH/L = адрес сбоя, D = просмотр)

; =====================================================================
; RAMT: RAM-тест 8000h-FFE7h (клавиша F). 4 паттерна 00/FF/55/AA:
; заполнение + контроль побайтно. Статический дисплей = глиф паттерна
; ("0000"/"FFFF"/"5555"/"AAAA"). Сбой: ADDRH/L = адрес сбоя, EEEE +
; длинный сигнал. Успех: короткий тик. Вход через KRAM с TMOFF:
; таймер СТОП - ISR не толкает стек в диапазон теста (в v27 глушилка
; TRAP писала 2 Б в FFDE/FFDF - приходилось оговаривать; здесь тест
; КРИСТАЛЬНО чистый). Стек до FFD4h не доходит (RAMT без длинных push).
; Портит всё (кроме клеток монитора).
; ---------------------------------------------------------------------
RAMT:   LXI H,RAMPAT        ; HL = текущая пара (value+glyph)
        MVI C,04h           ; 4 паттерна
RMT0:   MOV A,M             ; A = значение паттерна
        MOV E,A
        PUSH H              ; указатель пары - на стек (HL уйдёт под заполнение)
        INX H
        MOV A,M             ; глиф паттерна
        CALL LSTAT          ; статический дисплей ("0000" и т.д.)
        MOV A,E
        LXI H,8000h
RMF:    MOV M,A             ; заполнение
        INX H
        MOV A,H
        CPI 0FEh            ; до FFE7h включительно
        JNZ RMF
        MOV A,L
        CPI 0E8h
        JNZ RMF
        LXI H,8000h
RMV:    MOV A,M             ; контроль
        CMP E
        JNZ RMBAD
        INX H
        MOV A,H
        CPI 0FEh
        JNZ RMV
        MOV A,L
        CPI 0E8h
        JNZ RMV
        POP H               ; HL = пара паттерна
        INX H
        INX H               ; следующая пара
        DCR C
        JNZ RMT0
        CALL TICKON         ; ОК
        RET
RMBAD:  SHLD ADDRL          ; ADDRH/L = адрес сбоя (HL из RMV, до POP!)
        POP H               ; снять указатель пары (баланс стека)
        MVI A,79h           ; 'E' -> EEEE
        CALL LSTAT
        CALL LDBEEP
        RET                 ; в меню; D = просмотр байта по адресу сбоя

; =====================================================================
;                    XSTREAM: ЭКРАН -> UART (п.5: непрерывный поток,
;                    тик кадра = сама скорость канала, регенерацию
;                    ведёт TMISR - XDIG-паузы внутри посылки удалены)
; =====================================================================
; ---------------------------------------------------------------------
; XSINIT (из START, только холодный старт): демо-экран в B000h,
; SEQ = 0. Мониторные переменные не трогаются; B000-B7CF -
; пользовательская область: ЛЮБАЯ программа может рисовать туда
; свой текст/графику, клиент xstream_view.ps1 покажет окном.
; ---------------------------------------------------------------------
XSINIT: CALL XBLANK
        LXI H,XTBL
XSI1:   MOV E,M             ; DE = адрес назначения
        INX H
        MOV D,M
        INX H               ; HL -> src_lo
        MOV A,D             ; конец таблицы (dst == 0000)?
        ORA E
        JZ XSI3
        MOV C,M             ; BC = адрес строки (источник)
        INX H
        MOV B,M
        INX H               ; HL -> следующая запись
        PUSH H              ; указатель следующей записи -> стек
        MOV H,B
        MOV L,C
        CALL XCPY           ; ASCIZ [HL] -> [DE], 0 = конец
        POP H
        JMP XSI1
XSI3:   XRA A
        STA XSSEQ
        RET

XBLANK: LXI H,XBUF          ; 2000 пробелов
        LXI B,2000
XB1:    MVI A,20h
        MOV M,A
        INX H
        DCX B
        MOV A,B
        ORA C
        JNZ XB1
        RET

XCPY:   MOV A,M             ; ASCIZ: [HL]->[DE], 0 = конец (A/флаги)
        ORA A
        RZ
        STAX D
        INX H
        INX D
        JMP XCPY

; ---------------------------------------------------------------------
; XSEND: кадр XSTREAM в UART: A5 5A [SEQ] + 2000 Б из XBUF.
;   Сохраняет PSW/B/D/H. РАВНОМЕРНЫЙ пейсинг 35T/Б без опроса TXRDY:
;   на 2,5 МГц 35T = 14 мкс >= 10 мкс байта 1M; ISR-вставки только
;   УДЛИНЯЮТ гэпы (регенерация/скан в слоте) - ноль отбросов TX.
;   XDIG-паузы УДАЛЕНЫ против v27: регенерацию ведёт TMISR, поток
;   не замирает (урок 9 v1.2 закрыт архитектурно). E не трогает
;   (счётчик слотов ISR). Кадр ~56 мс @2,5 МГц (~18 FPS), ~42 мс
;   @3,125 МГц (~24 FPS).
; ---------------------------------------------------------------------
XSEND:  PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL XUPDCTR        ; живой счётчик SEQ в демо-экран
        MVI A,0A5h
        OUT TXPORT          ; шапка: равномерный пейсинг 33T (4 NOP)
        NOP
        NOP
        NOP
        NOP
        MVI A,05Ah
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        LDA XSSEQ
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        INR A
        STA XSSEQ           ; SEQ++ mod 256
        LXI H,XBUF          ; HL = экран
        MVI B,10            ; внешний: 10 групп по 200 Б
XSOUT:  MVI C,25            ; внутренний: 25 подгрупп по 8 Б
XSL:    MOV A,M
        OUT TXPORT          ; равномерный пейсинг: гэп OUT->OUT >= 25T байта
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        DCR C               ; подгруппа = 7x35T + 15T = 294T (36.75T/Б)
        JNZ XSL
        DCR B
        JNZ XSOUT
        POP H
        POP D
        POP B
        POP PSW
        RET

; ---------------------------------------------------------------------
; XUPDCTR: живой счётчик SEQ (hex, 2 цифры) в демо-экран, строка 22,
; колонки 4-5 - доказательство живого потока в клиенте.
; ---------------------------------------------------------------------
XUPDCTR: PUSH H
        LDA XSSEQ
        MOV C,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL XHEX
        STA XSCNT
        MOV A,C
        ANI 0Fh
        CALL XHEX
        STA XSCNT+1
        POP H
        RET

XHEX:   ADI '0'
        CPI 3Ah
        JC XHX1
        ADI 07h
XHX1:   RET

; ---- демо-экран (ASCII; NUL-конец; <= 80 символов на строку) ----
S_T0:   DB 'fw_monitor_ACdE_tm_xstream - 80x25 TEXT SCREEN B000h-B7CFh -> UART 1000000 8N1',0
S_T1:   DB 'FRAME: A5 5A [SEQ] + 2000 BYTES (ROW-MAJOR 80x25 / CP1251 AT PC CLIENT)',0
S_T2:   DB 'TICK: TMR-ISR RST 7.5 CPLD v28.5 - N=14 (56 US) - SLOT = 6 FRONTS ~0.7 MS',0
S_T3:   DB 'MONITOR: A=ADDR  C=CODE  D=VIEW  E=RUN  B=HEX LOAD  F=RAM TEST  F1=MENU',0
S_T4:   DB 'WRITE YOUR TEXT INTO B000h..B7CFh - THIS WINDOW IS THE PC SCREEN',0
S_T5:   DB 'SEQ:__ FRAME ~56 MS BACK-TO-BACK | REGEN+SCAN IN ISR - CPU-INDEPENDENT',0
XTBL:   DW XBUF, S_T0       ; строка 0
        DW XBUF+00A0h, S_T1 ; строка 2
        DW XBUF+00F0h, S_T2 ; строка 3
        DW XBUF+0280h, S_T3 ; строка 5
        DW XBUF+0320h, S_T4 ; строка 6
        DW XBUF+06E0h, S_T5 ; строка 22 (счётчик SEQ живой, кол. 4-5)
        DW 0000h, 0000h     ; конец таблицы

; =====================================================================
; MAIN: старт, главный цикл, клавиатура, GO (п.2, п.5, п.6)
; =====================================================================
START:  DI
        LXI SP,SP0
        MVI A,80h           ; адрес по умолчанию 8000h (начало ОЗУ)
        STA ADDRH
        XRA A
        STA ADDRL
        CALL XSINIT         ; демо-экран B000h, SEQ = 0
MAIN2:  XRA A
        OUT SEGP            ; дисплей погашен (после сброса горело "8.")
        OUT DIGP            ; разряды off, SND off
        OUT TMRP            ; v1.1 Шаг-1: колонки off + N=0 (СТОП; A=0
                            ; установлено выше) - на старте таймер не
                            ; тикает до TMON даже без масок
        STA SNDST
        STA ADCNT
        STA BDCNT
        STA DPIDX
        STA STATE           ; ST_MENU
        STA PREVST
        CALL REDRAW         ; "ACdE"
        LXI H,TXBAN         ; баннер: терминал 1M читает, 4800 = мусор
        CALL TXSTR
        CALL TMON           ; ПУСК слот-системы (EI внутри)

; ---- главный цикл: слоты ведут дисплей/скан, цикл декодирует
;      клавиатуру и непрерывно льёт кадры xstream (п.5) ----
SCAN:   LDA KRAW0           ; есть ли нажатие (образ ISR, п.3)?
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C               ; A/C = ИЛИ колонок (0 = нажатий нет)
        JZ NOKEY
        LXI H,KRAW0         ; ---- декод: колонка C_idx, ряд = бит ----
        MVI C,0             ; C = индекс колонки 0..3
KDL:    MOV A,M
        ORA A
        JNZ KDH
        INX H
        INR C
        MOV A,C
        CPI 04h
        JNZ KDL
        JMP NOKEY           ; (не бывает: OR ненулевой - защита)
KDH:    MOV B,A             ; B = образ рядов колонки C
        MVI D,0             ; D = номер ряда
KH1:    MOV A,B
        RRC
        MOV B,A
        JC KH2
        INR D
        JMP KH1
KH2:    MOV A,D             ; код = KEYTBL[row*4+col]
        RLC                 ; row*4 (row<=4 -> 0..16, БЕЗ ANI - ряд 4 = 10h,
        RLC                 ;  клавиши 0/F1/F2; ANI 0Ch тут убил бы ряд 4)
        ORA C
        MOV C,A
        MVI B,0
        LXI H,KEYTBL
        DAD B
        MOV A,M
        CPI 0FFh
        JZ SCAN             ; пустая позиция матрицы
        CALL DISPATCH
        ; ---- ожидание отпускания + дебаунс (KRAW живой - ISR сканит) ----
KRL:    LDA KRAW0
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ KRL             ; ждём отпускания (дисплей/скан идут в ISR)
        MVI H,TQ_MS         ; 15 мс дебаунс отпускания
KST:    CALL DLMS
        DCR H
        JNZ KST
        JMP SCAN
NOKEY:  CALL XSEND          ; нажатий нет - кадр xstream (дисплей/скан в ISR)
        JMP SCAN

; ---------------------------------------------------------------------
; DISPATCH: обработка кода клавиши (A). F1 - глобально в меню,
; F2 - глобально показать адрес (повторное F2 - назад).
; Меню: A/C/D/E + B (загрузчик Intel HEX, TMOFF на входе) +
; F (RAM-тест, TMOFF на входе). Тело - как v27 (проверено железом).
; ---------------------------------------------------------------------
DISPATCH: MOV C,A           ; C = КОД КЛАВИШИ (LDA STATE затирает A!)
        CPI K_F2
        JZ K_F2E
        CPI K_F1
        JZ K_F1E
        LDA STATE
        ORA A
        JZ DSM
        CPI 01h
        JZ DSA
        CPI 02h
        JZ DSP
        CPI 04h
        JZ DSW              ; показ адреса: прочие клавиши - игнор
        ; ================= ST_VIEW =================
DSV:    MOV A,C
        CPI K_ENT
        JZ VENT
        RET                 ; тетрады - игнор (режим только чтение)
VENT:   LDA ADDRL
        MOV L,A
        LDA ADDRH
        MOV H,A
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL TICKON
        CALL REDRAW         ; следующий байт на дисплее
        RET
        ; ================= ST_PROG =================
DSP:    MOV A,C
        CPI K_ENT
        JZ PENT
        CPI 10h
        JC PDIG             ; 00h..0Fh - тетрада байта
        RET
PDIG:   MOV A,C
        MOV B,A
        LDA BF0
        STA BF1             ; сдвиг: BF1 = BF0
        MOV A,B
        STA BF0
        LDA BDCNT
        CPI 02h
        JNC PDS
        INR A
        STA BDCNT
PDS:    CALL TICKON
        CALL REDRAW
        RET
PENT:   LDA BDCNT
        ORA A
        JZ PIGN             ; пусто - игнор (без записи)
        LDA BF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA BF0
        ORA C               ; C = байт
        MOV C,A
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,C             ; [ADDR] = байт (A15=0 железо отбросит)
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        XRA A
        STA BDCNT           ; поле гасится - ждём следующий байт
        CALL TICKON
        CALL REDRAW
PIGN:   RET
        ; ================= ST_ADDR =================
DSA:    MOV A,C
        CPI K_ENT
        JZ AENT
        CPI 10h
        JC ADIG             ; 00h..0Fh - тетрада адреса
        RET
ADIG:   MOV A,C
        MOV B,A
        LDA AF2
        STA AF3
        LDA AF1
        STA AF2
        LDA AF0
        STA AF1
        MOV A,B
        STA AF0
        LDA ADCNT
        CPI 04h
        JNC ADS
        INR A
        STA ADCNT
ADS:    CALL TICKON
        CALL REDRAW
        RET
AENT:   LDA ADCNT
        ORA A
        JZ AIGN             ; пусто - игнор
        LDA AF3
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF2
        ORA C
        STA ADDRH
        LDA AF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF0
        ORA C
        STA ADDRL
        XRA A
        STA STATE           ; в меню
        CALL TICKON
        CALL REDRAW
AIGN:   RET
        ; ================= ST_MENU =================
DSM:    MOV A,C             ; вернули код клавиши
        CPI 0Ah             ; 'A' - ввод адреса
        JZ KAD
        CPI 0Ch             ; 'C' - ввод кода (Code)
        JZ KPR
        CPI 0Dh             ; 'D' - просмотр кода
        JZ KVD
        CPI 0Eh             ; 'E' - выполнить
        JZ KGO
        CPI 0Bh             ; 'B' - загрузчик Intel HEX
        JZ KLD
        CPI 0Fh             ; 'F' - RAM-тест
        JZ KRAM
        RET                 ; остальные - игнор
KLD:    CALL TMOFF          ; СТОП слот-системы: RXD чист, дисплей статикой
        CALL LOADM
        JMP K_F1E
KRAM:   CALL TMOFF          ; СТОП: стек статичен - тест 8000h-FFE7h чист
        CALL RAMT
        JMP K_F1E
KAD:    MVI A,ST_ADDR
        STA STATE
        XRA A
        STA ADCNT
        CALL TICKON
        CALL REDRAW
        RET
KPR:    MVI A,ST_PROG       ; C: ввод кода (Code)
        STA STATE
        XRA A
        STA BDCNT
        CALL TICKON
        CALL REDRAW
        RET
KVD:    MVI A,ST_VIEW       ; D: просмотр кода
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
; ---- F2: показ адреса операций (глобально; повторное F2 - назад) ----
K_F2E:  LDA STATE
        CPI ST_SHOW
        JZ KF2B             ; уже показываем - вернуть прежний режим
        STA PREVST          ; запомнить, откуда пришли
        MVI A,ST_SHOW
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
KF2B:   LDA PREVST
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
DSW:    RET                 ; показ адреса: Enter/тетрады не действуют
K_F1E:  CALL TMON           ; реинициализация слот-системы (после B/F обяз.,
                            ;  после простого F1 - безвредный ре-арм)
        XRA A
        STA STATE           ; меню (из любого режима)
        CALL TICKON
        CALL REDRAW
        RET
        ; ================= GO: запуск =================
KGO:    XRA A
        OUT SEGP            ; сегменты 0
        OUT DIGP            ; разряды 0, SND 0
        OUT TMRP            ; v1.1 Шаг-1: колонки off + N=0 (СТОП; A=0);
                            ; следом TMOFF - двойной СТОП безвреден
        CALL TMOFF          ; СТОП таймера: программа пользователя - 100% ЦП
                            ; (в v27 TRAP-тик жрал 6,1% всегда - п.5)
        LXI SP,SP0
        LXI H,MONRET
        PUSH H              ; адрес возврата в монитор
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = адрес запуска
        XRA A
        MOV B,A
        MOV C,A
        MOV D,A
        MOV E,A             ; регистры обнулены
        PCHL                ; ушли в программу пользователя
MONRET: DI
        LXI SP,SP0
        CALL TMON           ; слот-система заново (чистка KRAW/DPIDX/EI)
        ; ждём отпускания всех клавиш + дебаунс (KRAW живой)
MNR1:   LDA KRAW0
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ MNR1
        MVI H,TQ_MS         ; 15 мс дебаунс
MNR3:   CALL DLMS
        DCR H
        JNZ MNR3
        JMP MAIN2           ; реинициализация, ADDR сохранён

        END
