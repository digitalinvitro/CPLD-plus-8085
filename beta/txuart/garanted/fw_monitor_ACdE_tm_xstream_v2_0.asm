; =====================================================================
; beta/txuart/rom -- fw_monitor_ACdE_tm_xstream v2.0: монитор для платы
; retro_pcld (CPLD top_txuart_por6_v37f11, XC95108). ПАРА ЖЁСТКО СВЯЗАНА:
; RTL v37F-11 <-> fw v2.0. Против v1.2 (пара RTL v2.9) изменилась СУТЬ
; ТАЙМЕРА и темп CPU:
;
;   1. ТАЙМЕР СТАЛ СВОБОДНЫМ (узел «ТАЙМЕР» удалён из RTL v37F ради
;      МЦ): N-таймера БОЛЬШЕ НЕТ. RST 7.5 стреляет КАЖДЫЙ ТИК 4 мкс
;      (edge-защёлка), фаза тика tmr_cnt[1:0] читается в IN 03h D6-D5
;      (0..3, полный цикл 16 мкс). ОСТАНОВИТЬ тик нельзя - только
;      замаскировать. OUT 06h: A[7:4] = колонки, A[3:0] ИГНОРИРУЮТСЯ.
;
;   2. ДИСЦИПЛИНА TMIARM (вместо армирования): прямой сервис тика
;      НЕВОЗМОЖЕН - ответ на прерывание ~19T + минимальное тело ~60T =
;      ~80T = 26 мкс >> 4 мкс тика (даже /4 = 16 мкс не хватает).
;      Поэтому ISR ВСЕГДА выходит ЗАМАСКИРОВАННЫМ (SIM 78h: M7.5=1 +
;      сброс защёлки), а главный код вызывает ТОЧКИ TMIARM:
;          TMIARM: MVI A,68h / SIM / NOP / RET
;      Защёлка RST 7.5 замаскированной НЕ блокирует захват фронтов -
;      она всегда заряжена (тики идут каждые 4 мкс); снятие маски
;      стреляет ПЕНДИНГ-фронтом СИНХРОННО на NOP. Замаскированные тики
;      стоят 0 тактов. Каденция ISR = частота вызовов TMIARM.
;      Точки TMIARM (полный список, IE обязан быть on):
;        SCAN (вершина главного цикла), XSL (каждая 8-Б подгруппа
;        XSEND, ~94 мкс), KRL/MNR1 (спин отпускания клавиш - БЕЗ
;        пульки KRAW застынет ненулевым и спин станет вечным!),
;        KST/MNR3 (дебаунс, 1 пулька на DLMS), TKL (тон, 1 на DLMS),
;        TMON (стартовый: EI + SIM 68h; первый слот придёт из SCAN).
;      ПОД ЗАПРЕТОМ: любые пульки в B/F/GO (RXD/RAMT требуют тишины -
;      TMOFF маскирует, пулька сняла бы маску в обход).
;
;   3. СЛОТЫ: каждый 6-й вызов ISR = СЛОТ: скан 1 колонки (KSCOL) +
;      регенерация 1 разряда (REFRESH) + фаза тона в SNDST.0 ведётся
;      TICKON'ом (см. п.5), счётчик в E (главный цикл написан БЕЗ E).
;      Каденция слота теперь ПЛАВАЮЩАЯ (зависит от плотности точек
;      TMIARM): меню/xstream ~0,7 мс, спин клавиши ~0,3 мс, паузы
;      DLMS ~1-6 мс. Питч тона и частота скана следуют за каденцией.
;
;   4. CPU 2,5 -> 3,125 МГц (T=400 -> 320 нс, CLKOUT = X1/2). Все
;      CPU-временные константы пересчитаны: K_MS 104 -> 130 (~1,0 мс),
;      RXHB 15 -> 19, RXFB 30 -> 41 (4800: бит = 75T фикс + 41x14T =
;      649T = 207,7 мкс; PAUSE-итерация = DCR+JNZ = 14T, в v1.2 считали
;      15T @400 нс). Каденция дисплея/скана NOT CPU-зависима от старого
;      N-таймера - теперь она зависит от точек TMIARM (см. п.3).
;
;   5. ЗВУК (ФИКС v1.2): в v1.2 REFRESH ставил D4 константой на всё
;      окно тона (ORA A по всему SNDST) - квадрат не образовывался
;      (слышен был щелчок). v2.0: D4 = БИТ ФАЗЫ SNDST.0; фазу тогглит
;      САМ TICKON раз в ~1 мс -> квадрат ~500 Гц, НЕ зависящий от
;      каденции слотов. SNDTOG из слота удалён.
;
;   6. ДИСЦИПЛИНА B/F/GO (проще v1.2 - OUT 06h не нужен):
;        TMOFF: DI + SIM 78h (маски 5.5/6.5/7.5 + СБРОС защёлки RST 7.5).
;        TMON : DI + SIM 78h + чистка KRAW/DPIDX/SNDST + E=6
;               + SIM 68h (снята маска 7.5) + EI.
;      GO (KGO): TMOFF - программа пользователя получает 100% ЦП при
;      ЗАМАСКИРОВАННОМ 7.5 (тики идут, защёлка заряжается, ЦП не трогают).
;      Программе, которой нужен тик, достаточно EI + SIM 68h (вектор
;      003Ch ведёт в ROM-TMISR монитора); при желании - своя ISR.
;      B (LOADM): RXD чист от джиттера (маски + DI). F (RAMT): стек
;      статичен, тест 8000h-FFE7h без чужих pushes.
;
;   7. ПОРТЫ v37F-11: ЗАПИСЬ 00h = сегменты A[6:0] (dp погашен
;      навсегда), 01h = разряды A[3:0] + звук A[4], 04h = TXDATA
;      (однократный строб; запись при busy - байт тихо теряется),
;      06h = колонки A[7:4]. ЧТЕНИЕ 03h = {TXRDY(D7), tmr_cnt[1:0]
;      (D6-D5, НОВОЕ), row4..row0 (D4-D0)}. 02h/05h/07h НЕМАПЛЕНЫ;
;      чтение немапленных = bus_reg (последние шинные данные).
;
;   8. XSTREAM (выдача экрана B000h): пейсинг 36,75T/Б сохранён
;      (11,8 мкс >= 10 мкс байта 1M), пулька TMIARM в шапке каждой
;      8-Б подгруппы: ISR-вставки только УДЛИНЯЮТ гэпы (ноль отбросов
;      TX), регенерация/скан идут ВНУТРИ посылки. Кадр ~37 мс
;      @3,125 МГц с пульками (~27 FPS против ~24 у v1.2). Клиент
;      xstream_view.ps1 (COM @1000000 8N1) - БЕЗ ИЗМЕНЕНИЙ:
;      A5 5A [SEQ] + 2000 Б. SEQ в FFFAh (шара с LST).
;
; СБОРКА (asm85.py, кодировка CP1251):
;   python3 ../../../tools/asm85.py fw_monitor_ACdE_tm_xstream_v2_0.asm -o
;          fw_monitor_ACdE_tm_xstream_v2_0.hex -l fw_monitor_ACdE_tm_xstream_v2_0.lst
; Прошивка: flash A29040B, offset 0000h (ROM-окно 0000h-7FFFh).
;
; КЛАВИАТУРА (как v27): тетрады 0-F + Enter + F1(меню) + F2(показ
; адреса); меню: A=адрес C=код D=просмотр E=выполнить B=загрузчик
; Intel HEX (SID 4800) F=RAM-тест. Выход из залипшего режима - RESET.
;
; ОЗУ: переменные FFE8h-FFFFh, стек с FFE7h вниз (SP0 = FFE8h).
; ГЛУБИНА СТЕКА: максимум XSEND (4 push) + TMISR слот (PSW+B/D/H +
; RST-адрес + KSCOL/REFRESH/SETTLE) ~ 26 Б - как v1.2, в свободном ОЗУ.
; =====================================================================

; ---- порты CPLD v37F-11 (декод по A2-A0, зеркала mod 8) ----
SEGP    EQU 00h             ; сегменты: D0=a..D6=g, D7=dp (погашен навсегда,
                            ; A7 игнорируется); 1 = горит
DIGP    EQU 01h             ; D3-D0 разряды (1 = горит), D4 = SND (прямой бит)
KBCOLP  EQU 06h             ; OUT: A[7:4] = колонки (1 = заведена); A[3:0]
                            ; ИГНОРИРУЮТСЯ - таймер НЕ пишется (п.1)
KBROWP  EQU 03h             ; IN: D7 = TXRDY (1 = готов принять след. байт),
                            ; D6-D5 = tmr_cnt[1:0] фаза тика 0..3 (НОВОЕ),
                            ; D4-D0 ряды (1 = нажата в активной колонке)
TXP     EQU 04h             ; OUT: TXDATA -> сериализатор CPLD (1M 8N1)
; 02h/05h/07h НЕМАПЛЕНЫ; символы KBCOLP=02h/STP/TMRP/TMN из v1.2 удалены

; ---- константы тайминга (CPU 3,125 МГц, T = 320 нс; тик 4 мкс) ----
TQ_MS   EQU 15              ; дебаунс отпускания ~15 мс (DLMS-единиц)
K_MS    EQU 130             ; DLMS-единица ~1,0 мс (130 x 24T x 320 нс)
RXHB    EQU 19              ; полбита 4800 (PAUSE-итераций, ~103 мкс)
RXFB    EQU 41              ; бит приёма 4800 (PAUSE-итераций, ~208 мкс)
; PAUSE-итерация = DCR D + JNZ = 14T; бит RX = 75T фикс + RXFB x 14T =
; 649T x 320 нс = 207,7 мкс (идеал 208,3; запас Uart +-10% покрывает)

; ---- коды клавиш ----
K_ENT   EQU 10h             ; Enter  (row3/col3, SW16)
K_F1    EQU 11h             ; F1     (row4/col1, SW18) - меню
K_F2    EQU 12h             ; F2     (row4/col2, SW19) - показ адреса
K_NONE  EQU 0FFh            ; пустая позиция матрицы

; ---- состояния ----
ST_MENU EQU 00h             ; меню "ACDE" (B = загрузчик, F = RAM-тест)
ST_ADDR EQU 01h             ; ввод адреса
ST_PROG EQU 02h             ; ввод кода (Code)
ST_VIEW EQU 03h             ; просмотр кода
ST_SHOW EQU 04h             ; показ адреса операций (F2)

; ---- ОЗУ монитора ----
SP0     EQU 0FFE8h          ; SP монитора
SNDST   EQU 0FFE8h          ; бит0 = фаза тона (тогглит TICKON), бит1 = тон вкл
STATE   EQU 0FFE9h          ; 0=меню, 1=адрес, 2=код, 3=просмотр, 4=показ
ADDRH   EQU 0FFEAh          ; текущий адрес (старший); в загрузчике = адрес записи
ADDRL   EQU 0FFEBh          ; текущий адрес (младший)
ADCNT   EQU 0FFECh          ; тетрады адреса (0..4); в загрузчике = счётчик байт данных
AF3     EQU 0FFEDh          ; тетрады адреса
AF2     EQU 0FFEEh
AF1     EQU 0FFEFh
AF0     EQU 0FFF0h
BDCNT   EQU 0FFF1h          ; введено тетрад байта (0..2)
BF1     EQU 0FFF2h
BF0     EQU 0FFF3h
DPIDX   EQU 0FFF4h          ; фаза регенерации 0..3 = колонка скана (владеет ISR)
DIGIMG  EQU 0FFF5h          ; глифы разрядов DIG0..DIG3
DIGIMG0 EQU 0FFF5h
DIGIMG1 EQU 0FFF6h
DIGIMG2 EQU 0FFF7h
DIGIMG3 EQU 0FFF8h
PREVST  EQU 0FFF9h          ; прежний режим для F2
; --- парсер Intel HEX (загрузчик B); FFFC-FFFF = шара с KRAW (п.3 v1.2) ---
LST     EQU 0FFFAh          ; состояние: 0=ждём ':' 1=count 2=addr 3=type 4=data 5=chk
                            ;   (шара с XSSEQ - см. п.8; LOADM чистит на входе)
LNIB    EQU 0FFFBh          ; осталось тетрад в текущем байте поля (1..2)
LBPC    EQU 0FFFBh+1        ; осталось байт в текущем поле   = KRAW0
LACC    EQU 0FFFBh+2        ; накопитель тетрад текущего байта = KRAW1
LSUM    EQU 0FFFBh+3        ; сумма байт записи (mod 256)      = KRAW2
LTY     EQU 0FFFBh+4        ; тип последней записи             = KRAW3
; --- сырой образ клавиатуры (пишет ISR, читает главный цикл) ---
KRAW0   EQU 0FFFBh+1        ; ряды колонки 0 (биты 0-4) = LBPC
KRAW1   EQU 0FFFBh+2        ; ряды колонки 1            = LACC
KRAW2   EQU 0FFFBh+3        ; ряды колонки 2            = LSUM
KRAW3   EQU 0FFFBh+4        ; ряды колонки 3            = LTY

; --- XSTREAM: экран -> UART (тик кадра = непрерывный поток, п.8) ---
TXPORT  EQU TXP             ; TXDATA (04h) - синоним для xstream-кода
XBUF    EQU 0B000h          ; ЭКРАН 80x25 = 2000 Б (B000h..B7CFh)
XSSEQ   EQU 0FFFAh          ; SEQ кадра mod 256 (ячейка LST - см. п.8)
XSCNT   EQU XBUF+06E4h      ; живой счётчик SEQ в демо-экране (строка 22, кол. 4-5)

; =====================================================================
        ORG 0000h
        JMP START

; ---- векторная зона: глушилки EI;RET -------------------------------
; RST 1..7, TRAP (0024h), RST 5.5/6.5. EI обязателен в каждой (снимает
; блокировку после приёма). На плате: TRAP = PGND (держатель '0'),
; 5.5/6.5 железно=0 и вдобавок замаскированы SIM - заглушки защитные.
; RST 7.5 (003Ch) = СВОБОДНЫЙ ТИК 4 мкс (п.1) - НЕ заглушка, обработчик
; ниже; под TMOFF маскируется, каденцию задаёт владелец точек TMIARM.
        ORG 0008h           ; RST 1
        EI
        RET
        ORG 0010h           ; RST 2
        EI
        RET
        ORG 0018h           ; RST 3
        EI
        RET
        ORG 0020h           ; RST 4
        EI
        RET
        ORG 0024h           ; TRAP - защитная заглушка (пин PGND)
        EI
        RET
        ORG 0028h           ; RST 5
        EI
        RET
        ORG 002Ch           ; RST 5.5
        EI
        RET
        ORG 0030h           ; RST 6
        EI
        RET
        ORG 0034h           ; RST 6.5
        EI
        RET
        ORG 0038h           ; RST 7
        EI
        RET
        ORG 003Ch           ; RST 7.5 = свободный тик 4 мкс (п.1, п.2)
        JMP TMISR

; =====================================================================
; Таблицы (ORG 0044h - векторная зона выше освобождена)
; =====================================================================
        ORG 0044h
; ---- глифы '0'..'F' (a,b,c,d,e,f,g = D0..D6) ----
GTBL:   DB 3Fh              ; '0'
        DB 06h              ; '1'
        DB 5Bh              ; '2'
        DB 4Fh              ; '3'
        DB 66h              ; '4'
        DB 6Dh              ; '5'
        DB 7Dh              ; '6'
        DB 07h              ; '7'
        DB 7Fh              ; '8'
        DB 6Fh              ; '9'
        DB 77h              ; 'A'
        DB 7Ch              ; 'b'
        DB 39h              ; 'C'
        DB 5Eh              ; 'd'
        DB 79h              ; 'E'
        DB 71h              ; 'F'

; ---- биты разрядов/колонок (индекс = DPIDX: 0=DIG0 правый ... 3=DIG3 левый) ----
BITTBL: DB 01h,02h,04h,08h

; ---- КАРТА КЛАВИШ: KEYTBL[row*4+col] ----
KEYTBL: DB 0Ah,0Bh,0Ch,0Dh  ; row0: A  B  C  D
        DB 07h,08h,09h,0Eh  ; row1: 7  8  9  E
        DB 04h,05h,06h,0Fh  ; row2: 4  5  6  F
        DB 01h,02h,03h,10h  ; row3: 1  2  3  Enter
        DB 00h,11h,12h,0FFh ; row4: 0  F1 F2 (нет)

; ---- баннер TX @1M (на терминале 4800 = короткая мусорная строка) ----
TXBAN:  DB 'ACDE-TM',0Dh,0Ah,00h

; ---- паттерны RAM-теста: значение + глиф для статического дисплея ----
RAMPAT: DB 00h,3Fh          ; 00h -> "0000"
        DB 0FFh,71h         ; FFh -> "FFFF"
        DB 55h,6Dh          ; 55h -> "5555"
        DB 0AAh,77h         ; AAh -> "AAAA"

; =====================================================================
; СИСТЕМА ТАЙМЕРА v2.0: TMOFF/TMON/TMIARM + TMISR + слоты (п.2, п.3, п.6)
; =====================================================================
        ORG 0100h

; ---------------------------------------------------------------------
; TMOFF: ТИШИНА слот-системы. DI + полные маски (SIM 78h = MSE+M7.5
; +M6.5+M5.5, заодно СБРОС защёлки RST 7.5). Фронты тика продолжают
; заряжать защёлку, но ЦП не трогают. Вызывается на входе B/F/GO.
; Портит A. (v1.2 OUT 06h,0 удалён - стопить нечего, п.1.)
; ---------------------------------------------------------------------
TMOFF:  DI
        MVI A,78h           ; MSE=1, M7.5=1 (маска+сброс защёлки), M6.5=1, M5.5=1
        SIM
        RET

; ---------------------------------------------------------------------
; TMON: ПУСК слот-системы (START, выход из B/F, MONRET). Чистит
; состояние ISR, заряжает E=6, снимает маску 7.5, EI. Первый слот
; придёт из ближайшей точки TMIARM (из START - вершина SCAN).
; ---------------------------------------------------------------------
TMON:   DI
        MVI  A, 78h     ; маски + сброс защёлки RST 7.5
        SIM
        XRA  A
        STA  SNDST      ; тон off, фаза 0
        STA  DPIDX      ; фаза регенерации / колонка 0
        STA  KRAW0      ; сырой образ клавиатуры - в ноль
        STA  KRAW1
        STA  KRAW2
        STA  KRAW3
        MVI  A, 68h     ; MSE=1, M7.5=0 (7.5 РАЗРЕШЁН), M6.5=1, M5.5=1
        SIM
        EI
        RET

; ---------------------------------------------------------------------
; TMIARM: ТОЧКА СИНХРОННОЙ ПУЛЬКИ (п.2). Снимает маску 7.5 - всегда
; заряженная защёлка (тики 4 мкс) стреляет СРАЗУ после NOP: ISR
; отрабатывает здесь же и снова замаскировывает 7.5 (дисциплина).
; Вызывать ТОЛЬКО при IE=on и в мониторном режиме (под TMOFF ЗАПРЕЩЕНО -
; пулька сняла бы маску в обход TMOFF, см. п.2). Портит A.
; ---------------------------------------------------------------------
TMIARM: RET             ; заглушка для старых вызовов CALL TMIARM

; ---------------------------------------------------------------------
; TMISR: RST 7.5 = тик 4 мкс, НО входит ISR только через точки TMIARM
; (п.2). Счётчик слотов В E; слот = каждый 6-й вызов: скан колонки +
; регенерация разряда. РЕ-АРМОВ БОЛЬШЕ НЕТ - вместо них МАСКА В КОНЦЕ
; обеих ветвей (SIM 78h: M7.5=1 + сброс защёлки). Сохраняем PSW всегда
; (флаги главного цикла), B/D/H - только в слоте; E НЕ сохраняем -
; главный цикл его не держит.
; Такты (@3,125 МГц, T=320 нс): быстрый вызов ~80T ~ 26 мкс (бюджет
; тика 4 мкс НЕ выдерживает - потому и дисциплина TMIARM, п.2); слот
; ~530T ~ 170 мкс. Каденция = частота точек TMIARM (п.3).
; ---------------------------------------------------------------------
TMISR:  PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL KSCOL      ; скан 1 колонки (колонка = фаза DPIDX)
        CALL REFRESH    ; регенерация 1 разряда (фаза ++ внутри)
        POP  H
        POP  D
        POP  B
        POP  PSW
        EI
        RET
TMTINY: MVI A,78h           ; 7   маска + сброс защёлки (v1.2: OUT TMRP
        SIM                 ; 10  ре-арм - удалён, п.1/п.2)
        POP PSW
        EI
        RET

; ---------------------------------------------------------------------
; KSCOL: скан ОДНОЙ колонки (вызывается из слота). Колонка = текущая
; фаза регенерации DPIDX - отдельного счётчика нет. Сырой образ рядов
; (биты 0-4) -> KRAW0..KRAW3[колонка]. Портит A/B/C/D/H/L (в ISR - под
; PUSH B/D/H). Колонка на выходе погашена. v2.0: записей в 06h две
; (завести/погасить), A[3:0] = 0 - таймер не пишется (п.1).
; ---------------------------------------------------------------------
KSCOL:  LDA DPIDX           ; колонка = фаза регенерации 0..3
        ANI 03h
        MOV C,A             ; B = индекс колонки
        MVI B,0
        LXI H,BITTBL
        DAD B               ; HL = BITTBL + колонка
        MOV D,M             ; D = бит колонки (01/02/04/08)
        LXI H,KRAW0
        DAD B               ; HL = KRAW0 + колонка (B/C целы)
        MOV A,D
        RLC                 ; бит колонки (01/02/04/08) -> старший ниббл
        RLC                 ; A[7:4] (RLC x4, переноса нет)
        RLC
        RLC
        OUT KBCOLP          ; колонка заведена (A[3:0]=0 - легально, п.1)
        CALL SETTLE
        IN KBROWP           ; ряды активной колонки (D6-D5 фаза тика и
        ANI 1Fh             ; D7 TXRDY маскируются - как в v1.2 Шаг-2)
        MOV M,A             ; KRAW[колонка] = сырой образ рядов
        XRA A
        OUT KBCOLP          ; колонки off (0000); вторая запись легальна -
        RET                 ; колонки просто гасятся (в v1.2 тут был +N)

; =====================================================================
; Системные процедуры (перенос из v1.2/monitor27, константы 3,125 МГц)
; =====================================================================

; ---------------------------------------------------------------------
; SETTLE: пауза ~26 мкс (LXI+3 итерации 24T @320 нс; установка рядов
; после заведения колонки). Портит A/B/C. H/L НЕ ТРОГАЕТ (нужно KSCOL).
; ---------------------------------------------------------------------
SETTLE: LXI B,3
STL:    DCX B
        MOV A,B
        ORA C
        JNZ STL
        RET

; ---------------------------------------------------------------------
; REFRESH: один слот регенерации (v27 БЕЗ ИЗМЕНЕНИЙ, кроме тона).
; ГАШЕНИЕ -> РАЗРЯД -> ГЛИФ. DIGIMG[DPIDX] на разряд DPIDX, фаза ++
; mod 4. v2.0 ФИКС тона (п.5): D4 = БИТ ФАЗЫ SNDST.0 (в v1.2 D4 горел
; константой на всё окно - квадрат не образовывался). D/E НЕ ТРОГАЕТ
; (в ISR критично: D = бит колонки уже погашен, E = счётчик слотов).
; Портит A/B/C/H/L.
; ---------------------------------------------------------------------
REFRESH: LDA DPIDX
        MOV C,A             ; C = индекс 0..3
        MVI B,0
        LXI H,BITTBL
        DAD B
        MOV B,M             ; B = бит разряда (01,02,04,08)
        LXI H,DIGIMG        ; HL = DIGIMG + DPIDX (цикл вместо ADD)
RFIL:   MOV A,C
        ORA A
        JZ RFGD
        INR L
        DCR C
        JMP RFIL
RFGD:   MOV C,M             ; C = глиф разряда
        LDA SNDST
        ANI 02h
        JZ RFN              ; тон не разрешён - D4 = 0
        LDA SNDST
        ANI 01h
        JZ RFN              ; фаза 0 - D4 = 0 (полуволна низа)
        MOV A,B
        ORI 10h
        MOV B,A             ; фаза 1 -> D4 = 1 (полуволна верха)
RFN:    XRA A
        OUT SEGP            ; (1) гашение: старый разряд погас
        MOV A,B
        OUT DIGP            ; (2) разряд переключён (сегменты пусты)
        MOV A,C
        OUT SEGP            ; (3) зажгли глиф нового разряда
        LDA DPIDX
        INR A
        ANI 03h
        STA DPIDX
        RET

; ---------------------------------------------------------------------
; TICKON: короткий тик подтверждения клавиши ~15 мс (TQ_MS единиц
; DLMS). v2.0 (п.5): фазу тона SNDST.0 тогглит САМ TICKON раз в ~1 мс
; -> квадрат ~500 Гц, НЕ зависящий от каденции слотов (в v1.2 фазу
; тогглил слот ~0,7 мс, но REFRESH ставил D4 константой - тона не было).
; Пулька TMIARM в итерации: слоты идут - дисплей/скан не замирают.
; Портит A/B/C/H.
; ---------------------------------------------------------------------
TICKON: LDA SNDST
        ORI 02h             ; тон разрешён
        STA SNDST
        MVI H,TQ_MS         ; 15 мс
TKL:    LDA SNDST
        XRI 01h             ; тоггл фазы (квадрат ~500 Гц)
        STA SNDST
        CALL TMIARM         ; слот на итерацию (дисплей жив под тоном)
        CALL DLMS
        DCR H
        JNZ TKL
        LDA SNDST
        ANI 0FDh            ; тон off
        STA SNDST
        RET

; ---------------------------------------------------------------------
; GLOOK: A = тетрада 0..F -> A = глиф (GTBL). Портит A/B/C/H/L.
; ---------------------------------------------------------------------
GLOOK:  MOV C,A
        MVI B,0
        LXI H,GTBL
        DAD B
        MOV A,M
        RET
; ---------------------------------------------------------------------
; REDRAW: пересобрать DIGIMG[0..3] по состоянию (как v5/v27).
;   меню : "ACdE"; адрес: тетрады вдвигаются справа; код "__C3";
;   просмотр: [ADDR] в правых разрядах; показ(F2): ADDR на 4 разрядах.
; Портит A/B/C/D/H/L (D - рабочий в RDW/RDV; ISR сохраняет D - безопасно).
; ---------------------------------------------------------------------
REDRAW: LDA STATE
        ORA A
        JZ RDM
        CPI 01h
        JZ RDA
        CPI 03h
        JZ RDV
        CPI 04h
        JZ RDW
        ; ---- ST_PROG ----
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA BDCNT
        CPI 02h
        JC RDPR0            ; <2 - старшая тетрада пуста
        LDA BF1
        CALL GLOOK
        STA DIGIMG1
RDPR0:  LDA BDCNT
        ORA A
        JZ RDRE             ; 0 - младшая тоже пуста
        LDA BF0
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDV:    LDA ADDRH           ; ---- ST_VIEW: [ADDR] в правых разрядах ----
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = ADDR
        MOV A,M             ; A = [ADDR] (HL>=8000h - ОЗУ)
        MOV D,A             ; D = байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh             ; старшая тетрада
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh             ; младшая тетрада
        CALL GLOOK
        STA DIGIMG0
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        JMP RDRE
RDW:    LDA ADDRH           ; ---- ST_SHOW: ADDR на 4 разрядах ----
        MOV D,A             ; D = старший байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG3
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG2
        LDA ADDRL
        MOV D,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDM:    MVI A,77h           ; 'A'
        STA DIGIMG3
        MVI A,39h           ; 'C'
        STA DIGIMG2
        MVI A,5Eh           ; 'd' (D)
        STA DIGIMG1
        MVI A,79h           ; 'E'
        STA DIGIMG0
        JMP RDRE
RDA:    XRA A               ; ---- ST_ADDR: последняя тетрада справа ----
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA ADCNT
        CPI 01h
        JC RDRE             ; 0 тетрад - всё пусто
        LDA AF0
        CALL GLOOK
        STA DIGIMG0
        LDA ADCNT
        CPI 02h
        JC RDRE
        LDA AF1
        CALL GLOOK
        STA DIGIMG1
        LDA ADCNT
        CPI 03h
        JC RDRE
        LDA AF2
        CALL GLOOK
        STA DIGIMG2
        LDA ADCNT
        CPI 04h
        JC RDRE
        LDA AF3
        CALL GLOOK
        STA DIGIMG3
RDRE:   RET

; =====================================================================
; UART-канал: передача OUT 04h @1M (TXRDY = IN 03h бит 7, v1.2 Шаг-2),
; приём RIM/SID @4800 - как v27
; =====================================================================

; ---------------------------------------------------------------------
; TXBYTE: A = байт -> сериализатор CPLD (1 000 000 8N1). Ожидает TXRDY
; (запись при busy аппаратно отбрасывается). Используется баннером/строками.
; ---------------------------------------------------------------------
TXBYTE: PUSH PSW
TXB1:   IN KBROWP           ; TXRDY = бит 7
        ANI 80h             ; tx_idle = ~|bit_cnt: 1 = готов принять байт
        JZ TXB1
        POP PSW
        OUT TXP
        RET

; ---------------------------------------------------------------------
; TXSTR: HL = строка с нулевым завершителем -> TX. Портит A/HL.
; ---------------------------------------------------------------------
TXSTR:  MOV A,M
        ORA A
        RZ
        CALL TXBYTE
        INX H
        JMP TXSTR

; ---------------------------------------------------------------------
; PAUSE: пауза D итераций по 4,5 мкс (DCR+JNZ = 14T @3,125 МГц;
; в v1.2 считали 15T @400 нс - значение пересчитано, см. EQU).
; ---------------------------------------------------------------------
PAUSE:  DCR D
        JNZ PAUSE
        RET

; ---------------------------------------------------------------------
; RXD: приём байта SID 4800 8N1 (фрагмент 7 + стоп-бит). Выход:
; C = байт, CY = 0 ОК / CY = 1 обрыв кадра (стоп-бит = 0). Портит A/B/C/D.
; Цикл строгий - в режиме B таймер ЗАМАСКИРОВАН (TMOFF: DI + SIM 78h)
; и пульки TMIARM запрещены - джиттера нет вообще.
; Константы v2.0: RXHB=19 (полбита ~103 мкс), RXFB=41 (бит ~208 мкс,
; расчёт в блоке EQU). v1.2: RXHB=15/RXFB=30 @2,5 МГц.
; ---------------------------------------------------------------------
RXD:    MVI B,08h
RXW:    RIM                 ; A7 = SID
        ORA A
        JM RXW              ; '1' (покой) - ждать старт-бит
        MVI D,RXHB          ; полбита - в середину старт-бита
        CALL PAUSE
        RIM                 ; подтвердить старт-бит
        ORA A
        JM RXW              ; '1' - ложный старт, ждать заново
        MVI C,00h
        MVI D,RXFB          ; бит - в середину D0
        CALL PAUSE
RXL:    RIM                 ; A7 = SID - центр очередного бита
        ANI 80h
        RAR                 ; бит -> CY
        MOV A,C
        RAR                 ; вставить сверху (LSB-first)
        MOV C,A
        MVI D,RXFB
        CALL PAUSE
        DCR B
        JNZ RXL
        ; после последней итерации RXL (выборка d7 + бит задержки)
        ; линия = середина стоп-бита
        RIM
        ANI 80h             ; CY = 0 (ANI сбрасывает перенос)
        JZ RXBAD            ; стоп-бит = 0 - обрыв кадра
        ORA A               ; CY = 0
        RET                 ; C = байт, CY = 0
RXBAD:  STC
        RET                 ; CY = 1

; ---------------------------------------------------------------------
; NIB: A = ASCII-символ -> CY = 1 и A = тетрада 0-F ('0'-'9','A'-'F',
; 'a'-'f'), иначе CY = 0. Портит A.
; ---------------------------------------------------------------------
NIB:    SUI 30h             ; '0'..'9' -> 0..9
        JC NIBX             ; < '0'
        CPI 0Ah
        JC NIBOK            ; цифра 0..9
        SUI 07h             ; 'A'..'F' -> 10..15
        CPI 10h
        JNC NIB2            ; > 'F' - попробовать строчные a..f
        JMP NIBOK
NIB2:   SUI 20h             ; ('a'-'0')-07h-20h = 10..15
        CPI 10h
        JNC NIBX
        JMP NIBOK
NIBOK:  STC
        RET
NIBX:   ORA A               ; CY = 0
        RET

; ---------------------------------------------------------------------
; LSTAT: A = глиф -> статический дисплей (все 4 разряда, слот-система
; стоит). Для режимов загрузчика/RAM-теста, где ISR замаскирован (TMOFF).
; ---------------------------------------------------------------------
LSTAT:  PUSH B
        MOV B,A
        XRA A
        OUT SEGP            ; гашение на время переключения
        MVI A,01h
        OUT DIGP            ; все 4 разряда, SND = 0
        MOV A,B
        OUT SEGP            ; глиф на все разряды
        POP B
        RET

; ---------------------------------------------------------------------
; DLMS: пауза ~1,02 мс (K_MS=130 итераций 24T @320 нс = 1,002 мс).
; Портит A/B/C. H/L целы. ВНИМАНИЕ (п.3): внутри DLMS пульки TMIARM
; нет - на время паузы слоты стоят (один разряд горит ~1 мс, яркость
; не страдает - скважность 1/4 как всегда; каденция возвращается на
; следующем TMIARM-вызове).
; ---------------------------------------------------------------------
DLMS:   LXI B,K_MS
DLS1:   DCX B
        MOV A,B
        ORA C
        JNZ DLS1
        RET

; ---------------------------------------------------------------------
; LDSUM: LSUM += B (mod 256). Портит A.
; ---------------------------------------------------------------------
LDSUM:  PUSH PSW
        LDA LSUM
        ADD B
        STA LSUM
        POP PSW
        RET

; ---------------------------------------------------------------------
; LDBEEP: длинный сигнал ~0,3 с (тоггл D4 DIGP вручную: в B/F 7.5
; замаскирован (TMOFF) - ISR не пишет DIGP, конфликта нет; пульки
; TMIARM здесь ЗАПРЕЩЕНЫ - см. п.2). Портит A/B/C/D.
; ---------------------------------------------------------------------
LDBEEP: MVI D,150
LDB1:   MVI A,1Fh           ; SND = 1, разряды on
        OUT DIGP
        CALL DLMS
        MVI A,0Fh           ; SND = 0
        OUT DIGP
        CALL DLMS
        DCR D
        JNZ LDB1
        RET

; =====================================================================
; LOADM: Intel HEX загрузчик (клавиша B). Приём SID 4800 8N1.
; Вход через KLD с TMOFF (7.5 замаскирован, DI) - как v27 по логике
; парсера. Формат записи: :nnaaaatt[dd...]cc, cc = (-сумма байт) mod 256.
; Статический дисплей LLLL; адрес каждой записи живёт в ADDRH/L.
; Запись только в ОЗУ (A15=1): попадание в ROM-окно = ошибка EEEE.
; Выход: EOF-запись (type 01) -> тик и меню; ошибка -> EEEE + сигнал.
; Выход из зависшего приёма - RESET (SW20).
; NOTE: LACC/LNIB/LBPC/LSUM/LTY = клетки FFFB-FFFF; в обычном режиме
; FFFC-FFFF заняты KRAW (ISR) - в B маски стоят (TMOFF), конфликта нет;
; TMON на выходе чистит KRAW. XSSEQ/LST = FFFA: на входе LST=0 (=SEQ 0 -
; клиент логирует рестарт потока), на выходе TMON -> новое SEQ с 0.
; ---------------------------------------------------------------------
LOADM:  XRA A
        STA LST             ; ждем ':' (и XSSEQ = 0 - рестарт потока клиента)
        STA LACC            ; накопитель тетрад тоже с нуля (баг v1.0:
                            ;  сталь ломала первый байт первой записи)
        MVI A,38h           ; 'L'
        CALL LSTAT
LDLP:   CALL RXD            ; C = байт, CY = ошибка кадра
        JC LDERR
        MOV A,C
        CPI ':'
        JZ LDNEW            ; начало записи
        CALL NIB            ; тетрада?
        JNC LDLP            ; прочее (\r\n и т.п.) - пропустить
        MOV E,A             ; E = тетрада (7.5 замаскирован - E свободен)
        LDA LACC
        RLC
        RLC
        RLC
        RLC                 ; накопитель << 4
        ORA E
        STA LACC
        LDA LNIB
        DCR A
        STA LNIB
        JNZ LDLP            ; байт поля ещё не собран
        ; --- байт поля собран - применить по состоянию ---
        LDA LACC
        MOV B,A             ; B = байт
        XRA A
        STA LACC            ; накопитель очищен к следующему байту
        LDA LST
        ORA A
        JZ LDLP             ; байт вне записи - игнор
        DCR A
        JZ LDCNT            ; 1 = count
        DCR A
        JZ LDADR            ; 2 = addr
        DCR A
        JZ LDTYP            ; 3 = type
        DCR A
        JZ LDDAT            ; 4 = data
        JMP LDCHK           ; 5 = checksum
LDCNT:  MOV A,B
        STA ADCNT           ; сколько байт данных в записи
        CALL LDSUM
        MVI A,02h           ; поле addr: 4 тетрады = 2 байта
        STA LST
        STA LBPC
        STA LNIB
        JMP LDLP
LDADR:  MOV A,B
        STA LTY             ; временно: тип ещё не читался
        LDA LBPC
        CPI 02h
        JNZ LDAD1
        LDA LTY
        STA ADDRH           ; старший байт адреса (big-endian)
        MVI A,01h
        STA LBPC
        CALL LDSUM
        JMP LDLP
LDAD1:  LDA LTY
        STA ADDRL           ; младший байт адреса
        CALL LDSUM
        MVI A,03h
        STA LST             ; type
        MVI A,01h
        STA LBPC
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP:  MOV A,B
        STA LTY
        CALL LDSUM
        LDA LTY
        CPI 01h
        JZ LDTYP1
        LDA ADCNT           ; type 00: данные
        STA LBPC
        MVI A,04h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP1: XRA A               ; type 01 (EOF): данных нет
        STA LBPC
        MVI A,05h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT:  LDA ADDRH
        ANI 80h             ; запись разрешена только в ОЗУ
        JZ LDERR            ; ROM-окно - ошибка
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,B             ; [ADDR] = байт (writeback CPLD)
        INX H
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL LDSUM
        LDA LBPC
        DCR A
        STA LBPC
        JNZ LDDAT2
        MVI A,05h           ; данные кончились - ждать checksum
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT2: MVI A,02h
        STA LNIB
        JMP LDLP
LDCHK:  LDA LSUM            ; контрольная сумма записи
        ADD B               ; сумма всех байт + cc = 0 mod 256?
        JNZ LDERR
        LDA LTY
        CPI 01h
        JZ LDDONE           ; EOF - конец загрузки
        XRA A
        STA LST             ; ждем ':' следующей записи
        JMP LDLP
LDNEW:  MVI A,01h           ; ':' - новая запись
        STA LST
        MVI A,02h
        STA LNIB
        XRA A
        STA LSUM
        JMP LDLP
LDDONE: CALL TICKON         ; подтверждение успешной загрузки
        RET
LDERR:  MVI A,79h           ; 'E' -> дисплей EEEE
        CALL LSTAT
        CALL LDBEEP         ; длинный сигнал
        RET                 ; в меню (ADDRH/L = адрес сбоя, D = просмотр)

; =====================================================================
; RAMT: RAM-тест 8000h-FFE7h (клавиша F). 4 паттерна 00/FF/55/AA:
; заполнение + контроль побайтно. Статический дисплей = глиф паттерна
; ("0000"/"FFFF"/"5555"/"AAAA"). Сбой: ADDRH/L = адрес сбоя, EEEE +
; длинный сигнал. Успех: короткий тик. Вход через KRAM с TMOFF:
; 7.5 замаскирован - ISR не толкает стек в диапазон теста, тест
; КРИСТАЛЬНО чистый. Стек до FFD4h не доходит (RAMT без длинных push).
; Портит всё (кроме клеток монитора).
; ---------------------------------------------------------------------
RAMT:   LXI H,RAMPAT        ; HL = текущая пара (value+glyph)
        MVI C,04h           ; 4 паттерна
RMT0:   MOV A,M             ; A = значение паттерна
        MOV E,A
        PUSH H              ; указатель пары - на стек (HL уйдёт под заполнение)
        INX H
        MOV A,M             ; глиф паттерна
        CALL LSTAT          ; статический дисплей ("0000" и т.д.)
        MOV A,E
        LXI H,8000h
        LXI H,8000h
RMF:    MOV A,E             ; <--- ВОССТАНАВЛИВАЕМ ПАТТЕРН ИЗ E НА КАЖДОМ ПРОХОДЕ!
        MOV M,A             ; заполнение
        INX H
        MOV A,H
        CPI 0FDh
        JNZ RMF
        MOV A,L
        CPI 0D8h
        JNZ RMF
        LXI H,8000h
RMV:    MOV A,M             ; контроль (8000h..FFD7h)
        CMP E
        JNZ RMBAD
        INX H
        MOV A,H
        CPI 0FDh
        JNZ RMV
        MOV A,L
        CPI 0D8h
        JNZ RMV
        POP H               ; HL = пара паттерна
        INX H
        INX H               ; следующая пара
        DCR C
        JNZ RMT0
        CALL TICKON         ; ОК
        RET
RMBAD:  SHLD ADDRL          ; ADDRH/L = адрес сбоя (HL из RMV, до POP!)
        POP H               ; снять указатель пары (баланс стека)
        MVI A,79h           ; 'E' -> EEEE
        CALL LSTAT
        CALL LDBEEP
        RET                 ; в меню; D = просмотр байта по адресу сбоя

; =====================================================================
;                    XSTREAM: ЭКРАН -> UART (п.8: непрерывный поток,
;                    тик кадра = сама скорость канала, регенерация/
;                    скан ведётся пульками TMIARM внутри посылки)
; =====================================================================
; ---------------------------------------------------------------------
; XSINIT (из START, только холодный старт): демо-экран в B000h,
; SEQ = 0. Мониторные переменные не трогаются; B000-B7CF -
; пользовательская область: ЛЮБАЯ программа может рисовать туда
; свой текст/графику, клиент xstream_view.ps1 покажет окном.
; ---------------------------------------------------------------------
XSINIT: CALL XBLANK
        LXI H,XTBL
XSI1:   MOV E,M             ; DE = адрес назначения
        INX H
        MOV D,M
        INX H               ; HL -> src_lo
        MOV A,D             ; конец таблицы (dst == 0000)?
        ORA E
        JZ XSI3
        MOV C,M             ; BC = адрес строки (источник)
        INX H
        MOV B,M
        INX H               ; HL -> следующая запись
        PUSH H              ; указатель следующей записи -> стек
        MOV H,B
        MOV L,C
        CALL XCPY           ; ASCIZ [HL] -> [DE], 0 = конец
        POP H
        JMP XSI1
XSI3:   XRA A
        STA XSSEQ
        RET

XBLANK: LXI H,XBUF          ; 2000 пробелов
        LXI B,2000
XB1:    MVI A,20h
        MOV M,A
        INX H
        DCX B
        MOV A,B
        ORA C
        JNZ XB1
        RET

XCPY:   MOV A,M             ; ASCIZ: [HL]->[DE], 0 = конец (A/флаги)
        ORA A
        RZ
        STAX D
        INX H
        INX D
        JMP XCPY

; ---------------------------------------------------------------------
; XSEND: кадр XSTREAM в UART: A5 5A [SEQ] + 2000 Б из XBUF.
;   Сохраняет PSW/B/D/H. РАВНОМЕРНЫЙ пейсинг 36,75T/Б без опроса TXRDY:
;   на 3,125 МГц 36,75T = 11,8 мкс >= 10 мкс байта 1M. ПУЛЬКА TMIARM в
;   шапке КАЖДОЙ 8-Б подгруппы (~94 мкс): ISR-вставки только УДЛИНЯЮТ
;   гэпы (мин. 25T соблюдён) - ноль отбросов TX; регенерация/скан идут
;   ВНУТРИ посылки (каденция слота ~0,7 мс, как у v1.2). E не трогает
;   (счётчик слотов ISR). Кадр ~37 мс с пульками (~27 FPS; v1.2: ~42).
; ---------------------------------------------------------------------
XSEND:  PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL XUPDCTR        ; живой счётчик SEQ в демо-экран
        MVI A,0A5h
        OUT TXPORT          ; шапка: равномерный пейсинг 33T (4 NOP)
        NOP
        NOP
        NOP
        NOP
        MVI A,05Ah
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        LDA XSSEQ
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        INR A
        STA XSSEQ           ; SEQ++ mod 256
        LXI H,XBUF          ; HL = экран
        MVI B,10            ; внешний: 10 групп по 200 Б
XSOUT:  MVI C,25            ; внутренний: 25 подгрупп по 8 Б
XSL:    CALL TMIARM         ; пулька слота на подгруппу (~94 мкс): ISR
        MOV A,M             ; удлиняет гэп, ноль отбросов TX (п.8)
        OUT TXPORT          ; равномерный пейсинг: гэп OUT->OUT >= 25T байта
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        DCR C               ; подгруппа = 7x35T + 15T = 294T (36.75T/Б)
        JNZ XSL
        DCR B
        JNZ XSOUT
        POP H
        POP D
        POP B
        POP PSW
        RET

; ---------------------------------------------------------------------
; XUPDCTR: живой счётчик SEQ (hex, 2 цифры) в демо-экран, строка 22,
; колонки 4-5 - доказательство живого потока в клиенте.
; ---------------------------------------------------------------------
XUPDCTR: PUSH H
        LDA XSSEQ
        MOV C,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL XHEX
        STA XSCNT
        MOV A,C
        ANI 0Fh
        CALL XHEX
        STA XSCNT+1
        POP H
        RET

XHEX:   ADI '0'
        CPI 3Ah
        JC XHX1
        ADI 07h
XHX1:   RET

; ---- демо-экран (ASCII; NUL-конец; <= 80 символов на строку) ----
S_T0:   DB 'fw_monitor_ACdE_tm_xstream v2.0 - 80x25 SCREEN B000h-B7CFh -> UART 1000000 8N1',0
S_T1:   DB 'FRAME: A5 5A [SEQ] + 2000 BYTES (ROW-MAJOR 80x25 / CP1251 AT PC CLIENT)',0
S_T2:   DB 'TICK: RST 7.5 FREE-RUN 4 US (RTL v37F-11) - ISR VIA TMIARM UNMASK POINTS',0
S_T3:   DB 'MONITOR: A=ADDR  C=CODE  D=VIEW  E=RUN  B=HEX LOAD  F=RAM TEST  F1=MENU',0
S_T4:   DB 'WRITE YOUR TEXT INTO B000h..B7CFh - THIS WINDOW IS THE PC SCREEN',0
S_T5:   DB 'SEQ:__ FRAME ~37 MS BACK-TO-BACK | REGEN+SCAN IN ISR - TMIARM PACED',0
XTBL:   DW XBUF, S_T0       ; строка 0
        DW XBUF+00A0h, S_T1 ; строка 2
        DW XBUF+00F0h, S_T2 ; строка 3
        DW XBUF+0280h, S_T3 ; строка 5
        DW XBUF+0320h, S_T4 ; строка 6
        DW XBUF+06E0h, S_T5 ; строка 22 (счётчик SEQ живой, кол. 4-5)
        DW 0000h, 0000h     ; конец таблицы

; =====================================================================
; MAIN: старт, главный цикл, клавиатура, GO (п.2, п.3, п.8)
; =====================================================================
START:  DI
        LXI SP,SP0
        MVI A,80h           ; адрес по умолчанию 8000h (начало ОЗУ)
        STA ADDRH
        XRA A
        STA ADDRL
        CALL XSINIT         ; демо-экран B000h, SEQ = 0
MAIN2:  XRA A
        OUT SEGP            ; дисплей погашен (после сброса горело "----")
        OUT DIGP            ; разряды off, SND off
        STA SNDST
        STA ADCNT
        STA BDCNT
        STA DPIDX
        STA STATE           ; ST_MENU
        STA PREVST
        CALL REDRAW         ; "ACdE"
        LXI H,TXBAN         ; баннер: терминал 1M читает, 4800 = мусор
        CALL TXSTR
        CALL TMON           ; ПУСК слот-системы (EI внутри; первый слот -
                            ; из вершины SCAN, см. п.2)

; ---- главный цикл: слоты ведут дисплей/скан по пулькам TMIARM,
;      цикл декодирует клавиатуру и непрерывно льёт кадры xstream ----
SCAN:   CALL TMIARM         ; пулька слота на проход цикла (п.2)
        LDA KRAW0           ; есть ли нажатие (образ ISR, п.3 v1.2)?
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C               ; A/C = ИЛИ колонок (0 = нажатий нет)
        JZ NOKEY
        LXI H,KRAW0         ; ---- декод: колонка C_idx, ряд = бит ----
        MVI C,0             ; C = индекс колонки 0..3
KDL:    MOV A,M
        ORA A
        JNZ KDH
        INX H
        INR C
        MOV A,C
        CPI 04h
        JNZ KDL
        JMP NOKEY           ; (не бывает: OR ненулевой - защита)
KDH:    MOV B,A             ; B = образ рядов колонки C
        MVI D,0             ; D = номер ряда
KH1:    MOV A,B
        RRC
        MOV B,A
        JC KH2
        INR D
        JMP KH1
KH2:    MOV A,D             ; код = KEYTBL[row*4+col]
        RLC                 ; row*4 (row<=4 -> 0..16, БЕЗ ANI - ряд 4 = 10h,
        RLC                 ;  клавиши 0/F1/F2; ANI 0Ch тут убил бы ряд 4)
        ORA C
        MOV C,A
        MVI B,0
        LXI H,KEYTBL
        DAD B
        MOV A,M
        CPI 0FFh
        JZ SCAN             ; пустая позиция матрицы
        CALL DISPATCH
        ; ---- ожидание отпускания + дебаунс (KRAW живой - ISR сканит) ----
KRL:    CALL TMIARM         ; КРИТИЧНО (п.2): без пульки KRAW застынет
        LDA KRAW0           ; ненулевым - вечное ожидание отпускания
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ KRL             ; ждём отпускания (дисплей/скан идут в ISR)
        MVI H,TQ_MS         ; 15 мс дебаунс отпускания
KST:    CALL TMIARM         ; слот на итерацию (дисплей жив под дебаунсом)
        CALL DLMS
        DCR H
        JNZ KST
        JMP SCAN
NOKEY:  CALL XSEND          ; нажатий нет - кадр xstream (пульки в XSL)
        JMP SCAN

; ---------------------------------------------------------------------
; DISPATCH: обработка кода клавиши (A). F1 - глобально в меню,
; F2 - глобально показать адрес (повторное F2 - назад).
; Меню: A/C/D/E + B (загрузчик Intel HEX, TMOFF на входе) +
; F (RAM-тест, TMOFF на входе). Тело - как v27 (проверено железом).
; ---------------------------------------------------------------------
DISPATCH: MOV C,A           ; C = КОД КЛАВИШИ (LDA STATE затирает A!)
        CPI K_F2
        JZ K_F2E
        CPI K_F1
        JZ K_F1E
        LDA STATE
        ORA A
        JZ DSM
        CPI 01h
        JZ DSA
        CPI 02h
        JZ DSP
        CPI 04h
        JZ DSW              ; показ адреса: прочие клавиши - игнор
        ; ================= ST_VIEW =================
DSV:    MOV A,C
        CPI K_ENT
        JZ VENT
        RET                 ; тетрады - игнор (режим только чтение)
VENT:   LDA ADDRL
        MOV L,A
        LDA ADDRH
        MOV H,A
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL TICKON
        CALL REDRAW         ; следующий байт на дисплее
        RET
        ; ================= ST_PROG =================
DSP:    MOV A,C
        CPI K_ENT
        JZ PENT
        CPI 10h
        JC PDIG             ; 00h..0Fh - тетрада байта
        RET
PDIG:   MOV A,C
        MOV B,A
        LDA BF0
        STA BF1             ; сдвиг: BF1 = BF0
        MOV A,B
        STA BF0
        LDA BDCNT
        CPI 02h
        JNC PDS
        INR A
        STA BDCNT
PDS:    CALL TICKON
        CALL REDRAW
        RET
PENT:   LDA BDCNT
        ORA A
        JZ PIGN             ; пусто - игнор (без записи)
        LDA BF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA BF0
        ORA C               ; C = байт
        MOV C,A
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,C             ; [ADDR] = байт (A15=0 железо отбросит)
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        XRA A
        STA BDCNT           ; поле гасится - ждём следующий байт
        CALL TICKON
        CALL REDRAW
PIGN:   RET
        ; ================= ST_ADDR =================
DSA:    MOV A,C
        CPI K_ENT
        JZ AENT
        CPI 10h
        JC ADIG             ; 00h..0Fh - тетрада адреса
        RET
ADIG:   MOV A,C
        MOV B,A
        LDA AF2
        STA AF3
        LDA AF1
        STA AF2
        LDA AF0
        STA AF1
        MOV A,B
        STA AF0
        LDA ADCNT
        CPI 04h
        JNC ADS
        INR A
        STA ADCNT
ADS:    CALL TICKON
        CALL REDRAW
        RET
AENT:   LDA ADCNT
        ORA A
        JZ AIGN             ; пусто - игнор
        LDA AF3
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF2
        ORA C
        STA ADDRH
        LDA AF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF0
        ORA C
        STA ADDRL
        XRA A
        STA STATE           ; в меню
        CALL TICKON
        CALL REDRAW
AIGN:   RET
        ; ================= ST_MENU =================
DSM:    MOV A,C             ; вернули код клавиши
        CPI 0Ah             ; 'A' - ввод адреса
        JZ KAD
        CPI 0Ch             ; 'C' - ввод кода (Code)
        JZ KPR
        CPI 0Dh             ; 'D' - просмотр кода
        JZ KVD
        CPI 0Eh             ; 'E' - выполнить
        JZ KGO
        CPI 0Bh             ; 'B' - загрузчик Intel HEX
        JZ KLD
        CPI 0Fh             ; 'F' - RAM-тест
        JZ KRAM
        RET                 ; остальные - игнор
KLD:    CALL TMOFF          ; ТИШИНА: RXD чист (маски+DI), дисплей статикой
        CALL LOADM
        JMP K_F1E
KRAM:   CALL TMOFF          ; ТИШИНА: стек статичен - тест 8000h-FFE7h чист
        CALL RAMT
        JMP K_F1E
KAD:    MVI A,ST_ADDR
        STA STATE
        XRA A
        STA ADCNT
        CALL TICKON
        CALL REDRAW
        RET
KPR:    MVI A,ST_PROG       ; C: ввод кода (Code)
        STA STATE
        XRA A
        STA BDCNT
        CALL TICKON
        CALL REDRAW
        RET
KVD:    MVI A,ST_VIEW       ; D: просмотр кода
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
; ---- F2: показ адреса операций (глобально; повторное F2 - назад) ----
K_F2E:  LDA STATE
        CPI ST_SHOW
        JZ KF2B             ; уже показываем - вернуть прежний режим
        STA PREVST          ; запомнить, откуда пришли
        MVI A,ST_SHOW
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
KF2B:   LDA PREVST
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
DSW:    RET                 ; показ адреса: Enter/тетрады не действуют
K_F1E:  CALL TMON           ; реинициализация слот-системы (после B/F обяз.,
                            ;  после простого F1 - безвредный ре-пуск)
        XRA A
        STA STATE           ; меню (из любого режима)
        CALL TICKON
        CALL REDRAW
        RET
        ; ================= GO: запуск =================
KGO:    XRA A
        OUT SEGP            ; сегменты 0
        OUT DIGP            ; разряды 0, SND 0
        CALL TMOFF          ; маски+сброс защёлки (v1.2 OUT 06h,0 удалён -
                            ; стопить нечего): программа пользователя - 100%
                            ; ЦП, тики идут в замаскированную защёлку; ей
                            ; нужен тик - EI + SIM 68h (вектор 003Ch = TMISR)
        LXI SP,SP0
        LXI H,MONRET
        PUSH H              ; адрес возврата в монитор
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = адрес запуска
        XRA A
        MOV B,A
        MOV C,A
        MOV D,A
        MOV E,A             ; регистры обнулены
        PCHL                ; ушли в программу пользователя
MONRET: DI
        LXI SP,SP0
        CALL TMON           ; слот-система заново (чистка KRAW/DPIDX/EI)
        ; ждём отпускания всех клавиш + дебаунс (KRAW живой)
MNR1:   CALL TMIARM         ; критично как KRL: без пульки KRAW застынет
        LDA KRAW0
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ MNR1
        MVI H,TQ_MS         ; 15 мс дебаунс
MNR3:   CALL TMIARM         ; слот на итерацию
        CALL DLMS
        DCR H
        JNZ MNR3
        JMP MAIN2           ; реинициализация, ADDR сохранён

        END
