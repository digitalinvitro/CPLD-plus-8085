;                               LOADM не сдвинулись - fw_test_rx_ok совместим.
;   v2.0.7  (пара v37G07)     - база переноса (v37gen/...v2_0_7.asm).
;   v3.0    (пара v39G02)     - ПОРТ НА v39G02 (аудит+симуляция 16.18):
;                               1) дисплей-конвейер DISPP 01h: символ =
;                               пара OUT (маска AD[3:0], глиф AD[6:0]);
;                               DIGP 02h НЕ СУЩЕСТВУЕТ (любая OUT 02h =
;                               TXDATA!). 2) TXP 02h, бит 1.0417М; TXRDY
;                               переехал D7 -> D6 (tx_idle, встаёт в
;                               НАЧАЛЕ стопа). 3) звук SND = SOD: SIM
;                               C0h/40h (SDE=1, MSE=0 - маски целы), из
;                               REFRESH D4 удалён. 4) джиффи 122.88 мкс
;                               (tmr_cnt[6], фронт раз в 128 тиков 960 нс):
;                               полный слот 545T НЕ влезает -> прескалер
;                               в SNDST[7:4], слот каждый 8-й джиффи
;                               (983 мкс, кадр 254 Гц, ~44% ЦП монитора,
;                               лайт 114T). 5) полярность LED - флаг
;                               сборки DPOL (0 = пин=1 горит, как G07;
;                               регистры v39 хранят ~AD -> таблицы/гашение
;                               пишутся инверсно). 6) RXUART в CPLD:
;                               подменю B: 0 = SID 4800 (без изменений,
;                               SID = RX passthrough), 1 = FAST 2.083М -
;                               байт = пара 0xC0|nib (d6=d7=1 => дефекты
;                               RX RTL 16.18 невозможны); пауза ПК >=
;                               15 мкс между байтами. 7) XSTREAM: пейсинг
;                               36.75T/Б >= 9.6 мкс байта 1.0417М, кадр
;                               ~37 -> ~52 мс (~19 FPS) из-за врезок ISR.
;                               Фичи v2.0.6 (LDCTR, SOS) сохранены.
;
;   1. ТАЙМЕР v37G07: RST 7.5 = СВОБОДНОЕ ДЖИФФИ 1,024 мс (счётчик
;      tmr_cnt[7:0] в CPLD шагом 4 мкс, импульс 1 клк при переполнении;
;      256 x 4 мкс = 1,024 мс = 976,56 Гц). Остановить нельзя - только
;      замаскировать (DI/маски). OUT 08h: A[7:4] = колонки, A[3:0]
;      игнорируются. IN 01h: D7 = TXRDY, D6-D5 = tmr_cnt[7:6] - фаза
;      (шаг 256 мкс, полный цикл 1,024 мс); D6 ЗАРЕЗЕРВИРОВАН под
;      RXRDY (при появлении RXUART фаза ужмётся/переедет - решение
;      при ревизии RTL); RXP = 00h (IN A0=0) - план RXDATA (сейчас
;      там bus_reg - последние шинные данные).
;
;   2. ISR САМОДОСТАТОЧЕН (против дисциплины TMIARM v2.0/v2.0.1):
;      ответ на прерывание ~80T ~ 26 мкс >> 4 мкс тика v37F-11 - там
;      прямой сервис был невозможен (пульки/маски/E=6). На джиффи
;      1,024 мс бюджет 3 200 тактов CPU - ISR входит сам, каденция
;      РОВНАЯ, пульки не нужны. Маска 7.5 снята ПОСТОЯННО (TMON:
;      SIM 3Bh), ISR маски не трогает - защёлка перезаряжается сама
;      к следующему джиффи.
;
;   3. СЛОТ = каждый вызов ISR: скан 1 колонки (KSCOL) + регенерация
;      1 разряда (REFRESH). Каденция ФИКСИРОВАННАЯ: 1 джиффи = 1,024 мс.
;      Кадр дисплея (4 разряда) = 4,096 мс ~ 244 Гц; полный цикл скана
;      4,096 мс; ответ на клавишу <= 1,1 мс; ISR ~170 мкс = 16,6% ЦП.
;      Фаза тона ведётся TICKON'ом (см. п.5), от слотов не зависит.
;
;   4. CPU 3,125 МГц (T=320 нс, CLKOUT = X1/2). Константы K_MS 130
;      (~1,0 мс), RXHB 17, RXFB 38 (v2.0.5: пересчёт по реальным тактам,
;      бит RX = 55T фикс + PAUSE(38) = 649-653T = 207,7-209,0 мкс;
;      см. блок EQU и шапку RXD).
;
;   5. ЗВУК (фикс v1.2): D4 = бит фазы SNDST.0; фазу тогглит TICKON
;      раз в ~1 мс -> квадрат ~500 Гц, независимый от слотов.
;
;   6. ДИСЦИПЛИНА B/F/GO (проще v1.2 - OUT 06h не нужен):
;        TMOFF: DI + SIM 1Fh (все маски 5.5/6.5/7.5 + СБРОС защёлки 7.5).
;        TMON : DI + SIM 1Fh + чистка KRAW/DPIDX/SNDST + SIM 3Bh
;               (маска 7.5 снята ПОСТОЯННО) + EI. Счётчика E нет.
;      GO (KGO): TMOFF - программа пользователя получает ~96% ЦП
;      (ISR ~170 мкс раз в 1,024 мс), дисплей/скан живут. Программе,
;      которой джиффи не нужен: DI или SIM 1Fh. Вектор 003Ch ведёт в
;      ROM-TMISR монитора.
;      B (LOADM): RXD чист от джиттера (маски + DI). F (RAMT): тест
;      8000h-FFD7h, стек FFD8h-FFE7h не трогается (см. блок RAMT).
;
;   7. ПОРТЫ v37G07 (линейный декод, канонические адреса): ЗАПИСЬ 01h =
;      сегменты A[6:0] (dp игнорируется), 02h = разряды A[3:0] +
;      звук A[4], 04h = TXDATA (однократный строб; запись при busy -
;      байт тихо теряется), 08h = колонки A[7:4]. ЧТЕНИЕ 01h =
;      {TXRDY(D7), tmr_cnt[7:6] (D6-D5, шаг 256 мкс; D6 - резерв
;      RXRDY), row4..row0 (D4-D0)}. Зеркала декода НЕ пустые: 03h/07h
;      пишут seg+dig (07h ещё и грузит TX), 05h/06h грузят TX, чтение
;      01h/03h/05h/07h = статус. Пользоваться ТОЛЬКО каноническими
;      адресами; IN с A0=0 (00h/02h/04h/06h) = bus_reg (RXP 00h -
;      план RXUART, декод io_rd_rx появится с RXUART в RTL).
;
;   8. XSTREAM (выдача экрана B000h): пейсинг 36,75T/Б сохранён
;      (11,8 мкс >= 10 мкс байта 1M), CALL TMIARM (заглушка RET) в
;      шапке каждой 8-Б подгруппы; слот приходит сам раз в 1,024 мс -
;      ISR-вставка ~170 мкс удлиняет текущий гэп (мин. 25T соблюдён) -
;      ноль отбросов TX, регенерация/скан идут ВНУТРИ посылки.
;      Кадр ~37 мс (~27 FPS). Клиент xstream_view.ps1 (COM @1000000
;      8N1) - БЕЗ ИЗМЕНЕНИЙ: A5 5A [SEQ] + 2000 Б. SEQ в FFFAh.
;
; СБОРКА (asm85.py, кодировка CP1251):
;   python3 ../../../tools/asm85.py fw_monitor_ACdE_tm_xstream_v2_0_3.asm
;          -o fw_monitor_ACdE_tm_xstream_v2_0_3.hex
;          -l fw_monitor_ACdE_tm_xstream_v2_0_3.lst
; Прошивка: flash A29040B, offset 0000h (ROM-окно 0000h-7FFFh).
;
; КЛАВИАТУРА (как v27): тетрады 0-F + Enter + F1(меню) + F2(показ
; адреса); меню: A=адрес C=код D=просмотр E=выполнить B=загрузчик
; Intel HEX (SID 4800) F=RAM-тест. Выход из залипшего режима - RESET.
;
; ОЗУ: переменные FFE8h-FFFFh, стек с FFE7h вниз (SP0 = FFE8h); зона
; FFD8h-FFE7h RAM-тестом не покрывается (стек, фикс v2.0.2).
; ГЛУБИНА СТЕКА: максимум XSEND (4 push) + TMISR (PSW+B/D/H +
; RST-адрес + KSCOL/REFRESH/SETTLE) ~ 26 Б - в свободном ОЗУ.
; =====================================================================
; ---- порты CPLD v39G02 (БИТ-декод по addr_latch; ТОЛЬКО канонические!) ----
; Декод по АДРЕСУ записи (addr_latch), данные на AD любые.
DISPP   EQU 01h             ; OUT (A0=1): КОНВЕЙЕР Rdig<-Rseg<-BUS. Каждая OUT:
                            ;  Rdig <- Rseg[3:0]; Rseg <- ~AD[6:0].
                            ;  СИМВОЛ = пара OUT: (1) маска разряда AD[3:0],
                            ;  (2) глиф AD[6:0]; между OUT пары ~7 мкс
                            ;  транзит (невидим). Полярность записи - DPOL.
TXP     EQU 02h             ; OUT (A1=1): TXDATA -> сериализатор 1.0417М 8N1;
                            ;  запись при busy (tx_idle=0) игнорируется
KBCOLP  EQU 08h             ; OUT (A3=1): AD[7:4] = колонки (1 = заведена)
KBROWP  EQU 01h             ; IN (A0=1): D7=1 (константа!), D6=tx_idle
                            ;  (1=готов - TXRDY; встаёт в НАЧАЛЕ стопа),
                            ;  D5=rx_ready (1=байт ждёт), D4-D0=row4..row0
RXP     EQU 00h             ; IN (A0=0): RXDATA = (байт&7F)<<1 (оф-бай-ван
                            ;  RTL, 16.18); чтение снимает rx_ready на
                            ;  подъёме RDn
; КОНФЛИКТЫ декода: OUT 03h = дисплей+TX; OUT 09h/0Bh = дисплей+клавиатура;
; IN 00h/02h/04h/06h = RXDATA. Записей в 02h вне TXBYTE/XSEND быть не должно
; (в v2.0.7 DIGP=02h - все такие записи переписаны: дисплей -> DISPP-пара,
;  звук -> SIM/SOD). Только канонические адреса!

; ---- константы тайминга (CPU 3,125 МГц, T = 320 нс; джиффи 1,024 мс) ----
TQ_MS   EQU 15              ; дебаунс отпускания ~15 мс (DLMS-единиц)
K_MS    EQU 130             ; DLMS-единица ~1,0 мс (130 x 24T x 320 нс)
RXHB    EQU 18              ; полбита 4800 (v2.0.5: PAUSE-итераций)
RXFB    EQU 41              ; бит приёма 4800 (v2.0.5: PAUSE-итераций)
DPOL    EQU 0               ; полярность LED платы: 0 = пин=1 горит
                            ;  (семантика G07; регистр v39 хранит ~AD ->
                            ;  таблицы/гашение пишутся инверсно);
                            ;  1 = пин=0 горит. Сборка: -D DPOL=1
; РЕАЛЬНАЯ тактовка 8085 (v2.0.5; модель "14T/итерация" врала на 6-8%:
; JNZ taken = 10T / not-taken = 7T не учтены в фикс-накладке):
; PAUSE(n) = 15n+24T c CALL/RET. Полубит: 19T (ORA/JM в RXW) + MVI D 7T
; + PAUSE(17) 279T + RIM+ORA 12T = 317T = 101 мкс = 0,49 бита от выборки
; фронта (+ джиттер обнаружения до 19T = 6 мкс). Бит RX: 55T фикс
; (ANI/RAR/MOVx2/MVI/DCR/JNZ/след.RIM) + PAUSE(38) = 649-653T = 207,7-
; 209,0 мкс (идеал 208,3). Выборки (rxd_cycles.py, RIM 8-12T): d0 1,45-
; 1,47, d7 8,42-8,49, стоп 9,43-9,50 бита. Было (19/41): d7 9,02-9,09 =
; СТОП-БИТ, стоп 10,10-10,16 = idle -> ':' читался как BAh (LLL!).

; ---- коды клавиш ----
K_ENT   EQU 10h             ; Enter  (row3/col3, SW16)
K_F1    EQU 11h             ; F1     (row4/col1, SW18) - меню
K_F2    EQU 12h             ; F2     (row4/col2, SW19) - показ адреса
K_NONE  EQU 0FFh            ; пустая позиция матрицы

; ---- состояния ----
ST_MENU EQU 00h             ; меню "ACDE" (B = загрузчик, F = RAM-тест)
ST_ADDR EQU 01h             ; ввод адреса
ST_PROG EQU 02h             ; ввод кода (Code)
ST_VIEW EQU 03h             ; просмотр кода
ST_SHOW EQU 04h             ; показ адреса операций (F2)

; ---- ОЗУ монитора ----
SP0     EQU 0FFE8h          ; SP монитора
SNDST   EQU 0FFE8h          ; бит0 = фаза тона (тогглит TICKON), бит1 = тон вкл
STATE   EQU 0FFE9h          ; 0=меню, 1=адрес, 2=код, 3=просмотр, 4=показ
ADDRH   EQU 0FFEAh          ; текущий адрес (старший); в загрузчике = адрес записи
ADDRL   EQU 0FFEBh          ; текущий адрес (младший)
ADCNT   EQU 0FFECh          ; тетрады адреса (0..4); в загрузчике = счётчик байт данных
AF3     EQU 0FFEDh          ; тетрады адреса
AF2     EQU 0FFEEh
AF1     EQU 0FFEFh
AF0     EQU 0FFF0h
BDCNT   EQU 0FFF1h          ; введено тетрад байта (0..2)
BF1     EQU 0FFF2h
BF0     EQU 0FFF3h
DPIDX   EQU 0FFF4h          ; фаза регенерации 0..3 = колонка скана (владеет ISR)
DIGIMG  EQU 0FFF5h          ; глифы разрядов DIG0..DIG3
DIGIMG0 EQU 0FFF5h
DIGIMG1 EQU 0FFF6h
DIGIMG2 EQU 0FFF7h
DIGIMG3 EQU 0FFF8h
PREVST  EQU 0FFF9h          ; прежний режим для F2
; --- парсер Intel HEX (загрузчик B); FFFC-FFFF = шара с KRAW (п.3 v1.2) ---
LST     EQU 0FFFAh          ; состояние: 0=ждём ':' 1=count 2=addr 3=type 4=data 5=chk
LDCTR   EQU 0FFF5h          ; v2.0.6: счётчик записей загрузки (= DIGIMG0: в
                            ;  режиме B ISR стоит, клетка свободна; на выходе
                            ;  REDRAW переписывает её как образ разряда)
                            ;   (шара с XSSEQ - см. п.8; LOADM чистит на входе)
LNIB    EQU 0FFFBh          ; осталось тетрад в текущем байте поля (1..2)
LBPC    EQU 0FFFBh+1        ; осталось байт в текущем поле   = KRAW0
LACC    EQU 0FFFBh+2        ; накопитель тетрад текущего байта = KRAW1
LSUM    EQU 0FFFBh+3        ; сумма байт записи (mod 256)      = KRAW2
LTY     EQU 0FFFBh+4        ; тип последней записи             = KRAW3
; --- сырой образ клавиатуры (пишет ISR, читает главный цикл) ---
KRAW0   EQU 0FFFBh+1        ; ряды колонки 0 (биты 0-4) = LBPC
KRAW1   EQU 0FFFBh+2        ; ряды колонки 1            = LACC
KRAW2   EQU 0FFFBh+3        ; ряды колонки 2            = LSUM
KRAW3   EQU 0FFFBh+4        ; ряды колонки 3            = LTY

; --- XSTREAM: экран -> UART (тик кадра = непрерывный поток, п.8) ---
TXPORT  EQU TXP             ; TXDATA (04h) - синоним для xstream-кода
XBUF    EQU 0B000h          ; ЭКРАН 80x25 = 2000 Б (B000h..B7CFh)
XSSEQ   EQU 0FFFAh          ; SEQ кадра mod 256 (ячейка LST - см. п.8)
XSCNT   EQU XBUF+06E4h      ; живой счётчик SEQ в демо-экране (строка 22, кол. 4-5)

; =====================================================================
        ORG 0000h
        JMP START

; ---- векторная зона: глушилки EI;RET -------------------------------
; RST 1..7, TRAP (0024h), RST 5.5/6.5. EI обязателен в каждой (снимает
; блокировку после приёма). На плате: TRAP = PGND (держатель '0'),
; 5.5/6.5 железно=0 и вдобавок замаскированы SIM - заглушки защитные.
; RST 7.5 (003Ch) = СВОБОДНЫЙ ТИК 4 мкс (п.1) - НЕ заглушка, обработчик
; ниже; под TMOFF маскируется, каденцию задаёт владелец точек TMIARM.
        ORG 0008h           ; RST 1
        EI
        RET
        ORG 0010h           ; RST 2
        EI
        RET
        ORG 0018h           ; RST 3
        EI
        RET
        ORG 0020h           ; RST 4
        EI
        RET
        ORG 0024h           ; TRAP - защитная заглушка (пин PGND)
        EI
        RET
        ORG 0028h           ; RST 5
        EI
        RET
        ORG 002Ch           ; RST 5.5
        EI
        RET
        ORG 0030h           ; RST 6
        EI
        RET
        ORG 0034h           ; RST 6.5
        EI
        RET
        ORG 0038h           ; RST 7
        EI
        RET
        ORG 003Ch           ; RST 7.5 = свободное джиффи 1,024 мс (п.1, п.2)
        JMP TMISR

