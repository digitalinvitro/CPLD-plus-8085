; Таблицы (ORG 0044h - векторная зона выше освобождена)
; =====================================================================
        ORG 0044h
; ---- глифы '0'..'F' (a,b,c,d,e,f,g = D0..D6) ----
IF DPOL
GTBL:   DB 3Fh              ; '0'
        DB 06h              ; '1'
        DB 5Bh              ; '2'
        DB 4Fh              ; '3'
        DB 66h              ; '4'
        DB 6Dh              ; '5'
        DB 7Dh              ; '6'
        DB 07h              ; '7'
        DB 7Fh              ; '8'
        DB 6Fh              ; '9'
        DB 77h              ; 'A'
        DB 7Ch              ; 'b'
        DB 39h              ; 'C'
        DB 5Eh              ; 'd'
        DB 79h              ; 'E'
        DB 71h              ; 'F'
ELSE
GTBL:   DB 127-3Fh           ; '0'  (пин = ~запись, 7 бит: пишем инверсию)
        DB 127-06h           ; '1'
        DB 127-5Bh           ; '2'
        DB 127-4Fh           ; '3'
        DB 127-66h           ; '4'
        DB 127-6Dh           ; '5'
        DB 127-7Dh           ; '6'
        DB 127-07h           ; '7'
        DB 127-7Fh           ; '8'
        DB 127-6Fh           ; '9'
        DB 127-77h           ; 'A'
        DB 127-7Ch           ; 'b'
        DB 127-39h           ; 'C'
        DB 127-5Eh           ; 'd'
        DB 127-79h           ; 'E'
        DB 127-71h           ; 'F'
ENDIF

; ---- биты разрядов/колонок (индекс = DPIDX: 0=DIG0 правый ... 3=DIG3 левый) ----
IF DPOL
BITTBL: DB 01h,02h,04h,08h  ; маска выбранного разряда (пин=0 горит)
ELSE
BITTBL: DB 0Eh,0Dh,0Bh,07h  ; ~маска (пин=1 горит): выбранный разряд = 0
ENDIF

; ---- КАРТА КЛАВИШ: KEYTBL[row*4+col] ----
KEYTBL: DB 0Ah,0Bh,0Ch,0Dh  ; row0: A  B  C  D
        DB 07h,08h,09h,0Eh  ; row1: 7  8  9  E
        DB 04h,05h,06h,0Fh  ; row2: 4  5  6  F
        DB 01h,02h,03h,10h  ; row3: 1  2  3  Enter
        DB 00h,11h,12h,0FFh ; row4: 0  F1 F2 (нет)

; ---- баннер TX @1M (на терминале 4800 = короткая мусорная строка) ----
TXBAN:  DB 'ACDE-3',0Dh,0Ah,00h   ; маркер v3 (RTL v39G02)

; ---- паттерны RAM-теста: значение + глиф для статического дисплея ----
RAMPAT: DB 00h,3Fh          ; 00h -> "0000"
        DB 0FFh,71h         ; FFh -> "FFFF"
        DB 55h,6Dh          ; 55h -> "5555"
        DB 0AAh,77h         ; AAh -> "AAAA"

; =====================================================================
; СИСТЕМА ТАЙМЕРА v2.0: TMOFF/TMON/TMIARM + TMISR + слоты (п.2, п.3, п.6)
; =====================================================================
        ORG 0100h

; ---------------------------------------------------------------------
; TMOFF: ТИШИНА слот-системы. DI + полные маски (SIM 1Fh = MSE+M7.5
; +M6.5+M5.5, заодно СБРОС защёлки RST 7.5). Фронты тика продолжают
; заряжать защёлку, но ЦП не трогают. Вызывается на входе B/F/GO.
; Портит A. (v1.2 OUT 06h,0 удалён - стопить нечего, п.1.)
; ---------------------------------------------------------------------
TMOFF:  DI
        MVI A,1Fh           ; MSE=1, M7.5=1, M6.5=1, M5.5=1 (ВСЕ ЗАМАСКИРОВАНЫ)
                            ; + R7.5=1 (сброс защёлки); SDE=0. (78h ВРАЛ:
                            ; снимал ВСЕ маски - регрессия v2.0.2, п.ченджлог)
        SIM
        RET

; ---------------------------------------------------------------------
; TMON: ПУСК слот-системы (START, выход из B/F, MONRET). Чистит
; состояние ISR, заряжает E=6, снимает маску 7.5, EI. Первый слот
; придёт из ближайшей точки TMIARM (из START - вершина SCAN).
; ---------------------------------------------------------------------
TMON:   DI
        MVI  A, 1Fh     ; все маски + сброс защёлки RST 7.5 (78h снимал ВСЕ!)
        SIM
        XRA  A
        STA  SNDST      ; тон off, фаза 0
        STA  DPIDX      ; фаза регенерации / колонка 0
        STA  KRAW0      ; сырой образ клавиатуры - в ноль
        STA  KRAW1
        STA  KRAW2
        STA  KRAW3
        MVI  A, 3Bh     ; MSE=1, M7.5=0 (7.5 РАЗРЕШЁН), M6.5=1, M5.5=1
                        ; + R7.5=1 (гасим фронты из DI-окна); SDE=0 (68h
                        ; снимал ВСЕ маски, а не только 6.5/5.5!)
        SIM
        EI
        RET

; ---------------------------------------------------------------------
; TMIARM: СОВМЕСТИМОСТЬ (п.2). На тике v37G01 ISR самодостаточен:
; маска 7.5 снята ПОСТОЯННО (TMON: SIM 3Bh), защёлка перезаряжается
; сама раз в 1,024 мс - пульки не нужны. Заглушка RET оставлена ради
; 7 мест CALL TMIARM (SCAN/XSL/KRL/KST/TKL/MNR1/MNR3): CALL/RET = 17T,
; безвредно. (В паре v37F-11 <-> v2.0.1 здесь была пулька MVI A,68h/
; SIM/NOP - дисциплина точек TMIARM; см. DEVLOG.) Ничего не портит.
; ---------------------------------------------------------------------
TMIARM: RET             ; заглушка для старых вызовов CALL TMIARM

; ---------------------------------------------------------------------
; ---------------------------------------------------------------------
; TMISR v3: RST 7.5 = джиффи 122.88 мкс (tmr_cnt[6]: фронт раз в 128
; тиков 960 нс). ПОЛНЫЙ слот (скан+реген ~545T = 174 мкс) НЕ влезает в
; джиффи -> ПРЕСКАЛЕР в SNDST[7:4] (пишущие клетки: TMON [STA 0 - сброс
; всего], TICKON [LDA/XRI/ORI/STA - полный байт, старшие целы], этот ISR
; [PUSH B + полный байт]); слот каждый 8-й джиффи = 983 мкс (кадр
; 4 слота = 3.93 мс ~254 Гц - как 244 Гц v2.0.7), лайт-путь 114T = 36.5 мкс.
; Средний ЦП ~44% в мониторе (GO: маски, ЦП пользователя 100%). Полный
; слот перехлёстывает следующий фронт - защёлка RST7.5 держит один
; ожидающий фронт, каденция 983+-122 мкс, кадр плывёт <9% - невидимо.
; Фаза тона SNDST[1:0] сохраняется ВЕЗДЕ (иначе квадрат 500 Гц умирает).
; ---------------------------------------------------------------------
; ---------------------------------------------------------------------
TMISR:  PUSH PSW
        PUSH B              ; C нужен как полный байт SNDST
        LDA SNDST
        MOV C,A             ; C = SNDST целиком
        ANI 0F0h            ; прескалер
        JZ TFULL
        DCR C               ; прескалер-- (только [7:4], младшие целы)
        MOV A,C
        STA SNDST
        POP B
        POP PSW
        EI
        RET
TFULL:  LDA SNDST           ; перезарядка 8<<4 С СОХРАНЕНИЕМ фазы тона
        ANI 003h
        ORI 080h
        STA SNDST
        PUSH D              ; KSCOL/REFRESH портят B/D/H (как v2.0.7)
        PUSH H
        CALL KSCOL          ; скан 1 колонки (колонка = фаза DPIDX)
        CALL REFRESH        ; регенерация 1 разряда (фаза ++ внутри)
        POP  H
        POP  D
        POP  B
        POP  PSW
        EI
        RET

; ---------------------------------------------------------------------
; KSCOL: скан ОДНОЙ колонки (вызывается из слота). Колонка = текущая
; фаза регенерации DPIDX - отдельного счётчика нет. Сырой образ рядов
; (биты 0-4) -> KRAW0..KRAW3[колонка]. Портит A/B/C/D/H/L (в ISR - под
; PUSH B/D/H). Колонка на выходе погашена. Записей в 08h две
; (завести/погасить), A[3:0] игнорируются (KBCOLP=08h).
; ФИКС v2.0.2 (tw): индекс - в МЛАДШИЙ байт BC (MOV C,A/MVI B,0):
; DAD B прибавляет пару BC. В v1.2-v2.0.1 индекс лежал в B
; (MOV B,A/MVI C,0) -> смещение индекс*256: работала ТОЛЬКО колонка 0
; (клавиши A,7,4,1,0), KRAW1-3 оставались нулями.
; ---------------------------------------------------------------------
KSCOL:  LDA DPIDX           ; колонка = фаза регенерации 0..3
        ANI 03h
        MOV C,A             ; C = младший байт BC (индекс 0..3)
        MVI B,0
        LXI H,BITTBL
        DAD B               ; HL = BITTBL + колонка
        MOV D,M             ; D = бит колонки (01/02/04/08)
        LXI H,KRAW0
        DAD B               ; HL = KRAW0 + колонка (B/C целы)
        MOV A,D
        RLC                 ; бит колонки (01/02/04/08) -> старший ниббл
        RLC                 ; A[7:4] (RLC x4, переноса нет)
        RLC
        RLC
        OUT KBCOLP          ; колонка заведена (A[3:0]=0 - легально, п.1)
        CALL SETTLE
        IN KBROWP           ; ряды активной колонки (D6-D5 фаза тика и
        ANI 1Fh             ; D7 TXRDY маскируются - как в v1.2 Шаг-2)
        MOV M,A             ; KRAW[колонка] = сырой образ рядов
        XRA A
        OUT KBCOLP          ; колонки off (0000); вторая запись легальна -
        RET                 ; колонки просто гасятся (в v1.2 тут был +N)

; =====================================================================
; Системные процедуры (перенос из v1.2/monitor27, константы 3,125 МГц)
; =====================================================================

; ---------------------------------------------------------------------
; SETTLE: пауза ~26 мкс (LXI+3 итерации 24T @320 нс; установка рядов
; после заведения колонки). Портит A/B/C. H/L НЕ ТРОГАЕТ (нужно KSCOL).
; ---------------------------------------------------------------------
SETTLE: LXI B,3
STL:    DCX B
        MOV A,B
        ORA C
        JNZ STL
        RET

; ---------------------------------------------------------------------
; REFRESH v3: ОДИН слот регенерации = ПАРА OUT в конвейер: (маска
; разряда, глиф). Гашение/переключение делает сам конвейер: OUT1 кладёт
; ~маску в Rseg (Rdig = мусор предыдущего глифа ~7 мкс - невидим), OUT2
; даёт стабильную пару (Rdig = ~маска, Rseg = ~глиф). Байты BITTBL/GTBL
; уже с полярностью DPOL (условная сборка). Звук из REFRESH удалён:
; SND = SOD, фазу тогглит TICKON (SIM). Портит A/B/C/H/L. Такты ~150T.
; ---------------------------------------------------------------------
REFRESH: LDA DPIDX
        ANI 03h             ; фаза 0..3 (прескалер теперь в SNDST[7:4])
        MOV C,A
        MVI B,0
        LXI H,BITTBL
        DAD B
        MOV B,M             ; B = маска разряда (с DPOL)
        LXI H,DIGIMG        ; HL = DIGIMG + DPIDX (цикл вместо ADD)
RFIL:   MOV A,C
        ORA A
        JZ RFGD
        INR L
        DCR C
        JMP RFIL
RFGD:   MOV C,M             ; C = глиф разряда (с DPOL)
        MOV A,B
        OUT DISPP           ; (1) маска -> конвейер (Rseg <- ~AD[6:0])
        MOV A,C
        OUT DISPP           ; (2) глиф -> Rdig <- ~маска: ПАРА готова
        LDA DPIDX
        ANI 03h
        INR A
        ANI 03h
        STA DPIDX
        RET

; ---------------------------------------------------------------------
; TICKON: короткий тик подтверждения клавиши ~15 мс (TQ_MS единиц
; DLMS). v2.0 (п.5): фазу тона SNDST.0 тогглит САМ TICKON раз в ~1 мс
; -> квадрат ~500 Гц, НЕ зависящий от каденции слотов (в v1.2 фазу
; тогглил слот ~0,7 мс, но REFRESH ставил D4 константой - тона не было).
; Пулька TMIARM в итерации: слоты идут - дисплей/скан не замирают.
; Портит A/B/C/H.
; ---------------------------------------------------------------------
TICKON: LDA SNDST
        ORI 02h             ; тон разрешён
        STA SNDST
        MVI H,TQ_MS         ; 15 мс
; v3: SOD/SIM вместо D4 DIGP: A = фаза -> 6x RLC (бит0 -> бит6) ->
; ORI 40h (SDE=1) -> SIM. MSE=0: МАСКИ НЕ ТРОГАЮТСЯ; b4=0: защёлка 7.5
; не сбрасывается. Пулька TMIARM (заглушка) остаётся - слоты идут.
TKL:    LDA SNDST
        XRI 01h             ; тоггл фазы (квадрат ~500 Гц)
        STA SNDST
        RLC                 ; бит0 фазы -> бит6 (SOD)
        RLC
        RLC
        RLC
        RLC
        RLC
        ORI 040h            ; SDE=1, SOD=фаза, MSE=0
        SIM                 ; SOD = фаза тона
        CALL TMIARM         ; слот на итерацию (дисплей жив под тоном)
        CALL DLMS
        DCR H
        JNZ TKL
        LDA SNDST
        ANI 0FDh            ; тон off
        STA SNDST
        MVI A,040h          ; SOD=0 (тишина), SDE=1
        SIM
        RET

; ---------------------------------------------------------------------
; GLOOK: A = тетрада 0..F -> A = глиф (GTBL). Портит A/B/C/H/L.
; ---------------------------------------------------------------------
GLOOK:  MOV C,A
        MVI B,0
        LXI H,GTBL
        DAD B
        MOV A,M
        RET
; ---------------------------------------------------------------------
; REDRAW: пересобрать DIGIMG[0..3] по состоянию (как v5/v27).
;   меню : "ACdE"; адрес: тетрады вдвигаются справа; код "__C3";
;   просмотр: [ADDR] в правых разрядах; показ(F2): ADDR на 4 разрядах.
; Портит A/B/C/D/H/L (D - рабочий в RDW/RDV; ISR сохраняет D - безопасно).
; ---------------------------------------------------------------------
REDRAW: LDA STATE
        ORA A
        JZ RDM
        CPI 01h
        JZ RDA
        CPI 03h
        JZ RDV
        CPI 04h
        JZ RDW
        ; ---- ST_PROG ----
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA BDCNT
        CPI 02h
        JC RDPR0            ; <2 - старшая тетрада пуста
        LDA BF1
        CALL GLOOK
        STA DIGIMG1
RDPR0:  LDA BDCNT
        ORA A
        JZ RDRE             ; 0 - младшая тоже пуста
        LDA BF0
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDV:    LDA ADDRH           ; ---- ST_VIEW: [ADDR] в правых разрядах ----
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = ADDR
        MOV A,M             ; A = [ADDR] (HL>=8000h - ОЗУ)
        MOV D,A             ; D = байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh             ; старшая тетрада
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh             ; младшая тетрада
        CALL GLOOK
        STA DIGIMG0
        XRA A
        STA DIGIMG3
        STA DIGIMG2
        JMP RDRE
RDW:    LDA ADDRH           ; ---- ST_SHOW: ADDR на 4 разрядах ----
        MOV D,A             ; D = старший байт (GLOOK портит B)
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG3
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG2
        LDA ADDRL
        MOV D,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG1
        MOV A,D
        ANI 0Fh
        CALL GLOOK
        STA DIGIMG0
        JMP RDRE
RDM:    MVI A,77h           ; 'A'
        STA DIGIMG3
        MVI A,39h           ; 'C'
        STA DIGIMG2
        MVI A,5Eh           ; 'd' (D)
        STA DIGIMG1
        MVI A,79h           ; 'E'
        STA DIGIMG0
        JMP RDRE
RDA:    XRA A               ; ---- ST_ADDR: последняя тетрада справа ----
        STA DIGIMG3
        STA DIGIMG2
        STA DIGIMG1
        STA DIGIMG0
        LDA ADCNT
        CPI 01h
        JC RDRE             ; 0 тетрад - всё пусто
        LDA AF0
        CALL GLOOK
        STA DIGIMG0
        LDA ADCNT
        CPI 02h
        JC RDRE
        LDA AF1
        CALL GLOOK
        STA DIGIMG1
        LDA ADCNT
        CPI 03h
        JC RDRE
        LDA AF2
        CALL GLOOK
        STA DIGIMG2
        LDA ADCNT
        CPI 04h
        JC RDRE
        LDA AF3
        CALL GLOOK
        STA DIGIMG3
RDRE:   RET

; =====================================================================
; UART-канал: передача OUT 04h @1M (TXRDY = IN 03h бит 7, v1.2 Шаг-2),
; приём RIM/SID @4800 - как v27
; =====================================================================

; ---------------------------------------------------------------------
; TXBYTE: A = байт -> сериализатор CPLD (1 000 000 8N1). Ожидает TXRDY
; (запись при busy аппаратно отбрасывается). Используется баннером/строками.
; ---------------------------------------------------------------------
TXBYTE: PUSH PSW
TXB1:   IN KBROWP           ; TXRDY = бит 6 (tx_idle, v39G02)
        ANI 040h            ; 1 = готов принять байт (busy-запись игнор)
        JZ TXB1
        POP PSW
        OUT TXP
        RET

; ---------------------------------------------------------------------
; TXSTR: HL = строка с нулевым завершителем -> TX. Портит A/HL.
; ---------------------------------------------------------------------
TXSTR:  MOV A,M
        ORA A
        RZ
        CALL TXBYTE
        INX H
        JMP TXSTR

; ---------------------------------------------------------------------
; PAUSE: пауза D итераций (v2.0.5: DCR 5T + JNZ 10T/7T -> PAUSE(n) =
; 15n+24T c CALL/RET = 4,8n+7,7 мкс; модель 14T врала на ~7%).
; ---------------------------------------------------------------------
PAUSE:  DCR D
        JNZ PAUSE
        RET

; ---------------------------------------------------------------------
; RXD: приём байта SID 4800 8N1 (фрагмент 7 + стоп-бит). Выход:
; C = байт, CY = 0 ОК / CY = 1 обрыв кадра (стоп-бит = 0). Портит A/B/C/D.
; Цикл строгий - в режиме B таймер ЗАМАСКИРОВАН (TMOFF: DI + SIM 1Fh)
; и пульки TMIARM запрещены - джиттера нет вообще.
; Константы v2.0.5: RXHB=17/RXFB=38, пересчёт по реальным тактам
; (scripts/rxd_cycles.py). Старые 19/41 (модель 14T) давали период бита
; 691-698T = 221-223 мкс вместо 208 -> d7 на 9,02-9,09 бита (СТОП-БИТ),
; стоп на 10,10-10,16 (idle): D7 всегда читалась как 1, ':' (3Ah) ->
; BAh, стоп высокий -> "успех" -> LOADM отбрасывал все ':' = вечный
; LLLL (diag_ph: 9F на любом символе - его d7 тоже уплывал в стоп).
; Новые: d0 1,45-1,47, d7 8,42-8,49, стоп 9,43-9,50 бита. v1.2: 15/30.
; ---------------------------------------------------------------------
RXD:    MVI B,08h
RXW:    RIM                 ; A7 = SID
        ORA A
        JM RXW              ; '1' (покой) - ждать старт-бит
        MVI D,RXHB          ; полбита - в середину старт-бита
        CALL PAUSE
        RIM                 ; подтвердить старт-бит
        ORA A
        JM RXW              ; '1' - ложный старт, ждать заново
        MVI C,00h
        MVI D,RXFB          ; бит - в середину D0
        CALL PAUSE
RXL:    RIM                 ; A7 = SID - центр очередного бита
        ANI 80h
        RLC                 ; SID (A7) -> CY. ФИКС v2.0.5: было RAR(1F),
                            ; но RAR берёт CY<-A0=0 и бит SID терялся;
                            ; C собирался как 00h при любой линии                 ; бит -> CY
        MOV A,C
        RAR                 ; вставить сверху (LSB-first)
        MOV C,A
        MVI D,RXFB
        CALL PAUSE
        DCR B
        JNZ RXL
        ; после последней итерации RXL (выборка d7 + бит задержки)
        ; линия = середина стоп-бита
        RIM
        ANI 80h             ; CY = 0 (ANI сбрасывает перенос)
        JZ RXBAD            ; стоп-бит = 0 - обрыв кадра

        MOV A,C
        ANI 7Fh             ; приводим принятый байт к чистому 7-битному ASCII (D7 = 0)
        MOV C,A

        ORA A               ; CY = 0
        RET                 ; C = байт, CY = 0
        ; СТАЛО (устойчивый приём стоп-бита на границе D7):
;        MVI B,15            ; окно ~100 мкс для дотягивания до стоп-бита
;RXST:   RIM
;        ANI 80h
;        JNZ RXOK            ; стоп-бит = 1 пойман!
;        DCR B
;        JNZ RXST
;        JMP RXBAD           ; линия застряла в 0 (реальный обрыв/Break)
;RXOK:   ORA A               ; CY = 0
;        RET                 ; C = байт, CY = 0


RXBAD:  STC
        RET                 ; CY = 1

; ---------------------------------------------------------------------
; ---------------------------------------------------------------------
; LMODE/GETB v3: источник байтов парсера по подменю B.
;   LMODE = 0: SID 4800 (RXD, без изменений; SID = RX passthrough v39G02).
;   LMODE = 1: FAST - CPLD RXUART 2.083М. Пир шлёт КАЖДЫЙ ASCII-байт
;   записи как ПАРУ байтов 0xC0|nib (hi-тетрада первой): у 0xC0|nib
;   d6=d7=1 - дефекты RX RTL (оф-бай-ван rx=(b&7F)<<1 и фантомный
;   перезапуск, 16.18) невозможны; CPLD отдаёт 0x80|(nib<<1), nib =
;   (rx>>1)&0F. Пауза ПК >= 15 мкс между байтами пары (poll-петля 27T
;   = 8.6 мкс должна успевать до следующего кадра - иначе перезапись
;   rx_data). Собранный ASCII-байт отдаётся парсеру как есть.
; LMODE в клетке AF0 (0FFF0h): в B-режиме тетрады адреса свободны.
; ---------------------------------------------------------------------
LMODE   EQU AF0             ; 0 = SID 4800, 1 = FAST (шара с AF0)

GETB:   LDA LMODE
        ORA A
        JZ RXD              ; SID: C = байт, CY = 0 ОК / 1 обрыв
        MVI B,002h          ; --- FAST: собрать ASCII-байт из 2 nib ---
GF1:    IN KBROWP
        ANI 020h            ; rx_ready (D5)
        JZ GF1
        IN RXP              ; rx = 0x80|(nib<<1); ready снялся сам
        RRC                 ; nib = (rx>>1)&0F
        ANI 00Fh
        RLC
        RLC
        RLC
        RLC                 ; hi-тетрада -> биты 7..4
        MOV C,A
GF2:    IN KBROWP
        ANI 020h
        JZ GF2
        IN RXP
        RRC
        ANI 00Fh
        ORA C               ; ASCII-байт (обычно ':' или тетрада-символ)
        MOV C,A
        ORA A               ; CY = 0 (обрывов нет; тишина = вечный poll ->
        RET                 ;  выход RESET, как в SID-режиме)

; ---------------------------------------------------------------------
; NIB: A = ASCII-символ -> CY = 1 и A = тетрада 0-F ('0'-'9','A'-'F',
; 'a'-'f'), иначе CY = 0. Портит A.
; ---------------------------------------------------------------------
NIB:    SUI 30h             ; '0'..'9' -> 0..9
        JC NIBX             ; < '0'
        CPI 0Ah
        JC NIBOK            ; цифра 0..9
        SUI 07h             ; 'A'..'F' -> 10..15
        CPI 10h
        JNC NIB2            ; > 'F' - попробовать строчные a..f
        JMP NIBOK
NIB2:   SUI 20h             ; ('a'-'0')-07h-20h = 10..15
        CPI 10h
        JNC NIBX
        JMP NIBOK
NIBOK:  STC
        RET
NIBX:   ORA A               ; CY = 0
        RET

; ---------------------------------------------------------------------
; ---------------------------------------------------------------------
; LSTAT v3: A = глиф -> статический разряд DIG0 парой OUT в конвейер.
; Маска DIG0 = BITTBL[0] (уже с DPOL), глиф из A (уже с DPOL - caller
; берёт из GTBL/GLOOK). Промежуточное состояние между OUT ~7 мкс -
; невидимо. Такты ~55T.
; ---------------------------------------------------------------------
LSTAT:  PUSH B
        MOV B,A             ; B = глиф (с DPOL)
        LDA BITTBL          ; [0] = маска DIG0 (0Eh при DPOL=0)
        OUT DISPP           ; (1) маска DIG0
        MOV A,B
        OUT DISPP           ; (2) глиф: пара готова - DIG0 = глиф
        POP B
        RET

; ---------------------------------------------------------------------
; DLMS: пауза ~1,02 мс (K_MS=130 итераций 24T @320 нс = 1,002 мс).
; Портит A/B/C. H/L целы. ВНИМАНИЕ (п.3): внутри DLMS пульки TMIARM
; нет - на время паузы слоты стоят (один разряд горит ~1 мс, яркость
; не страдает - скважность 1/4 как всегда; каденция возвращается на
; следующем TMIARM-вызове).
; ---------------------------------------------------------------------
DLMS:   LXI B,K_MS
DLS1:   DCX B
        MOV A,B
        ORA C
        JNZ DLS1
        RET

; ---------------------------------------------------------------------
; LDSUM: LSUM += B (mod 256). Портит A.
; ---------------------------------------------------------------------
LDSUM:  PUSH PSW
        LDA LSUM
        ADD B
        STA LSUM
        POP PSW
        RET

; ---------------------------------------------------------------------
; LDBEEP: длинный сигнал ~0,3 с (тоггл D4 DIGP вручную: в B/F 7.5
; замаскирован (TMOFF) - ISR не пишет DIGP, конфликта нет; CALL
; TMIARM здесь не нужен (заглушка). Портит A/B/C/D.
; ---------------------------------------------------------------------
; v3: тон на SOD (SIM): C0h = SDE+SOD=1, 40h = SDE+SOD=0; MSE=0 - маски
; целы. Дисплей в B/F - статика LSTAT, конвейер не трогаем.
LDBEEP: MVI D,150
LDB1:   MVI A,0C0h          ; SOD=1
        SIM
        CALL DLMS
        MVI A,040h          ; SOD=0
        SIM
        CALL DLMS
        DCR D
        JNZ LDB1
        RET

; =====================================================================
; LOADM: Intel HEX загрузчик (клавиша B). Приём SID 4800 8N1.
; Вход через KLD с TMOFF (7.5 замаскирован, DI) - как v27 по логике
; парсера. Формат записи: :nnaaaatt[dd...]cc, cc = (-сумма байт) mod 256.
; Статический дисплей 'L', после первой записи - счётчик записей mod 16
; на DIG0 (v2.0.6). Адрес каждой записи живёт в ADDRH/L.
; Запись только в ОЗУ (A15=1): попадание в ROM-окно = ошибка.
; Выход: EOF-запись (type 01) -> тик и меню; ошибка -> EEEE горит + звук
; SOS до нажатия Enter (v2.0.6), потом меню. Выход из зависшего приёма
; (тишина на SID) - RESET (SW20).
; NOTE: LACC/LNIB/LBPC/LSUM/LTY = клетки FFFB-FFFF; в обычном режиме
; FFFC-FFFF заняты KRAW (ISR) - в B маски стоят (TMOFF), конфликта нет;
; TMON на выходе чистит KRAW. XSSEQ/LST = FFFA: на входе LST=0 (=SEQ 0 -
; клиент логирует рестарт потока), на выходе TMON -> новое SEQ с 0.
; ---------------------------------------------------------------------
LOADM:  XRA A
        STA LST             ; ждем ':' (и XSSEQ = 0 - рестарт потока клиента)
        STA LACC            ; накопитель тетрад тоже с нуля (баг v1.0:
                            ;  сталь ломала первый байт первой записи)
        STA LDCTR           ; v2.0.6: счётчик записей = 0 ('L' до первой)
        MVI A,38h           ; 'L'
        CALL LSTAT

LDLP:   CALL GETB           ; v3: источник по LMODE (SID 4800 / FAST 2.083М)
        JC LDERR            ; v2.0.6: приборация этапов парсера (v2.0.5G)
        MOV A,C             ;  удалена - байт в A и дальше по состоянию
        CPI ':'

        JZ LDNEW            ; начало записи




        CALL NIB            ; тетрада?
        JNC LDLP            ; прочее (\r\n и т.п.) - пропустить
        MOV E,A             ; E = тетрада (7.5 замаскирован - E свободен)
        LDA LACC
        RLC
        RLC
        RLC
        RLC                 ; накопитель << 4
        ORA E
        STA LACC
        LDA LNIB
        DCR A
        STA LNIB
        JNZ LDLP            ; байт поля ещё не собран
        ; --- байт поля собран - применить по состоянию ---
        LDA LACC
        MOV B,A             ; B = байт
        XRA A
        STA LACC            ; накопитель очищен к следующему байту
        LDA LST
        ORA A
        JZ LDLP             ; байт вне записи - игнор
        DCR A
        JZ LDCNT            ; 1 = count
        DCR A
        JZ LDADR            ; 2 = addr
        DCR A
        JZ LDTYP            ; 3 = type
        DCR A
        JZ LDDAT            ; 4 = data
        JMP LDCHK           ; 5 = checksum
LDCNT:  MOV A,B
        STA ADCNT           ; сколько байт данных в записи
        CALL LDSUM
        MVI A,02h           ; поле addr: 4 тетрады = 2 байта
        STA LST
        STA LBPC
        STA LNIB
        JMP LDLP
LDADR:  MOV A,B
        STA LTY             ; временно: тип ещё не читался
        LDA LBPC
        CPI 02h
        JNZ LDAD1
        LDA LTY
        STA ADDRH           ; старший байт адреса (big-endian)
        MVI A,01h
        STA LBPC
        MVI A,02h           ; <--- ДОБАВИТЬ: зарядить счётчик тетрад для младшего байта адреса!
        STA LNIB            ; <--- ДОБАВИТЬ!
        CALL LDSUM
        JMP LDLP
LDAD1:  LDA LTY
        STA ADDRL           ; младший байт адреса
        CALL LDSUM
        MVI A,03h
        STA LST             ; type
        MVI A,01h
        STA LBPC
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP:  MOV A,B
        STA LTY
        CALL LDSUM
        LDA LTY
        CPI 01h
        JZ LDTYP1
        LDA ADCNT           ; type 00: данные
        STA LBPC
        MVI A,04h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDTYP1: XRA A               ; type 01 (EOF): данных нет
        STA LBPC
        MVI A,05h
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT:  LDA ADDRH
        ANI 80h             ; запись разрешена только в ОЗУ
        JZ LDERR            ; ROM-окно - ошибка
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,B             ; [ADDR] = байт (writeback CPLD)
        INX H
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL LDSUM
        LDA LBPC
        DCR A
        STA LBPC
        JNZ LDDAT2
        MVI A,05h           ; данные кончились - ждать checksum
        STA LST
        MVI A,02h
        STA LNIB
        JMP LDLP
LDDAT2: MVI A,02h
        STA LNIB
        JMP LDLP
LDCHK:  LDA LSUM            ; контрольная сумма записи
        ADD B               ; сумма всех байт + cc = 0 mod 256?
        JNZ LDERR
        LDA LTY
        CPI 01h
        JZ LDDONE           ; EOF - конец загрузки
        LDA LDCTR           ; v2.0.6: индикатор загрузки - счётчик записей
        INR A               ;  (mod 16) на DIG0: 1,2,3...F,0,1... - видно,
        STA LDCTR           ;  что приём жив и сколько записей прошло
        ANI 0Fh
        CALL GLOOK
        CALL LSTAT          ; v3: пара (маска DIG0 + глиф) - конвейер
        XRA A
        STA LST             ; ждем ':' следующей записи
        JMP LDLP
LDNEW:  MVI A,01h           ; ':' - новая запись
        STA LST
        MVI A,02h
        STA LNIB
        XRA A
        STA LSUM
        JMP LDLP
LDDONE: CALL TICKON         ; подтверждение успешной загрузки
        RET
LDERR:  MVI A,79h           ; 'E' в защёлке сегментов (глиф для всех разрядов)
        CALL LSTAT          ; DIG0 = 'E'; с этого момента EEEE/SOS до Enter

; ---------------------------------------------------------------------
; LDERR v2.0.6: ошибка загрузки -> EEEE горит ПОСТОЯННО + звук SOS до
; нажатия Enter. Точка ~100 мс, тире ~300 мс, пауза буквы 200 мс, пауза
; слова 800 мс. ISR стоит (TMOFF на входе B): тон ведём вручную через
; D4 DIGP (SND), разряды включены (1Fh на тоне, 0Fh в паузах) - EEEE не
; мигает; клавиатуру сканируем сами (SCAN1). Enter -> отпускание +
; дебаунс 15 мс -> RET (в меню через K_F1E: TMON+TICKON+REDRAW). Другие
; клавиши игнорируются. Портит A/B/C/D/H/L.
; ---------------------------------------------------------------------
SOSP:   CALL LET_S          ; S
        CALL WAITENT
        CALL LET_O          ; O
        CALL WAITENT
        CALL LET_S          ; S
        MVI E,4             ; пауза слова ~0,8 с (4 x 200 мс; MVI - imm8)
SOSW:   MVI D,200
        CALL MSD
        DCR E
        JNZ SOSW
        CALL WAITENT
        JMP SOSP

; ---- буква S: 3 точки + пауза буквы 200 мс ----
LET_S:  MVI D,3
LS1:    CALL BPNT
        DCR D
        JNZ LS1
        MVI D,200
        CALL MSD
        RET

; ---- буква O: 3 тире + пауза буквы 200 мс ----
LET_O:  MVI D,3
LO1:    CALL BDASH
        DCR D
        JNZ LO1
        MVI D,200
        CALL MSD
        RET

; ---- точка: тон 100 мс (EEEE горит) / пауза 100 мс ----
BPNT:   MVI A,0C0h          ; v3: SOD=1 (SIM)
        SIM
        MVI D,100
        CALL MSD
        MVI A,040h          ; SOD=0
        SIM
        MVI D,100
        CALL MSD
        RET

; ---- тире: тон 300 мс (3 x 100) / пауза 100 мс ----
BDASH:  MVI A,0C0h          ; v3: SOD=1 (SIM)
        SIM
        MVI E,3             ; 3 x 100 мс = 300 мс
BD1:    MVI D,100
        CALL MSD
        DCR E
        JNZ BD1
        MVI A,040h
        SIM
        MVI D,100
        CALL MSD
        RET

; ---- MSD: пауза D x ~1,02 мс (DLMS портит A/B/C, D цел) ----
MSD:    CALL DLMS
        DCR D
        JNZ MSD
        RET

; ---------------------------------------------------------------------
; SCAN1: полный скан клавиатурной матрицы (вручную - в B/F ISR стоит).
; Логика KSCOL, но все 4 колонки за проход. Возврат: A = код клавиши
; (KEYTBL) первой нажатой (младший ряд первенствует, как в KDL) или
; 0FFh. Портит A/B/C/D/H/L.
; ---------------------------------------------------------------------
SCAN1:  MVI C,0             ; колонка 0..3
SC1:    MVI B,0
        LXI H,BITTBL
        DAD B               ; HL = BITTBL + колонка (DAD B = +BC)
        MOV D,M             ; D = бит колонки (01/02/04/08)
        MOV A,D
        RLC
        RLC
        RLC
        RLC                 ; бит колонки -> старший ниббл
        OUT KBCOLP          ; колонка заведена (A[3:0] игнорируются)
        CALL SETTLE
        IN KBROWP
        ANI 1Fh             ; ряды (D7 TXRDY, D6-D5 фаза - маскируются)
        MOV B,A             ; B = образ рядов
        XRA A
        OUT KBCOLP          ; колонка off
        MOV A,B
        ORA A
        JZ SCNC             ; колонка пуста
        MVI D,0             ; D = номер ряда (младший установленный бит)
SC2:    MOV A,B
        RRC
        MOV B,A
        JC SC3
        INR D
        JMP SC2
SC3:    MOV A,D             ; код = KEYTBL[row*4+col]
        RLC
        RLC
        ORA C
        MOV C,A
        MVI B,0
        LXI H,KEYTBL
        DAD B
        MOV A,M
        CPI 0FFh
        RZ                  ; пустая позиция матрицы - клавиши нет
        RET                 ; A = код клавиши
SCNC:   INR C
        MOV A,C
        CPI 04h
        JZ SCX
        JMP SC1
SCX:    MVI A,0FFh          ; весь скан чист - клавиш нет
        RET

; ---------------------------------------------------------------------
; WAITENT: держим EEEE+SOS, пока не нажат Enter (K_ENT). Возврат после
; отпускания + дебаунс 15 мс. Другие клавиши - игнор.
; ---------------------------------------------------------------------
WAITENT:
WE1:    CALL SCAN1
        CPI K_ENT
        JZ WE2
        JMP WE1
WE2:    CALL SCAN1          ; ждём отпускания
        CPI 0FFh
        JNZ WE2
        MVI D,TQ_MS         ; 15 мс дебаунс (как KRL/MNR1)
        CALL MSD
        RET

; =====================================================================
; RAMT: RAM-тест 8000h-FFD7h (клавиша F). 4 паттерна 00/FF/55/AA:
; заполнение + контроль побайтно. Статический дисплей (DIG0) = глиф
; паттерна ("0000"/"FFFF"/"5555"/"AAAA"). Сбой: ADDRH/L = адрес сбоя,
; EEEE + длинный сигнал. Успех: короткий тик. Вход через KRAM с TMOFF:
; 7.5 замаскирован - ISR не толкает стек в диапазон теста.
; ГРАНИЦА: FFD8h-FFE7h НЕ тестируется (фикс v2.0.2/tw): там живёт стек
; монитора - собственный адрес возврата RAMT лежит в FFE7h/FFE6h, и
; заполнение до FFE7h затирало его -> после теста RET в мусор. Стек до
; FFD4h не доходит (RAMT без длинных push). Портит всё, кроме клеток.
; ФИКС v2.0.2 (tw): паттерн восстанавливается из E на каждом шаге
; (MOV A,E): в v1.2-v2.0.1 MOV A,H после INX H затирал паттерн в A и
; с 8001h писались МЛАДШИЕ БАЙТЫ АДРЕСА -> вечная "ошибка ОЗУ".
; ---------------------------------------------------------------------
RAMT:   LXI H,RAMPAT        ; HL = текущая пара (value+glyph)
        MVI C,04h           ; 4 паттерна
RMT0:   MOV A,M             ; A = значение паттерна
        MOV E,A
        PUSH H              ; указатель пары - на стек (HL уйдёт под заполнение)
        INX H
        MOV A,M             ; глиф паттерна
        CALL LSTAT          ; статический дисплей ("0000" и т.д.)
        MOV A,E
        LXI H,8000h
RMF:    MOV A,E             ; паттерн из E на КАЖДОМ шаге (фикс v2.0.2)
        MOV M,A             ; заполнение
        INX H
        MOV A,H
        CPI 0FDh
        JNZ RMF
        MOV A,L
        CPI 0D8h
        JNZ RMF
        LXI H,8000h
RMV:    MOV A,M             ; контроль (8000h..FFD7h)
        CMP E
        JNZ RMBAD
        INX H
        MOV A,H
        CPI 0FDh
        JNZ RMV
        MOV A,L
        CPI 0D8h
        JNZ RMV
        POP H               ; HL = пара паттерна
        INX H
        INX H               ; следующая пара
        DCR C
        JNZ RMT0
        CALL TICKON         ; ОК
        RET
RMBAD:  SHLD ADDRL          ; ADDRH/L = адрес сбоя (HL из RMV, до POP!)
        POP H               ; снять указатель пары (баланс стека)
        MVI A,79h           ; 'E' -> EEEE
        CALL LSTAT
        CALL LDBEEP
        RET                 ; в меню; D = просмотр байта по адресу сбоя

; =====================================================================
;                    XSTREAM: ЭКРАН -> UART (п.8: непрерывный поток,
;                    тик кадра = сама скорость канала, регенерация/
;                    скан ведётся пульками TMIARM внутри посылки)
; =====================================================================
; ---------------------------------------------------------------------
; XSINIT (из START, только холодный старт): демо-экран в B000h,
; SEQ = 0. Мониторные переменные не трогаются; B000-B7CF -
; пользовательская область: ЛЮБАЯ программа может рисовать туда
; свой текст/графику, клиент xstream_view.ps1 покажет окном.
; ---------------------------------------------------------------------
XSINIT: CALL XBLANK
        LXI H,XTBL
XSI1:   MOV E,M             ; DE = адрес назначения
        INX H
        MOV D,M
        INX H               ; HL -> src_lo
        MOV A,D             ; конец таблицы (dst == 0000)?
        ORA E
        JZ XSI3
        MOV C,M             ; BC = адрес строки (источник)
        INX H
        MOV B,M
        INX H               ; HL -> следующая запись
        PUSH H              ; указатель следующей записи -> стек
        MOV H,B
        MOV L,C
        CALL XCPY           ; ASCIZ [HL] -> [DE], 0 = конец
        POP H
        JMP XSI1
XSI3:   XRA A
        STA XSSEQ
        RET

XBLANK: LXI H,XBUF          ; 2000 пробелов
        LXI B,2000
XB1:    MVI A,20h
        MOV M,A
        INX H
        DCX B
        MOV A,B
        ORA C
        JNZ XB1
        RET

XCPY:   MOV A,M             ; ASCIZ: [HL]->[DE], 0 = конец (A/флаги)
        ORA A
        RZ
        STAX D
        INX H
        INX D
        JMP XCPY

; ---------------------------------------------------------------------
; XSEND: кадр XSTREAM в UART: A5 5A [SEQ] + 2000 Б из XBUF.
;   Сохраняет PSW/B/D/H. РАВНОМЕРНЫЙ пейсинг 36,75T/Б без опроса TXRDY:
;   на 3,125 МГц 36,75T = 11,8 мкс >= 10 мкс байта 1M. CALL TMIARM
;   (заглушка RET) в шапке КАЖДОЙ 8-Б подгруппы (~94 мкс): слот
;   приходит САМ раз в 1,024 мс, ISR-вставка ~170 мкс удлиняет текущий
;   гэп (мин. 25T соблюдён) - ноль отбросов TX; регенерация/скан идут
;   ВНУТРИ посылки. Кадр ~37 мс (~27 FPS; v1.2: ~42).
; ---------------------------------------------------------------------
XSEND:  PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL XUPDCTR        ; живой счётчик SEQ в демо-экран
        MVI A,0A5h
        OUT TXPORT          ; шапка: равномерный пейсинг 33T (4 NOP)
        NOP
        NOP
        NOP
        NOP
        MVI A,05Ah
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        LDA XSSEQ
        OUT TXPORT
        NOP
        NOP
        NOP
        NOP
        INR A
        STA XSSEQ           ; SEQ++ mod 256
        LXI H,XBUF          ; HL = экран
        MVI B,10            ; внешний: 10 групп по 200 Б
XSOUT:  MVI C,25            ; внутренний: 25 подгрупп по 8 Б
XSL:    CALL TMIARM         ; заглушка RET; слот приходит сам (1,024 мс)
        MOV A,M             ; ISR вставляет ~170 мкс; гэп OUT->OUT >= 25T
        OUT TXPORT          ; равномерный пейсинг: гэп OUT->OUT >= 25T байта
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        MOV A,M
        OUT TXPORT
        INX H
        NOP
        NOP
        NOP
        DCR C               ; подгруппа = 7x35T + 15T = 294T (36.75T/Б)
        JNZ XSL
        DCR B
        JNZ XSOUT
        POP H
        POP D
        POP B
        POP PSW
        RET

; ---------------------------------------------------------------------
; XUPDCTR: живой счётчик SEQ (hex, 2 цифры) в демо-экран, строка 22,
; колонки 4-5 - доказательство живого потока в клиенте.
; ---------------------------------------------------------------------
XUPDCTR: PUSH H
        LDA XSSEQ
        MOV C,A
        RRC
        RRC
        RRC
        RRC
        ANI 0Fh
        CALL XHEX
        STA XSCNT
        MOV A,C
        ANI 0Fh
        CALL XHEX
        STA XSCNT+1
        POP H
        RET

XHEX:   ADI '0'
        CPI 3Ah
        JC XHX1
        ADI 07h
XHX1:   RET

; ---- демо-экран (ASCII; NUL-конец; <= 80 символов на строку) ----
S_T0:   DB 'fw_monitor_ACdE_v39 v3.0 - SCREEN B000h-B7CFh -> UART (RTL v39G02 TX 1.0417M)',0
S_T1:   DB 'FRAME: A5 5A [SEQ] + 2000 BYTES (ROW-MAJOR 80x25 / CP1251 AT PC CLIENT)',0
S_T2:   DB 'TICK: RST7.5 JIFFY 122.88 US (v39G02 tmr_cnt[6]) - SLOT EVERY 8 JIFFIES',0
S_T3:   DB 'MONITOR: A=ADDR C=CODE D=VIEW E=RUN B=LOAD(0=SID4800 1=FAST 2M) F=RAM F1=MENU',0
S_T4:   DB 'WRITE YOUR TEXT INTO B000h..B7CFh - THIS WINDOW IS THE PC SCREEN',0
S_T5:   DB 'SEQ:__ FRAME ~37 MS BACK-TO-BACK | REGEN+SCAN IN ISR - TMIARM PACED',0
XTBL:   DW XBUF, S_T0       ; строка 0
        DW XBUF+00A0h, S_T1 ; строка 2
        DW XBUF+00F0h, S_T2 ; строка 3
        DW XBUF+0280h, S_T3 ; строка 5
        DW XBUF+0320h, S_T4 ; строка 6
        DW XBUF+06E0h, S_T5 ; строка 22 (счётчик SEQ живой, кол. 4-5)
        DW 0000h, 0000h     ; конец таблицы

; ---------------------------------------------------------------------
; DISPOFF v3: погасить дисплей парой OUT (конвейер). При DPOL=0 ("пин=1
; горит") маска-запись 0Fh -> пины разрядов 0 (off), сегмент-запись 7Fh
; (7 бит) -> пины сегментов 0 (off). При DPOL=1 - нули. Портит A.
; ---------------------------------------------------------------------
DISPOFF:
IF DPOL
        XRA A
        OUT DISPP           ; маска 00h
        OUT DISPP           ; сегменты 00h
ELSE
        MVI A,00Fh
        OUT DISPP           ; маска 0Fh (пины разрядов = 0 = off)
        MVI A,07Fh
        OUT DISPP           ; сегменты 7Fh (7 бит, пины = 0 = off)
ENDIF
        RET

; =====================================================================
; MAIN: старт, главный цикл, клавиатура, GO (п.2, п.3, п.8)
; =====================================================================
START:  DI
        LXI SP,SP0
        MVI A,80h           ; адрес по умолчанию 8000h (начало ОЗУ)
        STA ADDRH
        XRA A
        STA ADDRL
        CALL XSINIT         ; демо-экран B000h, SEQ = 0
MAIN2:  CALL DISPOFF        ; v3: гашение парой (после сброса конвейер 00/00)
        MVI A,040h          ; SOD=0 (SND off), SDE=1
        SIM
        STA SNDST
        STA ADCNT
        STA BDCNT
        STA DPIDX
        STA STATE           ; ST_MENU
        STA PREVST
        CALL REDRAW         ; "ACdE"
        LXI H,TXBAN         ; баннер: терминал 1M читает, 4800 = мусор
        CALL TXSTR
        CALL TMON           ; ПУСК слот-системы (EI внутри; первый слот -
                            ; через джиффи 1,024 мс, см. п.2)

; ---- главный цикл: слот приходит сам раз в джиффи 1,024 мс; цикл
;      декодирует клавиатуру и непрерывно льёт кадры xstream ----
SCAN:   CALL TMIARM         ; заглушка RET (п.2: слот приходит сам)
        LDA KRAW0           ; есть ли нажатие (образ ISR, п.3 v1.2)?
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C               ; A/C = ИЛИ колонок (0 = нажатий нет)
        JZ NOKEY
        LXI H,KRAW0         ; ---- декод: колонка C_idx, ряд = бит ----
        MVI C,0             ; C = индекс колонки 0..3
KDL:    MOV A,M
        ORA A
        JNZ KDH
        INX H
        INR C
        MOV A,C
        CPI 04h
        JNZ KDL
        JMP NOKEY           ; (не бывает: OR ненулевой - защита)
KDH:    MOV B,A             ; B = образ рядов колонки C
        MVI D,0             ; D = номер ряда
KH1:    MOV A,B
        RRC
        MOV B,A
        JC KH2
        INR D
        JMP KH1
KH2:    MOV A,D             ; код = KEYTBL[row*4+col]
        RLC                 ; row*4 (row<=4 -> 0..16, БЕЗ ANI - ряд 4 = 10h,
        RLC                 ;  клавиши 0/F1/F2; ANI 0Ch тут убил бы ряд 4)
        ORA C
        MOV C,A
        MVI B,0
        LXI H,KEYTBL
        DAD B
        MOV A,M
        CPI 0FFh
        JZ SCAN             ; пустая позиция матрицы
        CALL DISPATCH
        ; ---- ожидание отпускания + дебаунс (KRAW живой - ISR сканит) ----
KRL:    CALL TMIARM         ; заглушка RET (п.2): KRAW обновляет САМ ISR
        LDA KRAW0           ; раз в 1,024 мс - спин конечен без пулек
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ KRL             ; ждём отпускания (дисплей/скан идут в ISR)
        MVI H,TQ_MS         ; 15 мс дебаунс отпускания
KST:    CALL TMIARM         ; слот на итерацию (дисплей жив под дебаунсом)
        CALL DLMS
        DCR H
        JNZ KST
        JMP SCAN
NOKEY:  CALL XSEND          ; нажатий нет - кадр xstream (пульки в XSL)
        JMP SCAN

; ---------------------------------------------------------------------
; DISPATCH: обработка кода клавиши (A). F1 - глобально в меню,
; F2 - глобально показать адрес (повторное F2 - назад).
; Меню: A/C/D/E + B (загрузчик Intel HEX, TMOFF на входе) +
; F (RAM-тест, TMOFF на входе). Тело - как v27 (проверено железом).
; ---------------------------------------------------------------------
DISPATCH: MOV C,A           ; C = КОД КЛАВИШИ (LDA STATE затирает A!)
        CPI K_F2
        JZ K_F2E
        CPI K_F1
        JZ K_F1E
        LDA STATE
        ORA A
        JZ DSM
        CPI 01h
        JZ DSA
        CPI 02h
        JZ DSP
        CPI 04h
        JZ DSW              ; показ адреса: прочие клавиши - игнор
        ; ================= ST_VIEW =================
DSV:    MOV A,C
        CPI K_ENT
        JZ VENT
        RET                 ; тетрады - игнор (режим только чтение)
VENT:   LDA ADDRL
        MOV L,A
        LDA ADDRH
        MOV H,A
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        CALL TICKON
        CALL REDRAW         ; следующий байт на дисплее
        RET
        ; ================= ST_PROG =================
DSP:    MOV A,C
        CPI K_ENT
        JZ PENT
        CPI 10h
        JC PDIG             ; 00h..0Fh - тетрада байта
        RET
PDIG:   MOV A,C
        MOV B,A
        LDA BF0
        STA BF1             ; сдвиг: BF1 = BF0
        MOV A,B
        STA BF0
        LDA BDCNT
        CPI 02h
        JNC PDS
        INR A
        STA BDCNT
PDS:    CALL TICKON
        CALL REDRAW
        RET
PENT:   LDA BDCNT
        ORA A
        JZ PIGN             ; пусто - игнор (без записи)
        LDA BF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA BF0
        ORA C               ; C = байт
        MOV C,A
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A
        MOV M,C             ; [ADDR] = байт (A15=0 железо отбросит)
        INX H               ; ADDR++
        MOV A,H
        STA ADDRH
        MOV A,L
        STA ADDRL
        XRA A
        STA BDCNT           ; поле гасится - ждём следующий байт
        CALL TICKON
        CALL REDRAW
PIGN:   RET
        ; ================= ST_ADDR =================
DSA:    MOV A,C
        CPI K_ENT
        JZ AENT
        CPI 10h
        JC ADIG             ; 00h..0Fh - тетрада адреса
        RET
ADIG:   MOV A,C
        MOV B,A
        LDA AF2
        STA AF3
        LDA AF1
        STA AF2
        LDA AF0
        STA AF1
        MOV A,B
        STA AF0
        LDA ADCNT
        CPI 04h
        JNC ADS
        INR A
        STA ADCNT
ADS:    CALL TICKON
        CALL REDRAW
        RET
AENT:   LDA ADCNT
        ORA A
        JZ AIGN             ; пусто - игнор
        LDA AF3
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF2
        ORA C
        STA ADDRH
        LDA AF1
        RLC
        RLC
        RLC
        RLC
        MOV C,A
        LDA AF0
        ORA C
        STA ADDRL
        XRA A
        STA STATE           ; в меню
        CALL TICKON
        CALL REDRAW
AIGN:   RET
        ; ================= ST_MENU =================
DSM:    MOV A,C             ; вернули код клавиши
        CPI 0Ah             ; 'A' - ввод адреса
        JZ KAD
        CPI 0Ch             ; 'C' - ввод кода (Code)
        JZ KPR
        CPI 0Dh             ; 'D' - просмотр кода
        JZ KVD
        CPI 0Eh             ; 'E' - выполнить
        JZ KGO
        CPI 0Bh             ; 'B' - загрузчик Intel HEX
        JZ KLD
        CPI 0Fh             ; 'F' - RAM-тест
        JZ KRAM
        RET                 ; остальные - игнор
; v3: подменю B: показ 'b', клавиша 0 = SID 4800, клавиша 1 = FAST.
KLD:    CALL TMOFF          ; ТИШИНА: приём чист (маски+DI), дисплей статикой
        MVI A,00Bh          ; 'b'
        CALL GLOOK
        CALL LSTAT          ; 'b' на DIG0
KLDW:   CALL SCAN1
        CPI 00h
        JZ KLDS             ; 0 = SID 4800 (legacy, прежний PC-скрипт)
        CPI 01h
        JZ KLDF             ; 1 = FAST (CPLD RXUART 2.083М, пары 0xC0|nib)
        JMP KLDW
KLDS:   XRA A
        STA LMODE
        CALL LOADM
        JMP K_F1E
KLDF:   MVI A,01h
        STA LMODE
        IN RXP              ; сброс stale rx_ready (чтение снимает)
        CALL LOADM
        JMP K_F1E
KRAM:   CALL TMOFF          ; ТИШИНА: стек статичен - тест 8000h-FFE7h чист
        CALL RAMT
        JMP K_F1E
KAD:    MVI A,ST_ADDR
        STA STATE
        XRA A
        STA ADCNT
        CALL TICKON
        CALL REDRAW
        RET
KPR:    MVI A,ST_PROG       ; C: ввод кода (Code)
        STA STATE
        XRA A
        STA BDCNT
        CALL TICKON
        CALL REDRAW
        RET
KVD:    MVI A,ST_VIEW       ; D: просмотр кода
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
; ---- F2: показ адреса операций (глобально; повторное F2 - назад) ----
K_F2E:  LDA STATE
        CPI ST_SHOW
        JZ KF2B             ; уже показываем - вернуть прежний режим
        STA PREVST          ; запомнить, откуда пришли
        MVI A,ST_SHOW
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
KF2B:   LDA PREVST
        STA STATE
        CALL TICKON
        CALL REDRAW
        RET
DSW:    RET                 ; показ адреса: Enter/тетрады не действуют
K_F1E:  CALL TMON           ; реинициализация слот-системы (после B/F обяз.,
                            ;  после простого F1 - безвредный ре-пуск)
        XRA A
        STA STATE           ; меню (из любого режима)
        CALL TICKON
        CALL REDRAW
        RET
        ; ================= GO: запуск =================
KGO:    CALL DISPOFF        ; v3: гашение парой + SOD=0
        MVI A,040h
        SIM
        CALL TMOFF          ; маски+сброс защёлки (v1.2 OUT 06h,0 удалён -
                            ; стопить нечего): программа пользователя - 100%
                            ; ЦП, тики идут в замаскированную защёлку; ей
                            ; нужен тик - EI + SIM 3Bh (вектор 003Ch = TMISR)
        LXI SP,SP0
        LXI H,MONRET
        PUSH H              ; адрес возврата в монитор
        LDA ADDRH
        MOV H,A
        LDA ADDRL
        MOV L,A             ; HL = адрес запуска
        XRA A
        MOV B,A
        MOV C,A
        MOV D,A
        MOV E,A             ; регистры обнулены
        PCHL                ; ушли в программу пользователя
MONRET: DI
        LXI SP,SP0
        CALL TMON           ; слот-система заново (чистка KRAW/DPIDX/EI)
        ; ждём отпускания всех клавиш + дебаунс (KRAW живой)
MNR1:   CALL TMIARM         ; критично как KRL: без пульки KRAW застынет
        LDA KRAW0
        MOV C,A
        LDA KRAW1
        ORA C
        MOV C,A
        LDA KRAW2
        ORA C
        MOV C,A
        LDA KRAW3
        ORA C
        ORA A
        JNZ MNR1
        MVI H,TQ_MS         ; 15 мс дебаунс
MNR3:   CALL TMIARM         ; слот на итерацию
        CALL DLMS
        DCR H
        JNZ MNR3
        JMP MAIN2           ; реинициализация, ADDR сохранён

        END
