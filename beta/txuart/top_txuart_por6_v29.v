  // «Может быть уйти на более простой делитель тактовой, подать на
  // вход тактовой не 50, а 25, потом /4 и подать на процессор»):
  // вход 25 МГц (H1 С ШУНТОМ - DIV=/4 U7; БЕЗ шунта 50 МГц ЗАПРЕЩЕНО -
  // CPU 6,25 МГц, бод 3,125 М). ДЕЛИТЕЛЬ /4 на toggle-FF t0_q/x1_q/x2_q
  // на clk 25 МГц (период 160 нс); X1 = x1_q (6,25 МГц, duty 1/2),
  // X2 = x2_q (регистровая ~X1), внутренний /2 ВМ85А -> CPU 3,125 МГц.
  // clk25_q УДАЛЁН - ВСЯ логика (rst/TX/FSM/порты) на clk 25 МГц
  // (частота такта логики НЕ изменилась: clk25 базы = 25 МГц = clk
  // v2.2; /WE 80 нс, квалификатор 320 нс - тиковые константы живут
  // бит-в-бит). por-цепь - в домене clk 25 со стробом por_ce
  // (POR = 8 x 160 = 1280 нс, норма 3 x 320 = 960 нс, запас 1,33x).
  // История: узел v3.9.8 (кольцо r0..r6 N=7 на clk 50, X1 = r0 duty
  // 1/7, clk25_q = /2) - откат top_txuart_por6_v21.v.
  // v2.8.9 (Р-6): generate-обёртка удалена - прежнее ВНИМАНИЕ «ISE не
  // принимает reg-инициализаторы ВНУТРИ generate» больше не актуально.
  //=============================================================
  wire por_ce;

  // v2.4 (директива владельца 11-14, блок v2.4 шапки): состояние узла =
  // ДЕЛИТЕЛЬ /4 на toggle-триггерах t0_q/x1_q/x2_q («дедовский» /4,
  // 3 МЦ вместо кольца 5 МЦ). Период X1 = 160 нс - КАК у кольца,
  // фронты те же; меняется только duty X1: 1/4 -> 1/2. Строб
  // por_ce = ~t0_q & ~x1_q (домен clk 25). X1 = x1_q (IO-MC P68),
  // X2 = x2_q - РЕГИСТРОВАЯ точная противофаза (IO-MC P69).
  (* keep = "true", equivalent_register_removal = "no" *)
  reg t0_q = 1'b0;   // clk/2 = 12,5 МГц 50%: D = ~t0_q (1 ПТ, 1 лит)
  (* keep = "true", equivalent_register_removal = "no" *)
  reg x1_q = 1'b1;   // clk/4 = 6,25 МГц 50%: D = x1_q ^ t0_q (2 ПТ);
                     // INIT=1 - X1 стартует с '1' (как кольцо s0=1)
  // v2.8.7: x2_q ВОССТАНОВЛЕН (T1 v28.1 снял его ради -1 МЦ; в железе
  // v28.5 это убило генератор 8085: CLKOUT мёртв при живом X1). Форма
  // v2.6 (подтверждена железом и осциллографом): T-триггер, T = t0_q
  // (ТОТ ЖЕ провод, что у x1_q -> X2^X1 инвариант), INIT=RESET -
  // комб-логики на X2 НЕТ. Цена +1 МЦ -> ожидаем 105/108. Делитель /4
  // (t0_q, x1_q) НЕ ТРОНУТ: X1/CPU 3,125 МГц, тик-база 4 мкс - без
  // изменений.
  (* keep = "true", equivalent_register_removal = "no" *)
  reg x2_q = 1'b0;   // противофаза: x2_q ^= t0_q, INIT=0; X1 INIT=1 ->
                     // инвариант x2^x1 = 1 с 1-го такта; БРАК = INIT X2=SET
  // Самовыравнивание: D(x2_q) не зависит от x2_q - ЛЮБОЙ код -> точная
  // противофаза за 1 такт (кольцу требовалось 2-3 фронта). Состояний
  // залипания НЕТ: бинарный цикл 4 состояний, GSR кладёт INIT (0,1,0)
  // прямо в цикл - kill/рестарт-логика не нужна.

  // v2.8.9 (Р-6): generate-обёртка СНЯТА (была единственная ветка
  // g_div4 с условием CLK_DIV==4 && CLK_HALF==1); reg-инициализаторы
  // t0_q/x1_q/x2_q - на scope модуля, как и были.
  // por_ce = ~t0_q & ~x1_q: РОВНО ОДИН такт 40 нс за период 160 нс
  //   (фаза (t0,x1) = (0,0)); строб и por-цепь в ОДНОМ домене
  //   clk 25 - детерминировано, как v2.2; POR 8 x 160 = 1280 нс -
  //   БЕЗ ИЗМЕНЕНИЙ (калибровка не тронута).
  always @(posedge clk) begin
    t0_q <= ~t0_q;             // clk/2
    if (t0_q) x1_q <= ~x1_q;   // clk/4, 50%
    if (t0_q) x2_q <= ~x2_q;   // v2.8.7: противофаза (T = t0_q - ТОТ ЖЕ
                               // провод, что у x1_q -> X2^X1 инвариант,
                               // 0^1 = 1; БРАК = INIT X2 = SET)
  end
  assign X1 = x1_q;   // 6,25 МГц, период ровно 160 нс, duty 1/2 (80/80)
  assign X2 = x2_q;   // v2.8.7: регистровая точная противофаза X1 (T = t0_q)
  assign por_ce = ~t0_q & ~x1_q;  // v2.4: 1 такт 40 нс за период 160 нс -
                       // ровно ОДИН posedge за период по построению;
                       // строб и por-цепь в одном домене - детерминировано
  
  //=============================================================
  // POR (v2.2, п.23/п.34: 8-битный СДВИГОВЫЙ регистр por_sh в домене
  // clk 25 МГц): 0 в MSB сдвигается вправо, bit0 очищается
  // ПОСЛЕДНИМ -> por_run снимается ровно через 8 тиков por_ce.
  // ДЕКОДОВ НЕТ (ни ==0, ни !=0, НИ В СТРОБЕ): фиттер дважды печатал
  // por-декоды с потерянной инверсией (фит 7:31: por_cnt(0): T=NOT en
  // -> POR=1 клок; фит 8:55: por_run.D=(por_cnt==0)) - класс
  // конструкций убран; строб por_ce декодов не содержит вовсе.
  // ДОМЕН clk 25 (v2.4): строб por_ce - такт 40 нс в ТОМ ЖЕ домене, что
  // и por-цепь - синхронное включение того же такта,
  // детерминировано при любой фазе (в базе v3.9.8 строб был 20 нс в
  // 50-домене, и por-цепь обязана была жить там же - класс-урок
  // «фазовой лотереи»; в v2.2 оба в одном домене - лотерея
  // невозможна по построению).
  // INIT=FF/1 -> RESET_IN=0 до всякого клока (счёт только при живом
  // clk через por_ce из делителя); por_run остаётся РЕГИСТРОМ (v3.2,
  // п.8 шапки - защита от схлопывания PT / Placement Failed).
  // Длительность: POR = 8 x 160 нс = 1280 нс (строб por_ce - 1 раз за
  // период кольца 160 нс); норма 3 такта CLK OUT = 960 нс @ 3,125 МГц
  // (запас 1,33x - ТОТ ЖЕ, что в v3.9.2-3.9.7); фактический низ
  // RESET_IN от INIT ~1200 нс (дрейн 1000 нс + кромки).
  // Повторный POR невозможен: после 00 сдвиг держит нули навсегда.
  //=============================================================
  reg [7:0] por_sh = 8'hFF;      // v2.2 (п.23/34): сдвиг вправо, clk 25 МГц,
                                 // строб por_ce: FF -> 7F -> ... -> 01 -> 00 (8 стробов)
  reg  por_run = 1'b1;           // FF-копия для cpu_rst (v3.2; INIT=SET)
  always @(posedge clk) begin
    por_run <= por_sh[0];        // снятие, когда '0' дойдёт до bit0 (8-й тик)
    if (por_ce) por_sh <= {1'b0, por_sh[7:1]};
  end

  //=============================================================
  // v3.9.6 (п.21): ХАРДРЕНИНГ ЦЕПИ СБРОСА. Сырой пин RST входит в
  // кристалл ТОЛЬКО через 2FF-синхронизатор + квалификатор; решения
  // о сбросе принимают ТОЛЬКО регистры: мид-рейл/дребезг/помеха на
  // SW20 физически не доходят ни до 40 сбросовых входов триггеров,
  // ни до ноги RESET_IN (в v3.9.5 RST шёл НАПРЯМУЮ в гейт RESET_IN
  // и в PTC-сбросы NOT RESET_IN - fallback фита 11-5).
  //   rst_meta/rst_sync - синхронизатор (вне сброса, INIT=0);
  //   rst_qcnt/rst_press - квалификатор: переворот rst_press на 8-м
  //     такте ПОДРЯД устойчивого rst_sync != rst_press (двусторонний:
  //     и взвод, и снятие квалифицированы); дребезг короче 280 нс не
  //     виден вовсе, длиннее - полноценный повторный сброс (каждый
  //     взвод заново чистит все 40 триггеров - ПОСЛЕДНЕЕ снятие
  //     всегда из held-чистого состояния, регистровым фронтом);
  //   cpu_rst = rst_press | por_run - ТОЛЬКО регистровые источники;
  //   reset_q - РЕГИСТР выхода RESET_IN (INIT=0: CPU в сбросе с t=0
  //     до всякого клока; снятие - чистым фронтом, как по питанию).
  // Латентность кнопки: 11 тиков счёта (2FF + 8 такт квалификатора +
  // reset_q) = 400..440 нс от пина на взвод и снятие (кнопка живёт в
  // миллисекундах). POR НЕ ТРОНУТ: por_sh/
  // por_run бит-в-бит v3.9.4, низ RESET_IN по питанию до 1160 нс
  // (норма 840 нс, запас x1,35).
  //=============================================================
  reg  rst_meta  = 1'b0;         // ловец метастабильности (вне сброса, INIT=0)
  reg  rst_sync  = 1'b0;         // синхронизованный RST (вне сброса, INIT=0)
  reg  rst_press = 1'b0;         // квалифицированный сброс кнопки (INIT=0)
  reg [2:0] rst_qcnt = 3'b000;   // счётчик квалификации 0..7 (INIT=0)
  wire cpu_rst = rst_press | por_run; // v3.9.6: сброс ТОЛЬКО от регистров
  reg  reset_q = 1'b0;           // РЕГИСТР RESET_IN (INIT=0 - CPU держится с t=0)
  always @(posedge clk) begin   // v2.2: логика на clk 25 МГц (п.23/34)
    rst_meta <= RST;
    rst_sync <= rst_meta;
  end
  always @(posedge clk) begin   // v2.2: логика на clk 25 МГц (п.23/34)
    if (rst_sync != rst_press) begin
      if (&rst_qcnt) begin
        rst_press <= rst_sync;   // 8-й такт подряд - переворот состояния
        rst_qcnt  <= 3'b000;
      end else
        rst_qcnt  <= rst_qcnt + 3'b001;
    end else
      rst_qcnt  <= 3'b000;       // линия вернулась к состоянию - счёт с нуля
  end
  always @(posedge clk)       // v2.2: логика на clk 25 МГц (п.23/34)
    reset_q <= ~cpu_rst;         // снятие сброса CPU - всегда чистым фронтом

  //=============================================================
  // TX-транзит v3.7 (sod_q/tx_pass/tx_q) ВЫПИЛЕН (п.27, v2.0): передача
  // - аппаратный сериализатор TXUART (блок НИЖЕ, после объявлений
  // автомата шины: ядро декодирует state/S_T2/addr_latch - Verilog
  // требует объявления раньше использования, HDLCompilers:28 - класс
  // hwuart 11-4). Требование v3.7 «в сбросе TX='1' мгновенно и БЕЗ
  // клока» покрывает SET-ветка GSR ядра (INIT shreg=1FF, п.28);
  // «фиктивный start-bit» (SOD='0' после сброса) невозможен по
  // построению - линия TX не зависит от SOD вовсе (SOD - вход-
  // наблюдатель, п.27). GSR-источник v2.0 - cpu_rst (п.28): ядро
  // чистится и в окне POR (v1.0: GSR = сырой RST - POR не покрывал).
  //=============================================================

  //=============================================================
  // Автомат шины: 7 состояний = 3 триггера (v3; в v1 было 10/4 триггера -
  // WBW/WBS/WBS2 удалены: hold-off 0, см. п.4 шапки; WB1..WB4 ЗАЩИЩЕНЫ
  // от ALE)
  //=============================================================
  localparam S_IDLE = 3'd0,   // ожидание ALE; A/D в Hi-Z; /OE включён (декод)
             S_T1H  = 3'd1,   // T1: CPU держит адрес на A-сетях; идёт захват
             S_T2   = 3'd2,   // строб: чтение - выдача данных на A; запись - захват
             S_WB1  = 3'd3,   // WB: адрес на A + данные на D (t_AS 40 нс до /WE)
             S_WB2  = 3'd4,   // /WE=0 - импульс НАЧАЛСЯ: защищён от ALE
             S_WB3  = 3'd5,   // /WE=0 (импульс = 2 тика = 80 нс >= t_WP ОЗУ)
             S_WB4  = 3'd6;   // /WE=1: удержание адреса/данных (t_AH/t_DH памяти)

  // Task 46 / О-7 (v2.8.9): атрибут против ONE-HOT перекодировки
  // автомата XST ВКЛЮЧЁН (был закомментирован - ревью 11-16: one-hot
  // 7 состояний = 7 триггеров вместо 3 = +4 МЦ = 109 > 108, дизайн не
  // влезает; контроль по .rpt п.h остаётся: state_FSM_FFd4.. = БРАК).
  (* fsm_encoding = "compact" *) reg  [2:0] state  = S_IDLE;
  reg        rd_seen = 1'b0;    // строб чтения замечен в T2
  reg        wr_seen = 1'b0;    // строб записи замечен в T2

  // Захваченные шинные регистры
  reg [7:0] addr_latch = 8'h00;  // адрес с A-сетей (T1) - нужен writeback и декоду порта
  reg [7:0] bus_reg    = 8'h00;  // данные: чтение (с D-сети в T1) ИЛИ запись (с A-сети в T2)

  // Порты индикации/звука (§5): захват по записи в порт при IO/M#=1
  reg [6:0] seg_q = 7'h40;       // v2.8.9 (правка владельца 11-16): INIT=40 - горит
                                 // ТОЛЬКО сегмент g (бит 6) -> самотест «----»:
                                 // тире в КАЖДОМ разряде (все dig_q=1) до первой
                                 // записи fw в порты; 1 = сегмент горит
  reg [3:0] dig_q = 4'hF;        // v2.8.9 (правка владельца 11-16): INIT=F - все 4
                                 // разряда выбраны -> на индикаторе «----» (с
                                 // seg_q=40). ЦЕНА (осознана владельцем, см. шапку
                                 // О-2): сток ~68 мА через базы PNP (4 x ~17 мА
                                 // при R5/R10/R11/R12=240 Ом) в окне до первой
                                 // записи fw в 01h - это цена О-2, возвращённая
                                 // ради самотеста; НАГРУЗКА СЕГМЕНТОВ при этом в
                                 // 7 раз легче «8888» (4 сегмента, не 28).
                                 // 1 = цифра выбрана; выход инвертируется
  reg       snd_q = 1'b0;
  reg [3:0] kbcol_q = 4'h0;      // v2.9 Шаг-1: колонки = СТАРШИЙ НИББЛ A[7:4]
                                 // записи порта 06h (был отдельный порт 02h);
                                 // INIT 0000 = все выкл
  wire io_rd_kb = IOM & ~addr_latch[2] & addr_latch[1] & addr_latch[0]; // чтение 03h (KBROW)

  // Комбинационные группы (v3):
  //   wb_out = in_wb БЕЗ !ALE: драйверы A/D держат адреса/данные до конца
  //     защищённого импульса (п.4 шапки); снятие - при выходе в IDLE.
  //   rd_drive с !ALE - чтение как в v1 (мгновенный обрыв при новом цикле).
  // П-4 (v28.4): декод - ОДИН узел вместо ~16 схлопнутых копий
  // (8 A-строк + 5 D-драйверов + CS_n/OE_n-ветка): карманы ФБ открываются,
  // +2 МЦ -> 107 <= 108. Семантика не меняется (только именование).
  // wb_out = алиас in_wb - сливается в этот же узел; io_rd_kb/io_rd_st
  // сознательно БЕЗ keep (+2 МЦ = перебор 108).
  (* keep = "true" *) wire in_wb   = (state >= S_WB1);   // WB1..WB4: A/D драйвятся (П-4: узел)
  wire in_welo = (state == S_WB2) || (state == S_WB3);   // /WE низ
  wire wr_phase = (state >= S_T2);                       // T2..WB4: /OE памяти off
  wire wb_out   = in_wb;                                 // защищённый writeback-драйв
  (* keep = "true" *) wire rd_drive = (state == S_T2) && rd_seen && !RDn && !ALE; // A-пины отдают данные (П-4: узел)

  //=============================================================
  // TXUART v2.1 (п.27): ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ ПЕРЕДАТЧИК UART
  // (директива владельца 11-8веч: 144 нет - остаёмся на XC95108;
  // механика v1.0 (txclient v8/hwuart v4.0.1) СЖАТА 20 -> 18 МЦ:
  // shreg 9 бит сам-idle + bit_cnt 4 (1..10, idle=0) + baud_cnt 4 +
  // ld_tx_q; adv_q и tx_run свернуты - п.31).
  // OUT 04h = TXDATA: старт кадра 8N1 1 000 000 бод (clk 25 МГц / 25, v2.3).
  // IN 05h = статус: бит A1 = TXRDY (tx_idle = ~|bit_cnt), остальные
  // биты 0 (позиция бита - совместимость с hwuart v4.0.x).
  //   shreg[8:0]    9 МЦ - {данные, выход}: [0] -> TX (IO-MC, INIT=1 -
  //                 idle '1' до всякого клока, SET-ветка GSR);
  //                 загрузка по ld_tx_q: {A[7:0], 1'b0} с живых A-пинов
  //                 (CPU держит данные до подъёма WRn - запас >= 20
  //                 тиков); сдвиги вправо с инжекцией '1' - после кадра
  //                 shreg САМ приходит в все-'1' (idle по построению,
  //                 как shreg 9'h1FF txclient; ПАРАЛЛЕЛЬНЫХ ЗАГРУЗОК
  //                 IDLE НЕТ; сдвиг idle-регистра - НЕТ-ОП);
  //   bit_cnt[3:0]  4 МЦ - 1..10 = НОМЕР БИТ-ТАЙМА кадра (1 = старт,
  //                 2..9 = данные, 10 = стоп), 0 = idle; busy =
  //                 |bit_cnt - 1 ПТ/NOR; на 10-м сдвиге сам в 0 -
  //                 tx_run v2.0 свернут (TXRDY = ~|bit_cnt, 1 ПТ;
  //                 гейт io_wr_tx - 4 inline-литерала в тот же ПТ);
  //   baud_cnt[4:0] 5 МЦ - mod-25 СВОБОДНЫМ ХОДОМ: D = tick ? 0 : bc+1,
  //                 wrap ЯВНЫЙ (25 не степень двойки: компаратор == 24,
  //                 1 ПТ/5 вх, литерал ~tick входит в D всех 5 бит);
  //                 v2.2 был mod-16 (25/16 = 1 562 500 - вне сетки
  //                 CH340G -> мусор, урок железа 11-9);
  //                 baud_tick = (bc==24) - 1 ПТ/5 вх - тик сдвига;
  //   ld_tx_q       1 МЦ - РЕГИСТРОВЫЙ СТРОБ загрузки (п.30 = п.29
  //                 v2.0, БЕЗ ИЗМЕНЕНИЙ): декод io_wr_tx имеет
  //                 ЕДИНСТВЕННОГО потребителя; D-функция бита shreg =
  //                 3 ПТ/~6 вх {ld_tx_q, A[k], baud_tick, shreg[k+1],
  //                 shreg[k]} - все 9 бит в ОДНОМ ФБ (~25 вх <= 36).
  // ВЫПИЛЕНО против v2.0 (-2 МЦ): adv_q (хелпер тика: jam baud_cnt <= 0
  //                 вместо <= 1 даёт первый сдвиг на ТОТ ЖЕ фронт - лаг
  //                 adv_q 1 такт скомпенсирован, урок v8/hwuart
  //                 пересчитан; дифсим: сетка кадров 1-в-1) и tx_run
  //                 (кодировка bit_cnt 1..10 с idle=0: busy = |bit_cnt
  //                 - 1 ПТ; GSR-ветка bit_cnt - CLR, как v2.0).
  // Итого ядро: 19 МЦ (фит v2.3 = fit3: 103/108); узел v2.4: 5 -> 3 МЦ
  // (-2); ФИТ v2.4 (1:51PM): Successful, 101/108 - ровно прогноз, но
  // брак X2-D (печать XOR без NOT); ФИТ v2.5 (6:27PM): Successful,
  // 101/108, отчёт = фит v2.4 БАЙТ-В-БАЙТ (кроме даты) => D-форма
  // неаудитируема => v2.6: x2_q = T-триггер (T=t0_q, INIT=RESET);
  // ожидание фита v2.6: 101/108, ПТ ~338-339 (X2: 2 -> 0-1), резерв
  // под тик: 7 МЦ, 7 вх.ФБ (блок v2.6 шапки). ФИТ v2.6 (6:39PM):
  // Successful, 101/108, ПТ 339 (X2: 1 ПТ) - аудит 21/0 ШИТЬ, ЖЕЛЕЗО
  // ОК (11-14: противофаза X2, UART) => v2.7: ТИК вариант C (+6 МЦ =
  // 5 tick_cnt + tick_q, узел «ТИК»); ожидание фита v2.7: 107/108,
  // ПТ ~348-352, вх.ФБ ~210-215 (риск: если тик ляжет в ФБ без
  // baud_cnt - 7 внешних вх, до 215/216; лечить перекладкой узла),
  // резерв 1 МЦ.
  // ТАКТ ЯДРА - clk (25 МГц на входе, п.23/34), ЧАСТОТА такта 1-в-1
  // базе (clk25 базы = clk v2.2 = 25 МГц): бод = 25/25 = ровно 1 000 000 -
  // ТОЧНАЯ нижняя сетка CH340G (48М/48; 1 562 500 в сетке НЕТ - драйвер
  // молча 1,5 М, +4,17% = мусор, урок железа 11-9, шапка v2.3).
  //=============================================================
  localparam [4:0] BAUD_DIV = 5'd25;  // clk 25 МГц/25 = 1 000 000 бод 8N1 (сетка CH340G: 48М/48, ОШИБКА 0%);
                                      // 25 = 11001b - 5 бит; wrap ЯВНЫЙ (25 не степень двойки):
                                      // (== 24) ? 0 : +1 - компаратор 1 ПТ/5 вх; альтернативы:
                                      // 16 -> 1 562 500 (вне сетки CH340G - МУСОР, урок v2.2),
                                      // 27 -> 925 926 (к терминалу 921600 ошибка пары 0,47%),
                                      // 50 -> 500 000 (вдвое медленнее на том же счётчике)
  reg [8:0]  shreg    = 9'h1FF;  // [8:1] данные, [0] -> TX (IO-MC P39; INIT=1: idle до всякого клока)
  reg [3:0]  bit_cnt  = 4'd0;    // 1..10 = бит-тайм кадра (1=старт..10=стоп), 0 = idle; busy = |bit_cnt
  reg [4:0]  baud_cnt = 5'd0;    // mod-25 свободным ходом, wrap ЯВНЫЙ на тике; jam при загрузке
  reg        ld_tx_q = 1'b0;     // регистровый строб загрузки (п.30)
  // П-1 (v28.2): baud_tick - ИМЕНОВАННЫЙ УЗЕЛ с keep: ОДИН декод (== 24)
  // на ВСЕХ потребителей (baud_cnt wrap, shreg-сдвиг, tick_step). Без keep
  // XST разворачивает (baud_cnt == 24) в 5 литералов baud_cnt<0..4> в
  // D-пути КАЖДОГО потребителя: FB6 (+5 сетей в счётном разрешении
  // таймера), FB3/FB4 (строки shreg) - UIM-слоты ФБ выгорают (фит-сессии
  // 1-6: FB Inps 213-215/216). С keep: один 1-ПТ узел + 1 сеть на ФБ.
  (* keep = "true" *) wire baud_tick = (baud_cnt == (BAUD_DIV - 5'd1)); // == 24: тик каждые 25 тактов clk 25 МГц (П-1: ОДИН узел)
  wire tx_idle   = ~|bit_cnt;                                  // idle/TXRDY: 1 ПТ/4 вх (NOR) - inline в строб и статус
  // Старт кадра - ОДНОКРАТНЫЙ строб: первый тик !WRn в T2 записи порта 04h
  // (адрес защёлкнут в T1 - addr_latch стабилен, класс hwuart п.26).
  // Гейты: tx_idle && !ld_tx_q - повторные такты строба !WRn и запись при
  // busy БЛОКИРОВАНЫ (байт тихо отбрасывается, кадр не портится - контракт);
  // !por_run && !rst_press - шинные действия гейтятся ОБОИМИ источниками
  // сброса (класс п.21e; при GSR=cpu_rst FSM в окнах сброса и так в IDLE
  // - двойная страховка: floated-шина в окне POR/кнопки кадр не стартует)
  wire io_wr_tx = (state == S_T2) && !WRn && IOM
                  && addr_latch[2] && !addr_latch[1] && !addr_latch[0]  // порт 04h
                  && tx_idle && !ld_tx_q && !por_run && !rst_press;
  // Декод чтения статуса 05h - ЧИСТЫЙ (без state/!RDn - экономия литералов,
  // класс hwuart): статус живёт в A-драйве ниже (механизм KBROW, rd_drive)
  wire io_rd_st = IOM & addr_latch[2] & ~addr_latch[1] & addr_latch[0]; // чтение 05h
  always @(posedge clk or posedge cpu_rst) begin // п.27/п.34: асинхронный сброс ядра -> СЕТЬ GSR (cpu_rst = rst_press | por_run, п.20/21); такт clk 25 МГц
    if (cpu_rst) begin
      shreg    <= 9'h1FF;   // idle '1' (SET-ветка GSR)
      bit_cnt  <= 4'd0;     // idle (CLR-ветка - как v2.0)
      baud_cnt <= 5'd0;
      ld_tx_q  <= 1'b0;
    end else begin
      ld_tx_q  <= io_wr_tx;                    // строб загрузки - через регистр (п.30)
      baud_cnt <= baud_tick ? 5'd0 : baud_cnt + 5'd1; // mod-25: wrap ЯВНЫЙ на тике
                                               // (25 не степень двойки; jam при загрузке ниже перекрывает)
      if (ld_tx_q) begin
        // ЗАГРУЗКА (на тик позже строба io_wr_tx - п.30): байт с живых
        // A-пинов, старт-бит '0' на шине с этого такта; jam baud_cnt <= 0:
        // первый сдвиг ровно через 25 тиков - старт-бит РОВНО 25 тиков
        // (v2.0: jam 1 + лаг adv_q 1 такт = ТОТ ЖЕ фронт; дифсим v2.0
        // vs v2.1: сетка кадров 1-в-1); bit_cnt <= 1 (бит-тайм старта)
        shreg    <= {A, 1'b0};                 // [8:1] = данные (d7..d0), [0] = старт '0'
        bit_cnt  <= 4'd1;
        baud_cnt <= 5'd0;
      end else if (baud_tick) begin
        // ТИК СДВИГА (каждые 25 тактов clk 25 МГц; в idle сдвиг - НЕТ-ОП,
        // регистр уже весь '1'): инжекция '1' в MSB - на 9-м сдвиге
        // стоп сам встанет в [0] (бит-тайм 10), после кадра shreg ==
        // все-'1' (idle) без отдельных загрузок
        shreg <= {1'b1, shreg[8:1]};
      end
      if (|bit_cnt && baud_tick) begin
        // бит-тайм кадра кончился (сдвиг был): 1..9 -> ++, 10 (стоп
        // отработал) -> 0 = idle, TXRDY поднимается в конце стопа (тот
        // же тик, что !tx_run v2.0). НА ГРУЗКЕ НЕ РАБОТАЕТ: bit_cnt
        // (старое значение) = 0 - строб io_wr_tx возможен только в idle
        bit_cnt <= (bit_cnt == 4'd10) ? 4'd0 : bit_cnt + 4'd1;
      end
    end
  end

  //=============================================================
  // Шинный движок
  //=============================================================
  always @(posedge clk or posedge cpu_rst) begin // v3.9.6: сброс логики по cpu_rst = rst_press|por_run (регистры, п.21; асинхронная структура GSR п.18/20 сохранена); v2.2: такт логики clk 25 МГц (п.23/34)
    if (cpu_rst) begin
      state      <= S_IDLE;
      rd_seen    <= 1'b0;
      wr_seen    <= 1'b0;
      addr_latch <= 8'h00;
      bus_reg    <= 8'h00;
      seg_q      <= 7'h40;   // самотест «----» (правка владельца 11-16): только g;
                             // в POR/после кнопки RESET тире во всех 4 разрядах,
                             // пока fw не перехватит индикацию
      dig_q      <= 4'hF;   // самотест «----» (правка владельца 11-16): все 4
                            // разряда выбраны в сбросе/POR (возврат цены О-2,
                            // ~68 мА баз - осознанно, ради видимого самотеста)
      snd_q      <= 1'b0;
      kbcol_q    <= 4'h0;
    end else begin
      // --- захват повторным сэмплированием: последний сэмпл валиден ---
      // v3: захват возможен только в T1H, т.е. ПОСЛЕ завершения WB
      // (структурно: из WB в T1H попадаешь только через IDLE) - adm.
      // addr_latch НЕ может перезаписаться посреди импульса (п.6 шапки).
      if (state == S_T1H && ALE) begin
        addr_latch <= A;                 // адрес стабилен весь T1
        if (!IOM) bus_reg <= D;          // данные памяти (доступ начался в начале T1)
      end
      if (state == S_T2 && !WRn) begin
        bus_reg <= A;                    // данные записи (CPU держит до WR#(вверх))
        if (IOM) begin                   // запись в порт: декод по тройке A2,A1,A0 (Task 34)
          case (addr_latch[2:0])
            3'b000: seg_q <= A[6:0];     // 00h: сегменты (dp снят, T2)
            3'b001: begin                // 01h: разряды + SND
              dig_q <= A[3:0];
              snd_q <= A[4];
            end
            default: ;                   // 02h в v2.9 НЕМАПЛЕН (Шаг-1: колонки переехали
                                         // в старший ниббл записи 06h) - алиас Д-6;
                                         // 03h чтение; 04h - старт TX (ОДНОКРАТНЫЙ строб io_wr_tx
                                         // в ядре TXUART п.27, не здесь); 05h чтение статуса (io_rd_st);
                                         // 06h = ТАЙМЕР (загрузка tmr_cnt в своём always, узел «ТАЙМЕР»); 07h резерв
          endcase
        end
      end
      // --- трекинг стробов ---
      if (state == S_T2 && !RDn) rd_seen <= 1'b1;
      if (state == S_T2 && !WRn) wr_seen <= 1'b1;
      // --- переходы ---
      // v3: ALE ОБРЫВАЕТ только T2 (защита от глюка); в WB1..WB4 НЕ
      // вмешивается - импульс /WE защищён (п.4 шапки).
      if (ALE && state == S_T2 && !((wr_seen && WRn) || (rd_seen && RDn))) begin
        state   <= S_IDLE;
        rd_seen <= 1'b0;
        wr_seen <= 1'b0;
      end else begin
        case (state)
          S_IDLE: if (ALE) state <= S_T1H;
          S_T1H:  if (!ALE) state <= S_T2;
          S_T2: begin
            // приоритет записи: RDn-глюк во время записи не должен прерывать её
            if (wr_seen && WRn) begin
              wr_seen  <= 1'b0;
              // writeback только для записи в ОЗУ (8000-FFFF); запись в ПЗУ
              // отбрасывается (по железу /WE flash не подключён), порт пропускается
              // v3.9.3 (п.18): гейт POR - FSM в окне POR живой (GSR не
              // активен), шина CPU в сбросе «floated» (ВМ85А: управле-
              // ния/адрес/данные в 3-м состоянии) - вход в writeback
              // ЗАПРЕЩЁН, иначе плавающие ALE/WRn могли бы родить /WE
              state <= (!IOM && A15 && !por_run && !rst_press) ? S_WB1 : S_IDLE; // v3.9.6: гейт и на кнопку (п.21)
            end else if (rd_seen && RDn) begin
              rd_seen <= 1'b0;
              state <= S_IDLE;         // отпускание A-пинов через 1 тик после RD#(вверх)
            end
          end
          S_WB1: state <= S_WB2;       // t_AS 40 нс; hold-off 0 (см. п.4 шапки)
          S_WB2: state <= S_WB3;       // /WE низ - защищён, идёт до конца
          S_WB3: state <= S_WB4;
          S_WB4: state <= S_IDLE;      // импульс закончен, всё снято в IDLE
          default: state <= S_IDLE;
        endcase
      end
    end
  end

  //=============================================================
  // Тристейт-драйверы шины
  //=============================================================
  // Task 34: при чтении порта 03h A_I(0..4) = row0-4 (mux KBROW),
  // AD7-5 = 000. п.27 (TXUART): чтение 05h - статус {000000, TXRDY, 0}
  // (тот же механизм rd_drive/A-пины, класс hwuart); IN 04h НЕ определён
  // (RX нет - уходит в bus_reg, прошивкой не использовать).
  assign A = rd_drive ? (io_rd_kb ? {3'b000, row4, row3, row2, row1, row0}
                       : io_rd_st ? {6'b000000, tx_idle, 1'b0}
                                  : bus_reg)
            : wb_out   ? addr_latch : 8'bZZZZZZZZ;
  assign D = wb_out ? bus_reg : 8'bZZZZZZZZ;

  //=============================================================
  // Декод памяти минимальной ширины (§5): 1 терм на кристалл
  // v3.9.1 (п.16 шапки): /CE ОЗУ в writeback - ОТ СОСТОЯНИЯ FSM
  // (in_wb); защёлка wb_ram_q удалена - in_wb достижим только через
  // T2-запись в ОЗУ и уже влечёт её условие (эквивалентность v3.9
  // доказана: полный перебор состояний + дифсимуляция двух RTL).
  // Живой декод A15 во время конфликта адресов по-прежнему НЕ
  // участвует: в WB1..WB4 CS_n = 0 без A15/IOM - запись ОЗУ
  // защищена как в v3 (защита п.5 шапки сохранена построением).
  //=============================================================
  assign CSr_n = A15 | IOM;             // /CE_ROM = !( !A15 & !IOM )
  assign CS_n  = in_wb ? 1'b0 : (!A15 | IOM);   // v3.9.1: было (in_wb && wb_ram_q) ? ... (п.16)
  assign OEr_n = CSr_n | wr_phase;      // /OE гасится с T2 - данные уже захвачены,
  assign OE_n  = CS_n  | wr_phase;      // иначе SRAM воевала бы с CPLD на D в writeback
  // v3: /WE НЕ обрывается ALE - импульс доводится до конца (п.4 шапки);
  // безопасно: автомат доходит до WB4/IDLE за 5 тиков; сброс гасит импульс:
  // v3.9.2 - cpu_rst за такт (sync), v3.9.3 - GSR мгновенно (п.18);
  // v3.9.6 - импульс 80 нс квалификатор (400 нс) НЕ успевает оборвать:
  // начатая запись доводится до конца (полный t_WP ОЗУ), сброс гасит
  // драйвы сразу после её завершения (п.21f).
  assign WE_n  = !in_welo;
  assign CS1   = 1'b1;

  //=============================================================
  // ТИК (v2.7, вариант C): периодический NMI на CPU.TRAP (P74, нога 6).
  // ШАГ 4 мкс: tick_step = por_ce & baud_tick - совпадение ДВУХ уже
  // существующих свободных стробов (por_ce = ~t0_q & ~x1_q: 1 клк
  // каждые 4 клк = 160 нс; baud_tick: 1 клк каждые 25 клк = 1 мкс;
  // оба стартуют из INIT-нулей - фазы фиксированы конфигурацией):
  // ровно 1 клк на каждые LCM(4,25) = 100 клк = 4 мкс (первое - на
  // клке 74: 74 = 2 mod 4 = 24 mod 25).
  // СЧЁТЧИК tick_cnt[4:0] - свободный бинарный (32 шага x 4 мкс =
  // 128 мкс), CE = tick_step; в D-пути НЕТ декодов равенства
  // (урок п.9/фитов v2.4-v2.5: декоды теряют NOT - у тика ТОЛЬКО
  // литералы). ВЫХОД tick_q - ЗАЩЁЛКА-МУКС (И-ИЛИ 2 ПТ, 3 литерала,
  // БЕЗ XOR - печать с явными NOT, калибровано v2.5): на границе
  // шага (tick_step) сэмпл ЛИТЕРАЛА MSB tick_cnt[4], между шагами
  // - удержание: D = (tick_step & tick_cnt[4]) | (~tick_step &
  // tick_q). РЕЗУЛЬТАТ: квадрат 64/64 мкс, ФРОНТ каждые 128 мкс =
  // 7,8125 кГц. TRAP 8085A защёлкивает фронт (NMI, внутренняя
  // защёлка); high 64 мкс >> 2T CPU (640 нс), low 64 мкс -
  // перевзвода нет. Свободный ход: ветки сброса НЕТ (как у делителя
  // v2.4) - POR и кнопка RST тик не глушат (heartbeat ОС; фаза не
  // важна - NMI асинхронный). ЦЕНА: +6 МЦ = 5 (tick_cnt) + 1 (tick_q);
  // ожидание фита v2.7: 107/108, ПТ ~348-353, вх.ФБ ~210-215, резерв
  // 1 МЦ. ДЖИТТЕР (документировано): jam baud_cnt при загрузке TX
  // сдвигает фазу baud_tick -> ОДИН межшаговый интервал после каждой
  // загрузки краток/долог (до 2 шагов = 8 мкс), дальше сетка ровно
  // 100 клк; период тика в цикле с загрузкой 128 +/- 8 мкс (6%),
  // без загрузок - ровно 128 мкс. Для heartbeat ОС - допустимо;
  // безджиттерный вариант = собственный mod-25 делитель (+5 МЦ) -
  // вне бюджета варианта C.
  //=============================================================
  wire tick_step = por_ce & baud_tick;   // база таймера: 100 клк = 4 мкс (T3-трим: использовать напрямую)

  //=============================================================
  // v2.8: ПРОГРАММИРУЕМЫЙ ТАЙМЕР -> RST 7.5 (P75) - перенос
  // beta/01_timer v3.3b3 (лекарства v3.3b2 СОХРАНЕНЫ: тик и загрузка
  // стробируются в РЕГИСТРЫ, не схлопывать в D-путь счётчика;
  // RST75_r - NOR4 нуля в MC выхода P75, приёмникам 1 вход; П-3: 6 бит,
//  П-5 (v28.5): 4 бит).
  //=============================================================
  // П-3 (v28.3): tmr_cnt 8 -> 6 бит (-2 МЦ; фит-сессия 7: 109>108, перебор
  // 1 МЦ). Контракт: N <= 63 (4..252 мкс), RESET -> 3Fh (первый фронт
  // ~252 мкс); слот monitor27 = 2 фронтa (N=42/52 -> 336/416 мкс), ISR
  // действует на каждый 2-й (лишний вход ~3% ЦП; TMR_HW=0 ещё не включён).
  // П-5 (v28.5): tmr_cnt 6 -> 4 бита (-2 МЦ; фит-сессия 9: v28.4 не
  //  влезла). Контракт: N <= 15 (4..60 мкс), RESET -> 0Fh (первый фронт
  //  ~60 мкс); слот monitor27 = 6 фронтов (N=14 -> 56 мкс x 6 = 336 мкс,
  //  КАДР ТОТ ЖЕ 23.9 мс / 41.9 FPS, каденция CPU-независима), ISR /6
  //  (налог 19.4% ЦП @3.125 / 24.3% @2.5, было 6.5/8.2%). A[7:4]
  //  игнорируются. Шаг 4 мкс не тронут (бесплатен, см. шапку П-5).
  reg  [3:0] tmr_cnt = 4'hF;     // П-5: INIT 0F - первый фронт через ~60 мкс
  reg        RST75_r    = 1'b0;  // регистр нуля счётчика = уровень RST 7.5 (IO-MC P75)
  // T3/T4 (v28.1): tmr_tick_q/tmr_load_q СНЯТЫ (тримы 3-4 шапки; урок
  // v3.3b2 «строб в регистр» осознанно нарушен - фит-сессии 2-4 показали:
  // болезнь = насыщение UIM-слотов ФБ, а не ширина D-путей; -2 МЦ).
  // П-2 (v28.2): tmr_wr06 - ИМЕНОВАННЫЙ УЗЕЛ с keep (= $OpTx$FX_DC$91
  // фиттера, 1 ПТ / 8 входов, уже существует в FB2, но в биты tmr_cnt не
  // попал: XST разворачивал декод в D КАЖДОГО бита - tmr_cnt_D(0/1) =
  // 11-12 ПТ / 14-15 входов (state_FSM_FFd1..3 + addr_latch + IOM + WRn
  // в КАЖДОМ hold-члене) - биты не входят ни в один карман ФБ (FB6:
  // 18 св. ПТ < 11+12; FB1/FB3: 0 св. UIM). С keep: биты ссылаются на
  // ОДНУ сеть, D-мукс бита ~5 ПТ / ~7-8 входов.
  (* keep = "true" *) wire tmr_wr06 = (state == S_T2) && !WRn && IOM &&
                        (addr_latch[2:0] == 3'b110);       // OUT 06h: загрузка периода

  always @(posedge clk or posedge cpu_rst)   // Р-4 (v2.8.9): асинхронный сброс
    if (cpu_rst)               RST75_r <= 1'b0;               // RESET: RST75 = 0 (нет ложного фронта)
    // v2.8.8: УРОВЕНЬ до следующей загрузки (iron-баг П-5: импульс 40 нс
    // не ловился тактом CPU 320 нс - ISR на доле фронтов, фаза плыла).
    // Загрузка (tmr_wr06) сбрасывает уровень: след. фронт - через N x 4 мкс.
    // СТОП (OUT 06h,0): cnt=0 -> уровень встаёт на clk после загрузки
    // (защитный фронт) и держится до следующей загрузки.
    else if (tmr_wr06)         RST75_r <= 1'b0;
    else                       RST75_r <= (tmr_cnt == 4'h00) | RST75_r; // NOR4 нуля + hold

  always @(posedge clk or posedge cpu_rst) begin  // Р-4 (v2.8.9): как у всего ядра (GSR-структура; INIT 0Fh через PRE)
    if (cpu_rst)                    tmr_cnt <= 4'hF;         // RESET: 0F, RST75=0 (П-5)
    // T4: загрузка из ЖИВОЙ A-сети T2, тем же фронтом, что bus_reg <= A
    // (паттерн seg_q <= A с v3; из bus_reg было бы stale на такт)
    else if (tmr_wr06) begin        // Шаг-1 (v2.9): ОДНА загрузка на обе цели
              tmr_cnt <= A[3:0];    //   младший ниббл: N таймера (П-5: N <= 15)
              kbcol_q <= A[7:4];    //   старший ниббл: колонки клавиатуры (был порт 02h)
    end
    // T3 + О-3 (v2.8.9): гейт СЧЁТЧИКОМ (|tmr_cnt), не уровнем (!RST75_r):
    // счётчик сам останавливается в нуле, underflow 0->F при OUT 06h,0
    // закрыт по построению (модель ревью: 1 фаза из 100 давала 0->F на
    // клке после снятия tmr_wr06 - уровень маскировал, счётчик портился).
    // Бонус: RST75_r УШЁЛ из входов ФБ счётчика (-1 вход ФБ).
    else if (tick_step && |tmr_cnt) tmr_cnt <= tmr_cnt - 4'd1;
  end
  assign RST75 = RST75_r;

  //=============================================================
  // Поддержка CPU (§3, ред. Task 19) + TXUART (п.27): передача - аппаратный
  // сериализатор (OUT 04h, ядро выше); приём - программный (SID = RX, RIM 20h).
  // Держатели '0' (RST7.5/6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины (8 шт) заземлит фиттер (Ground on Unused IOs).
  // SID (P73) с Task 70-a - ВЫХОД CPLD (транзит RX); RST75 (P75) с v2.8
  // - ВЫХОД CPLD (таймер); TRAP (P74) с v2.8 СНЯТ из портов (тиковый
  // остров заменён таймером RST 7.5) -> PGND 8: {P74,P76,P78,P79,P81,
  // P95,P96,P98} (Н-8 п.c/п.h: «PGND 9 с P75» и «TRAP - выход тик» -
  // мёртвые строки v2.7-эпохи, вычищены).
  //=============================================================
  assign RESET_IN = reset_q;          // v3.9.6 (п.21): РЕГИСТР; активный 0 по даташиту: 0 = сброс CPU (кнопка после квалификатора или POR); INIT=0 - CPU держится с t=0; снятие - чистым регистровым фронтом
  assign READY = 1'b1;          // без wait-state - иначе вечные TW
  // Транзит RX -> SID (Task 70-a) сохранён; TX - ядро TXUART (п.27):
  assign SID = RX;              // приём:  CH340G.TXD (P38) -> CPU.SID (P73), RIM 20h
  assign TX  = shreg[0];        // передача: OUT 04h -> аппаратный передатчик TXUART (п.27);
                                // idle/стоп = '1' (INIT shreg=1FF, SET-ветка GSR):
                                // TX='1' до всякого клока и в сбросе (cpu_rst)

  //=============================================================
  // Индикация и звук: выходы инвертированы (общий анод, активный 0)
  //=============================================================
  assign seg = {1'b1, ~seg_q};   // О-1 (v2.8.9): dp (seg[7]) = '1' = ПОГАС навсегда.
                                 // БЫЛО 1'b0 - при активном-0 выходе (общий анод)
                                 // это ГОРИТ всегда на всех разрядах и не гасится
                                 // программно (порт 00h пишет только A[6:0]) -
                                 // класс «потеря инверсии» в исходнике.
                                 // ЖЕЛЕЗО: до первой записи в 00h - «8888» БЕЗ точек
  assign dig = ~dig_q;
  assign SND = snd_q;
  // Task 34: колонки клавиатуры - зарегистрированные выходы, прямые уровни
  // (активная колонка = 1, остальные 0; после сброса 0000 - безопасно)
  assign col0 = kbcol_q[0];
  assign col1 = kbcol_q[1];
  assign col2 = kbcol_q[2];
  assign col3 = kbcol_q[3];

endmodule