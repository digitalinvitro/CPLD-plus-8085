#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_v25.py - генератор txuart v2.5 из v2.4 (урок аудита фита v2.4).

ЕДИНСТВЕННОЕ ФУНКЦИОНАЛЬНОЕ ИЗМЕНЕНИЕ: D(x2_q) = ~(x1_q ^ t0_q) ->
ЯВНАЯ И-ИЛИ форма (x1_q & t0_q) | (~x1_q & ~t0_q). Функция ТА ЖЕ (XNOR,
2 ПТ), меняется ТОЛЬКО форма записи. Зачем: фит v2.4 (11-14 1:51PM,
Successful, 101/108) напечатал X2_D = t0_q XOR X1 БЕЗ NOT - таблица
истинности печати даёт X2 В ФАЗЕ с X1 (двухфазный такт разрушен).
Класс: «потеря инверсии» (прецеденты фит 7:31/8:55 с por-декодами).
И-ИЛИ форма печатается в калиброванном формате с явными NOT (проверено
на por_sh_T того же отчёта) -> следующий фит либо чист, либо аудит
(scripts/audit_fit_node.py - таблицей) опять ловит. Всё остальное -
БИТ-В-БИТ v2.4.

Порождает:
  top_txuart_por6_v25.v       (CP1251, канон для ISE)
  top_txuart_por6_v25_utf8.v  (UTF8-двойник)
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def rep1(text, old, new):
    n = text.count(old)
    if n != 1:
        raise SystemExit("ОШИБКА: шаблон встречен %d раз (ожидался 1):\n%r" % (n, old[:160]))
    return text.replace(old, new)


def main():
    src = io.open(os.path.join(ROOT, "top_txuart_por6_v24.v"), "rb").read().decode("cp1251")

    # --- 1. заголовок ---
    src = rep1(src,
"""// top_txuart.v v2.4 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 000 000 бод (такт ядра clk = 25 МГц / 25,
// BAUD_DIV=25 - явный wrap счётчика-делителя по (== 24), п.27)
// v2.4: узел тактирования - ДЕЛИТЕЛЬ владельца 3 FF (t0_q/x1_q/x2_q)
// вместо кольца one-hot s0..s3: -2 МЦ, X2 - регистровая точная
// противофаза, частота CPU НЕ изменена (период X1 = 160 нс, как был)""",
"""// top_txuart.v v2.5 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 000 000 бод (такт ядра clk = 25 МГц / 25,
// BAUD_DIV=25 - явный wrap счётчика-делителя по (== 24), п.27)
// v2.5: D(x2_q) - ЯВНАЯ И-ИЛИ форма (урок аудита фита v2.4: печатная
// XOR без NOT = X2 в фазе = БРАК, класс потери инверсии 7:31/8:55).
// Узел - делитель владельца 3 FF (t0_q/x1_q/x2_q), частота CPU 3,125 МГц""")

    # --- 2. блок v2.5 в шапке (перед блоком v2.4) ---
    src = rep1(src,
"""//
// v2.4 (директива владельца 11-14, УЗЕЛ ТАКТИРОВАНИЯ): кольцо one-hot""",
"""//
// v2.5 (урок АУДИТА ФИТА v2.4, 11-14 1:51PM): фит Successful, 101/108 -
// ровно прогноз (-2 МЦ); узел чист по всем статическим пунктам (3 FF,
// INIT (0,1,0): X1=SET/X2=RESET/t0=RESET, P68/P69 IO-MC FAST, строб
// ~X1&~t0_q свёрнут в D всех 8 бит por_sh, por_run.D=por_sh(0), SET;
// s0..s3/clk25_q/x1_n в нетлисте НЕТ; декодов равенства в узле НЕТ) -
// НО: печатное уравнение X2_D = t0_q XOR X1 БЕЗ NOT (RTL был XNOR
// ~(x1_q^t0_q)!). Таблица истинности ПЕЧАТИ: X2 В ФАЗЕ с X1 с первого
// фронта (INIT (0,1,0): e1 - t0:0->1, X1 hold 1 (T=t0_old=0), X2 <-
// 0^1 = 1 = X1) - двухфазный такт разрушен. КЛАСС: «потеря инверсии»,
// НЕ НОВЫЙ: фит 7:31 (por_cnt(0): T=NOT en -> POR=1 клок) и фит 8:55
// (por_run.D=(por_cnt==0)) - тот же класс; гейт п.9 («сверять
// ТАБЛИЦЕЙ, не полярностью одного терма») сработал как задуман.
// ЛЕКАРСТВО v2.5: D(x2_q) - ЯВНАЯ И-ИЛИ форма (x1_q & t0_q) |
// (~x1_q & ~t0_q): та же функция (XNOR, 2 ПТ), но печать попадает в
// КАЛИБРОВАННЫЙ И-ИЛИ формат (NOT печатаются явно - проверено на
// por_sh_T того же отчёта) -> следующий фит либо чисто печатается,
// либо аудит опять ловит. Аудитор: scripts/audit_fit_node.py -
// таблицей истинности печати, вердикт ШИТЬ/НЕ ШИТЬ (в fit4: 20 PASS /
// 1 FAIL - единственный FAIL = X2-D). BONUS: И-ИЛИ форма
// самовыравнивается из ЛЮБОГО кода (D не зависит от x2_q); T-форма
// (x2_q как FTCPE с T=t0_q) рассматривалась и ОТКЛОНЕНА: держится на
// инварианте, а не на D-функции. РЕЗЕРВ ПОСЛЕ ФИТА v2.4: 108-101 = 7
// МЦ, вх.ФБ 216-209 = 7, ПТ ~200 - тик (TRAP) влезает: вариант C
// (5 бит + CE-МЦ = +6 МЦ) с запасом, вариант A (7 МЦ) ровно впритык;
// решение - после ЧИСТОГО фита v2.5.
//
// v2.4 (директива владельца 11-14, УЗЕЛ ТАКТИРОВАНИЯ): кольцо one-hot""")

    # --- 3. код: единственная строка always ---
    src = rep1(src,
"        x2_q <= ~(x1_q ^ t0_q);    // будущий ~x1_q - противофаза без лага",
"""        x2_q <= (x1_q & t0_q) | (~x1_q & ~t0_q); // XNOR И-ИЛИ (v2.5, урок
                          // fit4: ~(x1^t0) печаталась XOR без NOT = в фазе
                          // = БРАК; И-ИЛИ печать - с явными NOT, аудит п.9)""")

    # --- 4. комментарий объявления x2_q ---
    src = rep1(src,
"""  reg x2_q = 1'b0;   // ПРОТИВОФАЗА-РЕГИСТР (п.10 в ред. v2.4):
                     // D = ~(x1_q ^ t0_q) = БУДУЩИЙ комплемент x1_q
                     // (x1_q(t+1) = x1_q(t) ^ t0_q(t)) -> x2_q(t) =
                     // ~x1_q(t) В КАЖДЫЙ такт БЕЗ лага; D структурно
                     // комплементарен D(x1_q) - same-D слияние невозможно
                     // по построению; ОДНОЛИТЕРАЛЬНАЯ D(x2)=~x1_q в .rpt
                     // = БРАК (лаг 40 нс, класс v3.4 - CPU не стартует).""",
"""  reg x2_q = 1'b0;   // ПРОТИВОФАЗА-РЕГИСТР (п.10 в ред. v2.4/2.5):
                     // D = (x1_q & t0_q) | (~x1_q & ~t0_q) = XNOR =
                     // БУДУЩИЙ комплемент x1_q (x1_q(t+1) = x1_q(t)^t0_q(t))
                     // -> x2_q(t) = ~x1_q(t) В КАЖДЫЙ такт БЕЗ лага.
                     // ФОРМА И-ИЛИ ОБЯЗАТЕЛЬНА (урок фита v2.4: запись
                     // ~(x1^t0) фиттер напечатал XOR БЕЗ NOT = X2 в фазе
                     // = БРАК; И-ИЛИ печать - с явными NOT, калибровано).
                     // D структурно комплементарен D(x1_q) - same-D
                     // слияние невозможно; однолитеральная ~x1_q = БРАК.""")

    # --- 5. комментарий в теле generate ---
    src = rep1(src,
"""      //   x2_q <= ~(x1_q ^ t0_q);   регистровая точная противофаза:
      //     D = БУДУЩИЙ комплемент x1_q - противофаза БЕЗ лага; БРАК
      //     п.10 в ред. v2.4 = D(x2_q) ОДНОЛИТЕРАЛЬНАЯ ~x1_q (регистр
      //     С ЛАГОМ, сэмплирующий ТЕКУЩИЙ комплемент - класс v3.4);""",
"""      //   x2_q <= (x1_q & t0_q) | (~x1_q & ~t0_q);
      //                             регистровая точная противофаза:
      //     D = XNOR в ЯВНОЙ И-ИЛИ форме = БУДУЩИЙ комплемент x1_q -
      //     противофаза БЕЗ лага; форма И-ИЛИ обязательна (урок фита
      //     v2.4: ~(x1^t0) напечатана XOR без NOT = в фазе = БРАК,
      //     класс потери инверсии 7:31/8:55); БРАК п.10 = D(x2_q)
      //     однолитеральная ~x1_q (лаг) ИЛИ печатный XOR без NOT (в
      //     фазе);""")

    # --- 6. чек-лист h) ---
    src = rep1(src,
"""//       x2_q.D = t0_q AND x1_q OR NOT t0_q AND NOT x1_q  (2 птерма,
//              XNOR = БУДУЩИЙ ~x1_q; ОДНОЛИТЕРАЛЬНАЯ NOT x1_q = БРАК -
//              регистр с лагом 40 нс, класс v3.4/п.10 в ред. v2.4);""",
"""//       x2_q.D = t0_q AND x1_q OR NOT t0_q AND NOT x1_q  (2 птерма,
//              XNOR = БУДУЩИЙ ~x1_q; ФОРМА И-ИЛИ ОБЯЗАТЕЛЬНА: урок
//              фита v2.4 - RTL XNOR напечатан XOR БЕЗ NOT = X2 в фазе
//              = БРАК (класс потери инверсии 7:31/8:55); печатная
//              XOR-форма без NOT = НЕ ШИТЬ; однолитеральная NOT x1_q
//              = БРАК - лаг 40 нс, класс v3.4);""")

    # --- 7. бюджет ---
    src = rep1(src,
"""  // Итого ядро: 19 МЦ (v2.3: baud_cnt +1 бит = +1 МЦ к 18 v2.2; фит
  // v2.3 = fit3 лёг ровно в 103/108, контрольный ре-фит 11-14 -
  // байт-в-байт); узел v2.4: 5 -> 3 МЦ (-2) => прогноз фита v2.4:
  // 103 - 2 = 101 наивно, ожидание 100-102/108 XC95108 (прецедент
  // v1.0/v2.3 -1..-2; резерв под тик 6-8 МЦ - блок v2.4 шапки).""",
"""  // Итого ядро: 19 МЦ (фит v2.3 = fit3: 103/108, контрольный ре-фит
  // 11-14 - байт-в-байт); узел v2.4: 5 -> 3 МЦ (-2); ФИТ v2.4 (11-14
  // 1:51PM): Successful, 101/108 - РОВНО прогноз (-2 МЦ), но брак
  // X2-D (печать XOR без NOT, шапка v2.5) => v2.5: логика та же,
  // D(x2_q) в И-ИЛИ форме; ожидание фита v2.5: те же 100-102/108
  // (резерв под тик: 7 МЦ, 7 вх.ФБ - блок v2.5 шапки).""")

    # --- контроль: в КОДЕ не осталось XOR-записи x2_q ---
    code = "\n".join((l.split("//")[0] if "//" in l else l) for l in src.split("\n"))
    if "x2_q <= ~(x1_q ^ t0_q)" in code:
        raise SystemExit("ОШИБКА: XOR-запись D(x2_q) осталась в коде")
    if "(x1_q & t0_q) | (~x1_q & ~t0_q)" not in code:
        raise SystemExit("ОШИБКА: И-ИЛИ форма D(x2_q) не внесена")

    # --- запись CP1251-канона и UTF8-двойника ---
    raw = src.encode("cp1251")
    io.open(os.path.join(ROOT, "top_txuart_por6_v25.v"), "wb").write(raw)
    io.open(os.path.join(ROOT, "top_txuart_por6_v25_utf8.v"), "w", encoding="utf-8").write(src)
    print("v2.5 записан: %d строк, %d байт (CP1251)" % (src.count("\n") + 1, len(raw)))


if __name__ == "__main__":
    main()
