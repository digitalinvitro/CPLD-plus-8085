rep(
"""            default: ;                   // 03h чтение; 04h-07h резерв (UART удалён, Task 69)
""",
"""            default: ;                   // 03h чтение; 04h - старт TX (ОДНОКРАТНЫЙ строб io_wr_tx
                                         // в ядре TXUART п.26, не здесь); 05h-07h резерв
""",
"E8a")

