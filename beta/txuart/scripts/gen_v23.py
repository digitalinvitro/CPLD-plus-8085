#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_v23.py - генератор txuart v2.3 из v2.2 (урок железа 11-9).

ЕДИНСТВЕННОЕ ФУНКЦИОНАЛЬНОЕ ИЗМЕНЕНИЕ: бод 25/16 = 1 562 500 -> 25/25 =
ровно 1 000 000 (сетка CH340G 48М/48, ошибка 0%; 1 562 500 в сетке CH340
НЕТ - драйвер молча ставит 1 500 000, +4,17% -> мусор в терминале).
baud_cnt 4 -> 5 бит, wrap ЯВНЫЙ (== 24) -> 0. Всё остальное (узел /4,
POR, FSM, порты, контракт) - БИТ-В-БИТ v2.2.

Порождает:
  top_txuart_por6_v23.v       (CP1251, канон для ISE)
  top_txuart_por6_v23_utf8.v  (UTF8-двойник для iverilog/чтения)
  tb_txuart_v23.v             (BITNS 640 -> 1000)
  scripts/run_tb_v23.sh
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def rep1(text, old, new):
    n = text.count(old)
    if n != 1:
        raise SystemExit("ОШИБКА: шаблон встречен %d раз (ожидался 1):\n%r" % (n, old[:120]))
    return text.replace(old, new)


def main():
    src = io.open(os.path.join(ROOT, "top_txuart_por6_v22.v"), "rb").read().decode("cp1251")

    # --- 1. заголовок (название/бод/делитель) ---
    src = rep1(src,
"""// top_txuart.v v2.2 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 562 500 бод (такт ядра clk = 25 МГц / 2^4,
// BAUD_DIV=16 - натуральный wrap счётчика-делителя БЕЗ декода, п.27)""",
"""// top_txuart.v v2.3 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 000 000 бод (такт ядра clk = 25 МГц / 25,
// BAUD_DIV=25 - явный wrap счётчика-делителя по (== 24), п.27)""")

    # --- 2. блок урока железа после строки про RST/регистры ---
    src = rep1(src,
"""// RST только через регистры, п.21
//
// ЛИНИЯ beta/txuart, ВЕРСИЯ 2.2""",
"""// RST только через регистры, п.21
//
// v2.3 (11-9, УРОК ПЕРВОГО ЖЕЛЕЗНОГО ПРОГОНА v2.2): терминал - МУСОР.
// Байтовая статистика дампа (1143 байта против эталона
// «TXUART v2.2 OK N=xx»): биты 0-6 ВСЕГДА точны, старший бит = '1'
// в ~половине байтов ('2'=0x32 -> 0xB2, '.'=0x2E -> 0xAE, '='=0x3D ->
// 0xBD, CR 0x0D -> 0x8D, LF 0x0A -> 0x8A), прочие байты точны.
// ДИАГНОЗ: TX-путь 1-в-1 (все байты опознаны - CPLD/прошивка ОК!),
// приёмник CH340G получил НЕ 1 562 500: сетка CH340G = 48 МГц/(2^k x m);
// 1 562 500 = 12 МГц/7,68 в сетке НЕ СУЩЕСТВУЕТ (даташит WCH:
// ...921600, 1500000, 2000000); драйвер МОЛЧА ставит 1 500 000
// (Linux ch341.c: div = 48М/(4х1562500) = 7.68 -> div 4, fact 0 =
// 48М/32 = ровно 1 500 000). Систематика +4,17%: семпл бита 7 в 93 нс
// от границы данных/стоп при дрожании квантования внутреннего 12 МГц
// (+-83 нс) - монетка: бит 7 = стоп '1' в ~половине кадров.
// ЛЕКАРСТВО: бод = 25 МГц/25 = РОВНО 1 000 000 - точная сетка ЛЮБОГО
// моста (12/24/30/48 МГц делятся на 1М нацело). Терминал 1 000 000 8N1.
// Цена: baud_cnt 4 -> 5 бит (+1 МЦ; ожидание фита 104/108); FW, узел,
// CPU, пор-цепь, контракт - БЕЗ ИЗМЕНЕНИЙ (кадр 10 мкс = 31 T, поллинг
// 27-90 T - тем более безопасен).
//
// ЛИНИЯ beta/txuart, ВЕРСИЯ 2.3 (история: v2.2 - директива владельца 11-9:""")

    # --- 3. п.28 спека ---
    src = rep1(src,
"""// п.28 СПЕКА (= v2.0 п.27; v2.2: такт clk): TX-only 8N1, бод = clk
//   (25 МГц) / 2^4 =
//   1 562 500 (BAUD_DIV=16 - СТЕПЕНЬ ДВОЙКИ: счётчик-делитель -
//   свободный двоичный mod-16, wrap натуральный БЕЗ декода
//   терминального счёта и сбросовой логики - «удобный для счетчиков
//   делителей бод рейтинг» по директиве 11-8; CH340G до 2 Мбит,
//   проверен владельцем на 1,92 М). Доступ CPU: OUT 04h = TXDATA""",
"""// п.28 СПЕКА (= v2.0 п.27; v2.2: такт clk; v2.3: бод 1М): TX-only 8N1,
//   бод = clk (25 МГц) / 25 =
//   1 000 000 (BAUD_DIV=25: счётчик-делитель - свободный двоичный
//   mod-25, wrap ЯВНЫЙ по (== 24): один компаратор 1 ПТ/5 вх в
//   D-функциях счётчика. 1М = ТОЧНАЯ сетка CH340G: 48 МГц/48 = 12 МГц/12,
//   ОШИБКА 0%; старый 25/16 = 1 562 500 в сетке НЕ ЛЕЖАЛ - драйвер
//   молча ставил 1,5 М (+4,17% = мусор, урок железа 11-9, шапка v2.3)).
//   Доступ CPU: OUT 04h = TXDATA""")

    src = rep1(src,
"""//   Такт ядра - clk (25 МГц, такт ЛОГИКИ п.23/34): бод на плате = РОВНО
//   1 562 500 - 2х-блокер фита v1.0 (3,125 М) снят ПО СТРОЕНИЮ.""",
"""//   Такт ядра - clk (25 МГц, такт ЛОГИКИ п.23/34): бод на плате = РОВНО
//   1 000 000 - и СТОЛЬКО ЖЕ у моста (кварц моста 12/24/30/48 МГц -
//   все делятся на 1М нацело, рассогласование 0 ПО СТРОЕНИЮ).""")

    # --- 4. п.34 история ---
    src = rep1(src,
"""//   логика на clk 25 МГц (такт логики 1-в-1 базе), ядро бит-в-бит
//   v2.1 (18 МЦ, бод = 25/16 = 1 562 500).""",
"""//   логика на clk 25 МГц (такт логики 1-в-1 базе), ядро v2.1 (18 МЦ),
//   v2.3: бод 25/16 -> 25/25 = 1 000 000 (урок CH340G, шапка).""")

    src = rep1(src,
"""//   3) бод TX 1 562 500 НЕ ИЗМЕНИЛСЯ (25/16 = 50/32; та же сетка
//      16 тиков x 40 нс = 640 нс/бит) - терминал/контракт те же;""",
"""//   3) бод TX В v2.3 ИЗМЕНЁН: 1 562 500 (25/16) -> 1 000 000 (25/25) -
//      терминал теперь 1 000 000 8N1 (сетка CH340G, 0% ошибки);""")

    src = rep1(src,
"""//  4) терминал 1 562 500 8N1 (такт ядра clk 25 МГц / 16), тест""",
"""//  4) терминал 1 000 000 8N1 (такт ядра clk 25 МГц / 25), тест""")

    # --- 5. блок ядра: заголовок порта ---
    src = rep1(src,
"""// OUT 04h = TXDATA: старт кадра 8N1 1 562 500 бод (clk 25 МГц / 2^4, v2.2).""",
"""// OUT 04h = TXDATA: старт кадра 8N1 1 000 000 бод (clk 25 МГц / 25, v2.3).""")

    # --- 6. МЦ-учёт baud_cnt ---
    src = rep1(src,
"""  //   baud_cnt[3:0] 4 МЦ - mod-16 СВОБОДНЫМ ХОДОМ: D = bc+1, wrap
  //                 НАТУРАЛЬНЫЙ (1111->0000) - декода терминального
  //                 счёта и сбросовой логики в D-функциях счётчика НЕТ
  //                 («удобный для счетчиков делителей бод рейтинг» -
  //                 директива владельца); baud_tick = (bc==15) -
  //                 1 ПТ/4 вх - тик сдвига;""",
"""  //   baud_cnt[4:0] 5 МЦ - mod-25 СВОБОДНЫМ ХОДОМ: D = tick ? 0 : bc+1,
  //                 wrap ЯВНЫЙ (25 не степень двойки: компаратор == 24,
  //                 1 ПТ/5 вх, литерал ~tick входит в D всех 5 бит);
  //                 v2.2 был mod-16 (25/16 = 1 562 500 - вне сетки
  //                 CH340G -> мусор, урок железа 11-9);
  //                 baud_tick = (bc==24) - 1 ПТ/5 вх - тик сдвига;""")

    # --- 7. бюджет ---
    src = rep1(src,
"""  // Итого ядро: 18 МЦ; минус TX-транзит v3.7 -3 => прогноз фита на
  // базе v3.9.8-clear с узлом v2.2 (94 - 3 узел - 1 clk25_q):
  // 94 - 3 (транзит) - 4 (узел + clk25_q) + 18 = 105 наивно, по
  // прецеденту v1.0 (-2) ожидание 101-103/108 XC95108 (п.31/п.34;
  // резерв п.33).""",
"""  // Итого ядро: 19 МЦ (v2.3: baud_cnt +1 бит = +1 МЦ к 18 v2.2; фит
  // v2.2 лёг ровно в 103/108); минус TX-транзит v3.7 -3 => прогноз
  // фита v2.3: 103 + 1 = 104 наивно, ожидание 103-105/108 XC95108
  // (п.31/п.34; резерв п.33).""")

    # --- 8. такт ядра ---
    src = rep1(src,
"""  // ТАКТ ЯДРА - clk (25 МГц на входе, п.23/34), ЧАСТОТА такта 1-в-1
  // базе (clk25 базы = clk v2.2 = 25 МГц): бод = 25/16 = ровно 1 562 500 -
  // 2х-блокер фита v1.0 (ядро на clk 50 МГц давало 3,125 М) снят ПО
  // СТРОЕНИЮ, фикс v1.1 mod-32 не нужен.""",
"""  // ТАКТ ЯДРА - clk (25 МГц на входе, п.23/34), ЧАСТОТА такта 1-в-1
  // базе (clk25 базы = clk v2.2 = 25 МГц): бод = 25/25 = ровно 1 000 000 -
  // ТОЧНАЯ нижняя сетка CH340G (48М/48; 1 562 500 в сетке НЕТ - драйвер
  // молча 1,5 М, +4,17% = мусор, урок железа 11-9, шапка v2.3).""")

    # --- 9. localparam ---
    src = rep1(src,
"""  localparam [4:0] BAUD_DIV = 5'd16;  // clk 25 МГц/16 = 1 562 500 бод 8N1 (CH340G до 2 Мбит, проверен на 1,92 М);
                                      // 5 бит - 16 не помещается в 4 (класс-урок: 4'd16 усёкся бы в 0);
                                      // степень двойки - wrap натуральный; альтернативы:
                                      // 8 -> 3 125 000 (вне диапазона CH340G), 32 -> 781 250,
                                      // 64 -> 390 625 (медленнее при том же ресурсе счётчика)""",
"""  localparam [4:0] BAUD_DIV = 5'd25;  // clk 25 МГц/25 = 1 000 000 бод 8N1 (сетка CH340G: 48М/48, ОШИБКА 0%);
                                      // 25 = 11001b - 5 бит; wrap ЯВНЫЙ (25 не степень двойки):
                                      // (== 24) ? 0 : +1 - компаратор 1 ПТ/5 вх; альтернативы:
                                      // 16 -> 1 562 500 (вне сетки CH340G - МУСОР, урок v2.2),
                                      // 27 -> 925 926 (к терминалу 921600 ошибка пары 0,47%),
                                      // 50 -> 500 000 (вдвое медленнее на том же счётчике)""")

    # --- 10. reg baud_cnt ---
    src = rep1(src,
"""  reg [3:0]  baud_cnt = 4'd0;    // mod-16 свободным ходом, wrap натуральный; jam при загрузке""",
"""  reg [4:0]  baud_cnt = 5'd0;    // mod-25 свободным ходом, wrap ЯВНЫЙ на тике; jam при загрузке""")

    # --- 11. baud_tick ---
    src = rep1(src,
"""  wire baud_tick = (baud_cnt == (BAUD_DIV - 5'd1));            // == 15: тик каждые 16 тактов clk 25 МГц""",
"""  wire baud_tick = (baud_cnt == (BAUD_DIV - 5'd1));            // == 24: тик каждые 25 тактов clk 25 МГц""")

    # --- 12. GSR-ветка ---
    src = rep1(src,
"""      bit_cnt  <= 4'd0;     // idle (CLR-ветка - как v2.0)
      baud_cnt <= 4'd0;""",
"""      bit_cnt  <= 4'd0;     // idle (CLR-ветка - как v2.0)
      baud_cnt <= 5'd0;""")

    # --- 13. счётчик: свободный ход с явным wrap ---
    src = rep1(src,
"""      baud_cnt <= baud_cnt + 4'd1;             // mod-16 СВОБОДНЫЙ ход: wrap натуральный,
                                               // декодов/сбросовой логики НЕТ (jam ниже перекрывает)""",
"""      baud_cnt <= baud_tick ? 5'd0 : baud_cnt + 5'd1; // mod-25: wrap ЯВНЫЙ на тике
                                               // (25 не степень двойки; jam при загрузке ниже перекрывает)""")

    # --- 14. комментарии загрузки/тика ---
    src = rep1(src,
"""        // первый сдвиг ровно через 16 тиков - старт-бит РОВНО 16 тиков""",
"""        // первый сдвиг ровно через 25 тиков - старт-бит РОВНО 25 тиков""")
    src = rep1(src,
"""        baud_cnt <= 4'd0;
      end else if (baud_tick) begin""",
"""        baud_cnt <= 5'd0;
      end else if (baud_tick) begin""")
    src = rep1(src,
"""        // ТИК СДВИГА (каждые 16 тактов clk 25 МГц; в idle сдвиг - НЕТ-ОП,""",
"""        // ТИК СДВИГА (каждые 25 тактов clk 25 МГц; в idle сдвиг - НЕТ-ОП,""")

    # --- контроль: не осталось "живых" упоминаний старого бода ---
    leftovers = []
    for i, l in enumerate(src.split("\n"), 1):
        if ("1 562 500" in l or "1562500" in l or "mod-16" in l or "25/16" in l):
            leftovers.append((i, l.strip()[:90]))
    if leftovers:
        print("ОСТАЛИСЬ упоминания (должны быть только исторические):")
        for i, l in leftovers:
            print("  %4d| %s" % (i, l))

    # --- запись CP1251-канона и UTF8-двойника ---
    raw = src.encode("cp1251")
    io.open(os.path.join(ROOT, "top_txuart_por6_v23.v"), "wb").write(raw)
    io.open(os.path.join(ROOT, "top_txuart_por6_v23_utf8.v"), "w", encoding="utf-8").write(src)
    print("v2.3 записан: %d строк, %d байт (CP1251)" % (src.count("\n") + 1, len(raw)))

    # --- tb: BITNS 640 -> 1000 ---
    tb = io.open(os.path.join(ROOT, "tb_txuart_v22.v"), "r", encoding="utf-8").read()
    tb = tb.replace("tb_txuart_v22.v - testbench for txuart v2.2 (beta/txuart).",
                    "tb_txuart_v23.v - testbench for txuart v2.3 (beta/txuart).")
    tb = tb.replace("""//    (POR = 8 x 160 = 1280 ns), TXUART core BIT-FOR-BIT v2.1 (18 MCs,
//    baud = 25/16 = 1562500 exactly, bit = 640 ns);""",
                    """//    (POR = 8 x 160 = 1280 ns), TXUART core v2.3 (19 MCs,
//    baud = 25/25 = 1000000 exactly, bit = 1000 ns - the EXACT CH340G
//    grid point 48MHz/48; 1562500 is NOT in the CH340 grid - the
//    driver silently picks 1500000, +4.17% = garbage, hw lesson 11-9);""")
    tb = tb.replace("frame grid 640 ns,", "frame grid 1000 ns,")
    tb = tb.replace("bash scripts/run_tb_v22.sh", "bash scripts/run_tb_v23.sh")
    tb = tb.replace("iverilog -g2001 -o tb_txuart.vvp tb_txuart_v22.v top_txuart_por6_v22_utf8.v",
                    "iverilog -g2001 -o tb_txuart.vvp tb_txuart_v23.v top_txuart_por6_v23_utf8.v")
    tb = tb.replace("  localparam BITNS = 640;     // 16 ticks of clk (40 ns) = 640 ns = 1562500 baud",
                    "  localparam BITNS = 1000;    // 25 ticks of clk (40 ns) = 1000 ns = 1000000 baud")
    tb = tb.replace('"C2(55): start bit exactly 640 ns (16 ticks of clk 25 MHz)"',
                    '"C2(55): start bit exactly 1000 ns (25 ticks of clk 25 MHz)"')
    tb = tb.replace("// ---- C2: TX frame 0x55, bit grid = 640 ns ----",
                    "// ---- C2: TX frame 0x55, bit grid = 1000 ns ----")
    tb = tb.replace("// still be running (6.4 us), a single poll would see TXRDY=0",
                    "// still be running (10 us), a single poll would see TXRDY=0")
    for pat in ("640", "1562500", "v22"):
        if pat in tb:
            print("tb: ОСТАЛОСЬ %r:" % pat)
            for i, l in enumerate(tb.split("\n"), 1):
                if pat in l:
                    print("  %4d| %s" % (i, l.strip()[:100]))
    io.open(os.path.join(ROOT, "tb_txuart_v23.v"), "w", encoding="utf-8").write(tb)
    print("tb_v23 записан")

    # --- runner ---
    sh = io.open(os.path.join(ROOT, "scripts", "run_tb_v22.sh"), "r", encoding="utf-8").read()
    sh = sh.replace("v22", "v23")
    io.open(os.path.join(ROOT, "scripts", "run_tb_v23.sh"), "w", encoding="utf-8").write(sh)
    print("run_tb_v23.sh записан")


if __name__ == "__main__":
    main()
