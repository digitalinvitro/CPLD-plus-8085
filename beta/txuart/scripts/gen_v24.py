ROOT = os.path.dirname(HERE)


def rep1(text, old, new):
    n = text.count(old)
    if n != 1:
        raise SystemExit("ОШИБКА: шаблон встречен %d раз (ожидался 1):\n%r" % (n, old[:160]))
    return text.replace(old, new)


