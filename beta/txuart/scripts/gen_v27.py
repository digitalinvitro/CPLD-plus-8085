#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_v27.py - генератор txuart v2.7 из v2.6: ТИК на TRAP (вариант C).

ЖЕЛЕЗНЫЙ ОК v2.6 получен (11-14: противофаза X2 осциллографом, UART
работает). Директива владельца: «собирай 2.7» - тик (TRAP), вариант C
(«5 бит + CE-МЦ = +6 МЦ», 128 мкс - записан в шапках v2.4/v2.6).

РЕШЕНИЕ (без новых МЦ на генерацию шага):
  tick_step = por_ce & baud_tick - совпадение двух СУЩЕСТВУЮЩИХ
  свободных стробов (por_ce 1 клк/4, baud_tick 1 клк/25, оба
  INIT-фиксированы) = 1 клк каждые LCM(4,25)=100 клк = 4 мкс.
  tick_cnt[4:0] - свободный бинарный счётчик (CE = tick_step), цикл
  32 шага = 128 мкс; в D-пути НЕТ декодов равенства (урок п.9).
  tick_q - D = tick_step & tick_cnt[4] (литерал MSB): квадрат
  64/64 мкс, фронт каждые 128 мкс. TRAP = tick_q (P74, был PGND).
  ЦЕНА: +6 МЦ (5+1). Ожидание фита: 107/108.

Порождает:
  top_txuart_por6_v27.v       (CP1251, канон для ISE)
  top_txuart_por6_v27_utf8.v  (UTF8-двойник)
  + патч UCF: NET "TRAP" LOC = "P74", держатели 9 -> 8.
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def rep1(text, old, new, what=""):
    n = text.count(old)
    if n != 1:
        raise SystemExit("ОШИБКА (%s): шаблон встречен %d раз (ожидался 1):\n%r" % (what, n, old[:160]))
    return text.replace(old, new)


TICK_NODE = """  //=============================================================
  // ТИК (v2.7, вариант C): периодический NMI на CPU.TRAP (P74, нога 6).
  // ШАГ 4 мкс: tick_step = por_ce & baud_tick - совпадение ДВУХ уже
  // существующих свободных стробов (por_ce = ~t0_q & ~x1_q: 1 клк
  // каждые 4 клк = 160 нс; baud_tick: 1 клк каждые 25 клк = 1 мкс;
  // оба стартуют из INIT-нулей - фазы фиксированы конфигурацией):
  // ровно 1 клк на каждые LCM(4,25) = 100 клк = 4 мкс (первое - на
  // клке 74: 74 = 2 mod 4 = 24 mod 25).
  // СЧЁТЧИК tick_cnt[4:0] - свободный бинарный (32 шага x 4 мкс =
  // 128 мкс), CE = tick_step; в D-пути НЕТ декодов равенства
  // (урок п.9/фитов v2.4-v2.5: декоды теряют NOT - у тика ТОЛЬКО
  // литералы). ВЫХОД tick_q - ЗАЩЁЛКА-МУКС (И-ИЛИ 2 ПТ, 3 литерала,
  // БЕЗ XOR - печать с явными NOT, калибровано v2.5): на границе
  // шага (tick_step) сэмпл ЛИТЕРАЛА MSB tick_cnt[4], между шагами
  // - удержание: D = (tick_step & tick_cnt[4]) | (~tick_step &
  // tick_q). РЕЗУЛЬТАТ: квадрат 64/64 мкс, ФРОНТ каждые 128 мкс =
  // 7,8125 кГц. TRAP 8085A защёлкивает фронт (NMI, внутренняя
  // защёлка); high 64 мкс >> 2T CPU (640 нс), low 64 мкс -
  // перевзвода нет. Свободный ход: ветки сброса НЕТ (как у делителя
  // v2.4) - POR и кнопка RST тик не глушат (heartbeat ОС; фаза не
  // важна - NMI асинхронный). ЦЕНА: +6 МЦ = 5 (tick_cnt) + 1 (tick_q);
  // ожидание фита v2.7: 107/108, ПТ ~348-353, вх.ФБ ~210-215, резерв
  // 1 МЦ. ДЖИТТЕР (документировано): jam baud_cnt при загрузке TX
  // сдвигает фазу baud_tick -> ОДИН межшаговый интервал после каждой
  // загрузки краток/долог (до 2 шагов = 8 мкс), дальше сетка ровно
  // 100 клк; период тика в цикле с загрузкой 128 +/- 8 мкс (6%),
  // без загрузок - ровно 128 мкс. Для heartbeat ОС - допустимо;
  // безджиттерный вариант = собственный mod-25 делитель (+5 МЦ) -
  // вне бюджета варианта C.
  //=============================================================
  wire tick_step = por_ce & baud_tick;
  reg [4:0] tick_cnt = 5'd0;
  reg       tick_q  = 1'b0;
  always @(posedge clk) begin
    if (tick_step) tick_cnt <= tick_cnt + 5'd1;
    tick_q <= (tick_step & tick_cnt[4]) | (~tick_step & tick_q);
  end
  assign TRAP = tick_q;

"""


def main():
    src = io.open(os.path.join(ROOT, "top_txuart_por6_v26_utf8.v"), encoding="utf-8").read()

    # --- 1. заголовок ---
    src = rep1(src, """// top_txuart.v v2.6 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 000 000 бод (такт ядра clk = 25 МГц / 25,
// BAUD_DIV=25 - явный wrap счётчика-делителя по (== 24), п.27)
// v2.6: x2_q - T-ТРИГГЕР с T = t0_q, INIT=RESET (урок фитов v2.4/v2.5:
// D-форма X2 неаудитируема - печать XOR без NOT при ЛЮБОЙ записи RTL).
// Узел - делитель 3 FF, X2 = ~X1 инвариантно, частота CPU 3,125 МГц""",
"""// top_txuart.v v2.7 - retro_pcld_top + TXUART: ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ
// ПЕРЕДАТЧИК UART 8N1 1 000 000 бод (такт ядра clk = 25 МГц / 25,
// BAUD_DIV=25 - явный wrap счётчика-делителя по (== 24), п.27)
// v2.7: ТИК на TRAP (P74, cpu10, нога 6) - квадрат 64/64 мкс, фронт
// каждые 128 мкс; узел 6 FF БЕЗ декодов в D-пути (вариант C, +6 МЦ).
// Узел - делитель 3 FF, X2 = ~X1 инвариантно, частота CPU 3,125 МГц""")

    # --- 2. блок v2.7 в шапке (перед блоком v2.6) ---
    src = rep1(src, """//
// v2.6 (урок ФИТА v2.5, 11-14 6:27PM): фит Successful, 101/108, и ДИФ""",
"""//
// v2.7 (ТИК, директива владельца «собирай 2.7» 11-14 после железного
// ОК v2.6: противофаза X2 подтверждена осциллографом, UART работает):
// периодический NMI на CPU.TRAP (P74, нога 6) - сердце ОС. РЕШЕНИЕ =
// ВАРИАНТ C (записан в шапках v2.4/v2.6: «5 бит + CE-МЦ = +6 МЦ»,
// 128 мкс; вариант A «6 бит + CE-МЦ = 7 МЦ»/256 мкс был впритык -
// отклонён, резерв должен остаться).
// ГЕНЕРАЦИЯ ШАГА 4 МКС БЕЗ НОВЫХ МЦ: tick_step = por_ce & baud_tick -
// совпадение двух УЖЕ существующих свободных стробов (por_ce: 1 клк
// каждые 4 клк = 160 нс; baud_tick: 1 клк каждые 25 клк = 1 мкс).
// Оба стартуют из INIT-нулей -> фазы фиксированы конфигурацией,
// совпадение ровно 1 клк на каждые LCM(4,25) = 100 клк = 4 мкс
// (первое на клке 74 после конфигурации: 74 = 2 mod 4 = 24 mod 25).
// СЧЁТЧИК: tick_cnt[4:0] свободный бинарный, CE = tick_step, цикл
// 32 шага x 4 мкс = 128 мкс. В D-пути счётчика декодов НЕТ (только
// CE-инкремент - урок п.9: декоды равенства теряют NOT, класс
// фитов v2.4-v2.5/7:31/8:55). ВЫХОД: tick_q - ЗАЩЁЛКА-МУКС (И-ИЛИ
// 2 ПТ, БЕЗ XOR - урок v2.5: только И-ИЛИ печатается с явными NOT):
// D = (tick_step & tick_cnt[4]) | (~tick_step & tick_q) - на
// границе шага сэмпл ЛИТЕРАЛА MSB tick_cnt[4], между шагами
// удержание. РЕЗУЛЬТАТ: квадрат 64/64 мкс, ФРОНТ каждые 128 мкс =
// 7,8125 кГц. TRAP защёлкивает фронт (8085A NMI - внутренняя
// защёлка, снимается программно/RESET); high 64 мкс >> 2T = 640 нс
// - распознавание гарантировано; между фронтами low 64 мкс -
// перевзвода нет.
// НОГА: P74 - бывший держатель '0' (PGND-набор 9 -> 8, UCF
// обновлён; PGND проверяется в P&R-отчёте владельца - в .rpt
// фиттера заземлённые пины НЕ видны). Свободный ход тика: ветки
// сброса НЕТ (как у делителя v2.4) - POR и кнопка RST тик не
// глушат (heartbeat ОС; фаза не важна - NMI асинхронный).
// ДЖИТТЕР (честно): jam baud_cnt при загрузке TX сдвигает фазу
// baud_tick -> ОДИН межшаговый интервал после каждой загрузки
// краток/долог (до 8 мкс), дальше сетка ровно 100 клк; период тика
// в цикле с загрузкой 128 +/- 8 мкс (6%), без загрузок ровно
// 128 мкс. Heartbeat ОС это держит; безджиттерный вариант =
// собственный mod-25 делитель (+5 МЦ) - вне бюджета варианта C.
// АУДИТ v2.7: audit_fit_node.py режим v27 (по умолчанию) - печатные
// уравнения тика симулируются 6400 клк (2 периода): tick_step
// каждые ровно 100 клк, фронт tick_q каждые ровно 3200 клк,
// high 1600 клк; XOR на D-битах счётчика ДОПУСТИМ (toggle
// симметричен), XOR/потеря NOT в D(tick_q) = БРАК (класс потери
// инверсии). TRAP в .rpt: P74, выход registered.
//
// v2.6 (урок ФИТА v2.5, 11-14 6:27PM): фит Successful, 101/108, и ДИФ""")

    # --- 3. резервная пометка в блоке v2.6 ---
    src = rep1(src, """// РЕЗЕРВ: 7 МЦ / 7 вх.ФБ / ~200 ПТ (ПТ у X2: 2 -> 0-1) - тик (TRAP)
// влезает, решение после ЧИСТОГО фита v2.6.""",
"""// РЕЗЕРВ: 7 МЦ / 7 вх.ФБ / ~200 ПТ (ПТ у X2: 2 -> 0-1) - тик (TRAP)
// РЕШЁН: реализован в v2.7 вариантом C (блок v2.7 выше).""")

    # --- 4. порт TRAP (после RESET_IN) ---
    src = rep1(src, """    output wire       RESET_IN,     // P84 cpu7, нога 36: активный 0 = сброс CPU; v3.9.6: регистр reset_q (п.21)""",
"""    output wire       RESET_IN,     // P84 cpu7, нога 36: активный 0 = сброс CPU; v3.9.6: регистр reset_q (п.21)
    output wire       TRAP,         // P74 cpu10, нога 6 (CPU.TRAP, NMI): ТИК v2.7 = tick_q (квадрат 64/64 мкс, фронт каждые 128 мкс - узел «ТИК» ниже); был заземлён как держатель '0' (PGND 9 -> 8)""")

    # --- 5. узел тика (перед секцией «Поддержка CPU») ---
    src = rep1(src, """  //=============================================================
  // Поддержка CPU (§3, ред. Task 19) + TXUART (п.27): передача - аппаратный""",
    TICK_NODE + """  //=============================================================
  // Поддержка CPU (§3, ред. Task 19) + TXUART (п.27): передача - аппаратный""")

    # --- 6. комментарий секции CPU: держатели 9 -> 8 ---
    src = rep1(src, """  // Держатели '0' (TRAP, RST7.5/6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины (9 шт) заземлит фиттер (Ground on Unused IOs).
  // SID (P73) с Task 70-a - ВЫХОД CPLD (транзит RX), в держатели
  // больше не входит (PGND 10 -> 9).""",
"""  // Держатели '0' (RST7.5/6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины (8 шт) заземлит фиттер (Ground on Unused IOs).
  // SID (P73) с Task 70-a - ВЫХОД CPLD (транзит RX), в держатели
  // больше не входит (PGND 10 -> 9). TRAP (P74) с v2.7 - ТОЖЕ ВЫХОД
  // (тик, узел выше): PGND 9 -> 8; держателей осталось 8.""")

    # --- 7. бюджет ---
    src = rep1(src, """  // ожидание фита v2.6: 101/108, ПТ ~338-339 (X2: 2 -> 0-1), резерв
  // под тик: 7 МЦ, 7 вх.ФБ (блок v2.6 шапки).""",
"""  // ожидание фита v2.6: 101/108, ПТ ~338-339 (X2: 2 -> 0-1), резерв
  // под тик: 7 МЦ, 7 вх.ФБ (блок v2.6 шапки). ФИТ v2.6 (6:39PM):
  // Successful, 101/108, ПТ 339 (X2: 1 ПТ) - аудит 21/0 ШИТЬ, ЖЕЛЕЗО
  // ОК (11-14: противофаза X2, UART) => v2.7: ТИК вариант C (+6 МЦ =
  // 5 tick_cnt + tick_q, узел «ТИК»); ожидание фита v2.7: 107/108,
  // ПТ ~348-352, вх.ФБ ~210-215 (риск: если тик ляжет в ФБ без
  // baud_cnt - 7 внешних вх, до 215/216; лечить перекладкой узла),
  // резерв 1 МЦ.""")

    # --- 8. чек-лист: пункты тика после хвоста h) ---
    src = rep1(src, """//              печатный FDCPE_X2 = НЕ ШИТЬ;""",
"""//              печатный FDCPE_X2 = НЕ ШИТЬ;
//       ТИК v2.7 (вариант C): tick_cnt = 5 триггеров (свободный
//              бинарный, CE = tick_step, D-пути БЕЗ декодов
//              равенства; XOR на D-битах ДОПУСТИМ - toggle
//              симметричен, каденцию ловит сим), tick_q = 1
//              триггер-защёлка: D = (tick_step AND tick_cnt(4))
//              OR (NOT tick_step AND tick_q) - И-ИЛИ 2 ПТ БЕЗ
//              XOR (урок v2.5); XOR или потеря NOT в D(tick_q)
//              = БРАК (класс потери инверсии);
//              TRAP = P74 выход registered (IO-MC); печать
//              симулируется 6400 клк: tick_step каждые ровно 100
//              клк (4 мкс), фронт tick_q каждые ровно 3200 клк
//              (128 мкс), high ровно 1600 клк (64 мкс); PGND теперь
//              8 шт {P75,P76,P78,P79,P81,P95,P96,P98} (P74 ушёл
//              на тик - проверять в P&R-отчёте владельца, в .rpt
//              фиттера заземлённые пины НЕ видны);""")

    # --- контроль узла ---
    for pat in ("wire tick_step = por_ce & baud_tick;",
                "reg [4:0] tick_cnt = 5'd0;",
                "reg       tick_q  = 1'b0;",
                "if (tick_step) tick_cnt <= tick_cnt + 5'd1;",
                "tick_q <= (tick_step & tick_cnt[4]) | (~tick_step & tick_q);",
                "assign TRAP = tick_q;"):
        if pat not in src:
            raise SystemExit("ОШИБКА: в коде нет %r" % pat)
    if "tick_cnt ==" in src or "(tick_cnt == " in src:
        raise SystemExit("ОШИБКА: декод равенства в узле тика")
    if "\n  always @(posedge clk) begin\n    if (tick_step)" not in src:
        raise SystemExit("ОШИБКА: always-блок тика не на месте")

    # --- запись RTL ---
    io.open(os.path.join(ROOT, "top_txuart_por6_v27.v"), "wb").write(src.encode("cp1251"))
    io.open(os.path.join(ROOT, "top_txuart_por6_v27_utf8.v"), "w", encoding="utf-8").write(src)

    # --- UCF: NET TRAP P74 + дисциплина 9 -> 8 ---
    ucf = io.open(os.path.join(ROOT, "top_txuart.ucf"), encoding="cp1251").read()
    ucf = rep1(ucf, """NET "RESET_IN"   LOC = "P84";  # cpu7,  RESET IN#(36) = регистр reset_q (п.21d базы: INIT=0 - CPU в сбросе с t=0; снятие чистым фронтом), активный 0 по даташиту 8085A (Task 25)""",
"""NET "RESET_IN"   LOC = "P84";  # cpu7,  RESET IN#(36) = регистр reset_q (п.21d базы: INIT=0 - CPU в сбросе с t=0; снятие чистым фронтом), активный 0 по даташиту 8085A (Task 25)
NET "TRAP"       LOC = "P74";  # cpu10, TRAP(6): ТИК v2.7 = tick_q (квадрат 64/64 мкс, фронт каждые 128 мкс = 7,8125 кГц); БЫЛ заземлён как держатель '0' - PGND 9 -> 8""", "ucf TRAP")
    ucf = rep1(ucf, """#  - ДЕВЯТЬ держателей '0' (TRAP, RST7.5/6.5/5.5, INTR, HOLD, A16, A17,
#    A18) в HDL NET: их пины (P74, P75, P76, P78, P79, P81, P95, P96,
#    P98) фиттер заземлит опцией "Ground on Unused IOs" = ON — это""",
"""#  - ВОСЕМЬ держателей '0' (RST7.5/6.5/5.5, INTR, HOLD, A16, A17,
#    A18) в HDL NET: их пины (P75, P76, P78, P79, P81, P95, P96,
#    P98) фиттер заземлит опцией "Ground on Unused IOs" = ON — это""", "ucf дисциплина 1")
    ucf = rep1(ucf, """#  - чек-лист .rpt: PGND == ровно {P74,P75,P76,P78,P79,P81,P95,P96,P98}
#    (9 шт!);""",
"""#  - чек-лист .rpt: PGND == ровно {P75,P76,P78,P79,P81,P95,P96,P98}
#    (8 шт; P74 с v2.7 = ВЫХОД тика TRAP — в PGND НЕ входит; сам PGND
#    в .rpt фиттера НЕ виден - проверять в P&R-отчёте владельца);""", "ucf чек-лист")
    io.open(os.path.join(ROOT, "top_txuart.ucf"), "wb").write(ucf.encode("cp1251"))

    print("v2.7 записан: %d строк, %d байт (CP1251); UCF обновлён (TRAP P74, PGND 8)"
          % (src.count("\n") + 1, len(src.encode("cp1251"))))


if __name__ == "__main__":
    main()
