def sub(old, new, count=1):
    """Точная замена; старая строка обязана встретиться РОВНО count раз."""
    global text, n_ops
    c = text.count(old)
    assert c == count, "ANCHOR FAIL (count=%d, expected %d): %r" % (c, count, old[:120])
    text = text.replace(old, new)
    n_ops += 1


def span(start_marker, end_marker, new_body, include_end=True):
    """Замена диапазона [start_marker .. end_marker] новым телом.
    Маркеры обязаны встретиться ровно по 1 разу, start раньше end."""
    global text, n_ops
    i = text.find(start_marker)
    assert i >= 0 and text.count(start_marker) == 1, "SPAN START FAIL: %r" % start_marker[:80]
    j = text.find(end_marker, i)
    assert j >= 0, "SPAN END FAIL: %r" % end_marker[:80]
    assert text.count(end_marker) == 1, "SPAN END NOT UNIQUE: %r" % end_marker[:80]
    j2 = j + len(end_marker) if include_end else j
    text = text[:i] + new_body + text[j2:]
    n_ops += 1


