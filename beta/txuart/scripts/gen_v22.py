def strip_comments(t):
    out = []
    for ln in t.split("\n"):
        # убираем // комментарии (в этом RTL их синтаксис тривиален)
        p = ln.find("//")
        out.append(ln if p < 0 else ln[:p])
    return "\n".join(out)

