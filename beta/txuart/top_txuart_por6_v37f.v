//  7. порты индикации/звука/клавиатуры.
// tb: scripts/tb_poweron_v37e.v (Icarus 12.0/13.0; P0-P5: POR-полка,
// мёртвый CLKOUT, кнопка, глитч, повторный взвод, /WE-пульсы, счёт;
// T1-T3: свободный таймер - период/ширина импульса/фаза, OUT 06h
