//  1. такт и глобальный сброс: делитель /4 (t0_q/x1_q), X1/X2/por_ce;
//  2. сброс CPU: 2FF-синхронизатор RST + квалификатор (п.21), полка по
//     фронтам CLKOUT (п.35), регистр cpu_rst_r (источник GSR);
//  3. FSM шины i8085 (T1H/T2/WB1..WB4, п.4 writeback);
