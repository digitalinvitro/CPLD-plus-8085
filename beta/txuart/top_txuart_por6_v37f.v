// ТАКТ (п.23/п.34):
//  - вход clk 25 МГц на P29 (GCK3); перемычка H1 С ШУНТОМ ОБЯЗАТЕЛЬНА
//    (DIV=/4 генератора U7; БЕЗ шунта 50 МГц -> CPU 6,25 МГц = 1,75x
//    разгона ВМ85А/ОЗУ, бод 3,125 М вне сетки CH340G - ЗАПРЕЩЕНО);
//  - делитель /4 = t0_q/x1_q (toggle-FF); X1 = x1_q: 6,25 МГц, период
//    ровно 160 нс, duty 1/2 (80/80); внутренний /2 ВМ85А -> CPU
//    3,125 МГц (на 12,5% медленнее калибровочного 3,571 МГц: fw-константы,
//    калиброванные тактами, тянутся x1,143);
//  - X2 (P69) = ОТКРЫТЫЙ ВХОД (Hi-Z; даташит CA80C85B: при внешнем такте
//    X1 открытый X2 допустим, GND/нуль ЗАПРЕЩЕНЫ); keep + Keep Unused
//    Inputs ON - нога не trim'ится и не заземляется фиттером;
//  - ВСЯ логика в ОДНОМ домене clk 25 МГц; por_ce = ~t0_q & ~x1_q -
//    ровно 1 такт (40 нс) за 160 нс; tick_step = por_ce & baud_tick -
//    ровно 1 такт на каждые LCM(4,25) = 100 клк = 4 мкс (база таймера;
//    фазы фиксированы INIT-значениями);
//  - ДЖИТТЕР: jam baud_cnt при загрузке TX (OUT 04h) сдвигает фазу
//    baud_tick - один межшаговый интервал после каждой загрузки краток/
//    долог (до 2 шагов = 8 мкс), дальше сетка ровно 100 клк;
//  - CLKOUT CPU = X1/2 = 3,125 МГц (сверка платы осциллографом: 2,5 или
//    3,125 МГц - на дизайн не влияет, меняет FPS xstream и единицы
//    K_MS монитора).
//=====================================================================
// СБРОС (п.21/п.35):
//  - сырой пин RST (SW20, активный 1) входит в кристалл ТОЛЬКО через
//    2FF-синхронизатор (rst_meta/rst_sync, вне сброса) и квалификатор;
//    решения о сбросе принимают ТОЛЬКО регистры (мид-рейл/дребезг/
//    помеха на SW20 не доходят ни до сбросовых входов триггеров, ни до
//    ноги RESET_IN);
//  - квалификатор rst_press/rst_qcnt: переворот rst_press на 8-м тике
//    por_ce ПОДРЯД устойчивого rst_sync != rst_press (двусторонний: и
//    взвод, и снятие квалифицированы); сходство обнуляет счёт (строже
//    сдвига: частичное накопление через одиночные сходства не
//    переносится); помеха короче 1280 нс не видна вовсе, длиннее -
//    полноценный повторный сброс; латентность кнопки ~1,44 мкс;
//  - полка сброса (п.35): reset_q (регистр RESET_IN, INIT=0 - CPU в
//    сбросе с t=0) поднимается 8-м фронтов CLKOUT (регистр-память
//    CLKOUT, детектор фронта) = 2560 нс (норма 3 такта CPU = 960 нс, запас
//    2,67x; замер tb 2340 нс); сброс снимается по факту ЖИВОГО такта
//    процессора; если CLKOUT в сбросе заглохнет - reset_q не поднимется
//    НИКОГДА (детерминированный отказ старта); повторное срабатывание
//    исключено (после снятия ветка !reset_q закрыта);
//  - cpu_rst_r = rst_press | ~reset_q (РЕГИСТР сброса, INIT=1) -
//    единый источник GSR: CLR всех ФБ = ОДИН вход; вне GSR сознательно:
//    делитель (фаза X1/CLKOUT не прыгает), таймер, rst-цепь;
//  - FSM в окне сброса в IDLE (GSR), шина CPU «floated» - вход в
//    writeback ЗАПРЕЩЁН гейтом !cpu_rst_r (импульс /WE в окне сброса
//    невозможен ПО ПОСТРОЕНИЮ); начатый импульс /WE (80 нс) не обрывается
//    ни ALE, ни сбросом (квалификатор длиннее импульса - запись
//    доводится до конца полного t_WP ОЗУ, п.21f).
//=====================================================================
// FSM ШИНЫ (7 состояний = 3 триггера; (* fsm_encoding = "compact" *)
// против one-hot XST: one-hot = 7 триггеров = +4 МЦ = 109 > 108;
// контроль .rpt: state_FSM_FFd4.. = БРАК):
//  IDLE -> T1H (ALE): захват адреса addr_latch <= A (повторным
//       сэмплированием - последний сэмпл валиден; адрес стабилен весь T1;
//       из WB в T1H можно попасть только через IDLE - посреди импульса
//       addr_latch не перезаписывается, п.6);
//  T1H -> T2 (!ALE): захват данных bus_reg (bus_ld_t1 ? D : A - стробы
//       взаимоисключающие, CE-форма FF без self-столбца);
//  T2: чтение - rd_drive (A-пины отдают bus_reg/KBROW); запись -
//      wr_seen; завершение цикла - fsm_wrdone/fsm_rddone; ALE обрывает
//      ТОЛЬКО T2 (защита от глюка), в WB1..WB4 НЕ вмешивается;
//  WB1..WB4: writeback в ОЗУ (!IOM && A15 && !cpu_rst_r): /WE импульс
//      2 тика = 80 нс (>= t_WP ОЗУ), адрес/данные удерживаются
//      (t_AH/t_DH памяти); запись в ПЗУ отбрасывается; CS_n - от FSM
//      (п.16: защёлки нет);
//  keep-узлы (паттерн «ОДИН узел вместо инлайн-копий» - открывает
//  карманы ФБ): in_wb, rd_drive, io_wr, bus_ld_t1/bus_ld_t2,
//  fsm_wrdone/fsm_rddone, baud_tick, kbcol_wr06.
//=====================================================================
// ЯДРО TXUART (п.27-п.31): OUT 04h = TXDATA -> shreg 9 бит -> TX
// (shreg[0]); 8N1, бод = 25 МГц / 25 = ровно 1 000 000 (ТОЧНАЯ сетка
// CH340G: 48М/48, ошибка 0%; 1 562 500 в сетке НЕТ - драйвер молча
// 1,5 М = мусор). Терминал 1 000 000 8N1.
//  - shreg 9 бит: сам-idle (INIT=1FF, SET-ветка GSR: TX='1' до всякого
//    клока и в сбросе); сдвиги вправо с инжекцией '1' - после кадра сам
//    в все-'1' (idle по построению; параллельных загрузок idle НЕТ);
//  - bit_cnt 1..10 (1=старт..10=стоп), 0=idle; busy = |bit_cnt; на 10-м
//    сдвиге сам в 0; TXRDY = ~|bit_cnt - бит 7 чтения 03h;
//  - baud_cnt mod-25 свободным ходом, wrap ЯВНЫЙ (== 24); jam <= 0 при
//    загрузке: старт-бит ровно 25 тиков, сетка кадров детерминирована;
//  - ld_tx_q - регистровый строб загрузки; io_wr_tx (декод 04h +
//    tx_idle + !ld_tx_q + !cpu_rst_r): ОДНОКРАТНОСТЬ (повторные такты
//    строба и запись при busy БЛОКИРОВАНЫ - байт тихо отбрасывается,
//    кадр не портится);
//  - приём - программный (SID = RX, RIM 20h); IN 04h не определён.
//=====================================================================
// ПОРТЫ (IOM=1, адрес по addr_latch[2:0]; алиас каждые 8 адресов -
// 00h=08h=...=F8h, A[15:3] don't care, «неиспользуемые адреса» НЕ
// безопасны):
//  ЗАПИСЬ: 00h - сегменты A[6:0] (dp погашен навсегда: seg = {1'b1,~seg_q});
//          01h - разряды A[3:0] + звук A[4];
//          04h - TXDATA (старт кадра, ОДНОКРАТНЫЙ строб io_wr_tx);
//          06h - колонки клавиатуры A[7:4] (строб kbcol_wr06; таймер НЕ
//          пишется - свободный ход, A[1:0] записи игнорируются);
//  ЧТЕНИЕ: 03h - {TXRDY, tmr_cnt[1:0], row4..row0};
//  02h/05h/07h НЕМАПЛЕНЫ; чтение немапленных = bus_reg (последние
//  захваченные шинные данные, НЕ константа: тени держать в ОЗУ);
//  запись в немапленные игнорируется (bus_reg <= A выполняется);
//  OUT 04h при busy - байт молча теряется (статуса ошибки нет).
//  Индикация: общий анод, выходы активным 0; INIT seg_q=7'h40/dig_q=4'hF
//  - самотест «----» (тире в каждом разряде, dp погашен) до первой
//  записи fw в порты; цена - сток ~68 мА через базы PNP (4 x ~17 мА при
//  R5/R10/R11/R12=240 Ом) в окне до инициализации fw (осознанный
//  компромисс); нагрузка сегментов в 7 раз легче «8888».
//  Клавиатура: колонки - зарегистрированные выходы (активная = 1,
//  INIT 0); кнопка скан не гасит (продолжается с текущего места).
//=====================================================================
// ТАЙМЕР -> RST 7.5 (P75; CPU.RST 7.5 - edge-защёлка, МАСКИРУЕМЫЙ,
// вектор 003Ch; TRAP P74 - держатель '0', PGND 8: {P74,P76,P78,P79,
// P81,P95,P96,P98}): полный контракт Р-5 - в блоке ТАЙМЕР тела файла.
//  КОНТРАКТ ПРОШИВКИ (Р-5E): RST 7.5 защёлкивается фронтом НЕЗАВИСИМО
//  от маски IM/IE; тик 4 мкс идёт СКВОЗЬ сброс (таймер вне сети
//  сброса) - защёлка получит фронты уже в окне сброса: SIM со сбросом
//  защёлки РАНЬШЕ первого EI ОБЯЗАТЕЛЕН; после сброса RST 7.5
//  замаскирован (IM=FF); векторные глушилки EI;RET в ROM - страховка.
//  Периодический режим = ИМПУЛЬС на каждый тик (4 мкс): ISR читает
//  фазу из 03h (tmr_cnt[1:0]) и ветвлением выбирает эвент; пропуск
//  тиков (маска/длинное тело ISR) синхронизацию НЕ ломает - фаза
//  всегда актуальна в 03h (маскировать между тяжёлыми участками и
//  догонять по фазе - решение ПО).
//=====================================================================
// ПРАВИЛА ФИТТЕРА (п.9/п.10):
//  п.9 - декоды равенства в узле тактирования и D-путях регистров:
//        XST теряет NOT в развёртке -> счётчики БЕЗ декодов (литералы/
//        переносы); декоды равенства - только в keep-узлах;
//  п.10 - X2 строится БЕЗ одиночной инверсии регистра (печать XOR без
//        NOT неаудитируема) - X2 - открытый вход, регистровая
//        противофаза не строится.
//=====================================================================
// ЧЕК-ЛИСТ ФИТА (п.32, владельцу после прогона ISE): УСТРОЙСТВО
// xc95108-15pq100c; опции: Input Limit 28, Pterm Limit 18, Exhaustive
// OFF, DENSITY (НЕ IL/PT=1 + Exhaustive ON - коллапсинг выключается и
// дизайн раздувается в фантом МЦ); ERROR 891/892 - на аудит (НЕ
// включать Exhaustive самовольно):
//  a) Successful, 0 ERROR; WARNING:Cpld:897 <= 1-2 (класс буфера D<7>);
//     WARNING:Xst:1780 БЫТЬ НЕ ДОЛЖНО (мёртвых идентификаторов в RTL нет);
//  b) shreg - РОВНО 9 триггеров (TX = shreg[0], IO-MC P39, idle '1');
//     bit_cnt - РОВНО 4 (idle = 0000); tmr_cnt - РОВНО 2 триггера
//     (INIT=00, свободный ход); RST75_r - 1 триггер (IO-MC P75,
//     импульс 1 клк на каждый тик);
//  c) GSR: «GSR : 1» (или fallback PT-сбросов от cpu_rst_r - на разбор);
//     D-функции логики БЕЗ литералов сырого RST (п.21: RST - только во
//     входах rst_meta); rst-цепь (rst_meta/rst_sync/rst_qcnt/rst_press/
//     reset_q, clkout_d) и таймер - ВНЕ GSR; ядро + FSM/шина -
//     CLR/SET=cpu_rst_r;
//  d) делитель: РОВНО 2 регистра t0_q/x1_q (D = ~t0_q / x1_q^t0_q),
//     ДЕКОДОВ РАВЕНСТВА В УЗЛЕ НЕТ; INIT: t0=RESET, x1=SET;
//     x2_q/clk25_q/por_sh/por_run/s0..s3 в нетлисте НЕТ - появились:
//     собран не тот исходник;
//  e) baud_cnt: D-функции БЕЗ декода терминального счёта (свободный
//     инкремент, wrap явный == 24 в baud_tick-узле); строб загрузки -
//     через регистр ld_tx_q (1 МЦ, в .rpt есть);
//  f) пины: TX P39 вых, SOD P72 вх (наблюдатель), SID P73 вых, RX P38
//     вх, X2 P69 ВХОД (INP - НЕ выход!), PGND ровно 8 ({P74,P76,P78,
//     P79,P81,P95,P96,P98}); clk -> GCK3, RST = P1; все constraint-ноги
//     со знаком "~" (фиттер НЕ переставлял);
//  g) ресурсы сверить с фактом фита (допуск +-2 МЦ / +-10 вх.ФБ);
//     Maximum Frequency: логика 25 МГц - должна закрыться (один домен);
//  h) литералы сброса в термах: rst_press/cpu_rst_r - RESET-класс;
//     сырого RST в термах НЕТ.
//  КОНФИГУРАЦИЯ ПЛАТЫ (i): H1 С ШУНТОМ = 25 МГц - ОБЯЗАТЕЛЬНО ДО ПОДАЧИ
//  ПИТАНИЯ; осциллограф: GCK3 = 25 МГц, X1 = 6,25 МГц (период ровно
//  160 нс, high 80 / low 80 - duty 1/2), X2 - НЕ управляется CPLD
//  (Hi-Z вход), CLKOUT = 3,125 МГц duty 50%, RESET_IN низ = полка
//  (замер tb ~2340 нс).
//=====================================================================
// Топология шины: AD0-AD7 процессора, A0-A7 flash/SRAM и CPLD - ОДНА
// медь (сети A0..A7). CPLD = регистровый трансивер:
//   чтение: память видит адрес в T1 (ALE=1) -> данные на D0-D7
//   захватываются в последний тик T1 -> в T2 (CPU отпустил AD) CPLD
//   выдаёт данные на A-сети;
//   запись: в T2 CPU гонит данные по A-сетям (CPLD Hi-Z), CPLD
//   захватывает; после WR#(вверх) - «отложенная запись» (writeback):
//   CPLD сам ставит защёлкнутый адрес на A-сети + данные на D-сети и
//   даёт импульс /WE_RAM (импульс защищён от ALE - п.4).
// Сброс: SW20 -> RST (нажатие = 1) + POR (п.35: счёт фронтов CLKOUT от
// INIT) -> RESET_IN=0; сброс ЛОГИКИ - асинхронный по cpu_rst_r через
// СЕТЬ GSR (п.18/20); сырой RST - только в синхронизатор (п.21);
// RESET_IN - регистр reset_q. RAM подтверждена на железе (4 паттерна x
// 32K без ошибок, T=1280 нс; режим T=320 нс - этот файл).
//=====================================================================
module retro_pcld_top (   // параметров нет: делитель единственный, обёртка
                          // generate не используется (молчаливая сборка «не
                          // того исходника» при чужом значении параметра);
                          // tb линии - Verilog scripts/tb_poweron_v37e.v
    // ---- такт и глобальный сброс ----
    input  wire       clk,          // 25 МГц (перемычка H1 С ШУНТОМ ОБЯЗАТЕЛЬНА - DIV=/4 генератора U7; без шунта 50 МГц ЗАПРЕЩЕНО - п.23/34), U1.29 (P29, GCK3)
    input  wire       RST,          // SW20, U1.1 (P1, GSR): покой = 0, нажатие = 1 (актив.1 - доказано платой); пин входит ТОЛЬКО в синхронизатор rst_meta (п.21), GSR-ресурс ноги не задействован
    // ---- шина i8085 (входы автомата) ----
    input  wire       ALE,          // cpu1 U1.93 (P93), нога 30
    input  wire       WRn,          // cpu2 U1.92 (P92), нога 31 (активный 0)
    input  wire       RDn,          // cpu3 U1.91 (P91), нога 32 (активный 0)
    input  wire       IOM,          // cpu5 U1.88 (P88), нога 34: 1=IO, 0=память
    input  wire       A15,          // U1.97 (P97) - декод памяти
    // ---- мультиплексированная шина AD0-AD7 = сети A0..A7 (bidir) ----
    inout  wire [7:0] A,            // A0=P26 A1=P21 A2=P19 A3=P17 A4=P15 A5=P13 A6=P11 A7=P9
    // ---- шина данных памяти (bidir) ----
    inout  wire [7:0] D,            // D0=P30 D1=P32 D2=P35 D3=P36 D4=P34 D5=P31 D6=P27 D7=P22
    // ---- управление памятью (активный 0) ----
    output wire       CSr_n,        // P20 /CE_ROM -> U10.22 (flash /CE)
    output wire       OEr_n,        // P16 /OE_ROM -> U10.24
    output wire       CS_n,         // P25 /CE_RAM -> U4.22  (RAM /CE)
    output wire       OE_n,         // P37 /OE_RAM -> U4.24
    output wire       WE_n,         // P24 /WE_RAM -> U4.29 (только writeback!)
    input wire        CS1,          // P99 CS(CE2) -> U4.30, константа '1'
    // ---- поддержка процессора ----
    output wire       X1,           // P68 cpu21, нога 1: 6,25 МГц (x1_q, duty 1/2: high 80 / low 80 нс, период ровно 160 нс) -> CPU 3,125 МГц (внутренний /2 ВМ85А; фронты те же, что у кольца)
    input wire        READY,        // P87 cpu6, нога 35: константа '1' (без wait)
    output wire       RESET_IN,     // P84 cpu7, нога 36: активный 0 = сброс CPU; регистр reset_q (п.21)
    output wire       RST75,        // P75 cpu15, U3.7 (CPU.RST 7.5, edge-защёлка, МАСКИРУЕМЫЙ): выход RST75_r - импульс 1 клк на каждый тик 4 мкс (свободный таймер, узел «ТАЙМЕР» ниже); TRAP (P74) - держатель '0' (PGND)
    // ---- soft-UART транзиты ----
    output wire       SID,          // P73 cpu17, нога 5 (CPU.SID): транзит RX -> приём (RIM 20h)
    output wire       TX,           // P39: цепь платы «RX» -> CH340G.RXD; TX = shreg[0] - аппаратный передатчик TXUART (п.27, IO-MC регистр)
    // ---- индикация и звук (выходы активным 0, §6) ----
    output wire [7:0] seg,          // {dp56,g,f,e,d,c,b,a} = P60/5/66/58/57/61/62/45
    output wire [3:0] dig,          // dig0..3 = P6/63/65/48 -> R -> VT1..VT4
    output wire       SND,          // P67 -> BUZZER1.1 (пассивный, прямой бит; A4 порта 01h)
    // ---- наблюдатели: «мёртвые» пины как Hi-Z входы (* keep *) ----
    // (* keep *) обязателен для ног БЕЗ нагрузки: без него XST выкидывает
    // входы (Xst:3005), а выкиннутый пин опция "Ground on Unused IOs"
    // ЗАЗЕМЛИТ - там выходы CPU (SOD и др.). RX (P38) используется
    // (транзит SID); SOD (P72) - вход-НАБЛЮДАТЕЛЬ БЕЗ нагрузки.
    (* keep = "TRUE" *) input wire  X2,  // P69 cpu20, нога 2: ОТКРЫТЫЙ ВХОД - CPLD не управляет ногой
                                         // (Hi-Z). Даташит CA80C85B: при внешнем такте X1 открытый X2
                                         // допустим, GND/нуль ЗАПРЕЩЕНЫ. Keep - порт не trim'ится XST,
                                         // Keep Unused Inputs ON сохраняет P69 входом.
    (* keep = "TRUE" *) input wire RSTOUT,    // P70 cpu19, нога 3
    (* keep = "TRUE" *) input wire SOD,       // P72 cpu18, нога 4 (CPU.SOD): наблюдатель без нагрузки (keep: выход CPU)
    (* keep = "TRUE" *) input wire INTAn,     // P80 cpu11, нога 11
    (* keep = "TRUE" *) input wire HLDA,      // P82 cpu9,  нога 38
    (* keep = "TRUE" *) input wire CLKOUT,    // P83 cpu8,  нога 37: ФУНКЦИОНАЛЬНЫЙ вход - счёт фронтов полки сброса (п.35); 3,125 МГц = X1/2
    (* keep = "TRUE" *) input wire S0,        // P94 cpu0,  нога 29
    (* keep = "TRUE" *) input wire S1,        // P89 cpu4,  нога 33
    (* keep = "TRUE" *) input wire AH8,       // P10 цепь A8,  нога 21 - адрес памяти
    (* keep = "TRUE" *) input wire AH9,       // P12 цепь A9,  нога 22
    (* keep = "TRUE" *) input wire AH10,      // P18 цепь A10, нога 23
    (* keep = "TRUE" *) input wire AH11,      // P14 цепь A11, нога 24
    (* keep = "TRUE" *) input wire AH12,      // P4  цепь A12, нога 25
    (* keep = "TRUE" *) input wire AH13,      // P8  цепь A13, нога 26
    (* keep = "TRUE" *) input wire AH14,      // P3  цепь A14, нога 27
    input  wire       RX,           // P38 цепь платы «TX» (CH340G.TXD) - транзит в SID; заземлять НЕЛЬЗЯ (выход CH340G)
    // ---- клавиатура ----
    output wire       col0,         // P44 SW1/SW5/SW9/SW13/SW17 (KBCOL.0)
    output wire       col1,         // P43 SW2/SW6/SW10/SW14/SW18 (KBCOL.1)
    output wire       col2,         // P42 SW3/SW7/SW11/SW15/SW19 (KBCOL.2)
    output wire       col3,         // P41 SW4/SW8/SW12/SW16 (KBCOL.3; SW20 вне матрицы)
    input  wire       row0,         // P56 R25 подтяжка, SW1
    input  wire       row1,         // P55 R24, SW5
    input  wire       row2,         // P54 R23, SW9
    input  wire       row3,         // P52 R22, SW13
    input  wire       row4          // P51 R21, SW17
);

  //=============================================================
  // Узел тактирования: вход 25 МГц (H1 С ШУНТОМ - DIV=/4 U7; БЕЗ
  // шунта 50 МГц ЗАПРЕЩЕНО - CPU 6,25 МГц, бод 3,125 М). ДЕЛИТЕЛЬ /4
  // на toggle-FF t0_q/x1_q (период 160 нс); X1 = x1_q (6,25 МГц,
  // duty 1/2), внутренний /2 ВМ85А -> CPU 3,125 МГц; X2 - ОТКРЫТЫЙ
  // вход (см. порт). ВСЯ логика (rst/TX/FSM/порты) на clk 25 МГц;
  // строб por_ce - в том же домене. Детали - п.23/п.34 шапки.
  //=============================================================
  wire por_ce;

  // ДЕЛИТЕЛЬ /4 на toggle-триггерах t0_q/x1_q. Строб por_ce =
  // ~t0_q & ~x1_q (домен clk 25). X1 = x1_q (IO-MC P68); X2 - открытый
  // вход P69 (см. порт).
  (* keep = "true", equivalent_register_removal = "no" *)
  reg t0_q = 1'b0;   // clk/2 = 12,5 МГц 50%: D = ~t0_q (1 ПТ, 1 лит)
  (* keep = "true", equivalent_register_removal = "no" *)
  reg x1_q = 1'b1;   // clk/4 = 6,25 МГц 50%: D = x1_q ^ t0_q (2 ПТ);
                     // INIT=1 - X1 стартует с '1'

  // por_ce = ~t0_q & ~x1_q: РОВНО ОДИН такт 40 нс за период 160 нс
  //   (фаза (t0,x1) = (0,0)); строб в домене clk 25 -
  //   детерминировано.
  always @(posedge clk) begin
    t0_q <= ~t0_q;             // clk/2
    if (t0_q) x1_q <= ~x1_q;   // clk/4, 50%
  end
  assign X1 = x1_q;   // 6,25 МГц, период ровно 160 нс, duty 1/2 (80/80)
  assign por_ce = ~t0_q & ~x1_q;  // 1 такт 40 нс за период 160 нс -
                       // ровно ОДИН posedge за период по построению;
                       // строб в домене квалификатора Р-2 и таймера -
                       // детерминировано (п.35)
  
  //=============================================================
  // П.35: СБРОС CPU = СЧЁТ ФРОНТОВ CLKOUT. Кнопка (квалификатор п.21)
  // или INIT (reset_q=0 - XC9500 держит '0' с первых вольт, RC не
  // нужен) опускают reset_q; пока CPU в сбросе, счётчик считает
  // ФРОНТЫ CLKOUT (вход P83, 3,125 МГц = X1/2); 8-й фронт поднимает
  // reset_q - полка 8 x 320 нс = 2560 нс (норма 3 такта CLKOUT =
  // 960 нс, запас 2,67x; замер tb 2340 нс). Суть: сброс снимается не
  // вслепую по выдержке, а по факту ЖИВОГО такта процессора. ЕСЛИ
  // CLKOUT В СБРОСЕ ЗАГЛОХНЁТ - счёт не идёт, reset_q не поднимется
  // НИКОГДА (детерминированный отказ старта). ПОВТОРНОЕ СРАБАТЫВАНИЕ
  // ИСКЛЮЧЕНО: после снятия ветка !reset_q закрыта, счёт не идёт до
  // следующего взвода кнопки.
  // БЕЗ СИНХРОНИЗАТОРА: CLKOUT - производное нашего же клка (X1/2 =
  // clk/8), фазово стабильно (расхождение - наносекунды задержек
  // ввода), метастабильности нет. Детектор фронта: регистр clkout_d -
  // память предыдущего сэмпла, edge = CLKOUT & ~clkout_d (rising,
  // 1 тик clk). ДЕКОДОВ НЕТ (без ==0/!=0 ни в счёте, ни в снятии).
  // Init=0 - старт детерминирован.
  //=============================================================
  // Р-2: квалификатор кнопки п.21 - окно 1280 нс = 8 тиков por_ce
  // ПОДРЯД, двусторонний (и взвод, и снятие); 3-битный счётчик
  // rst_qcnt с порогом «8 подряд» (переворот на 8-м тике расхождения),
  // обнуление на любом тике сходства (СТРОЖЕ сдвига: частичное
  // накопление через одиночные сходства не переносится). por_ce жив
  // (строб таймера tick_step).
  reg  rst_meta  = 1'b0;         // ловец метастабильности (вне сброса, INIT=0)
  reg  rst_sync  = 1'b0;         // синхронизованный RST (вне сброса, INIT=0)
  reg  rst_press = 1'b0;         // квалифицированный сброс кнопки (INIT=0)
  reg [2:0] rst_qcnt = 3'b000;   // Р-2: счёт тиков por_ce 0..7 (INIT=0)
  reg  clkout_d    = 1'b0;       // память сэмпла CLKOUT (детектор фронта; INIT=0);
                                 // синхронизатора НЕТ: CLKOUT = clk/8 - производное
                                 // нашего клка, фазово стабильно
  reg [2:0] rst_cnt = 3'b000;    // счёт фронтов CLKOUT 0..7 (INIT=0)
  reg  reset_q  = 1'b0;          // РЕГИСТР RESET_IN (INIT=0 - CPU держится с t=0;
                                 // POR = INIT, RC не нужен)
  always @(posedge clk) begin   // п.35: память сэмпла CLKOUT (синхронизатор не нужен - clk/8)
    clkout_d <= CLKOUT;
  end
  wire clkout_edge = CLKOUT & ~clkout_d;       // фронт CLKOUT (1 тик clk)
  always @(posedge clk) begin   // логика на clk 25 МГц (п.23/34)
    rst_meta <= RST;
    rst_sync <= rst_meta;
  end
  always @(posedge clk) begin   // Р-2: квалификатор = счётчик 8 подряд
    if (por_ce) begin
      if (rst_sync != rst_press) begin
        if (&rst_qcnt) begin
          rst_press <= rst_sync; // 8-й тик подряд расхождения - переворот (1280 нс)
          rst_qcnt  <= 3'b000;   // счёт закрыт - следующий эпизод с нуля
        end else
          rst_qcnt  <= rst_qcnt + 3'b001;
      end else
        rst_qcnt  <= 3'b000;     // сходство: счёт с нуля
    end
  end

  //=============================================================
  // п.21: ХАРДРЕНИНГ ЦЕПИ СБРОСА. Сырой пин RST входит в кристалл
  // ТОЛЬКО через 2FF-синхронизатор + квалификатор; решения о сбросе
  // принимают ТОЛЬКО регистры: мид-рейл/дребезг/помеха на SW20
  // физически не доходят ни до сбросовых входов триггеров (таймер
  // вне сети сброса), ни до ноги RESET_IN.
  //   rst_meta/rst_sync - синхронизатор (вне сброса, INIT=0);
  //   rst_qcnt/rst_press - квалификатор (см. Р-2 выше; дребезг короче
  //     1280 нс не виден вовсе, длиннее - полноценный повторный сброс:
  //     каждый взвод заново чистит все 40 триггеров - ПОСЛЕДНЕЕ снятие
  //     всегда из held-чистого состояния, регистровым фронтом);
  //   cpu_rst_r = rst_press | !reset_q - ТОЛЬКО регистровые источники;
  //   reset_q - РЕГИСТР выхода RESET_IN (INIT=0: CPU в сбросе с t=0
  //     до всякого клока; снятие - 8-й фронт CLKOUT, чистым
  //     регистровым фронтом - п.35).
  // Латентность кнопки: 2FF + до 9 тиков por_ce (1280 нс) + cpu_rst_r
  // + reset_q = ~1,44 мкс от пина на взвод. Снятие: после
  // квалифицированного отпускания - 8 фронтов CLKOUT = 2560 нс +
  // <= 2 такта синхронизатора + cpu_rst_r. POR - тот же счёт от INIT.
  //=============================================================
  // cpu_rst_r - РЕГИСТР сброса вместо kept-проводки: у 5В XC9500 у
  // сети GSR НЕТ внутреннего драйвера (только пин I/O/GSR, а пин 1 =
  // кнопка SW20), РЕГИСТР фиттер растворить не может. Эффект: CLR
  // всех ФБ = ОДИН вход cpu_rst_r вместо пары. Сброс буквально
  // «только от регистров» (п.21). Цена: сброс пайплайнится на 1 клк
  // (40 нс); латентность кнопки ~1,44 мкс.
  reg  cpu_rst_r = 1'b1;         // РЕГИСТР сброса (INIT=1: CPU в сбросе с t=0;
                                 // reset_q INIT=0 -> значение в момент t0 то же)
  always @(posedge clk)          // сброс пайплайнится на 1 клк (rst_press | ~reset_q)
    cpu_rst_r <= rst_press | ~reset_q;
  always @(posedge clk) begin  // п.35: полка сброса = 8 фронтов CLKOUT
    if (rst_press) begin
      reset_q <= 1'b0;          // кнопка (квалификатор п.21): сброс немедленно, счёт с нуля
      rst_cnt <= 3'b000;
    end else if (!reset_q) begin
      if (clkout_edge) begin    // CPU в сбросе - считаем фронты CLKOUT
        rst_cnt <= rst_cnt + 3'b001;
        if (&rst_cnt)           // 8-й фронт (rst_cnt==7): снятие полки,
          reset_q <= 1'b1;      //   чистым регистровым фронтом (п.21)
      end
    end                         // reset_q=1: счёт стоит - повтор исключён
  end

  //=============================================================
  // Автомат шины: 7 состояний = 3 триггера (WB1..WB4 ЗАЩИЩЕНЫ от ALE)
  //=============================================================
  localparam S_IDLE = 3'd0,   // ожидание ALE; A/D в Hi-Z; /OE включён (декод)
             S_T1H  = 3'd1,   // T1: CPU держит адрес на A-сетях; идёт захват
             S_T2   = 3'd2,   // строб: чтение - выдача данных на A; запись - захват
             S_WB1  = 3'd3,   // WB: адрес на A + данные на D (t_AS 40 нс до /WE)
             S_WB2  = 3'd4,   // /WE=0 - импульс НАЧАЛСЯ: защищён от ALE
             S_WB3  = 3'd5,   // /WE=0 (импульс = 2 тика = 80 нс >= t_WP ОЗУ)
             S_WB4  = 3'd6;   // /WE=1: удержание адреса/данных (t_AH/t_DH памяти)

  // атрибут против ONE-HOT перекодировки автомата XST: one-hot
  // 7 состояний = 7 триггеров вместо 3 = +4 МЦ = 109 > 108, дизайн
  // не влезает; контроль по .rpt п.h: state_FSM_FFd4.. = БРАК.
  (* fsm_encoding = "compact" *) reg  [2:0] state  = S_IDLE;
  reg        rd_seen = 1'b0;    // строб чтения замечен в T2
  reg        wr_seen = 1'b0;    // строб записи замечен в T2

  // Захваченные шинные регистры
  reg [7:0] addr_latch = 8'h00;  // адрес с A-сетей (T1) - нужен writeback и декоду порта
  reg [7:0] bus_reg    = 8'h00;  // данные: чтение (с D-сети в T1) ИЛИ запись (с A-сети в T2)

  // Порты индикации/звука (§5): захват по записи в порт при IO/M#=1
  reg [6:0] seg_q = 7'h40;       // INIT=40 - горит ТОЛЬКО сегмент g (бит 6) ->
                                 // самотест «----»: тире в КАЖДОМ разряде (все
                                 // dig_q=1) до первой записи fw в порты;
                                 // 1 = сегмент горит
  reg [3:0] dig_q = 4'hF;        // INIT=F - все 4 разряда выбраны -> индикатор
                                 // «----» (с seg_q=40). ЦЕНА (осознана): сток
                                 // ~68 мА через базы PNP (4 x ~17 мА при
                                 // R5/R10/R11/R12=240 Ом) в окне до первой записи
                                 // fw в 01h; НАГРУЗКА СЕГМЕНТОВ при этом в 7 раз
                                 // легче «8888» (4 сегмента, не 28).
                                 // 1 = цифра выбрана; выход инвертируется
  reg       snd_q = 1'b0;
  reg [3:0] kbcol_q = 4'h0;      // колонки = СТАРШИЙ НИББЛ A[7:4] записи порта
                                 // 06h; INIT 0000 = все выкл; сброс снят -
                                 // кнопка скан не гасит
  wire io_rd_kb = IOM & ~addr_latch[2] & addr_latch[1] & addr_latch[0]; // чтение 03h (KBROW)

  // Комбинационные группы:
  //   wb_out = in_wb БЕЗ !ALE: драйверы A/D держат адреса/данные до конца
  //     защищённого импульса (п.4 шапки); снятие - при выходе в IDLE.
  //   rd_drive с !ALE - мгновенный обрыв при новом цикле.
  // П-4: декод - ОДИН узел вместо ~16 схлопнутых копий (8 A-строк +
  // 5 D-драйверов + CS_n/OE_n-ветка): карманы ФБ открываются.
  // Семантика не меняется (только именование). wb_out = алиас in_wb -
  // сливается в этот же узел; io_rd_kb сознательно БЕЗ keep (перебор
  // бюджета МЦ).
  (* keep = "true" *) wire in_wb   = (state >= S_WB1);   // WB1..WB4: A/D драйвятся (П-4: узел)
  wire in_welo = (state == S_WB2) || (state == S_WB3);   // /WE низ
  wire wr_phase = (state >= S_T2);                       // T2..WB4: /OE памяти off
  wire wb_out   = in_wb;                                 // защищённый writeback-драйв
  (* keep = "true" *) wire rd_drive = (state == S_T2) && rd_seen && !RDn && !ALE; // A-пины отдают данные (П-4: узел)
  // fsm_wrdone/fsm_rddone - завершение цикла шины: 2 сети вместо 4
  // литералов в КАЖДОЙ из 4 инлайн-копий (ALE-гейт FSM, ветка записи,
  // ветка чтения, clear rd_seen/wr_seen): -2 вх.ФБ на каждого из 4
  // читателей (rd_seen, wr_seen, FSM_FFd1, FSM_FFd2). rd_drive НЕ
  // тронут: rd_seen && !RDn - обратная полярность, своя функция.
  (* keep = "true" *) wire fsm_wrdone = wr_seen && WRn; // запись завершена (T2-флаг + WRn вверх)
  (* keep = "true" *) wire fsm_rddone = rd_seen && RDn; // чтение завершено (T2-флаг + RDn вверх)
  // Р-5: ОДИН узел записи в порт вместо ~5 инлайн-копий
  // (state == S_T2) && !WRn && IOM (копии жили в io_wr_tx, kbcol_wr06,
  // гейте IOM над case портов): 3-4 литерала в каждом ФБ -> 1 сеть.
  // bus_reg/wr_seen на узел НЕ переводятся - bus_reg ловит и записи
  // памяти (см. ниже).
  (* keep = "true" *) wire io_wr = (state == S_T2) && !WRn && IOM; // строб записи в порт (T2, !WRn, IO)
  // СТРОБЫ ЗАГРУЗКИ bus_reg - keep-узлы (паттерн П-4/Р-5: ОДИН узел
  // вместо инлайн-копий; иначе фильтр сворачивает термы загрузки в
  // 12-входовые функции КАЖДОГО из 8 D-пинов - bus_reg уложен в МЦ
  // D-пинов: D-пин -> FF -> тот же пин). Два узла: каждый D-пин платит
  // 2 сети вместо ~5-6 развёрнутых. Семантика 1-в-1: те же термы,
  // только именованные (bus_ld_t2 - база io_wr выше: io_wr = bus_ld_t2 && IOM).
  (* keep = "true" *) wire bus_ld_t1 = (state == S_T1H) && ALE && !IOM; // захват данных ОЗУ (T1H, адресная фаза)
  (* keep = "true" *) wire bus_ld_t2 = (state == S_T2) && !WRn;         // захват данных записи (T2; без IOM!)

  //=============================================================
  // TXUART (п.27): ИСКЛЮЧИТЕЛЬНО АППАРАТНЫЙ ПЕРЕДАТЧИК UART.
  // OUT 04h = TXDATA: старт кадра 8N1 1 000 000 бод (clk 25 МГц / 25).
  // TXRDY (tx_idle = ~|bit_cnt) = БИТ 7 чтения 03h ({tx_idle,
  // tmr_cnt[1:0], row4..row0}); порт 05h НЕМАПЛЕН.
  //   shreg[8:0]    9 МЦ - {данные, выход}: [0] -> TX (IO-MC, INIT=1 -
  //                 idle '1' до всякого клока, SET-ветка GSR);
  //                 загрузка по ld_tx_q: {A[7:0], 1'b0} с живых A-пинов
  //                 (CPU держит данные до подъёма WRn - запас >= 20
  //                 тиков); сдвиги вправо с инжекцией '1' - после кадра
  //                 shreg САМ приходит в все-'1' (idle по построению;
  //                 ПАРАЛЛЕЛЬНЫХ ЗАГРУЗОК IDLE НЕТ; сдвиг idle-регистра
  //                 - НЕТ-ОП);
  //   bit_cnt[3:0]  4 МЦ - 1..10 = НОМЕР БИТ-ТАЙМА кадра (1 = старт,
  //                 2..9 = данные, 10 = стоп), 0 = idle; busy =
  //                 |bit_cnt - 1 ПТ/NOR; на 10-м сдвиге сам в 0
  //                 (TXRDY = ~|bit_cnt, 1 ПТ);
  //   baud_cnt[4:0] 5 МЦ - mod-25 СВОБОДНЫМ ХОДОМ: D = tick ? 0 : bc+1,
  //                 wrap ЯВНЫЙ (25 не степень двойки: компаратор == 24,
  //                 1 ПТ/5 вх, литерал ~tick входит в D всех 5 бит);
  //                 baud_tick = (bc==24) - 1 ПТ/5 вх - тик сдвига;
  //   ld_tx_q       1 МЦ - РЕГИСТРОВЫЙ СТРОБ загрузки (п.30): декод
  //                 io_wr_tx имеет ЕДИНСТВЕННОГО потребителя;
  //                 D-функция бита shreg = 3 ПТ/~6 вх {ld_tx_q, A[k],
  //                 baud_tick, shreg[k+1], shreg[k]} - все 9 бит в
  //                 ОДНОМ ФБ (~25 вх <= 36).
  // ТАКТ ЯДРА - clk (25 МГц, п.23/34): бод = 25/25 = ровно 1 000 000 -
  // ТОЧНАЯ нижняя сетка CH340G (48М/48; 1 562 500 в сетке НЕТ - драйвер
  // молча 1,5 М, +4,17% = мусор).
  //=============================================================
  localparam [4:0] BAUD_DIV = 5'd25;  // clk 25 МГц/25 = 1 000 000 бод 8N1 (сетка CH340G: 48М/48, ОШИБКА 0%);
                                      // 25 = 11001b - 5 бит; wrap ЯВНЫЙ (25 не степень двойки):
                                      // (== 24) ? 0 : +1 - компаратор 1 ПТ/5 вх; альтернативы:
                                      // 16 -> 1 562 500 (вне сетки CH340G - мусор),
                                      // 27 -> 925 926 (к терминалу 921600 ошибка пары 0,47%),
                                      // 50 -> 500 000 (вдвое медленнее на том же счётчике)
  reg [8:0]  shreg    = 9'h1FF;  // [8:1] данные, [0] -> TX (IO-MC P39; INIT=1: idle до всякого клока)
  reg [3:0]  bit_cnt  = 4'd0;    // 1..10 = бит-тайм кадра (1=старт..10=стоп), 0 = idle; busy = |bit_cnt
  reg [4:0]  baud_cnt = 5'd0;    // mod-25 свободным ходом, wrap ЯВНЫЙ на тике; jam при загрузке
  reg        ld_tx_q = 1'b0;     // регистровый строб загрузки (п.30)
  // П-1 (v28.2): baud_tick - ИМЕНОВАННЫЙ УЗЕЛ с keep: ОДИН декод (== 24)
  // на ВСЕХ потребителей (baud_cnt wrap, shreg-сдвиг, tick_step). Без keep
  // XST разворачивает (baud_cnt == 24) в 5 литералов baud_cnt<0..4> в
  // D-пути КАЖДОГО потребителя: FB6 (+5 сетей в счётном разрешении
  // таймера), FB3/FB4 (строки shreg) - UIM-слоты ФБ выгорают (фит-сессии
  // 1-6: FB Inps 213-215/216). С keep: один 1-ПТ узел + 1 сеть на ФБ.
  (* keep = "true" *) wire baud_tick = (baud_cnt == (BAUD_DIV - 5'd1)); // == 24: тик каждые 25 тактов clk 25 МГц (П-1: ОДИН узел)
  wire tx_idle   = ~|bit_cnt;                                  // idle/TXRDY: 1 ПТ/4 вх (NOR) - inline в строб и мукс 03h (Шаг-2, бит 7)
  // Старт кадра - ОДНОКРАТНЫЙ строб: первый тик !WRn в T2 записи порта
  // 04h (адрес защёлкнут в T1 - addr_latch стабилен). Гейты: tx_idle &&
  // !ld_tx_q - повторные такты строба !WRn и запись при busy БЛОКИРОВАНЫ
  // (байт тихо отбрасывается, кадр не портится - контракт); !cpu_rst_r -
  // шинные действия гейтятся сбросом (класс п.21e; при GSR FSM в окнах
  // сброса и так в IDLE - двойная страховка: floated-шина в окне
  // сброса кадр не стартует).
  wire io_wr_tx = io_wr                                     // Р-5: общий строб записи в порт (узел выше)
                  && addr_latch[2] && !addr_latch[1] && !addr_latch[0]  // порт 04h
                  && tx_idle && !ld_tx_q && !cpu_rst_r; // ОДНОКРАТНОСТЬ + гейт сброса
  // (декода чтения статуса 05h нет: TXRDY - бит 7 чтения 03h,
  // см. assign A ниже.)
  always @(posedge clk or posedge cpu_rst_r) begin // п.27/п.34: асинхронный сброс ядра -> СЕТЬ GSR (cpu_rst_r, п.20/21); такт clk 25 МГц
    if (cpu_rst_r) begin
      shreg    <= 9'h1FF;   // idle '1' (SET-ветка GSR)
      bit_cnt  <= 4'd0;     // idle (CLR-ветка GSR)
      baud_cnt <= 5'd0;
      ld_tx_q  <= 1'b0;
    end else begin
      ld_tx_q  <= io_wr_tx;                    // строб загрузки - через регистр (п.30)
      baud_cnt <= baud_tick ? 5'd0 : baud_cnt + 5'd1; // mod-25: wrap ЯВНЫЙ на тике
                                               // (25 не степень двойки; jam при загрузке ниже перекрывает)
      if (ld_tx_q) begin
        // ЗАГРУЗКА (на тик позже строба io_wr_tx - п.30): байт с живых
        // A-пинов, старт-бит '0' на шине с этого такта; jam baud_cnt <= 0:
        // первый сдвиг ровно через 25 тиков - старт-бит РОВНО 25 тиков
        // (jam 1 + лаг adv_q 1 такт = ТОТ ЖЕ фронт; сетка кадров
        // 1-в-1); bit_cnt <= 1 (бит-тайм старта)
        shreg    <= {A, 1'b0};                 // [8:1] = данные (d7..d0), [0] = старт '0'
        bit_cnt  <= 4'd1;
        baud_cnt <= 5'd0;
      end else if (baud_tick) begin
        // ТИК СДВИГА (каждые 25 тактов clk 25 МГц; в idle сдвиг - НЕТ-ОП,
        // регистр уже весь '1'): инжекция '1' в MSB - на 9-м сдвиге
        // стоп сам встанет в [0] (бит-тайм 10), после кадра shreg ==
        // все-'1' (idle) без отдельных загрузок
        shreg <= {1'b1, shreg[8:1]};
      end
      if (|bit_cnt && baud_tick) begin
        // бит-тайм кадра кончился (сдвиг был): 1..9 -> ++, 10 (стоп
        // отработал) -> 0 = idle, TXRDY поднимается в конце стопа (тот
        // же тик, что конец стопа). НА ГРУЗКЕ НЕ РАБОТАЕТ: bit_cnt
        // (старое значение) = 0 - строб io_wr_tx возможен только в idle
        bit_cnt <= (bit_cnt == 4'd10) ? 4'd0 : bit_cnt + 4'd1;
      end
    end
  end

  //=============================================================
  // Шинный движок
  //=============================================================
  always @(posedge clk or posedge cpu_rst_r) begin // сброс логики по cpu_rst_r = rst_press|~reset_q (регистры, п.21; асинхронная структура GSR п.18/20); такт логики clk 25 МГц (п.23/34)
    if (cpu_rst_r) begin
      state      <= S_IDLE;
      rd_seen    <= 1'b0;
      wr_seen    <= 1'b0;
      addr_latch <= 8'h00;
      bus_reg    <= 8'h00;
      seg_q      <= 7'h40;   // самотест «----»: только g; в POR/после кнопки
                             // RESET тире во всех 4 разрядах, пока fw не
                             // перехватит индикацию
      dig_q      <= 4'hF;   // самотест «----»: все 4 разряда выбраны в
                            // сбросе/POR (~68 мА баз - осознанно, ради
                            // видимого самотеста)
      snd_q      <= 1'b0;
      // kbcol_q сброса здесь НЕТ: единственный always-водитель - в блоке
      // ТАЙМЕР (второй водитель = XST 528)
    end else begin
      // --- захват повторным сэмплированием: последний сэмпл валиден ---
      // захват возможен только в T1H, т.е. ПОСЛЕ завершения WB
      // (структурно: из WB в T1H попадаешь только через IDLE).
      // addr_latch НЕ может перезаписаться посреди импульса (п.6 шапки).
      if (state == S_T1H && ALE)
        addr_latch <= A;                 // адрес стабилен весь T1 (строб bus_ld_t1 несёт !IOM - в plain-стробе он есть)
      if (bus_ld_t1 || bus_ld_t2)        // CE-ФОРМА: стробы взаимоисключающие
        bus_reg <= bus_ld_t1 ? D : A;    //   (T1H/T2 - разные состояния FSM),
                                         //   XST выводит CE-FF БЕЗ self-столбца:
                                         //   D-пины 7 -> 6 вх.ФБ (-5 FB3, -3 FB1).
                                         //   t1-фаза = D (чтение памяти, T1),
                                         //   t2-фаза = A (запись, CPU держит до
                                         //   WR#(вверх)) - И ЗАПИСИ ПАМЯТИ,
                                         //   поэтому НЕ io_wr (Р-5)
      if (io_wr) begin                   // Р-5: запись в порт - ОДИН узел; декод A2,A1,A0
        case (addr_latch[2:0])
          3'b000: seg_q <= A[6:0];       // 00h: сегменты (dp снят, T2)
          3'b001: begin                  // 01h: разряды + SND
            dig_q <= A[3:0];
            snd_q <= A[4];
          end
          default: ;                     // 02h НЕМАПЛЕН - алиас; 03h чтение;
                                         // 04h - старт TX (ОДНОКРАТНЫЙ строб
                                         // io_wr_tx в ядре TXUART, не здесь); 05h
                                         // НЕМАПЛЕН (TXRDY -> бит 7 чтения 03h);
                                         // 06h - колонки (строб kbcol_wr06, узел
                                         // «ТАЙМЕР» ниже; таймер НЕ пишется -
                                         // свободный ход); 07h резерв
        endcase
      end
      // --- трекинг стробов ---
      if (state == S_T2 && !RDn) rd_seen <= 1'b1;
      if (state == S_T2 && !WRn) wr_seen <= 1'b1;
      // --- переходы ---
      // ALE ОБРЫВАЕТ только T2 (защита от глюка); в WB1..WB4 НЕ
      // вмешивается - импульс /WE защищён (п.4 шапки).
      if (ALE && state == S_T2 && !(fsm_wrdone || fsm_rddone)) begin // узлы вместо инлайн-пар
        state   <= S_IDLE;
        rd_seen <= 1'b0;
        wr_seen <= 1'b0;
      end else begin
        case (state)
          S_IDLE: if (ALE) state <= S_T1H;
          S_T1H:  if (!ALE) state <= S_T2;
          S_T2: begin
            // приоритет записи: RDn-глюк во время записи не должен прерывать её
            if (fsm_wrdone) begin // узел вместо инлайн-пары
              wr_seen  <= 1'b0;
              // writeback только для записи в ОЗУ (8000-FFFF); запись в ПЗУ
              // отбрасывается (по железу /WE flash не подключён), порт пропускается
              // гейт сброса (п.18): FSM в окне сброса живой (GSR не активен),
              // шина CPU «floated» (ВМ85А: управления/адрес/данные в 3-м
              // состоянии) - вход в writeback ЗАПРЕЩЁН, иначе плавающие
              // ALE/WRn могли бы родить /WE
              state <= (!IOM && A15 && !cpu_rst_r) ? S_WB1 : S_IDLE; // гейт и на кнопку (п.21); cpu_rst_r - регистр
            end else if (fsm_rddone) begin // узел вместо инлайн-пары
              rd_seen <= 1'b0;
              state <= S_IDLE;         // отпускание A-пинов через 1 тик после RD#(вверх)
            end
          end
          S_WB1: state <= S_WB2;       // t_AS 40 нс; hold-off 0 (см. п.4 шапки)
          S_WB2: state <= S_WB3;       // /WE низ - защищён, идёт до конца
          S_WB3: state <= S_WB4;
          S_WB4: state <= S_IDLE;      // импульс закончен, всё снято в IDLE
          default: state <= S_IDLE;
        endcase
      end
    end
  end

  //=============================================================
  // ШАГ ТАЙМЕРА 4 мкс: tick_step = por_ce & baud_tick - совпадение
  // двух стробов (por_ce: 1 клк каждые 4 клк; baud_tick: 1 клк каждые
  // 25 клк; оба стартуют из INIT-значений - фазы фиксированы
  // конфигурацией): ровно 1 клк на каждые LCM(4,25) = 100 клк = 4 мкс.
  // ДЖИТТЕР: jam baud_cnt при загрузке TX сдвигает фазу baud_tick ->
  // ОДИН межшаговый интервал после каждой загрузки краток/долог (до
  // 2 шагов = 8 мкс), дальше сетка ровно 100 клк.
  //=============================================================
  wire tick_step = por_ce & baud_tick;   // база таймера: 100 клк = 4 мкс

  //=============================================================
  // СВОБОДНЫЙ ТАЙМЕР -> RST 7.5 (P75). Контракт Р-5E (v37E):
  //  - tmr_cnt[1:0] (INIT=2'h0) - фазовый счётчик СВОБОДНОГО ХОДА:
  //    инкремент по tick_step (оборот 16 мкс), НЕТ ни записи, ни
  //    сброса, ни стопа - детерминирован INIT с подачей питания;
  //  - RST75_r - ИМПУЛЬС 1 клк (40 нс) на КАЖДЫЙ тик tick_step:
  //    защёлка RST 7.5 в CPU ловит фронт независимо от маски; пропуск
  //    тика (маска/длинный ISR) систему НЕ ломает - фаза всегда
  //    доступна чтением 03h (самоисцеление: следующий тик через 4 мкс);
  //  - ПО синхронизируется ЧТЕНИЕМ фазы: IN 03h -> {TXRDY, tmr_cnt[1:0],
  //    row4..row0}, ветвление по tmr_cnt[1:0] выбирает эвент
  //    (эвентная логика в ПО - маневр размещения);
  //  - таймер ВНЕ сети сброса (INIT-старт): тик идёт сквозь сброс -
  //    защёлка RST 7.5 получит фронты в окне сброса, SIM со сбросом
  //    защёлки РАНЬШЕ первого EI ОБЯЗАТЕЛЕН (шапка); после кнопки счёт
  //    продолжается с текущего места - принятая жертва (см. шапку);
  //  - чтение фазы НЕ гонится с инкрементом: смена раз в 4 мкс, сэмпл
  //    IN одномоментный - старое/новое значение оба валидны (семантика:
  //    номер текущего слота);
  //  - kbcol_wr06 - ОДИН keep-узел декода 06h: строб КОЛОНОК (таймер
  //    в записи НЕ участвует; без keep XST разворачивал декод в D
  //    КАЖДОГО бита счётчика).
  //=============================================================
  reg  [1:0] tmr_cnt = 2'h0;     // 2 бита фазы: слоты 0..3 x 4 мкс, оборот 16 мкс
  reg        RST75_r    = 1'b0;  // импульс 1 клк на каждый тик (IO-MC P75)
  (* keep = "true" *) wire kbcol_wr06 = io_wr &&             // Р-5: общий строб записи в порт (узел выше)
                        (addr_latch[2:0] == 3'b110);       // OUT 06h: колонки (таймер не пишется)

  always @(posedge clk)   // сброс СНЯТ - таймер вне сети сброса; INIT RST75_r=0
    RST75_r <= tick_step; // ИМПУЛЬС 1 клк на каждый тик: строб зарегистрирован -
                          // чистый фронт на P75 (без комбинационного гонка
                          // por_ce&baud_tick на ноге)

  always @(posedge clk) begin  // сброс СНЯТ - таймер вне сети сброса; INIT 00;
    // после кнопки счёт продолжается с текущего места - принятая
    // жертва (см. шапку)
    // СВОБОДНЫЙ ХОД: инкремент без записи/сброса/стопа; D без декодов
    // (п.9); на первом тике фаза 1, далее слоты 1,2,3,0 повторяются
    if (tick_step) tmr_cnt <= tmr_cnt + 2'd1;
  end

  always @(posedge clk)      // колонки в СВОЁМ always - чистый CE = kbcol_wr06
    if (kbcol_wr06)          //   БЕЗ self-столбца: col0-3 2 вх.ФБ; сброс СНЯТ
      kbcol_q <= A[7:4];     //   (INIT=00; после кнопки скан продолжается с
                             //   текущего места - принятая жертва). Загрузка
                             //   из ЖИВОЙ A-сети T2, тем же фронтом, что
                             //   bus_reg <= A (из bus_reg было бы stale на
                             //   такт). A[1:0] записи игнорируются: таймер
                             //   свободный ход - в v37E НЕ пишется.
  assign RST75 = RST75_r;

  //=============================================================
  // Тристейт-драйверы шины
  //=============================================================
  // при чтении порта 03h A_I(0..4) = row0-4 (mux KBROW), A7 = TXRDY
  // (tx_idle), A6-5 = tmr_cnt[1:0] - ОДИН декод на оба чтения
  // (kb+статус+фаза);
  // IN 04h НЕ определён (RX нет - уходит в bus_reg, прошивкой не
  // использовать); IN 05h = bus_reg (немаплен).
  assign A = rd_drive ? (io_rd_kb ? {tx_idle, tmr_cnt, row4, row3, row2, row1, row0}
                                  : bus_reg)
          : wb_out   ? addr_latch : 8'bZZZZZZZZ;
  assign D = wb_out ? bus_reg : 8'bZZZZZZZZ;

  //=============================================================
  // Декод памяти минимальной ширины (§5): 1 терм на кристалл.
  // /CE ОЗУ в writeback - ОТ СОСТОЯНИЯ FSM (in_wb); защёлки нет:
  // in_wb достижим только через T2-запись в ОЗУ и уже влечёт её
  // условие. Живой декод A15 во время конфликта адресов НЕ участвует:
  // в WB1..WB4 CS_n = 0 без A15/IOM - запись ОЗУ защищена построением
  // (п.5 шапки).
  //=============================================================
  assign CSr_n = A15 | IOM;             // /CE_ROM = !( !A15 & !IOM )
  assign CS_n  = in_wb ? 1'b0 : (!A15 | IOM);   // от FSM (п.16)
  assign OEr_n = CSr_n | wr_phase;      // /OE гасится с T2 - данные уже захвачены,
  assign OE_n  = CS_n  | wr_phase;      // иначе SRAM воевала бы с CPLD на D в writeback
  // /WE НЕ обрывается ALE - импульс доводится до конца (п.4 шапки):
  // автомат доходит до WB4/IDLE за 5 тиков. Начатый импульс /WE (80 нс)
  // НЕ обрывается: квалификатор длиннее импульса - начатая запись
  // доводится до конца (полный t_WP ОЗУ), сброс гасит драйвы сразу
  // после её завершения (п.21f).
  assign WE_n  = !in_welo;


  //=============================================================
  // Поддержка CPU (§3) + TXUART (п.27): передача - аппаратный
  // сериализатор (OUT 04h, ядро выше); приём - программный (SID = RX,
  // RIM 20h). Держатели '0' (RST6.5/5.5, INTR, HOLD, A16-A18) удалены
  // из HDL - их пины заземлит фиттер (Ground on Unused IOs).
  // SID (P73) - ВЫХОД CPLD (транзит RX); RST75 (P75) - ВЫХОД CPLD
  // (таймер); TRAP (P74) - держатель '0' -> PGND 8: {P74,P76,P78,P79,
  // P81,P95,P96,P98}.
  //=============================================================
